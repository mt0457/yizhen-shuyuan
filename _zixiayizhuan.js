卜商（前507—前400），字子夏，卫国温邑人。孔子弟子，孔门十哲之一，以文学著称。孔子殁后居西河教授，为魏文侯师。《史记》载孔子传易于商瞿，而刘向《别录》谓子夏亦传易学。《隋书·经籍志》著录《子夏易传》二卷。孔颖达《周易正义》引子夏易说十余条，李鼎祚《周易集解》多采其说。今本十一卷经后人辑佚编次，为先秦易学义理派之祖。

