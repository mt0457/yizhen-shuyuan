天尊地卑，乾坤定矣。卑高以陈，贵贱位矣。动静有常，刚柔断矣。方以类聚，物以群分，吉凶生矣。在天成象，在地成形，变化见矣。

子夏曰：此言乾坤定位而万物之理备。天尊地卑，君尊臣卑，父尊子卑，各有定位。动静刚柔，各有常道。同方者聚，同物者分。善与善交，恶与恶党。吉凶由此生焉。

一阴一阳之谓道。继之者善也，成之者性也。仁者见之谓之仁，知者见之谓之知。

子夏曰：道不可见，因阴阳以显。阴阳者气之两端。人继此道则善，成此道则性。各因其禀而见有不同。

易有太极，是生两仪。两仪生四象，四象生八卦。八卦定吉凶，吉凶生大业。

子夏曰：太极者天地未分之前也。两仪者天地也。四象者四时也。八卦者万物之象也。圣人观象设卦，以定吉凶。吉凶既定，则大业由此而生。

易与天地准，故能弥纶天地之道。仰以观于天文，俯以察于地理。是故知幽明之故。原始反终，故知死生之说。精气为物，游魂为变。是故知鬼神之情状。

子夏曰：易之道与天地准。大则弥纶天地，细则察见幽明。原始反终而知死生，察精气游魂而知鬼神。圣人作易，其用无穷。

君子居其室，出其言善，则千里之外应之。出其言不善，则千里之外违之。言行，君子之枢机。枢机之发，荣辱之主也。

子夏曰：言行者君子之枢机。如弩之发，如门之转。一发之后或荣或辱，不可不谨。此圣人戒慎之教也。

