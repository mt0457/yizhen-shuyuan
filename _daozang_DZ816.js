<p style="line-height:2.2;">
<b>甲子符详解：</b>甲子神将符（亦称"玄武水帝符"），以青纸朱砂书之，符长六寸（约二十厘米），宽三寸。符头为三清敕令之云头纹；符身为波浪纹三道（代表三江四海之水），中央书"王文卿"三字之行书体，三字之上各点一点朱砂（代表三清之光加持）；符胆为"水"字之秘文变体（非普通"水"字，而是在"水"之左右各加三点以象征"上善若水"之道家理念）；符脚为玄武龟蛇相缠之图形简化。此符专用于水厄防护、祈雨、肾脏疾病之辅助治疗。佩带时符面向内，贴近后腰（命门穴处——中医认为肾俞穴在命门旁，以符近腰可直达肾气）。此法用于行船者或居住于水边之人家尤为适宜。</p>
