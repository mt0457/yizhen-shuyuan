全经详述初入道者从俗入道、舍凡归真之完整仪程——自洁身改服、焚香启坛、盟誓告天、受持戒律、赐授法名、登名录籍，至谢师礼成，凡七大环节。
每一环节皆有特定之威仪轨范、存思口诀、密咒真文，使初入道者依此仪轨如法行之，则天魔拱卫、地祇护持、三官注籍、万神证明。
此仪乃正一道士入道之根本规矩，凡欲入正一门庭者，必先习此仪，知初入道之次第规矩，方可正式投师受度。
正一道以“正一”为宗——正者不邪，一者不二；正以治邪，一以统万。
入此门者，当先正其心、一其志，而后方可承受太上正一盟威之道法。
此经自东汉祖天师创立五斗米道（即正一道前身）以来，经魏晋南北朝之完善，至唐代始有定型文本行世，为历代正一道士入道必行之根本仪轨。
祖天师于汉顺帝汉安元年（公元142年）正月七日，在鹤鸣山遇太上老君下降，老君授以“正一盟威之道”及“三天正法”，命天师代天行道、教化百姓。
天师受法之后，设立“二十四治”（二十四传教点），以《道德经》为根本经典，以五斗米为入道之信物（凡入道者出五斗米以供道团日常之需），遂创正一道。
当时初入道者之仪轨极为简朴——入道者只需向天师奉上五斗米，天师为之说《道德经》要义，令其持守“诚信不欺”之基本戒律，即为正式入道。此乃最早之入道仪。
其后经张衡天师（第二代）、张鲁天师（第三代）之扩充，将汉末三张（张角、张宝、张梁太平道）之影响吸收，入道仪逐渐增加了饮食禁忌、集体聚会（二十四治之定期集会）等内容。
