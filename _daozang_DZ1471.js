<p style="font-size:16px;color:#8b1a1a;line-height:2.2;margin:0;">
<b>
太上垂训，三山立教。龙虎正一，盟威斩邪。
茅山上清，存思飞天。阁皂灵宝，斋醮济度。
三山合一，正一为宗。二十四阶，次第而升。
符不离箓，箓不离符。运炁入符，心正符灵。
受箓行符，济度群生。轻慢妄用，自招祸殃。
法脉绵延，近两千载。天师代代，法灯常明。
一炁化三山，三山归正一。符为道之用，人道不可欺。
至心皈命太上正一三山符箓无上法门。
皈命太上老君。
皈命三山历代宗师。
皈命道经师三宝。
福生无量天尊。
</b>
</p>
