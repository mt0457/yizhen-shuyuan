读易当以经为主、传为辅。先观卦爻辞，玩其辞、审其象，而后参夫子之传。汉儒主象数，宋儒主义理。今折中诸家，以程朱为主，择汉儒象数之精，取宋儒义理之纯。庶几易道之大全可见。

