此书为中国汉代成书之地质堪舆学早期经典，以地表草木土石云气水泉之征候推断地下矿藏水脉吉穴之位置与性质。全书十六卷，涵盖：学术源流、草木辨宝篇、云气望气篇、地形地貌篇、泉水占篇、山石辨篇、实际应用、择地篇、辨灾篇、辨物篇、历代传承、矿藏详辨篇（金银铜铁锡铅汞七种矿藏详辨）、地下建筑探测篇、风水篇（龙脉砂水明堂）、比较研究篇。为世界最早之地质矿物学文献之一。
