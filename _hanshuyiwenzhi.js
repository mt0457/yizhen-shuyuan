诸子十家，其可观者九家而已。皆起于王道既微，诸侯力政，时君世主好恶殊方。是以九家之术，蜂出并作，各引一端，崇其所善，以此驰说，取合诸侯。其言虽殊，辟犹水火，相灭亦相生也。若能修六艺之术，而观此九家之言，舍短取长，则可以通万方之略矣。

