六者，横灾不能及其门。
七者，夜卧安隐，无诸噩梦。
八者，出行平安，无诸险难。
九者，家宅清吉，人口安宁。
十者，田蚕丰收，衣食丰足。
十一者，所求如意，所愿成就。
十二者，官府敬重，横事不干。
十三者，口舌消灭，是非远离。
十四者，冤家消散，仇敌和解。
十五者，祖先升天，不受幽冥之苦。
十六者，子孙昌盛，门庭光大。
十七者，寿命延长，身无疾病。
十八者，颜色悦泽，气力强健。
十九者，智慧开发，明了经义。
二十者，心神安定，烦恼不生。
二十一者，常得吉神护身，出入随逐。
二十二者，常得善缘相遇，道业增进。
二十三者，临终之时，心不迷乱。
