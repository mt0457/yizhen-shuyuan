【注释】
三十六种功德：三十六在道教为天罡之数，与三十六天、三十六雷将等概念相应。大罗：大罗天，道教最高天界，元始天尊所居。此段详列诵咒功德，为洞渊经中鼓励信众受持神咒的核心段落，后世道士为人宣讲洞渊经时，常引此段以劝人信受。三十六功德涵盖现世利益（平安、丰收、如意）、修行利益（智慧、定力、道业）及终极利益（升入大罗），体现了道教济度思想的完整性。

