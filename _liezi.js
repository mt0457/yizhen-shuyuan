列子，名御寇，战国前期郑国圃田人。道家重要代表人物，其学本于黄帝老子。唐天宝元年诏封冲虚真人，其书尊为《冲虚真经》。全书八篇，多寓言故事，以浅喻深。《愚公移山》《杞人忧天》《两小儿辩日》《纪昌学射》《高山流水》等名篇皆出此书。文辞瑰丽，哲理深邃，与《庄子》并为道家文学双璧。
