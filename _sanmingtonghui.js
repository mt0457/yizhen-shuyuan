大运十年一换，流年一年一变。大运为经，流年为纬。大运吉流年吉——双吉，大喜之年。大运凶流年凶——双凶，大凶之年。大运吉流年凶——吉中带阻。大运凶流年吉——凶中见救。

流年天干看上半年（春夏），地支看下半年（秋冬）。流年冲提纲——根基动摇。流年合日主——自身变化。流年伏吟——重复之事。流年反吟——对立之变。

