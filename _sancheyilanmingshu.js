三车论十干禄身配合。禄车与身车顺生者天生有福——禄木身水（水生木）、禄火身木（木生火）、禄土身火（火生土）、禄金身土（土生金）、禄水身金（金生水）。禄身比和者自我意识强。禄克身者天生财格善于经营。身克禄者天生压力须奋斗。禄身相生为上，比和次之，相克为下。

