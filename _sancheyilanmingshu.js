三车论地支刑冲。子午冲水火激——禄车水命车火者根基动摇。丑未冲两墓击——禄车土命车土者自相消耗。寅申冲金木战加驿马——奔波劳碌。卯酉冲门户——家宅不宁。辰戌冲魁罡——刚毅好斗。巳亥冲驿马——奔波变动。三车以静为安，冲则动变。少年运逢冲——离祖别乡。中年运逢冲——事业变动。晚年运逢冲——晚景不安。

