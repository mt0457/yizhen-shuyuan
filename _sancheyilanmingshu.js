三车论地支合会。地支六合：子丑合土、寅亥合木、卯戌合火、辰酉合金、巳申合水、午未合日月。地支三合：申子辰水局、亥卯未木局、寅午戌火局、巳酉丑金局。地支三会：寅卯辰东方木、巳午未南方火、申酉戌西方金、亥子丑北方水。合会之力：三会最强（同一方位），三合次之（生旺墓），六合又次之。合则聚，聚则力大。三车以合为吉——禄命身三车得合局者根基稳固。

