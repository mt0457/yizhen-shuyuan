【三车日诀】甲子顺生上吉昌，庚辰辛巳亦同光。壬申癸酉金生水，甲申通关更无双。己丑己未火生土，戊申己酉土生金。庚子辛丑土生金，壬寅癸卯顺生良。庚戌辛亥亦顺生，甲寅乙卯水生木。十七上吉日须记，大事行之日日祥。

【三车月诀】正二三月木车旺，禄木命木此时强。四五六月火车旺，禄火命火正堂堂。七八九月金车旺，禄金命金刚锐扬。十冬腊月水车旺，禄水命水智谋长。四季之月土车旺，禄土命土稳如岗。

【三车改运诀】禄弱补禄五行方，木禄东居青色装。火禄南居红枣食，金禄西居白色裳。水禄北居黑豆补，土禄中居小米尝。命冲合解根基固，身战通关福泽长。

【三车万法诀】三车本是命之纲，禄命身分各自强。禄为天车观贵贱，命为地车定寿长。身为人车看福祉，三车合断命全彰。宋后子平虽为主，三车古法不可忘。

