三车论十干禄命身。甲禄寅命寅身水——三车水木相生。乙禄卯命卯身水——同。丙禄巳命巳身土——火土相生。丁禄午命午身水——水火既济。戊禄巳命巳身木——火生土，木克土。己禄午命午身木——火生土，木克土。庚禄申命申身木——金克木。辛禄酉命酉身木——金克木。壬禄亥命亥身木——水生木。癸禄子命子身木——水生木。十干三车各有特质。

