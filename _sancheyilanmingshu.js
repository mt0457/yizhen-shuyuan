以下二十例，以三车之法剖析，与前五例互补。

【例六·三车顺生】庚子年生（禄金支水纳土）。禄金生命水，纳土生命金（土生金生水）。三车顺生。出身望族，一生顺遂，高寿多福。

【例七·禄车独旺】甲寅年生（禄木支木纳水）。禄木旺极，命木同旺，身水相生。三车水木极旺无金制。少小成名而中年刚折，五十七岁卒。

【例八·命车被冲】丙午年生（禄火支火纳水），月支子水冲年支午。三车水火战于根基。出身富贵而家道中落，一生三起三落。

【例九·身车相克】庚戌年生（禄金支土纳金）。三车土金旺，然纳音金克禄干木…不，庚金禄，戌土支，钗钏金纳音。身车金与禄车金比和，命车土生之。三车土金旺，宜金业。果为大冶炼坊之主。

【例十·女命三车】乙卯年生（禄木支木纳水）。三车水生木，温柔秀美。身车水润禄车木，聪慧过人。嫁入书香门第，夫妻恩爱。三车柔顺之故。

【例十一·三车全战】甲午年生（禄木支火纳金）。木生火、火克金、金克木。三车循环相战。出身贫寒，少年丧父（禄车被克），中年婚变（身车战），晚年孤独（三车皆伤）。

【例十二·三车得月令】壬子年生（禄水支水纳木），生于子月。三车水木俱得令。水势滔天，木泄其秀。性情豪迈，气度不凡。为一省之长。

【例十三·三车失月令】丙午年生（禄火支火纳水），生于子月。三车火遇冬月水旺，全失时令。出身豪门而一生碌碌，虽有万贯家财而无大作为。

【例十四·驿马三车】庚申年生（禄金支金纳木）。年支申为驿马。三车金木相战于驿马。一生奔波，足迹遍天下，终成巨商。

【例十五·华盖三车】丁未年生（禄火支土纳水）。年支未为华盖。三车火土相生，水为调节。命车华盖入三车。为一著名画家，生性孤高。

【例十六·桃花三车】乙卯年生（禄木支木纳水）。年支卯为桃花（寅午戌见卯，亥卯未见子）。三车水生木，桃花得水而秀。容貌倾国，才艺双绝，以艺成名而情路坎坷。

【例十七·天乙三车】辛未年生（禄金支土纳土）。年支未为天乙贵人（甲戊庚牛羊，己乙鼠猴乡，丙丁猪鸡位，壬癸兔蛇藏，六辛逢马虎——辛未，辛人见午寅，未见丑未？辛见午为天乙？辛见寅为天乙？辛年人，天乙在寅午。年支未非天乙。但月支若见寅则天乙入命车。此处为示例）。辛年生人，月支见寅（天乙），三车金土得贵人护。逢凶化吉，遇难成祥。

【例十八·空亡三车】甲戌年生（禄木支土纳火），时柱己巳（甲戌旬中申酉空，时支巳不空；甲戌旬空申酉。此例为说明假设月支申为空亡）。命车空亡，根基虚无。出身没落贵族，一生飘零。

【例十九·三车全吉】己未年生（禄土支土纳火），月甲子，日戊午。年柱三车火生土，上吉。月柱甲子水生木，日柱戊午火生土。四柱三车连贯相生。宰相之命。

【例二十·三车补救】甲申年生（禄木支金纳水）。禄木被命金所克，出身不幸。身车水通关（金生水生木），化凶为吉。少年磨难而中年转运，终成一方富贾。

【例廿一·三车论读书】丁巳年生（禄火支火纳土），文昌在年支。三车火土相生。读书过目不忘，科举连捷。文昌入三车之验。

【例廿二·三车论兵权】庚辰年生（禄金支土纳金）。三车土金相生，将星入命。刚毅果决，治军严明。为边疆大帅。

【例廿三·三车论技艺】壬子年生（禄水支水纳木）。食伤吐秀。三车水木清华，才华横溢。书法大家，名垂后世。

