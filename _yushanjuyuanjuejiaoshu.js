浩浩太素，阳曜阴凝。二仪陶化，人伦肇兴。厥初冥昧，不虑不营。欲以物开，患以事成。犯机触害，智不救生。宗长归仁，自然之情。故君道自然，必托贤明。茫茫在昔，罔或不宁。赫胥既往，绍以皇羲。默静无文，大朴未亏。万物熙熙，不夭不离。爰及唐虞，犹笃其绪。体资易简，应天顺矩。絺褐其裳，土木其宇。物或失性，惧若在予。畴咨熙载，终禅舜禹。夫统之者劳，仰之者逸。至人重身，弃而不恤。故子州称疾，石户乘桴。许由鞠躬，辞长九州。先王仁爱，愍世忧时。哀万物之将颓，然后莅之。下逮德衰，大道沈沦。智惠日用，渐私其亲。惧物乖离，擘画违仁。利巧愈竞，繁礼屡陈。刑教争施，天性丧真。季世陵迟，继体承资。凭尊恃势，不友不师。宰割天下，以奉其私。故君位益侈，臣路生心。竭智谋国，不吝灰沈。赏罚虽存，莫劝莫禁。若乃骄盈肆志，阻兵擅权。矜威纵虐，祸蒙丘山。刑本惩暴，今以胁贤。昔为天下，今为一身。下疾其上，君猜其臣。丧乱弘多，国乃陨颠。故居帝王者，无曰我尊，慢尔德音。无曰我强，肆于骄淫。弃彼佞幸，纳此逆颜。谀言顺耳，染德生患。悠悠庶类，我控我告。唯贤是授，何必亲戚。顺乃造好，民实肯效。治乱之原，岂无昌教。穆穆天子，思闻其愆。虚心导人，允求谠言。师臣司训，敢告在前。



