夫民之性，好安而恶危，好逸而恶劳。故不扰则其愿得，不逼则其志从。洪荒之世，大朴未亏，君无文于上，民无竞于下，物全理顺，莫不自得。饱则安寝，饥则求食，怡然鼓腹，不知为至德之世也。若此，则安知仁义之端，礼律之文？

及至人不存，大道陵迟，乃始作文墨，以传其意。区别群物，使有类族。造立仁义，以婴其心。制为名分，以检其外。劝学讲文，以神其教。故六经纷错，百家繁炽，开荣利之涂，故奔骛而不觉。是以贪生之禽，食园池之梁菽；求安之士，乃诡志以从俗。操笔执觚，足容苏息；积学明经，以代稼穑。是以困而后学，学以致荣；计而后习，好而习成。有似自然，故令吾子谓之自然耳。

推其原也，六经以抑引为主，人性以从欲为欢。抑引则违其愿，从欲则得自然。然则自然之得，不由抑引之六经；全性之本，不须犯情之礼律。故仁义务于理伪，非养真之要术；廉让生于争夺，非自然之所出也。由是言之：则鸟不毁以求驯，兽不群而求畜；则人之真性，无为正当。自然，耽此礼学矣。

论又云：嘉肴珍膳，虽未所尝，尝必美之，适于口也。处在暗室，睹烝烛之光，不教而悦得于心。况以长夜之冥，得照太阳，人情变则晓其义。且昼坐夜寝，明作暗息，天道使之自然。人知向明背暗，岂须人教而后能者？

今子立六经以为准，仰仁义以为主，以规矩为轩驾，以讲诲为哺乳。由其涂则通，乖其路则滞。游心极视，不睹其外。终年驰骋，思不出位。聚族献议，唯学为贵。执书擿句，俯仰咨嗟。使服膺其言，以为荣华。故吾子谓六经为太阳，不学为长夜耳。今若以明堂为丙舍，以讽诵为鬼语，以六经为芜秽，以仁义为臭腐。睹文籍则目瞧，修揖让则变伛，袭章服则转筋，谭礼典则齿龋。于是兼而弃之，与万物为更始。则吾子虽好学不倦，犹将阙焉。则向之不学，未必为长夜，六经未必为太阳也。俗语曰：乞儿不辱马医。若遇上古无文之治，可不学而获安，不勤而得志，则何求于六经，何欲于仁义哉？以此言之，则今之学者，岂不先计而后学耶？苟计而后动，则非自然之应也。子之云云，恐故得菖蒲葅耳。



