朝发太华，夕宿神州。弹琴咏诗，聊以忘忧。

其五
琴诗自乐，远游可珍。含道独往，弃智遗身。
寂乎无累，何求于人。长寄灵岳，怡志养神。

其六
流俗难悟，逐物不还。至人远鉴，归之自然。
万物为一，四海同宅。与彼共之，予何所惜。
生若浮寄，暂见忽终。世故纷纭，弃之八戎。
泽雉虽饥，不愿园林。安能服御，劳形苦心。
身贵名贱，荣辱何在。贵得肆志，纵心无悔。


【四言诗】

淡淡流水，沦胥而逝。泛泛柏舟，载浮载滞。
微啸清风，鼓楫容裔。放棹投竿，优游卒岁。


【五言诗三首】

其一
人生譬朝露，世变多百罗。苟必有终极，彭聃不足多。
仁义浇淳朴，前识丧道华。留弱丧自然，天真难可和。
郢人审匠石，钟子识伯牙。真人不屡存，高唱谁当和。

其二
修夜家无为，独步光庭侧。仰首看天衢，流光曜八极。
抚心悼季世，遥念大道逼。飘飘当路士，悠悠进自棘。
得失自己来，荣辱相蚕食。朱紫虽玄黄，太素贵无色。
渊淡体至道，色化同消息。

其三
俗人不可亲，松乔是可邻。何为秽浊间，动摇增垢尘。
慷慨之远游，整驾俟良辰。轻举翔区外，濯翼扶桑津。
徘徊戏灵岳，弹琴咏太真。沧水澡五藏，变化忽若神。
恒娥进妙药，毛羽翕光新。一纵发开阳，俯视当路人。
哀哉世间人，何足久托身。


【酒会诗】

乐哉苑中游，周览无穷已。百卉吐芳华，崇台邈高跱。
林木纷交错，玄池戏鲂鲤。轻丸毙翔禽，纤纶出鳣鲔。
坐中发美赞，异气同音轨。临川献清酤，微歌发皓齿。
素琴挥雅操，清声随风起。斯会岂不乐，恨无东野子。
酒中念幽人，守故弥终始。但当体七弦，寄心在知己。


【述志诗二首】

其一
潜龙育神躯，濯鳞戏兰池。延颈慕大庭，寝足俟皇羲。
庆云未垂景，盘桓朝阳陂。悠悠非吾匹，畴肯应俗宜。
殊类难遍周，鄙议纷流离。轗轲丁悔吝，雅志不得施。
耕耨感宁越，马席激张仪。逝将离群侣，杖策追洪崖。
焦股振六翮，罗者安所羁。浮游太清中，更求新相知。
比翼翔云汉，饮露餐琼枝。多念世间人，夙驾咸驱驰。
冲静得自然，荣华安足为。

其二
斥鷃擅蒿林，仰笑神凤飞。坎井蝤蛭宅，神龟安所归。
恨自用身拙，任意多永思。远实与世殊，义誉非所希。
往事既已谬，来者犹可追。何为人事间，自令心不夷。
慷慨思古人，梦想见容辉。愿与知己遇，舒愤启幽微。
岩穴多隐逸，轻举求吾师。晨登箕山巅，日夕不知饥。
玄居养营魄，千载长自绥。


