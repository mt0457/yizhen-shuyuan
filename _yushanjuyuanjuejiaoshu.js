人无志，非人也。但君子用心，所欲准行，自当量其善者，必拟议而后动。若志之所之，则口与心誓，守死无二。耻躬不逮，期于必济。若心疲体懈，或牵于外物，或累于内欲，不堪近患，不忍小情，则议于去就。议于去就，则二心交争。二心交争，则向所以见役之情胜矣。或有中道而废，或有不成一匮而败之。以之守则不固，以之攻则怯弱。与之誓则多违，与之谋则善泄。临乐则肆情，处逸则极意。故虽繁华熠耀，无结秀之勋；终年之勤，无一旦之功。斯君子所以叹息也。

若夫申胥之长吟，夷齐之全洁，展季之执信，苏武之守节，可谓固矣。故以无心守之，安而体之，若自然也，乃是守志之盛者也。

所居长吏，但宜敬之而已矣。不当极亲密，不宜数往来，往当有时。其有众人，又不当独在后，又不当前。所以然者，长吏喜问外事，或时发举，则恐为人所说，无以自免也。

夫言语，君子之机。机动物应，则是非之形著矣。故不可不慎。若于意不善，了而了之。非意所及者，而强为之说，则必有龃龉之失。人有相与争者，未知得失所在，慎勿预之也。

不须行小小束修之意气，若见穷乏而有可以赈济者，便见义而作。若人从我有所求，欲先自思省。若所济有伤于义，则辞以他故，不可与之。若其理不足，而强欲相求者，便当正色却之。

凡行事先当审其机宜，然后行之。其有不可，急遽而行者，犹当权其轻重，不可卒然为之也。

