易者，日月之象也。上日下月为易，阴阳相推而生变化。伏羲画八卦以通神明之德，文王重六十四卦以类万物之情，周公系爻辞以断吉凶，孔子赞十翼以阐微言。四圣相继，易道大明。

夫易，圣人之所以极深而研几也。唯深也，故能通天下之志；唯几也，故能成天下之务。易与天地准，故能弥纶天地之道。仰以观于天文，俯以察于地理，是故知幽明之故。原始反终，故知死生之说。精气为物，游魂为变，是故知鬼神之情状。

昔者圣人之作易也，将以顺性命之理。是以立天之道曰阴与阳，立地之道曰柔与刚，立人之道曰仁与义。兼三才而两之，故易六画而成卦。分阴分阳，迭用柔刚，故易六位而成章。

