（正末扮张飞，上，云）某姓张名飞，字翼德，涿州范阳人也。自从桃园结义，跟随大哥刘备、二哥关羽，破黄巾，讨董卓。今日十八路诸侯，会兵虎牢关。董卓义子吕布，骁勇无敌。某奉大哥将令，前去搦战。（唱）

