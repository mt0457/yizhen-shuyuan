【第一折】

（正旦扮樊素，上，诗云）寂寥深院日初长，花落莺啼春自伤。昨夜西风凋碧树，独上高楼望尽天涯路。妾身樊素娥。自从嫁给白敏中，琴瑟和谐。只是相公近日，常常出外游宴，妾身独守空闺，好不寂寞。（唱）

【仙吕·点绛唇】春日迟迟，花影重重。画堂东，柳絮蒙蒙。对景难排，这幽怨千种。

【混江龙】想当初，花前月下，他曾说，海誓山盟。到如今，酒阑歌罢，剩我个，冷清清。这的是，男儿心，如流水。女儿意，似山凝。可叹我，一片痴心，都付与，薄幸东风。

（白敏中上，云）夫人，小生回来了。（正旦做不理科）（白敏中云）夫人为何不睬小生？（正旦云）相公，你日日游宴，将妾身置于何地？（唱）

【天下乐】你那里，走马章台，醉眼迷。俺这里，独对菱花，泪暗滴。说什么，在天比翼，在地连理。到如今，都做了，东流水，一去不回。

（白敏中云）夫人息怒。小生知罪了。从今以后，再不出外游宴，只在书房读书，陪夫人闲话。（正旦云）此话当真？（白敏中云）当真。（正旦唱）

【寄生草】你若肯，转心意，回心肠。俺便也，展愁眉，舒笑眼。从今后，琴棋书画，共盘桓。再休提，章台走马，醉花间。

【第二折】

（正旦扮樊素，上，云）自从相公改过，果然日日在家读书。妾身心中欢喜。今日春光正好，且到后花园，赏花一回。（唱）

【中吕·粉蝶儿】则见那，桃红似火，柳绿如烟。一对对，粉蝶儿，穿花度叶。一双双，燕子在，画梁间，呢喃不歇。好一派，春光也！

【醉春风】俺这里，拈花枝，嗅花蕊，满袖香。步苍苔，过小桥，心意畅。若不是，相公他，回心转意，俺怎得，这般般，欢喜模样？

（白敏中上，云）夫人，你在花园中。小生特来陪伴。（正旦云）相公来了。你看这牡丹，开得正好。（白敏中云）果然国色天香。只是比起夫人，还差三分颜色。（正旦笑科，云）贫嘴！（唱）

【石榴花】说甚么，牡丹虽好，不及人娇。俺只是，蒲柳之姿，怎比花妖？但愿得，年年岁岁，花好人团圆。不负这，良辰美景，赏心乐事，艳阳天。

