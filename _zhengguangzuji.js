【第一折】

（正末扮伊尹，上，云）老汉伊尹是也。耕于有莘之野，以乐尧舜之道。非其义也，非其道也，禄之以天下，弗顾也；系马千驷，弗视也。今有商汤，遣使来聘。且看使者如何说。（唱）

【仙吕·点绛唇】耕田野，乐尧舜。藜藿饱，布衣温。虽然是，身在畎亩，志在经纶。待时来，展平生，济世安民。

（使臣上，云）奉商汤之命，聘伊尹先生为相。先生请了。汤王闻先生贤德，特遣小臣，备礼来聘。（伊尹云）老夫有何德能，敢劳汤王三聘？

【混江龙】他那里，三番两次，礼聘频频。俺这里，细思量，这的是，天降大任。想桀王，无道暴虐，民坠涂炭。汤王他，修德行政，吊民伐罪。俺今日，出山辅佐，也是那，顺天应人。

【第四折】

（正末扮伊尹，上，云）老夫自在商为相，辅佐汤王，伐桀救民。如今汤王，三分天下有其二。正要约会诸侯，共伐夏桀。（唱）

【双调·新水令】想当日，耕田野，抱膝长吟。到如今，佩相印，调鼎鼐。俺这里，辅明君，伐暴桀。这的是，顺天者昌，逆天者亡。眼见得，夏家天下，一旦休也。

（众诸侯上，云）愿从汤王伐桀！（汤王上，云）多谢诸公相助。伊相，传令进军！（伊尹云）得令！大小三军，兵发鸣条！（唱）

【收尾】则见那，旌旗蔽日，刀枪耀空。眼见得，鸣条一战，定雌雄。从今后，商汤六百载，基业崇。

