<p style="line-height:2.2;">
<b>【步罡感降】</b>三十二天感降法有配合之步罡法——步三十二天罡。此罡法以坛场中心为起点，先向东方踏出三步（象征东方八天之三数——三为木之生数），然后顺次向南方、西方、北方各依其数踏出相应步数。每一步口中诵一天帝之名号，心中观想该天帝在足下涌出光明托住行足。步完三十二天罡后，回到坛场中心，双手结“三十二天总印”——双手十指交叉，掌心向内，两大指并立向上（象征三十二天归于一元），然后静立片刻，感受三十二天之炁汇于一身。此步罡法须在师父指导下学习，不可仅凭文字自学——步罡之法，差之毫厘则失之千里，必须口传心授。
</p>

