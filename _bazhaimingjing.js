五问：办公室风水——比住宅风水重要吗？
答：住宅风水——为——根基——管——人生——总体——运势——与——健康——平安。办公室风水——为——枝叶——管——事业——发展——与——职场——关系。根——深——则——枝——繁——根基——不——牢——枝——叶——再——茂——盛——也是——暂时的——风——一吹——就——倒——了。故——两者——都——重要——而——住宅风水——更——根本——不可——为——事业——而——忽略——家庭——为——成功——而——牺牲——健康——此——本末倒置——得不偿失——也。

