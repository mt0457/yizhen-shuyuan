德器者，道德之容器也。有德无器，德无所载。有器无德，器为虚设。德器兼备，是为全人。

修道者，天之道也。德者，人之本也。器者，德之载也。观人之相，先观德器。德器深厚者，虽形貌平常，亦为大器。德器浅薄者，虽貌美形端，终非上品。

天庭饱满，地阁方圆，此器之厚也。眼光清澈，声音洪亮，此德之充也。器厚而德充者，必为大贵。天庭窄削，地阁尖薄，此器之薄也。眼光混浊，声音低哑，此德之亏也。器薄而德亏者，贫贱夭折。

何为德之征？目清而不昏，声洪而不哑，色润而不枯，气舒而不促，此四者德之见于外者也。何为器之征？天庭高广，地阁方圆，鼻直口方，颧骨有势，此四者器之见于外者也。德器相称者上，德胜器者次之，器胜德者又次之，德器两亏者下。

德器歌曰：

天高地厚德器真，日月光明照万春。
鼻直口方根基固，颧隆颌满福自臻。
目清声润心神足，气舒色正德器纯。
劝君莫羡潘安貌，德器深厚是贵人。

