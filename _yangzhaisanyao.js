一忌——门在绝命方——纳绝灭之气——主绝后灭族——此阳宅第一大忌。
二忌——灶在生气方——火泄旺气——主家运日衰——此阳宅第二大忌。
三忌——灶在宅中宫——火冲太极——主家人心脑血管与消化系统之疾。
四忌——主卧床在横梁下——横梁压顶——主失眠多梦神经衰弱。
五忌——大门对厕所——秽气冲门——主家运不洁名誉受损。
六忌——大门对楼梯向下——卷帘水泄气——主财运一落千丈。
七忌——大门对死巷——死气不通风——主诸事不顺前途渺茫。
八忌——主卧对房门——开门见床——主隐私不保心神不宁。
九忌——主卧对镜子——夜半惊魂——主噩梦连连精神萎靡。
十忌——灶与门直对——火气外泄——主财运不聚财来财去。
十一忌——灶与水槽紧邻——水火相激——主家庭不睦口舌争执。
十二忌——宅前有大树——树阴遮门——阳气不入阴盛阳衰。

