子平真诠论十神生克总纲。印生比劫，比劫生食伤，食伤生财，财生官杀，官杀生印——十神循环生。印克食伤，食伤克官杀，官杀克比劫，比劫克财，财克印——十神循环克。生则扶助，克则制约。生克得宜，格局清纯。生克失当，格局破败。用神宜生不宜克，忌神宜克不宜生。此十神生克之总纲，格局论命之根基。

