格局为正，神煞为辅。格局为主干，神煞为枝叶。主干已定，再以神煞点缀，不可本末倒置。

正官格逢天乙贵人：贵上加贵，官运亨通。若天乙又为相神（如天乙在印星），双贵临门。
七杀格逢将星：将帅之威，统御之才。杀格本武贵，将星更添威势。
