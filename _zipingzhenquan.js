子平真诠论地支六合。子丑合土寅亥合木卯戌合火辰酉合金巳申合水午未合日月。合则和也聚也。格局逢合：用神逢合——失其用（被合去）。忌神逢合——去其害（大吉）。日支逢合——配偶宫动。月支逢合——提纲变化。合化条件：得月令之气方化。合而不化则合绊。合之吉凶以格局喜忌为断。

