子平真诠论十神定位。正官为克我之异——上司、法律、夫星（女）。七杀为克我之同——竞争、压力、偏夫。正印为生我之异——母亲、学问、庇护。偏印为生我之同——特殊才能、宗教。正财为我克之异——稳定收入、妻子。偏财为我克之同——意外之财、父亲。食神为我生之同——口福、才艺、子星（女）。伤官为我生之异——才华、自由、叛逆。比肩为同我之同——兄弟、朋友。劫财为同我之异——姐妹、损友。十神定位，各有所主。格局由此而分，吉凶由此而判。

