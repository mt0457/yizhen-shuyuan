子平真诠论十神配六亲。正印为母，偏财为父。比肩兄弟劫财姐妹。正官为夫（女命），七杀偏夫。正财为妻（男命），偏财为妾。食神为子（女命），伤官为女。十神六亲各安其位。格局中某十神为喜得力——该亲有助有恩。某十神为忌肆虐——该亲有损有怨。大运扶喜神——该亲发达之年。大运扶忌神——该亲有灾之年。

