子平真诠论四时用神。春木旺——用神火泄木（食伤），金制木（官杀）。夏火旺——用神土泄火（食伤），水制火（官杀）。秋金旺——用神水泄金（食伤），火制金（官杀）。冬水旺——用神木泄水（食伤），土制水（官杀）。四季土旺——用神金泄土（食伤），木制土（官杀）。旺者宜泄宜制，弱者宜扶宜助。四时用神大法也。

