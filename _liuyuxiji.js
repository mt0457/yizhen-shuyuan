武夫何洸洸，衣紫袭绛裳。借问胡为尔，列校在鹰扬。依倚将军势，交结少年场。探丸害公吏，抽刃妒名倡。家产既不事，顾盼自生光。酣歌高楼上，袒裼大道傍。昔为编户人，秉未甘糠秕。今来从军乐，跃马饫膏粱。犹思风尘起，无种取侯王。

