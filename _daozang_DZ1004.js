<p style="font-size:16px;color:#8b1a1a;line-height:2.2;margin:0;">
<b>三元者，人身之三宝。守三元者，修道之根本。
上元守脑元神朗，中元守心丹元昌，下元守脐精命固。
三元各自守得牢，精炁神自凝一不散。
凝一不散即是丹，丹成九转即成仙。
守三元者守大道，守道不失终成道。
皈依道经师三宝。太上道君。福生无量天尊。</b>
</p>
