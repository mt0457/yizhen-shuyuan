<p style="font-size:16px;color:#8b1a1a;line-height:2.2;margin:0;">
<b>老君慈愍垂训真切，噎疾根源心急为最。细嚼慢咽化食为糜，三十六转金津玉液。
食不言寝不语三昧，调息静气通关开结。丹田深息次第九转，七息急救解噎秘诀。
食疗十二润养食道，导引三式舒展胸胁。十戒谨守防伤护功，五要修心化急为悦。
三时修持融入日用，诸法归一治心急耳。心平气和食自通彻。
愿天下噎疾者悉皆痊愈，饮食顺畅各得其乐，身心康健延年益寿，以食入道与道合德。
至心皈依道经师三宝。福生无量天尊。</b>
</p>
