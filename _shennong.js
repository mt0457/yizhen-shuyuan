神农本草经·药物归经引经举要

药物归经，创于张元素，成于李东垣，而为临床用药之纲领。归经者，药物作用于特定脏腑经络之谓也。桔梗、紫菀、款冬花入肺经而治咳喘；酸枣仁、柏子仁、远志入心经而安神志；白术、茯苓、山药入脾经而健运化；柴胡、香附、川芎入肝经而疏郁滞；杜仲、熟地黄、山茱萸入肾经而补精髓。一药可归数经，如石膏入肺胃二经，清肺胃之热；大黄入脾胃大肠肝心包五经，泻诸经之热结。引经药者，能引导他药直达病所之药也。太阳经用羌活、藁本；阳明经用升麻、葛根、白芷；少阳经用柴胡；太阴经用苍术；少阴经用独活；厥阴经用细辛、川芎。引经之妙，如舟楫载药，直达病所，事半功倍。此皆古人临床经验之精华，学者不可不知也。

