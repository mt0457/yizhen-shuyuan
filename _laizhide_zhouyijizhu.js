【集注】初柔得位。错家人初为闲有家——解初无咎者难初解，闲家者豫防。刚柔之际。

九二：田获三狐，得黄矢，贞吉。
【集注】二中正。错家人二为在中馈——获三狐者除邪去奸，中馈者主内。得中道也。

六三：负且乘，致寇至，贞吝。
【集注】三柔乘刚。错家人三为嗃嗃嘻嘻——负乘者位不当，嗃嗃者严整。致寇至自我致戎。

