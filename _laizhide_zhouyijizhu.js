遁，亨，小利贞。

【集注】艮下乾上，天下有山。山形高而天远，遁之象。错临——遁退临长。综大壮——遁退大壮进。中爻巽乾，巽入乾健。二阴浸长，阳当退避。小利贞者阴渐长。

初六：遁尾，厉，勿用有攸往。
