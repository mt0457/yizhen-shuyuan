【集注】五柔中居尊，乘四之刚。错小畜五为有孚挛如——贞疾者守正而若有疾，挛如者固结不解。中爻坎为疾。恒不死者守正则无大害。

上六：冥豫，成有渝，无咎。
【集注】上为豫极。错小畜上为既雨——冥豫者昏冥沉溺，既雨者畜极而通。中爻坎险在上。冥豫能变，则可无咎。

