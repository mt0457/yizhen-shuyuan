【集注】坤下震上，雷出地奋。雷出于地，万物奋起而皆悦豫。错小畜——豫悦与畜止，悦极则止。综谦——豫悦而谦卑。中爻艮坎，艮止坎险。豫悦之中有止险之道。利建侯行师者，动而顺也。

