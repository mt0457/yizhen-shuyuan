来知德（1525—1604），字矣鲜，号瞿塘，梁山（今重庆梁平）人。隐居求溪山中二十九年，覃思易学，著成此书。其注以象为主，每卦首列错卦、综卦，次析中爻，再次释卦爻辞。发明错卦（阴阳对错）、综卦（上下颠倒）、中爻（二至四、三至五互体）三法，于汉宋之外别开生面。万历年间诏授翰林待诏，辞不赴。学者称瞿塘先生。

其注易之法：一卦入手，先观其错卦为何卦，综卦为何卦，明其对待流行。次取中爻，观其所包涵之象。然后逐爻解之，每爻必先明象，由象以通辞，由辞以达意。象明则辞通，辞通则意显。此来氏二十九年来之独得之秘也。

