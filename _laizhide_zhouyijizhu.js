六五：帝乙归妹，以祉元吉。
【集注】五柔中居尊，下应九二。错否五为休否——归妹者柔下于刚，休否者大人吉。中爻兑为少女为妹，震为帝。帝乙归妹，以柔降尊，以祉元吉。阴阳和合之象。

上六：城复于隍，勿用师，自邑告命，贞吝。
【集注】泰极将否，城复于隍。错否上为倾否——城复者泰极崩毁，倾否者否终倾覆。中爻兑为口为告，震为声为命。城倾入隍，泰运将终。治乱循环，不可忽也。

