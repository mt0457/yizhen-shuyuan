睽，小事吉。

【集注】兑下离上，上火下泽。火炎上泽润下，交相违也。错蹇——睽乖与蹇难。综家人——家人合与睽乖。中爻离坎，既济之体。睽而能合小事吉。

初九：悔亡。丧马勿逐自复。见恶人无咎。
【集注】初无应。错蹇初为往蹇来誉——丧马自复者无求于外，往蹇来誉者待时。见恶人辟咎也。

九二：遇主于巷，无咎。
【集注】二遇五。错蹇二为王臣蹇蹇——遇主巷者非正途而遇，蹇蹇者尽心。未失道也。

六三：见舆曳，其牛掣，其人天且劓，无初有终。
【集注】三应上。错蹇三为往蹇来反——舆曳者见阻于四，牛掣者见阻于二。中爻坎为舆离为目。无初有终。

九四：睽孤，遇元夫，交孚，厉无咎。
【集注】四与初应。错蹇四为往蹇来连——睽孤遇元夫者同志相孚，来连者当位。交孚无咎。

六五：悔亡，厥宗噬肤，往何咎。
【集注】五柔中。错蹇五为大蹇朋来——噬肤者易合，大蹇者朋来。往有庆也。

上九：睽孤，见豕负涂，载鬼一车，先张之弧，后说之弧。匪寇婚媾。往遇雨则吉。
【集注】上为睽极。错蹇上为往蹇来硕——先张后说者疑释，来硕者志内。群疑亡也。

