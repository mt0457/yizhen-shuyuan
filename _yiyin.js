世应为夫妻之位。世应相生——两情相悦，天生一对。世应相克——性情难合。世应比和——平等相处，相敬如宾。

六合卦——婚事必然可成，婚后亦和美。六冲卦——婚事有变数，即使成婚亦恐不长久。

