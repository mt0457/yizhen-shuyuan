《太上洞玄灵宝天尊说禳喉痹经》，一卷，收入明《正统道藏》洞玄部本文类，编号第1393部。此经乃灵宝天尊（即太上道君）于赤明开图之初，在碧落天中观见下界众生为喉痹之疾所苦——咽喉闭塞、饮食不通、言语不出、痛楚难忍、甚则窒息而亡——悲悯众苦，特为宣说此禳解喉痹之无上法门。喉痹者，咽门闭塞不通之总称，涵盖喉风、喉痈、喉蛾、缠喉风、锁喉风、喉菌、喉瘖、喉痧等诸般咽喉重症。此经以“禳”为核心——禳者，以道力祈祷消解灾病也，不同于世俗纯用针药攻伐之法，而是从天地造化、因果承负、阴阳失调、邪毒侵扰等多个维度，综合运用诵经、持咒、书符、存思、服炁、饮符水、朝真礼斗、积德行善等道法，标本兼治、内外双修，以禳除喉痹之厄。经中备载灵宝天尊所传之四十九道祛喉灵符、七篇禳喉秘咒、十二种除痹药方（皆以道家炼丹之法配合世药）、五季喉痹预防之要（春防风热喉痹、夏防暑毒喉痹、长夏防湿热喉痹、秋防燥火喉痹、冬防寒郁喉痹），以及针对不同病因——风热上攻、心火上炎、肺胃积热、痰火郁结、虚火上浮、疫毒侵喉、气滞血瘀、梅核气（痰气交阻）——之八大门径分别治法。此经亦详述喉痹与因果之关系：世间喉痹之病，其深层次根源多与口业有关——恶口骂詈、两舌挑拨、妄语欺诳、绮语惑人、谤毁大道——口造诸业，报应在喉。故除疾必先忏悔口业，此为治本之道。经末详列受持此经之十大功德利益——疾除痛止、喉门通利、声音清亮、饮食安和、口业消除、善缘广结、百邪不侵、福德增长、延年益寿、终证道果。千百年来，此经灵验事迹不绝于道门记载——自唐代孙思邈真人将经中部分药方辑入《千金要方》，至宋代道藏编修时将其正式收录，至明清民间每逢喉疫流行即开坛诵此经以禳灾，其祛喉疾、保咽喉之功效为历代医家道士所共同推崇。灵宝天尊以无量慈悲，于此经中开示：咽喉乃人身之“十二重楼”，为饮食呼吸之要道，亦为心语神识出纳之门户，咽喉通则百脉安和，咽喉塞则性命堪忧，故护咽喉即是护性命之本。此经融道教医学、符箓咒术、因果教义、养生预防于一体，为道藏中专门针对单一病种——喉痹——之最为系统完善之禳解经典，诚为咽喉疾病患者之无上法宝、医家道士之珍贵参考。
