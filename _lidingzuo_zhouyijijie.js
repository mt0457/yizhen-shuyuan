【昔者圣人之作易也，幽赞于神明而生蓍。】

【集解】虞翻曰：幽，深也。赞，助也。圣人深助于神明，而生蓍草为占筮之用。

【参天两地而倚数。】

【集解】虞翻曰：参天者，天一天三天五，三位之合为九。两地者，地二地四，二位之合为六。九六者，老阳老阴之数，为易之根本。

【观变于阴阳而立卦，发挥于刚柔而生爻。】

【集解】虞翻曰：观阴阳之变，以立八卦。发挥于刚柔之中，以生三百八十四爻。

【和顺于道德而理于义，穷理尽性以至于命。】

【集解】虞翻曰：和顺道德而调理于义。穷极物理，尽达本性，以至于天命。此易道之终极。

【昔者圣人之作易也，将以顺性命之理。是以立天之道曰阴与阳，立地之道曰柔与刚，立人之道曰仁与义。】

【集解】虞翻曰：阴阳者天道，柔刚者地道，仁义者人道。三才各二，故六位以成卦。

【兼三才而两之，故易六画而成卦。分阴分阳，迭用柔刚，故易六位而成章。】

【集解】虞翻曰：兼天地人三才而各以两画象之，故六画成一卦。阴阳分位，柔刚迭用，六位相杂而成文采。

【天地定位，山泽通气，雷风相薄，水火不相射，八卦相错。】

【集解】虞翻曰：乾坤定位于上下，艮兑通气于山泽，震巽相薄于雷风，坎离不相射害于水火。八卦交错为六十四卦。此先天八卦方位。

【数往者顺，知来者逆，是故易逆数也。】

【集解】虞翻曰：数往者自一而二，顺也。知来者自二而一，逆也。易以知来为主，故曰逆数。

【雷以动之，风以散之，雨以润之，日以烜之，艮以止之，兑以说之，乾以君之，坤以藏之。】

【集解】虞翻曰：震雷动万物，巽风散万物，坎雨润万物，离日烜万物，艮山止万物，兑泽说万物，乾天以君临万物，坤地以包藏万物。八卦各司其功。

【帝出乎震，齐乎巽，相见乎离，致役乎坤，说言乎兑，战乎乾，劳乎坎，成言乎艮。】

【集解】虞翻曰：此后天八卦方位。帝者，天之主宰。出乎震者，万物始出，震东方，春也。齐乎巽者，巽东南，春夏之交，万物齐洁。相见乎离者，离南方，夏也，万物相见。致役乎坤者，坤西南，夏秋之交，万物致养。说言乎兑者，兑西方，秋也，万物成熟而说。战乎乾者，乾西北，秋冬之交，阴阳相搏。劳乎坎者，坎北方，冬也，万物劳倦归藏。成言乎艮者，艮东北，冬春之交，万物终始。

【万物出乎震，震东方也。齐乎巽，巽东南也。离也者，明也，万物皆相见，南方之卦也。坤也者，地也，万物皆致养焉。兑，正秋也，万物之所说也。战乎乾，乾西北之卦也。坎者水也，正北方之卦也。艮，东北之卦也，万物之所成终而所成始也。】

【集解】虞翻曰：此言后天八卦方位与四时万物的关系。震东春，巽东南，离南夏，坤西南，兑西秋，乾西北，坎北冬，艮东北。四时八节，万物生长收藏，皆循此序。

【神也者，妙万物而为言者也。】

【集解】虞翻曰：神者，妙也。阴阳不测之谓神。八卦之功用，微妙难测，化育万物。

【动万物者莫疾乎雷，挠万物者莫疾乎风，燥万物者莫熯乎火，说万物者莫说乎泽，润万物者莫润乎水，终万物始万物者莫盛乎艮。】

【集解】虞翻曰：震雷以动万物，巽风以挠万物，离火以燥万物，兑泽以说万物，坎水以润万物，艮山以终始万物。八卦各以其德用作用于万物。

【故水火相逮，雷风不相悖，山泽通气，然后能变化既成万物也。】

【集解】虞翻曰：八卦虽各司其功，而又互相配合。水火相及，雷风不相悖逆，山泽通其气息。八卦相错，变化以成万物。

【乾为天，为圜，为君，为父，为玉，为金，为寒，为冰，为大赤，为良马，为老马，为瘠马，为驳马，为木果。】

【集解】虞翻曰：乾为天，天体圜。天者君之象，故为君；父者家之君，故为父。其德刚，故为玉为金。居西北，故为寒为冰。大赤盛阳之色。健而善走，故为良马老马瘠马驳马。天圆而实，故为木果。

【坤为地，为母，为布，为釜，为吝啬，为均，为子母牛，为大舆，为文，为众，为柄，为黑。】

【集解】虞翻曰：坤为地，万物之母。布者，地之所出。釜者，化生成熟。吝啬者，地静而藏。均者，地无私载。子母牛者，地之生育。大舆者，地之载物。文者，地之万物文采。众者，地载万物之多。柄者，万物之根本。黑者，极阴之色。

【震为雷，为龙，为玄黄，为旉，为大涂，为长子，为决躁，为苍筤竹，为萑苇。其于马也，为善鸣，为馵足，为作足，为的颡。其于稼也，为反生。其究为健，为蕃鲜。】

【集解】虞翻曰：震为雷，龙以雷兴。玄黄者，天地之杂色。旉者，花叶之布。大涂者，大道。长子者，一索得男。决躁者，动而刚决。苍筤竹萑苇，皆青色之物。善鸣馵足作足的颡者，皆马之象。反生者，稼禾倒生。蕃鲜者，繁茂鲜明。

【巽为木，为风，为长女，为绳直，为工，为白，为长，为高，为进退，为不果，为臭。其于人也，为寡发，为广颡，为多白眼，为近利市三倍。其究为躁卦。】

【集解】虞翻曰：巽为木，木随风。长女者，一索得女。绳直者，木直可以准绳。工者，曲直成器。白者，风色白。长者，风行远。高者，木上耸。进退不果者，风性犹豫。臭者，风传气。寡发广颡多白眼近利市三倍者，皆巽之人象。躁者，风性急。

【坎为水，为沟渎，为隐伏，为矫輮，为弓轮。其于人也，为加忧，为心病，为耳痛，为血卦，为赤。其于马也，为美脊，为亟心，为下首，为薄蹄，为曳。其于舆也，为多眚。为通，为月，为盗。其于木也，为坚多心。】

【集解】虞翻曰：坎为水，沟渎隐伏皆水之象。矫輮使直为曲，弓轮弯曲，皆坎之形。加忧心病耳痛血卦赤，皆坎险之象。美脊亟心下首薄蹄曳，皆马在坎之象。多眚者，舆多灾眚。通者，水流通。月者，水之精。盗者，水潜行如盗。坚多心者，水浸木坚而多心。

【离为火，为日，为电，为中女，为甲胄，为戈兵。其于人也，为大腹。为乾卦，为鳖，为蟹，为蠃，为蚌，为龟。其于木也，为科上槁。】

【集解】虞翻曰：离为火，日、电皆火之精。中女者，再索得女。甲胄戈兵者，刚在外。大腹者，中虚外实。乾卦者，火性燥。鳖蟹蠃蚌龟，皆外刚内柔、离之象。科上槁者，木中空而上枯。

【艮为山，为径路，为小石，为门阙，为果蓏，为阍寺，为指，为狗，为鼠，为黔喙之属。其于木也，为坚多节。】

【集解】虞翻曰：艮为山，径路小石皆山之物。门阙者，止出入。果蓏者，止于地。阍寺者，守门之官。指者，手之止。狗鼠黔喙，皆山之兽。坚多节者，山木坚韧而多节。

【兑为泽，为少女，为巫，为口舌，为毁折，为附决。其于地也，为刚卤。为妾，为羊。】

【集解】虞翻曰：兑为泽，少女者，三索得女。巫者，以口舌通神明。口舌毁折附决，皆兑之象。刚卤者，泽水所浸，地为盐卤。妾者，少女之卑。羊者，外柔内刚。

