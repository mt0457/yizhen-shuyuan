玉皇心印之法，不假外求，唯在方寸之中——人心若能与玉皇真心相印，则顷刻之间超凡入圣。
此法被誉为“玉皇之密藏、修道之捷径、超证之慈航”，道门中虽有诸经万卷，然论及心法之直接、功效之神速，以此《心印妙经》为第一。
