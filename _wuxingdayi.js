	【第一】释五行名

	夫万物自有体质，圣人象类而制其名。故曰：名以定体。无名乃天地之始，有名则万物之母。以其因功涉用，故立称谓。《礼》云：子生三月，咳而名之。及其未生，本无名字。五行为万物之先，形用资于造化，岂不先立其名，然后明其体用？

	《春秋元命苞》曰：木者，触也。触地而生。许慎曰：木者，冒也。言冒地而出。字从于屮，下象其根。其时春，其日甲乙。《乐纬》曰：木之为言，触也。阳气触动，冒地而生也。《春秋元命苞》又曰：木之为言，触也。气触动也。

	《白虎通》云：火之为言，化也。阳气用事，万物变化也。许慎曰：火者，炎上也。其字炎而上，象形者也。其时夏，其日丙丁。火之为言，委随也，言万物布施。火之为言，化也，随也，阳气用事，万物变化随也。

	《春秋元命苞》曰：土之为言，吐也。含吐气精，以生于物。许慎曰：土者，吐生者也。王肃曰：土者，地之别号，以为五行也。许慎曰：其字二，以象地之下，与地之中，以一一直画，象物初出地也。其时季夏，其日戊己。土之为言，吐也，吐生万物也。

	《春秋元命苞》曰：金之为言，禁也。禁万物使不妄动也。许慎曰：金者，禁也。阴气始起，万物禁止也。生于土，字从土，左右注，象金在土中之形也。其时秋，其日庚辛。金在西方，万物既成，杀气之始也。

	《春秋元命苞》曰：水之为言，准也。阴化淖濡，流施潜行也。许慎曰：水者，准也。平准万物。故立字，二水并肩，中一直，象水之流动也。其时冬，其日壬癸。水之为言，演也，阴化淖濡，流施潜行也。

	《尚书·洪范》箕子对武王曰：五行：一曰水，二曰火，三曰木，四曰金，五曰土。水曰润下，火曰炎上，木曰曲直，金曰从革，土爰稼穑。润下作咸，炎上作苦，曲直作酸，从革作辛，稼穑作甘。此五行命名之原典，后世言五行者莫不宗之。

	【第二】论支干

	干支者，因五行而立之。昔轩辕之时，大挠之所制也。蔡邕《月令章句》云：大挠采五行之情，占斗机所建也。始作甲乙以名日，谓之干；作子丑以名月，谓之支。有事于天则用日，有事于地则用辰。阴阳之别，故有干支名也。

	支干之义，多所配合。《史记·律书》曰：甲者，言万物剖符甲而出也。乙者，言万物生轧轧也。丙者，言阳道著明，故曰丙。丁者，言万物之丁壮也，故曰丁。庚者，言阴气庚万物，故曰庚。辛者，言万物之辛生，故曰辛。壬者，任也，言阳气任养万物于下也。癸者，揆也，言万物可揆度，故曰癸。

	《汉书·律历志》云：出甲于甲，奋轧于乙，明炳于丙，大盛于丁，丰楙于戊，理纪于己，敛更于庚，悉新于辛，怀任于壬，陈揆于癸。此十天干名义之大略也。

	十二地支：《史记·律书》云：子者，滋也。滋者，言万物滋于下也。丑者，纽也。言阳气在上未降，万物厄纽未敢出也。寅者，言万物始生螾然也，故曰寅。卯之为言，茂也，言万物茂也。辰者，言万物之蜄也。巳者，言阳气之已尽也。午者，阴阳交，故曰午。未者，言万物皆成，有滋味也。申者，言阴用事，申贼万物，故曰申。酉者，万物之老也，故曰酉。戌者，言万物尽灭，故曰戌。亥者，该也，言阳气藏于下，故该也。

	此干支名义，皆以万物生长收藏之象取义，而五行之气行乎其间，阴阳消长，莫不寓焉。

	【第三】论支干配合五行

	天干配五行：甲乙寅卯为木，位在东方。丙丁巳午为火，位在南方。戊己辰戌丑未为土，位在中央，分王四季，寄治四维。庚辛申酉为金，位在西方。壬癸亥子为水，位在北方。

	甲为阳木，乙为阴木。丙为阳火，丁为阴火。戊为阳土，己为阴土。庚为阳金，辛为阴金。壬为阳水，癸为阴水。此天干之阴阳配五行也。

	地支：寅卯为木，寅为阳木，卯为阴木。巳午为火，巳为阳火，午为阴火。申酉为金，申为阳金，酉为阴金。亥子为水，亥为阳水，子为阴水。辰戌丑未为土，辰戌为阳土，丑未为阴土。

	凡五行有阴阳之别，有刚柔之分。阳者刚健，阴者柔顺。木之阳者，松柏之类；木之阴者，杨柳之类。火之阳者，太阳之火；火之阴者，灯烛之火。土之阳者，山岳之土；土之阴者，田园之土。金之阳者，刀斧之金；金之阴者，钗钏之金。水之阳者，江海之水；水之阴者，雨露之水。此阴阳五行之大别也。

	《白虎通》曰：五行之性，或上或下何？火者，阳也，尊，故上。水者，阴也，卑，故下。木者，少阳也，故次水。金者，少阴也，故次火。土者，最大，苞含万物，将生者出，将归者入，不嫌清浊为万物母。

	【第四】论纳音

	纳音者，谓干支合而为音也。子属坎，丑属艮，寅属艮，卯属震，辰属巽，巳属巽，午属离，未属坤，申属坤，酉属兑，戌属乾，亥属乾。八卦之位，各有所属。干支合之，各成其音。

	甲子乙丑金者，子属坎水，其数一；丑属艮土，其数五；甲数九，乙数八，子数九，丑数八，凡四十有三。以五除之，余三，故属金。凡纳音之数，皆以干支之数合计而取其余，视其余为何，即为何音。此纳音之大法也。

