	【第九】论配五色

	《左氏传》子产曰：天地之经，而民实则之。则天之明，因地之性，生其六气，用其五行。气为五味，发为五色，章为五声。淫则昏乱，民失其性。是故为礼以奉之。为六畜、五牲、三牺，以奉五味；为九文、六采、五章，以奉五色；为九歌、八风、七音、六律，以奉五声。

	木色青，东方之色也。象草木之青翠。火色赤，南方之色也。象火焰之赤烈。土色黄，中央之色也。象大地之黄土。金色白，西方之色也。象金属之白洁。水色黑，北方之色也。象深渊之玄黑。

	《考工记》曰：东方谓之青，南方谓之赤，西方谓之白，北方谓之黑，天谓之玄，地谓之黄。青与白相次也，赤与黑相次也，玄与黄相次也。青与赤谓之文，赤与白谓之章，白与黑谓之黼，黑与青谓之黻，五采备谓之绣。

	五色之正者，青赤黄白黑是也。五色之间有间色：青黄之间为绿，赤白之间为红，黄黑之间为骍，白青之间为碧，黑赤之间为紫。此所谓五行相克而生间色也。青克黄而生绿，赤克白而生红，黄克黑而生骍，白克青而生碧，黑克赤而生紫。五行之运，无往而不在，即颜色亦不能外也。

	五色配五行，在命名学中寓意深远。如命主木不足者，可取青绿色系寓意之字——碧、翠、绿、苍、青、葱、蔚。火不足者，可取赤红色系寓意之字——丹、彤、赤、红、绛、赫、朱。土不足者，可取黄色系寓意之字——黄、缃、黈。金不足者，可取白色系寓意之字——白、素、皓、皎、皑。水不足者，可取黑色系寓意之字——玄、墨、黛、黝。此五色命名之大法也。

	【第十】论配五音

	《乐记》曰：凡音之起，由人心生也。人心之动，物使之然也。感于物而动，故形于声。声相应，故生变。变成方，谓之音。比音而乐之，及干戚羽旄，谓之乐。乐者，音之所由生也，其本在人心之感于物也。

	《律历志》云：五声者，宫商角徵羽也。所以经纬天地，错综人声。宫为君，商为臣，角为民，徵为事，羽为物。五者不乱，则无惉懘之音矣。

	宫音配土，其数八十一，声重而尊，为君之象。其声弘大，从容和平。商音配金，其数七十二，声明而敏，为臣之象。其声铿锵，廉直劲正。角音配木，其数六十四，声条而畅，为民之象。其声圆长，通澈中正。徵音配火，其数五十四，声疾而清，为事之象。其声抑扬，递续分明。羽音配水，其数四十八，声沈而细，为物之象。其声掩抑，深邃悠远。

	宫声感人而和气应，商声感人而义气应，角声感人而仁气应，徵声感人而礼气应，羽声感人而智气应。五音之感人，各以其类应也。故名学中，字音之五行，以宫商角徵羽为准，以求与命主五行相谐也。

	字音五行之大法：凡字之发音属喉音者多为宫（土），属齿音者多为商（金），属牙音者多为角（木），属舌音者多为徵（火），属唇音者多为羽（水）。取名时不仅看字形之五行，更要审字音之五行。音韵和谐、五行相生之名为上乘佳名。

	【第十一】论配五味

	《尚书·洪范》曰：润下作咸，炎上作苦，曲直作酸，从革作辛，稼穑作甘。此五行配五味之大纲也。

	水润下，味咸。咸者，所以坚筋骨也。凡海味、咸物皆属水。火炎上，味苦。苦者，所以长精神也。凡焦苦之物皆属火。木曲直，味酸。酸者，所以收涩也。凡果实未熟之时皆酸，属木。金从革，味辛。辛者，所以发散也。凡辛辣之物皆属金。土稼穑，味甘。甘者，所以和中也。凡甘甜之物皆属土。

	五味入五藏：酸入肝，苦入心，甘入脾，辛入肺，咸入肾。五味调和，则五藏安和；五味偏胜，则五藏受病。此养生之本，医道之源，亦命名之参考也——取名可以五味调补五行之不足。

	《黄帝内经·素问》曰：五味所入：酸入肝，辛入肺，苦入心，咸入肾，甘入脾。又曰：五味所禁：辛走气，气病无多食辛；咸走血，血病无多食咸；苦走骨，骨病无多食苦；甘走肉，肉病无多食甘；酸走筋，筋病无多食酸。是谓五禁，无令多食。此饮食养生之要道，亦五行命名之旁参也。

	【第十二】论配五常

	《易》曰：立人之道，曰仁与义。五常之道，配于五行。

	木为仁。仁者，好生爱物，如春木之长养万物也。仁者，人也，亲亲为大。恻隐之心，仁之端也。火为礼。礼者，文明章美，如火之光明照耀也。礼者，履也，所以事神致福也。辞让之心，礼之端也。土为信。信者，诚实无欺，如土之厚重不移也。信者，诚也，言必由衷也。金为义。义者，刚断制裁，如金之锋利决断也。义者，宜也，断决得中也。羞恶之心，义之端也。水为智。智者，深虑通微，如水之深远周流也。智者，知也，是非之心，智之端也。

	五常之德，各本五行之气。仁者，木德也。礼者，火德也。信者，土德也。义者，金德也。智者，水德也。五常备则人伦立，五行和则天地平。人秉五行之气以生，五常之德即随之而具。然气有偏全，故德有厚薄。取名之时，可参酌五常之义，使名与德相配，补其不足而损其有余。

	【第十三】论配五藏

	《黄帝内经》曰：天有四时五行，以生长收藏，以生寒暑燥湿风。人有五藏化五气，以生喜怒悲忧恐。

	肝属木，主筋，其华在爪，开窍于目。肝藏魂，在志为怒。肝气和则目能辨五色。心属火，主血脉，其华在面，开窍于舌。心藏神，在志为喜。心气和则舌能知五味。脾属土，主肌肉，其华在唇，开窍于口。脾藏意，在志为思。脾气和则口能知五谷。肺属金，主皮毛，其华在毛，开窍于鼻。肺藏魄，在志为忧。肺气和则鼻能知臭香。肾属水，主骨髓，其华在发，开窍于耳。肾藏志，在志为恐。肾气和则耳能闻五音。

	五藏之间又有生克关系：肝木生心火，心火生脾土，脾土生肺金，肺金生肾水，肾水生肝木。此为五藏相生之序。肝木克脾土，心火克肺金，脾土克肾水，肺金克肝木，肾水克心火。此为五藏相克之序。五藏生克平衡则体健无病，失衡则疾生焉。

	五藏配五行，为中医之本，亦为命名之参考。如命主肝木不足者，可取名以水行之字（水生木）；心火不足者，可取名以木行之字（木生火）。命名之五行调补法，正本于此也。又名字之音韵不可与命主五藏之忌音相冲，当求和谐调畅。

	【第十四】论五事

	《尚书·洪范》曰：五事：一曰貌，二曰言，三曰视，四曰听，五曰思。貌曰恭，言曰从，视曰明，听曰聪，思曰睿。恭作肃，从作乂，明作哲，聪作谋，睿作圣。

	貌属木，木主貌，貌贵恭。貌之不恭，是谓不肃。言属金，金主言，言贵从。言之不从，是谓不乂。视属火，火主视，视贵明。视之不明，是谓不哲。听属水，水主听，听贵聪。听之不聪，是谓不谋。思属土，土主思，思贵睿。思之不睿，是谓不圣。

	五事配五行，各以类从。貌取其威仪如木之挺秀，言取其果断如金之铿锵，视取其光明如火之照耀，听取其深远如水之周流，思取其厚重如土之凝定。五事修则德行备，五行和则灾异消。

