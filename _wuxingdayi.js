	隔八生子者，律吕相生之道也。黄钟九寸，隔八生林钟；林钟六寸，隔八生太簇；太簇八寸，隔八生南吕；南吕五寸三分，隔八生姑洗；姑洗七寸一分，隔八生应钟；应钟四寸七分，隔八生蕤宾；蕤宾六寸三分，隔八生大吕；大吕八寸四分，隔八生夷则；夷则五寸六分，隔八生夹钟；夹钟七寸五分，隔八生无射；无射五寸，隔八生仲吕；仲吕六寸六分，隔八复生黄钟。所谓律娶妻而吕生子，阴阳升降，配合之义也。

	纳音之法，以干支之数定五行之所属。每一组干支合而取其余数，余一为水，余二为火，余三为木，余四为金，余五为土。此即纳音五行之定法也。纳音五行与正五行不同，正五行以天干地支各配五行，纳音则以干支合而配之。纳音为阴阳之深理，非浅学者所能窥也。在命理取名中，纳音五行可作为命主五行属性之重要参考，与正五行配合使用，相得益彰。

