	【第五】论五行相生

	五行者，所以通天地之变，类万物之情者也。其相生也，各有序次。

	《白虎通》曰：五行所以相生者，天地之性，众胜寡，故水胜火也。精胜坚，故火胜金。刚胜柔，故金胜木。专胜散，故木胜土。实胜虚，故土胜水也。

	《春秋繁露》云：天地之气，合而为一，分为阴阳，判为四时，列为五行。行者，行也。其行不同，故谓之五行。行者，言其为天行之气也。董仲舒曰：五行之随，各如其序；五行之官，各致其能。是故木居东方而主春气，火居南方而主夏气，金居西方而主秋气，水居北方而主冬气，土居中央而主四时之气。是故木主生而金主杀，火主暑而水主寒。使人必以其序，官人必以其能，天之数也。

	木生火者，木性温暖，火伏其中，钻灼而出，故木生火。
	火生土者，火热故能焚木，木焚而成灰，灰即土也，故火生土。
	土生金者，金居石依山，津润而生，聚土成山，山必生石，故土生金。
	金生水者，少阴之气，润泽流津，销金亦为水，故金生水。
	水生木者，因水润而能生，故水生木。

	《元命苞》曰：木生火者，木性温暖，火伏其中，钻之而出。火生土者，火能焚木，木焚而成灰土。土生金者，金依土而生。金生水者，金冷则凝，遇热则流。水生木者，木得水则荣。此五行相生之义也。

	五行相生，乃天地之常道。譬如母子相生，循环无穷。生我者为父母，我生者为子孙。生而不已，万物化醇；克而不已，万物消亡。故圣人制礼作乐，法于阴阳，和于术数，皆以五行之生克为之本也。相生之中又有生之太过与生之不及之辨。生之太过者，如木多火炽，母旺子实，虽生而反晦；生之不及者，如木少火微，母衰子弱，虽有若无。取名调候，不可不察。

	【第六】论五行相克

	《白虎通》云：五行所以相害者，天地之性。众胜寡，故水胜火也。精胜坚，故火胜金。刚胜柔，故金胜木。专胜散，故木胜土。实胜虚，故土胜水也。此五行相克之大义也。

	木克土：木能入土，根深蒂固。木专而土散，故木胜土。然土厚而木弱者，木不能克土，反为土所困。
	土克水：土能壅水，堤防以制。土实而水虚，故土胜水。然水大而土少者，土不能克水，反为水所冲。
	水克火：水能灭火，众寡之势。水众而火寡，故水胜火。然火烈而水微者，水不能克火，反为火所灼。
	火克金：火能铄金，精坚之别。火精而金坚，故火胜金。然金多而火少者，火不能克金，反为金所冷。
	金克木：金能断木，刚柔之分。金刚而木柔，故金胜木。然木坚而金钝者，金不能克木，反为木所折。

	夫克者，制也。制则不能过，过则为灾。故《尚书》云：水曰润下，火曰炎上，木曰曲直，金曰从革，土爰稼穑。润下作咸，炎上作苦，曲直作酸，从革作辛，稼穑作甘。此五行之性，各有所胜，胜而不已，则反受其害矣。

	相生相克，互为体用。有生无克，则过盛而为害；有克无生，则衰耗而灭亡。惟生克得宜，五行始能平衡运行。此天地自然之理也。正如《素问》所云：亢则害，承乃制，制则生化。五行之理，尽于此矣。

	【第七】论五行相杂

	凡五行之气，非纯一而不变。木中有火，火中有土，土中有金，金中有水，水中有木。犹人五藏，肝中有心气，心中有脾气，脾中有肺气，肺中有肾气，肾中有肝气。五气周流，互相含孕，此五行相杂之义也。

	五行之杂，各有所主。春木王，而其气中含火、土、金、水，特以木为主耳。夏火王，而其气中含土、金、水、木，特以火为主耳。秋金王，而其气中含水、木、火、土，特以金为主耳。冬水王，而其气中含木、火、土、金，特以水为主耳。四季土王，而其气中含金、水、木、火，特以土为主耳。此乃五行相杂之精义，不可不知也。

	又如方位之五行相杂：东方木位，而其地亦有金石水土；南方火位，而其地亦有木石水土；西方金位，而其地亦有水木火土；北方水位，而其地亦有木火土金；中央土位，而其地亦有金木水火。五行之气，周流六虚，无有间隙。

	【第八】论五行体性

	木者，少阳之精也。其性仁，其情和，其味酸，其色青。木形之人，长而瘦，多才艺，劳心少力，多忧劳于事。木气太过者，好高骛远，优柔寡断；木气不及者，懦弱畏缩，无有主见。

	火者，太阳之精也。其性礼，其情恭，其味苦，其色赤。火形之人，上尖下阔，多明理，好华饰，少信多虑。火气太过者，急躁狂暴，燎原焚林；火气不及者，萎靡不振，畏寒怕冷。

	土者，中和之气也。其性信，其情厚，其味甘，其色黄。土形之人，圆面大耳，多敦厚，好利人，不喜权势，善附人也。土气太过者，板滞愚钝，不知变通；土气不及者，浮华无根，随波逐流。

	金者，少阴之精也。其性义，其情烈，其味辛，其色白。金形之人，方面白色，小头曲肩，多刚毅，好为吏，刻薄寡恩。金气太过者，残酷无情，刚愎自用；金气不及者，优柔怯懦，任人宰割。

	水者，太阴之精也。其性智，其情深，其味咸，其色黑。水形之人，大头不平，曲面广颐，多智谋，好欺诈，无所不纳。水气太过者，阴险狡诈，泛滥无归；水气不及者，愚钝浅薄，枯竭无力。

	此五行体性之大略也。人之生也，各以类应。善相者，察其形色而知其五行之禀赋焉。

