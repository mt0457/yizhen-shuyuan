	【第十五】论律吕

	律吕者，天地阴阳之声也。阳气之动而为律，阴气之静而为吕。律以统气，吕以和声。律有十二，阳六为律，阴六为吕。

	黄钟、太簇、姑洗、蕤宾、夷则、无射，此六者阳律也。大吕、夹钟、仲吕、林钟、南吕、应钟，此六者阴吕也。

	律吕配五行：黄钟属土，太簇属金，姑洗属木，蕤宾属火，夷则属金，无射属木。大吕属土，夹钟属火，仲吕属水，林钟属土，南吕属金，应钟属水。

	律吕之生，始于黄钟。黄钟之管，长九寸，径三分，围九分。三分损一，下生林钟；林钟三分益一，上生太簇；太簇三分损一，下生南吕；南吕三分益一，上生姑洗；姑洗三分损一，下生应钟；应钟三分益一，上生蕤宾；蕤宾三分损一，下生大吕；大吕三分益一，上生夷则；夷则三分损一，下生夹钟；夹钟三分益一，上生无射；无射三分损一，下生仲吕；仲吕三分益一，上生黄钟。此三分损益以生十二律吕之法，亦五行相生之理寓于其中也。

	《乐纬》曰：黄钟为宫，林钟为徵，太簇为商，南吕为羽，姑洗为角，应钟为变宫，蕤宾为变徵。此五音配十二律之法，亦五行配属之延伸。

	【第十六】论八卦八风

	《易》有八卦，以通神明之德，以类万物之情。八卦配五行，各有其属。

	震为雷，东方也，属木。其风曰滔风，万物之所出也。巽为风，东南也，属木。其风曰熏风，万物之所齐也。离为火，南方也，属火。其风曰巨风，万物之所见也。坤为地，西南也，属土。其风曰凉风，万物之所致养也。兑为泽，西方也，属金。其风曰飂风，万物之所说也。乾为天，西北也，属金。其风曰厉风，万物之所终也。坎为水，北方也，属水。其风曰寒风，万物之所归也。艮为山，东北也，属土。其风曰炎风，万物之所成终而成始也。

	八风者，八方之风也。风者，天之号令，五行之气所发也。八风各以五行所属，其至也各有其时，其应也各以其类。圣人观八风之变，以知吉凶祸福。

	《易纬》曰：冬至四十五日条风至，条风至四十五日明庶风至，明庶风至四十五日清明风至，清明风至四十五日景风至，景风至四十五日凉风至，凉风至四十五日阊阖风至，阊阖风至四十五日不周风至，不周风至四十五日广莫风至。条风者，立春之候，其风属木；明庶风者，春分之候，属木；清明风者，立夏之候，属火；景风者，夏至之候，属火；凉风者，立秋之候，属金；阊阖风者，秋分之候，属金；不周风者，立冬之候，属水；广莫风者，冬至之候，属水。八风之来，各以时令，顺则为祥，逆则为灾。

	【第十七】论七政

	七政者，日月五星也。五星者，岁星（木星）、荧惑（火星）、镇星（土星）、太白（金星）、辰星（水星）也。日月五星，运行于天，各有其道，各有其德，而五行之气，实主宰之。

	岁星属木，其色青，其时应春，其德为仁。岁星十二年一周天。其行顺则为福，逆则为灾。荧惑属火，其色赤，其时应夏，其德为礼。荧惑二年一周天。其行疾则为乱，徐则为治。镇星属土，其色黄，其时应季夏，其德为信。镇星二十八年一周天。其居宿久则为福厚，速则为福薄。太白属金，其色白，其时应秋，其德为义。太白一年一周天。其出西方为太白，出东方为启明。辰星属水，其色黑，其时应冬，其德为智。辰星一年一周天。其出有时，见则为祥，匿则为灾。

	五星之行，各有迟速顺逆。其行顺则为吉，逆则为凶。五行之气，寄于五星，散于万物。观五星之变，可以知五行之盛衰；知五行之盛衰，可以推人事之吉凶。此天道与人道相通之理也。

	【第十八】论诸神

	五行各有其神主之。东方木德，其神句芒，人面鸟身，乘两龙。句芒者，木官之神，主春，其祀在户。南方火德，其神祝融，兽身人面，乘两龙。祝融者，火官之神，主夏，其祀在灶。中央土德，其神后土，人面蛇身。后土者，土官之神，主季夏，其祀在中霤。西方金德，其神蓐收，人面白毛，虎爪，执钺。蓐收者，金官之神，主秋，其祀在门。北方水德，其神玄冥，人面鸟身，珥两蛇，践两蛇。玄冥者，水官之神，主冬，其祀在行。

	此五神者，五行之精也。春则句芒司之，夏则祝融司之，季夏则后土司之，秋则蓐收司之，冬则玄冥司之。五行之气行于四时，五神各以其时司其职，则风雨以时，万物以育。若其不时，则灾变生焉。天子祭五神，各以其时，以祈岁稔民安，此古之制也。

