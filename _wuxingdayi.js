	【第二十五】论地支藏干

	地支藏干者，地支之中各藏天干之气，乃天地交融之象也。十二地支所藏天干如下：

	子藏癸水。子为阳水之正位，所藏独癸水而已。
	丑藏己土、癸水、辛金。丑为金库，故藏辛金；土之本气为己土；又含水之余气。
	寅藏甲木、丙火、戊土。寅为火之长生，故藏丙火；木之本气为甲木；又含戊土。
	卯藏乙木。卯为阴木之正位，所藏独乙木而已。
	辰藏戊土、乙木、癸水。辰为水库，故藏癸水；土之本气为戊土；又含乙木。
	巳藏丙火、戊土、庚金。巳为金之长生，故藏庚金；火之本气为丙火；又含戊土。
	午藏丁火、己土。午为阴火之正位，火土同宫，故兼藏己土。
	未藏己土、乙木、丁火。未为木库，故藏乙木；土之本气为己土；又含丁火。
	申藏庚金、戊土、壬水。申为水之长生，故藏壬水；金之本气为庚金；又含戊土。
	酉藏辛金。酉为阴金之正位，所藏独辛金而已。
	戌藏戊土、辛金、丁火。戌为火库，故藏丁火；土之本气为戊土；又含辛金。
	亥藏壬水、甲木。亥为木之长生，故藏甲木；水之本气为壬水。

	支藏干各有本气、中气、余气之分。本气最旺，中气次之，余气最弱。藏干之说于命理取名至关重要，八字地支之五行不可仅看本气，必究其藏干，方能准确判断五行之强弱虚实，然后定取名之宜忌。

	【第二十六】论十二长生

	五行之气在天干地支中各有十二种状态，名曰十二长生，亦曰十二运。其名为：长生、沐浴、冠带、临官、帝旺、衰、病、死、墓、绝、胎、养。

	长生者，犹人之初生也，气始萌发，欣欣向荣。沐浴者，犹人之初生而洗浴也，气尚柔弱。冠带者，犹人渐长而加冠带也，气渐旺盛。临官者，犹人出仕为官也，气已壮盛。帝旺者，犹人至极盛之位也，气之顶点，过此则衰。衰者，盛极而衰，气渐退减。病者，气衰而病，力弱不振。死者，气尽而死，形存实亡。墓者，死而入墓，气藏于库。绝者，气绝而尽，形体消散。胎者，绝处逢生，气始结胎。养者，胎成而养，气渐孕育。

	五行十二长生表：
	木：长生于亥，沐浴于子，冠带于丑，临官于寅，帝旺于卯，衰于辰，病于巳，死于午，墓于未，绝于申，胎于酉，养于戌。
	火：长生于寅，沐浴于卯，冠带于辰，临官于巳，帝旺于午，衰于未，病于申，死于酉，墓于戌，绝于亥，胎于子，养于丑。
	土：长生于申，沐浴于酉，冠带于戌，临官于亥，帝旺于子，衰于丑，病于寅，死于卯，墓于辰，绝于巳，胎于午，养于未。（土随水之十二长生，此为一说。亦有土随火之说，学者当兼参。）
	金：长生于巳，沐浴于午，冠带于未，临官于申，帝旺于酉，衰于戌，病于亥，死于子，墓于丑，绝于寅，胎于卯，养于辰。
	水：长生于申，沐浴于酉，冠带于戌，临官于亥，帝旺于子，衰于丑，病于寅，死于卯，墓于辰，绝于巳，胎于午，养于未。

	此十二长生诀为命理推断旺衰之基础。取名时某行若值长生、冠带、临官、帝旺则为旺，不宜再多补；若值死、墓、绝则为衰，急宜补救。

	【第二十七】论地支三合六合

	地支相合者，五行之气交感会合之义也。有三合、六合之分。

	三合者，三地支合为一气：
	申子辰三合水局——申为水之长生，子为水之帝旺，辰为水之墓库。
	亥卯未三合木局——亥为木之长生，卯为木之帝旺，未为木之墓库。
	寅午戌三合火局——寅为火之长生，午为火之帝旺，戌为火之墓库。
	巳酉丑三合金局——巳为金之长生，酉为金之帝旺，丑为金之墓库。

	六合者，两地支阴阳相合：
	子丑合土，寅亥合木，卯戌合火，辰酉合金，巳申合水，午未合土（亦合日月）。

	地支相合，五行之气融汇贯通。八字中有合则五行配置更为复杂，取名时须留意地支之合所化之气，化气之五行亦为命名之参考。

	【第二十八】论五行与二十四节气

	二十四节气者，天地之气运行之节序也。五行之气在节气中各有所司。

	立春（寅月始）木气始旺，雨水木气渐盛。
	惊蛰（卯月始）木气正旺，春分木气至极。
	清明（辰月始）木气渐衰土气始入，谷雨土气渐旺。
	立夏（巳月始）火气始旺，小满火气渐盛。
	芒种（午月始）火气正旺，夏至火气至极。
	小暑（未月始）火气渐衰土气始入，大暑土气渐旺。
	立秋（申月始）金气始旺，处暑金气渐盛。
	白露（酉月始）金气正旺，秋分金气至极。
	寒露（戌月始）金气渐衰土气始入，霜降土气渐旺。
	立冬（亥月始）水气始旺，小雪水气渐盛。
	大雪（子月始）水气正旺，冬至水气至极。
	小寒（丑月始）水气渐衰土气始入，大寒土气渐旺。

	二十四节气中，以四立（立春立夏立秋立冬）为四季之始，以二分二至（春分秋分夏至冬至）为四季之中。五行之气随时序而流转，春木夏火秋金冬水，四季土王。命名取字之五行宜忌，与出生节气密切相关，节气之深浅决定五行之旺衰程度，不可不察。

	【第二十九】论天干五合

	天干五合者，阴阳天干相合而化气也。

	甲己合化土——甲为阳木，己为阴土，木克土而为合，中正之合也。
	乙庚合化金——乙为阴木，庚为阳金，金克木而为合，仁义之合也。
	丙辛合化水——丙为阳火，辛为阴金，火克金而为合，威制之合也。
	丁壬合化木——丁为阴火，壬为阳水，水克火而为合，淫慝之合也。
	戊癸合化火——戊为阳土，癸为阴水，土克水而为合，无情之合也。

	合化以月令为纲，月令之气与所化之气相同则化真，不同则化假。真化则五行发生根本变化，取名之五行喜忌亦随之而变。如日主甲木合己土而化土成真，则日主按土论，取名宜忌亦按土命处理。

	【第三十】论地支六冲

	地支六冲者，两地支方位相对而冲也。

	子午相冲——水火相克，南北相冲。
	丑未相冲——二土相冲，湿燥相搏。
	寅申相冲——金木相克，刚柔相冲。
	卯酉相冲——金木相克，东西相冲。
	辰戌相冲——二土相冲，寒暖相争。
	巳亥相冲——水火相克，阴阳相冲。

	相冲者，战克也。冲则有动，动则有变。八字中遇冲，五行之气受损，取名时宜以通关之字解冲。如寅申相冲，以水通关（金生水，水生木，化干戈为玉帛），取名用带水行之字可解寅申之冲。

