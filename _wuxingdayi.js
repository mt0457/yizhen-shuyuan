	【第十九】论诸人

	人秉五行之气以生，各有所受之多寡偏全。故人之性情、才质、智愚、贤不肖，皆与所秉之五行相关。

	木气多者，其人仁爱恻隐，好生恶杀，长而修美。但或优柔寡断，曲直不定。火气多者，其人明礼恭敬，威仪赫赫，言辞明朗。但或急躁轻浮，炎上无制。土气多者，其人忠信敦厚，言行相顾，宽柔有容。但或凝滞不化，稼穑失时。金气多者，其人刚毅果断，义烈慷慨，志节高迈。但或残酷刻薄，从革过甚。水气多者，其人智谋深远，通达事理，善藏其用。但或阴险多诈，润下无节。

	五气均平，则五行调和，其人中正和平，五德兼备。一气偏胜，则五行失和，其人性情亦有所偏。取名之道，正为调补所偏，使五行趋于平衡也。凡命名不可仅观日主，尤须通观全局，于八字五行之偏全盈虚了然于心，然后选字命名。

	【第二十】论五行与政治

	五帝之德，各配五行。太皞伏羲氏以木德王天下，炎帝神农氏以火德王天下，黄帝轩辕氏以土德王天下，少皞金天氏以金德王天下，颛顼高阳氏以水德王天下。

	木德之政尚仁——宽惠爱民，省刑薄赋。火德之政尚礼——文明教化，秩序井然。土德之政尚信——敦厚诚信，安土重迁。金德之政尚义——刚正严明，赏罚必信。水德之政尚智——深谋远虑，以柔克刚。

	《孔子家语》曰：凡五政，各以其德。德盛则政美，德衰则政恶。五行之运，循环无穷。自伏羲至汉，五德递相嬗代，各以其德兴替。此天人相应之大道也。邹衍五德终始之说，正以此五行相胜之理推演历史之变迁。

	【第二十一】论禽虫

	禽虫之属，亦各配五行。《大戴礼》云：虫之精者，各有攸属。

	毛虫属木——凡有毛者，如虎豹犬羊之类。其长为麒麟，木之精也。麒麟牡曰麒，牝曰麟，麕身牛尾，狼项一角，黄色圆蹄，不履生虫，不折生草。羽虫属火——凡有羽者，如凤凰燕雀之类。其长为凤凰，火之精也。凤凰牡曰凤，牝曰凰，首戴德，颈揭义，背负仁，心入信，翼挟义，足履正，尾系武。裸虫属土——凡无羽毛鳞甲者，如人为裸虫之长。土之精也。介虫属金——凡有甲壳者，如龟鳖蚌蛤之类。其长为龟，金之精也。龟上隆象天，下平象地。鳞虫属水——凡有鳞者，如龙蛇鱼鳖之类。其长为龙，水之精也。龙能大能小，能升能隐，春分而登天，秋分而潜渊。

	五虫之长，各为五行之精。麒麟为仁兽，木德之应也。凤凰为瑞鸟，火德之应也。圣人为人中之圣，土德之主也。龟为灵物，金德之象也。龙为神物，水德之应也。五灵现则天下太平，五灵隐则世道衰微。

	【第二十二】论灾异

	五行失其常度，则灾异生焉。《洪范五行传》曰：貌之不恭，是谓不肃，厥咎狂，厥罚恒雨，厥极恶，时则有服妖，时则有龟孽，时则有鸡祸，时则有下体生上之痾，时则有青眚青祥，惟金沴木。言之不从，是谓不乂，厥咎僭，厥罚恒旸，厥极忧，时则有诗妖，时则有介虫之孽，时则有犬祸，时则有口舌之痾，时则有白眚白祥，惟木沴金。视之不明，是谓不哲，厥咎舒，厥罚恒燠，厥极疾，时则有草妖，时则有裸虫之孽，时则有羊祸，时则有目痾，时则有赤眚赤祥，惟水沴火。听之不聪，是谓不谋，厥咎急，厥罚恒寒，厥极贫，时则有鼓妖，时则有鱼孽，时则有豕祸，时则有耳痾，时则有黑眚黑祥，惟火沴水。思之不容，是谓不圣，厥咎霿，厥罚恒风，厥极凶短折，时则有脂夜之妖，时则有华孽，时则有牛祸，时则有心腹之痾，时则有黄眚黄祥，惟金木水火沴土。

	木失其性则为雨淫，稼穑不成，草木不荣，民多疫疠。火失其性则为旱虐，川竭井枯，蝗虫为灾，民多流亡。土失其性则为地震，山崩川决，饥馑荐臻，民多流离。金失其性则为兵革，寇盗蜂起，刑戮妄加，民多杀伤。水失其性则为洪水，堤防溃决，田庐漂没，民多溺死。

	灾异之来，皆五行失和之所致也。人君修德，则五行顺序，灾异不生；人君失德，则五行错乱，灾异并至。此天人相感之微义也。

	【第二十三】论五行生死

	五行之气，有生有死，有王有废。《淮南子》曰：木生于亥，壮于卯，死于未，三辰皆木也。火生于寅，壮于午，死于戌，三辰皆火也。土生于午，壮于戌，死于寅，三辰皆土也。金生于巳，壮于酉，死于丑，三辰皆金也。水生于申，壮于子，死于辰，三辰皆水也。

	故木王于春，死于秋；火王于夏，死于冬；金王于秋，死于夏；水王于冬，死于土；土王于四季，而寄于四维。五行生死各有定数，此天地大象之自然也。

	木死于未，未中有乙木藏焉，死中有生也。火死于戌，戌中有丁火藏焉，死中有生也。金死于丑，丑中有辛金藏焉，死中有生也。水死于辰，辰中有癸水藏焉，死中有生也。土死无所寄，故土无死位。此则死中有生之义，物不可终极之理也。

	又五行各有王、相、休、囚、死五态：王为最旺，相为次旺，休为退休，囚为困囚，死为死绝。立春木王，火相，水休，金囚，土死。立夏火王，土相，木休，水囚，金死。立秋金王，水相，土休，火囚，木死。立冬水王，木相，金休，土囚，火死。四季土王，金相，火休，木囚，水死。此五行随时旺衰之纲要，命名选字时必明乎此。

	【第二十四】论五行与九宫

	九宫者，太一行九宫之法也。坎一宫属水，坤二宫属土，震三宫属木，巽四宫属木，中五宫属土，乾六宫属金，兑七宫属金，艮八宫属土，离九宫属火。

	太一者，北辰之神也。其行也，始于坎宫，终于离宫。冬至之日，太一居坎宫，坎一宫属水，故冬之始也。立春之日，太一居艮宫，艮八宫属土，故春之始也。春分之日，太一居震宫，震三宫属木，故春之中也。立夏之日，太一居巽宫，巽四宫属木，故夏之始也。夏至之日，太一居离宫，离九宫属火，故夏之中也。立秋之日，太一居坤宫，坤二宫属土，故秋之始也。秋分之日，太一居兑宫，兑七宫属金，故秋之中也。立冬之日，太一居乾宫，乾六宫属金，故冬之始也。

	九宫之数：坎一、坤二、震三、巽四、中五、乾六、兑七、艮八、离九。此即洛书之数，亦术数之本也。其图曰：戴九履一，左三右七，二四为肩，六八为足，五居中央。纵横十五，错综无穷。此九宫配五行之本，后世玄空飞星、奇门遁甲、太乙神数，皆以此为基础。

