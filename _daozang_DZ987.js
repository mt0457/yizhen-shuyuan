太上垂训，一百八十戒以正人心。<br>
上品戒心、中品戒身、下品戒口。<br>
三品一百八十戒，是修道者之明灯、是入道者之阶梯、是成道者之根基。<br>
戒法庄严、戒德无上。<br>
能持一戒有一戒之福，能持百戒有百戒之功。<br>
能持一百八十戒圆满无缺者，即是人间之真人、世间的活神仙。<br>
皈依太上无极大道，皈依三十六部尊经，皈依玄中大法师。<br>
志心称念：太上老君道德天尊，正一系师三天大法师。<br>
一百八十戒护戒神王，不可思议功德。<br>
太上正一一百八十戒，度人无量天尊。
