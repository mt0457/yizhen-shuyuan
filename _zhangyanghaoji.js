十一、一枝花套曲·咏喜雨
═══════════════════════════════════════

（一枝花）用尽我为国为民心，祈下些值玉值金雨。数年空盼望，一旦遂沾濡。唤省焦枯，喜万象春如故。恨流民尚在途，留不住都弃业抛家，当不的也离乡背土。

（梁州）恨不得把野草翻腾做菽粟，澄河沙都变化做金珠。直使千门万户家豪富，我也不枉了受天禄。眼觑着灾伤教我没是处，只落得雪满头颅。

（尾声）青天多谢相扶助，赤子从今罢叹吁。只愿的三日霖霪不停住，便下当街上似五湖，都淹了九衢，犹自洗不尽从前受过的苦。

