上国。去客。停飞盖、促离筵。长安古道绵绵。见岸花啼露，对堤柳愁烟。物情人意，向此触目，无处不凄然。
醉拥征骖犹伫立，盈盈泪眼相看。况绣帏人静，更山馆春寒。今宵怎向漏永，顿成两处孤眠。

