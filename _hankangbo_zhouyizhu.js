【系辞上传】凡十二章。首章明天尊地卑，乾坤定位，易简之理。次章设卦观象，明吉凶悔吝，三极之道。三章释彖爻之义，位卦辞之辨。四章论易与天地准，范围天地，曲成万物。五章明一阴一阳之谓道，生生之谓易。六章赞易之广大，配天地四时日月。七章论崇德广业，知崇礼卑，成性存存。八章拟议爻辞，举中孚同人大过谦节等爻，明言行慎密之义。九章述大衍之数，蓍法之原。十章明易有圣人之道四——辞变象占。十一章论易有太极，生两仪四象八卦。十二章论书不尽言、言不尽意，立象尽意、变通尽利。
【系辞下传】凡十二章。首章论八卦成列，变通趣时，天地大德曰生。次章述圣人制器尚象，盖取诸离以下十三卦。三章明易者象也，彖者材也，爻者效也，阳卦多阴、阴卦多阳之义。四章申天下何思何虑，精义入神，屈伸相感。五章论乾坤为易之门，彰往察来，显微阐幽，申九卦之德。六章论文王忧患，九德之卦。七章明易道屡迁、变动不居、不可为典要、唯变所适。八章原始要终，论六爻之位与功。九章明易书广大悉备，兼三才而两之。十章论文王当殷末世，其辞危，危者使平。十一章论乾健坤顺，变化云为，人谋鬼谋，百姓与能。十二章论吉凶以情迁，六辞辨情伪。
【说卦传】首章言圣人作易，幽赞于神明而生蓍，参天两地而倚数。次章述性命之理，立天之道曰阴与阳，立地之道曰柔与刚，立人之道曰仁与义。三章天地定位，八卦相错。四章八卦之用：雷以动之，风以散之。五章帝出乎震，八卦配八方四时。六章详列八卦之德、之畜、之身、之家，及广象之全体。
【序卦传】上经三十卦，始于乾坤终于坎离。下经三十四卦，始于咸恒终于既济未济。序卦之例有相因相反二义，前卦之终即为后卦之始，如环无端，物不可穷。
【杂卦传】杂糅六十四卦之义，多以两两相对，不拘序卦之次第，明六十四卦相生相反之关系，终之以君子道长小人道忧。

