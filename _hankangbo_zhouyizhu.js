乾刚坤柔。比乐师忧。临观之义，或与或求。屯见而不失其居，蒙杂而著。震，起也。艮，止也。损益，盛衰之始也。大畜，时也。无妄，灾也。萃聚而升不来也。谦轻而豫怠也。噬嗑，食也。贲，无色也。兑见而巽伏也。随，无故也。蛊，则饬也。剥，烂也。复，反也。晋，昼也。明夷，诛也。井通而困相遇也。咸，速也。恒，久也。涣，离也。节，止也。解，缓也。蹇，难也。睽，外也。家人，内也。否泰，反其类也。大壮则止，遁则退也。大有，众也。同人，亲也。革，去故也。鼎，取新也。小过，过也。中孚，信也。丰，多故也。亲寡，旅也。离上而坎下也。小畜，寡也。履，不处也。需，不进也。讼，不亲也。大过，颠也。姤，遇也，柔遇刚也。渐，女归待男行也。颐，养正也。既济，定也。归妹，女之终也。未济，男之穷也。夬，决也，刚决柔也。君子道长，小人道忧也。

【韩注】杂卦者，杂糅众卦，错综其义。或以同相类，或以异相明。不拘上下经之序，唯以义之相反相对者排比之。六十四卦之义，略尽于此。君子道长小人道忧，终之以扶阳抑阴之义。

