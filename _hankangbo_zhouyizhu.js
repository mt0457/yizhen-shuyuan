韩康伯（332—380），名伯，字康伯，颍川长社（今河南长葛）人。东晋玄学家，简文帝时官至吏部尚书。其舅殷浩善玄谈，康伯幼从之游，遂通玄理。王弼注《周易》仅及六十四卦及《彖》《象》《文言》诸传，《系辞》以下未暇为之。康伯承王弼义理易学之余绪，补注《系辞》上下、《说卦》《序卦》《杂卦》五传，与王弼注合为全书。唐孔颖达撰《周易正义》，王韩并采，遂成定本。其注以简驭繁，以无摄有，与王弼一脉相承，而于天道人事之际尤多发明。

