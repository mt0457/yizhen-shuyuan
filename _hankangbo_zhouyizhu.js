有天地，然后万物生焉。盈天地之间者唯万物，故受之以屯。屯者，盈也。屯者，物之始生也。物生必蒙，故受之以蒙。蒙者，蒙也，物之稚也。物稚不可不养也，故受之以需。需者，饮食之道也。饮食必有讼，故受之以讼。讼必有众起，故受之以师。师者，众也。众必有所比，故受之以比。比者，比也。比必有所畜，故受之以小畜。物畜然后有礼，故受之以履。履而泰然后安，故受之以泰。泰者，通也。物不可以终通，故受之以否。物不可以终否，故受之以同人。与人同者，物必归焉，故受之以大有。有大者不可以盈，故受之以谦。有大而能谦必豫，故受之以豫。豫必有随，故受之以随。以喜随人者必有事，故受之以蛊。蛊者，事也。有事而后可大，故受之以临。临者，大也。物大然后可观，故受之以观。可观而后有所合，故受之以噬嗑。嗑者，合也。物不可以苟合而已，故受之以贲。贲者，饰也。致饰然后亨则尽矣，故受之以剥。剥者，剥也。物不可以终尽剥，穷上反下，故受之以复。复则不妄矣，故受之以无妄。有无妄然后可畜，故受之以大畜。物畜然后可养，故受之以颐。颐者，养也。不养则不可动，故受之以大过。物不可以终过，故受之以坎。坎者，陷也。陷必有所丽，故受之以离。离者，丽也。

【韩注·上经】上经三十卦，始于乾坤，终于坎离。乾坤者，易之门户，天地定位而万物育焉。屯蒙者，物之始生而蒙昧也。需讼者，饮食之争也。师比者，众之聚散也。小畜履者，礼义之兴也。泰否者，治乱之循环也。同人大有者，人与物之盛也。谦豫者，谦受益、豫防患也。随蛊者，随时而有事也。临观者，君临天下而观民也。噬嗑贲者，刑与文也。剥复者，消长之机也。无妄大畜者，诚而能畜也。颐大过者，养与过也。坎离者，险与明也。其间先后相承，如环无端。一治一乱、一消一息，莫非天道人事之自然也。
【韩注·下经】下经三十四卦，始于咸恒，终于既济未济。咸恒者，夫妇之道，人伦之始。夫妇居室，父子君臣以次而立。遁大壮者，进退之节也。晋明夷者，明暗之际也。家人睽者，亲疏之变也。蹇解者，难易之相寻也。损益者，盛衰之始也。夬姤者，决遇之机也。萃升者，聚而上升也。困井者，穷而能养也。革鼎者，去故取新也。震艮者，动静之体也。渐归妹者，进之有归也。丰旅者，盛衰之无常也。巽兑者，入而说也。涣节者，散而能止也。中孚小过者，信与过也。既济未济者，成与未成也。序卦之义，前卦之终即为后卦之始，因果相承、得失相寻。六十四卦如天运之循环，无一息之停。物不可穷，故以未济终焉。《易》之为书，教人知进退存亡而不失其正也。
【韩注·序卦总论】序卦者，文王所序六十四卦之次第也。其序非出于偶然，乃本于天地万物自然之伦序。韩氏承王弼之说，谓序卦有相因、相反二义。相因者，如屯后继以蒙，物生必蒙也。相反者，如泰后继以否，通极则塞也。读易者明乎此，则知吉凶消长非无常也，皆有渐次之序、必然之理。君子观序卦而知天命，故乐天知命而不忧。

