星命之学，源于上古观星之术。周有冯相氏掌天文，秦有甘公石公著星经。至汉唐而大盛，张果老（张果）创星命一派，李淳风、袁天罡、一行禅师皆精于此道。宋元以降，星命与子平并行，各有传承。明代星命之学犹为显学，朝廷设有钦天监掌天文星算，民间星命家亦众。

