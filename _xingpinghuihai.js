【星平总诀】星为天象平为地，天地合参命乃全。星看根基定贵贱，平看运程推变迁。星平俱贵上上格，星平俱贱下下篇。一贵一贱各有应，大运流年细分研。

【星盘观诀】命宫何星是根基，日月光明最有辉。木金守照福禄厚，火土临垣仔细推。紫气照命多长寿，罗计当头阻且危。庙旺之星虽凶吉，衰绝之星吉亦悲。

【星平互补诀】八字缺水星中有，水星照命补其亏。八字缺金金星补，星盘调济八字符。星盘火星太刚烈，八字水旺制其威。星平互补如医理，君臣佐使两不违。

【星平择吉诀】婚嫁看星夫妻宫，兼看八字日支中。开业看星星官禄，兼看八字官星通。出行看星迁移宫，兼看八字驿马冲。大事星平俱吉日，百无禁忌万事通。

