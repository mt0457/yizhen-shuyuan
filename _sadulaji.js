萨都剌（约1272年—约1355年），字天锡，号直斋，先世为西域色目人（一说回族），祖父以勋留镇云中，遂为雁门（今山西代县）人。元代著名诗人、词人。泰定四年（1327年）进士，历任京口录事司达鲁花赤、江南行御史台掾、燕南宪司经历等职。晚年寓居杭州，以山水自娱。

萨都剌诗风清丽俊逸，兼雄浑沉郁。山水诗清新如画，宫词流丽婉转，边塞诗有盛唐余韵。词作虽不多，而气象恢宏，感慨深沉。《满江红·金陵怀古》《念奴娇·登石头城》等，寓兴亡之感于江山形胜之中，为元代词坛压卷之作。著有《雁门集》十四卷，存诗近八百首。
