北斗延生者，礼北斗以延寿命也。
道教认为，北斗七星（加辅弼二星则为北斗九皇）为天之中枢，主司人间生死命籍——南斗注生，北斗注死，人的寿命长短、福禄厚薄、灾厄轻重，皆由北斗星君掌其簿籍。
