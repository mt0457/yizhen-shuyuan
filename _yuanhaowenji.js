元好问集评：

郝经《遗山先生墓铭》：
"诗自三百篇以来，极于李杜，而遗山以沈郁顿挫之气，振起衰靡之风。其诗上薄风雅，中师李杜，下该苏黄，粹然一出于正。"

《四库全书总目提要》：
"好问才雄学赡，金元之际，屹然为文章大宗。其诗奇崛而绝雕镂，巧缛而谢绮丽。五言高古沉郁，七言乐府不用古题，特出新意。歌谣慷慨，挟幽并之气。至值金源亡国，以宗社丘墟之感，发为慷慨悲歌，尤足动人。"

赵翼《瓯北诗话》：
"元遗山诗，专以精思锐笔，清炼而出。其廉悍沉挚处，较胜于苏陆。盖生长云朔，其天禀本多豪健英杰之气，又值金元改物之际，故其诗多悲壮苍凉之音。七律尤见功力，如《岐阳》《出都》《眼中》《秋夜》诸作，可谓诗史。"

刘熙载《艺概》：
"金元遗山诗，兼杜、韩、苏、黄之胜，俨然集大成之学。遗山词，亦浑雅，亦博大，有骨干，有气象。"

王国维《人间词话》：
"元遗山词，学苏辛而能得其真髓者。其《摸鱼儿·雁丘词》云：'问世间、情是何物，直教生死相许？'千古情语之极则也。"

陈廷焯《白雨斋词话》：
"遗山词，慷慨沉雄，直承稼轩衣钵。虽稍逊其横放，而清雄顿挫，自是一代作手。《水调歌头·赋三门津》一篇，何等气魄！"

