《康熙字典》为清代康熙皇帝钦命编纂之大型汉字字典，成书于康熙五十五年（1716年），是中国古代收字最多、规模最大、影响最深远之字典。康熙四十九年（1710年），清圣祖爱新觉罗·玄烨谕令文渊阁大学士张玉书、文华殿大学士陈廷敬为总阅官，翰林院侍讲学士凌绍霄等三十余人组成编纂班子，历时六年，于康熙五十五年告成。康熙帝亲制序文，赐名《康熙字典》。

