按照五格姓名学理论，一至八十一数各有其吉凶含义。以下为最常见之吉数：

一画（太极之数）：万物开泰，生发无穷。大吉。
三画（三才之数）：天地人和，大事大业。大吉。
五画（五行之数）：五行俱权，循环相生。大吉。
六画（六爻之数）：发展变化，天赋美德。大吉。
七画（七政之数）：精悍严谨，天赋之力。吉。
八画（八卦之数）：八卦之象，乾坎艮震。大吉。
十一画（旱苗逢雨）：万物更新，调顺发达。大吉。
十三画（春日牡丹）：才艺多能，智谋奇略。大吉。
十五画（福寿之数）：福寿圆满，富贵荣誉。大吉。
十六画（厚重之数）：厚重载德，安富尊荣。大吉。
二十一画（明月中天）：光风霁月，万物确立。大吉。
二十三画（旭日东升）：旭日升天，名显四方。大吉。
二十四画（掘藏得金）：家门余庆，金钱丰盈。大吉。
二十九画（智谋之数）：智谋优秀，财力归集。大吉。
三十一画（春日花开）：智勇得志，博得名利。大吉。
