【梁州第七】我为他，废寝忘餐，减尽了芳容。我为他，朝思暮想，望断了青骢。若得个，琴瑟和同，也不负，我一片深衷。

（梅香云）小姐，书已写好，我这就送去。（下，马彬上，梅香递书科，马彬接看科，云）原来是董小姐的书信。好才华也！待我回书一封。（写书科，云）诗云：东墙花影月朦胧，人在瑶台第几重。欲寄相思何处寄，夜深和泪写春风。梅香，将这书送与你家小姐。（梅香下）

（正旦接书看科，喜科，云）好一个才子！待我禀过母亲，成就这段姻缘。（唱）

【牧羊关】他那里，才高八斗，我这里，情愿相投。趁良宵，花好月圆，成就了，凤鸾俦。

【第三折选段】

（马彬上，云）小生自与董小姐互通书信，两情相悦。今蒙董母不弃，允了亲事。但小生功名未就，不敢完婚。今当上朝取应，若得一官半职，再来迎娶小姐。（正旦上，云）郎君此去，须要保重。妾身在此，专候佳音。（唱）

【越调·斗鹌鹑】他去也，我愁锁眉尖。他去也，我泪湿罗衫。此一去，鹏程万里，鱼跃深渊。但愿他，早夺魁元，莫忘了，旧日缠绵。

【调笑令】我嘱付你，一路上，风霜自保。我嘱付你，客邸中，饮食宜调。我嘱付你，文章仔细校。莫负我，灯前泪，枕上潮。

