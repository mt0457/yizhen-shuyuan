我望山形，虎踞龙盘，壮哉建康。忆黄旗紫盖，中兴东晋；雕阑玉砌，下逮南唐。步步金莲，朝朝琼树，宫殿吴时花草香。今何日，尚寺留萧帝，山拥孙郎。

