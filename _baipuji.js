【董秀英花月东墙记】（选段）

白朴第三部存世杂剧。写书生马彬与董秀英的爱情故事。

【第一折选段】

（正旦扮董秀英，引梅香上，云）妾身董秀英是也。父亲董府尹，早年亡过。母亲在堂。妾身年方一十八岁，未曾许聘于人。今日春光明媚，庭院中花柳争妍。妾身与梅香，去东墙下赏花一番。（唱）

【仙吕·点绛唇】春满皇都，花枝低簇。香风度，万紫千红，尽把春光助。

【混江龙】柳垂金线，桃吐丹霞。燕语莺啼，蝶舞蜂衙。这春光，一刻千金价。休辜负，美景良辰，花朝月夜。

（云）梅香，你看东墙外，是谁家书生？好一个俊秀人物也！（马彬上，云）小生马彬，字文辅。临阳人也。来京应试，寄寓于此。今日春光融和，不免去郊外闲步一回。（做望科，与正旦四目相视科，正旦唱）

【油葫芦】我见他，眉清目秀，丰姿洒落。楚楚衣冠，儒雅规模。他那里，有意偷睛觑。不由人，心忙意促。

【天下乐】我觑了那生，他气宇轩昂，言谈俊爽。一表人物，不比寻常。若得他，共结丝萝，也不枉了，春光一场。

（梅香云）小姐，那生看你看呆了！（正旦做羞科，云）休得胡说！回去罢。（做回顾科，下）（马彬云）好一个女子！看他那秋波一转，令人魂销。不知是谁家宅眷？待我打听来。正是：只疑身在武陵源，流水桃花洞口边。尘世何人能到此，神仙窟宅在人间。（下）

【第二折选段】

（正旦上，云）自那日东墙下见了那生，好生牵挂。今日母亲不在家，不免修书一封，叫梅香送去。（做写书科，唱）

