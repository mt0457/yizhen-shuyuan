<b>三十二天，四梵所成。欲色无色，层层叠升。东方青灵，南方丹明。西方皓灵，北方玄精。各天帝君，各有赞颂。朔望诵持，遥闻鉴听。诸天遥唱，万帝设礼。消灾延寿，度人济冥。至心诵者，罪灭福生。功满德就，飞升玉清。皈依元始灵宝道德三清道祖。三十二天帝君度人无量天尊。</b>
