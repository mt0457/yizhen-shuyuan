<p style="font-size:16px;color:#8b1a1a;line-height:2.2;margin:0;"><b>元始混洞，赤文结成。八威龙文，天真皇人。屈曲如龙，蜿蜒似星。东方震威，青龙吐焰，破滞祛邪以起生。南方离威，赤龙衔珠，照明炼形以辟邪。西方兑威，白龙捧剑，决断斩魔以金刚。北方坎威，黑龙负图，藏真通玄以伏魔。东北艮威、东南巽威、西南坤威、西北乾威——四隅龙文，辅翼四方。八威合德，万神护持。佩之护身，悬之镇宅。诵之消灾，书之合道。返八归一，与道合真。皈依道经师三宝。八威龙文天尊。</b></p>
