+"<p style=\"line-height:2.2;\">"
+"<b>一、禳心斋醮——集体疗愈之大道场：</b>"
+"心疾之治疗，除个人自修外，尚有集体斋醮一法——此为借众力以破心魔之大道场。"
+"世间有一种心疾叫做\"孤绝感\"——患者觉得自己是世界上唯一受苦的人、没人理解自己、"
+"自己与整个世界隔绝。这种孤绝感本身就是加重心疾之重要因素。禳心斋醮正是对治此孤绝感之法——"
+"将一群同病相怜者聚集在道场中，在庄严的宗教仪式中，每个人都会发现：原来不是只有我一个受苦，"
+"原来这么多人和我一样。这个发现本身就有疗愈之力量。禳心斋醮之科仪程序略说如下。"
+"一、开设道场：择吉日（以三元日、八节日、庚申甲子日、本命日为上），于宫观静室或斋主家中之堂屋，"
+"悬灵宝天尊圣像（或红纸书\"太上灵宝天尊\"六字供奉），设香案、陈列供品——香三炷、花三朵、"
+"清水三杯、灯三盏、时果三盘（三三见九应九天之数），另备黄表纸若干、朱砂新笔、禳心九符之黄素绢。"
+"二、净坛结界：高功法师（主持醮仪之高道）先以净水遍洒坛场四方上下，口诵净天地神咒："
+"\"天地自然，秽气氛散。洞中玄虚，晃朗太元。八方威神，使我自然。灵宝符命，普告九天。"
+"乾罗答那，洞罡太玄。斩妖缚邪，杀鬼万千。中山神咒，元始玉文。持诵一遍，却鬼延年。"
+"按行五岳，八海知闻。魔王束首，侍卫我轩。凶秽消散，道气长存。急急如律令。\"洒净之后，"
+"以五色线绕坛场一周（象征结界，令外邪不入内病不出）。三、启师：法师率众向上三礼九叩，"
+"口诵启师文：\"太上无极大道灵宝天尊玉清圣境元始天尊太清仙境道德天尊三清上圣十方诸天尊"
+"三官大帝青童道君一切圣前——伏以众生心疾荼毒至深，药石罔效，唯道可医。"
+"今有信士某甲等若干人，为心疾所困日久，至诚恳切祈禳于此。伏乞天尊慈悲，"
+"放大光明，照诸信士心腑，消其忧烦恐嗔悲郁痴狂妄一切心病，复其清净本来面目。"
+"某年月日主持法师某甲百拜谨启。\"启师毕，焚启师疏文一道。四、诵经："
+"大众齐诵《太上洞玄灵宝天尊说禳心疾经》正文（即此经之全文），诵七遍——"
+"第一遍为总启，第二遍至第七遍分别针对九种心疾（忧烦恐嗔悲为一遍，郁痴狂妄为一遍，"
+"九疾通禳为一遍，以此七遍覆盖九疾）。诵时节奏平缓均匀，一字一句清清楚楚，"
