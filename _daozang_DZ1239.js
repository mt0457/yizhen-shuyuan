+"<p style=\"line-height:2.2;\">"
+"<b>二、每日禳心十二时辰修行要诀：</b>"
+"灵宝天尊为便利行者将禳心修炼融入日常生活之一切时段，特开示十二时辰修行要诀——"
+"每个时辰皆有一个与其阴阳五行属性相应的禳心方法，行者依此时辰表修持，"
+"可将一整天的每一刻都转化为禳心之道场。子时（23-1时）：夜半一阳生，此时天地之气最为安静。"
+"宜在此时行\"回顾清心\"——将一整天之心念过一遍，若有负面情绪淤积，即刻以\"观心无常\"之法一一消解，"
+"不留一丝挂碍到次日。如睡前扫地，令心屋洁净后安然入眠。丑时（1-3时）："
+"肝经气血最旺之时，肝主疏泄、与情绪之舒畅密切相关。若此时未睡（失眠者多醒于此），"
+"可以五指梳头——以双手十指代梳，从前额发际向后脑勺缓慢梳理三十六次，"
+"同时默诵\"嘘\"字诀（嘘为肝之音，六字诀中\"嘘\"字平肝气），梳头毕以掌心搓热覆于双目之上，"
+"静默三分钟。此法有助于引肝气下行、平复烦躁，常行可改善睡眠。寅时（3-5时）："
+"肺经气血最旺，肺主悲忧。若忧愁悲戚之人宜于此时起床（不必强行起床，顺其自然即可），"
+"面向西方（西方为肺之本方），深呼吸二十一次——吸时意想吸入白色清纯之金气（肺属金），"
+"呼时意想呼出灰色之悲忧浊气。深呼吸毕，轻微扩胸运动三十六次（双臂侧平举向后扩，"
+"尽量打开胸腔——扩胸即宣肺，宣肺即舒悲）。卯时（5-7时）：日出之时，天地清新。"
+"此乃一日之中禳心修炼之黄金时段。宜于此时行\"晨朝禳心三法\"——其一行晨礼："
+"面向东方（日出之方，灵宝天尊所居之方），叩齿九通，诵禳心总咒三遍；其二行吐纳："
+"深呼吸九次，吸日初升之清新阳气，呼出体内淤积之浊气；其三是日定课："
+"以纸笔写下当日之心愿——不是\"我要做什么\"的工作计划，而是\"今天我希望以什么心态面对生活\"的心态设定。"
+"例如：\"今天我以平静之心面对一切。\"\"今天我不对任何人发脾气。\""
+"\"今天我微笑着面对每一个遇见的人。\"写好后随身携带，日间时时取出默读，提醒自己不偏离当日之心愿。"
+"辰时（7-9时）：胃经气血最旺，此时进食早餐。饮食与心疾关系极大——脾胃为气血生化之源，"
+"脾胃不佳则气血不足，气血不足则心神失养而易生心病。故禳心不可忽略饮食：早餐宜温热清淡，"
+"忌生冷油腻；进食时细嚼慢咽，不看手机不看书，专心吃饭——吃饭时吃饭，即是\"吃饭禅\"，"
+"可在进食之中训练专注力。巳时（9-11时）：脾经气血最旺，脾主思虑。"
+"此时是工作学习之黄金时段，宜在此时处理需集中精力之事务。工作之中不失觉知——"
+"打字时知觉自己在打字，开会时知觉自己在开会，写作时知觉自己在写作。"
+"大约工作一小时后，暂停三五分钟——站起来走动一下、看看窗外远处绿色植物，"
+"以右手掌心按于腹部（中脘穴位置，脐上四寸），顺时针轻轻揉腹三十六圈，"
+"此即\"揉中脘\"——和中理气，防止思虑过度伤脾。午时（11-13时）：心经气血最旺，"
+"心主神明。此时宜\"午养心神\"——取午休约十五至三十分钟，不是睡觉，而是闭目养神。"
+"坐或卧均可，全身放松，心念系于膻中穴（两乳连线中点），默诵\"灵宝天尊\"圣号，"
+"不急不缓，声声入心。此即\"午时养心法\"——短短二十分钟胜过夜晚两小时之睡眠。"
+"未时（13-15时）：小肠经气血最旺，小肠泌别清浊——分清别浊，犹如人心的\"择善弃恶\"功能。"
+"此时宜反省上午之心念：上午之中可有负面情绪？可有不善之念？若有，即刻以\"观心无常\"之法消之；"
+"若无，则当庆幸并勉励自己保持下午。申时（15-17时）：膀胱经气血最旺，"
+"膀胱为\"州都之官\"，主水液代谢。此时宜补水——慢慢饮温水两三杯，不是一口气灌下去，"
+"而是小口慢饮，每口在口中含片刻再咽下。水为生命之源，充足的水分可以促进新陈代谢、"
+"排出体内代谢废物，间接改善心神之清明度。饮水之时默想：此水为灵宝天尊之甘露，"
+"入我体内涤除一切心病之浊气。酉时（17-19时）：肾经气血最旺，肾藏志、主恐惧。"
+"此时宜\"收摄归元\"——结束一天之工作学习，将外散之心神收回。具体做法：静坐十五分钟，"
+"闭目观想一天之中所经历的一切喜怒哀乐如电影回放般过一遍，然后想象将这些画面收入一个金色的盒子里，"
+"盒子盖上，放入心中最深处——今天的情绪\"存档\"了，不再带着它们进入夜晚。"
+"此法甚利于恐惧患者——恐惧因肾气不足，收摄归元可以固肾气而安心神。戌时（19-21时）："
+"心包经气血最旺，心包为心之外围保护层，代心受邪。此时宜与家人或友人交流沟通——"
+"心疾患者最忌封闭自己，与人真诚交流是打破\"孤绝感\"之最佳方法。交流时不谈是非、"
+"不论人过、不诉苦水（诉苦会加重痛苦的感受），而是谈论积极正面之话题、分享日常之小确幸、"
+"互相鼓励支持。若独居无人交流，可于此时读道经一卷、或抄写禳心经文一段、"
+"或听道教仙乐静心——总之以\"打开心扉\"为宗旨。亥时（21-23时）：三焦经气血最旺，"
+"三焦通行元气于全身。此时宜为入眠做准备——热水泡脚二十分钟（水没过脚踝，水温以能耐受之最热为佳），"
+"泡脚时默诵禳心总咒二十一遍。泡毕擦干，以右手掌心搓左脚涌泉穴一百零八次，"
+"左手掌心搓右脚涌泉穴一百零八次（涌泉为肾经起点穴，搓涌泉可引火下行、交通心肾、安神助眠）。"
+"然后上床，右侧卧，心中默诵\"灵宝天尊\"圣号，待圣号与呼吸节奏自然合一时，"
+"不知不觉中便进入了安宁的睡眠。以上十二时辰修行法，不必死板地全部照做——"
+"各人可根据自己的生活规律与心疾类型，选取最相关的若干时辰执行。"
+"若能坚持一月，则整个人的身心状态必有明显提升。</p>"
+"<p style=\"line-height:2.2;\">"
+"<b>三、禳心修行之辅助善法四则：</b>"
+"除观心打坐持咒诵经外，灵宝天尊另开示四种\"辅助善法\"作为禳心修行之重要补充。"
+"此四法看似与禳心无直接关系，实则滴滴归源——日常生活中行此善法可转化心念、培养正念、"
+"涵养道心，对于心疾康复有不可或缺之辅助作用。第一善法曰\"节言\"——每日减少不必要的言语。"
+"言语是心念的外在表现，心乱则言多，言多则心更乱——此为恶性循环。修行者当学会\"节言\"，"
+"该说的说，不该说的不说；有意义的说，无意义的不说。尤其要戒除\"抱怨语\"\"是非语\""
+"\"炫耀语\"\"刻薄语\"——此四类言语最伤心神。每日择一时段（建议午时前后）行\"止语\"——"
+"半个时辰或一个时辰之内完全不说话（可用纸笔代替必要之交流），让心神在寂静中得到休养。"
+"第二善法曰\"节视\"——每日减少不必要的视觉信息输入。现今之世，人每日通过手机电脑电视"
+"接收海量信息，心神被各类信息风暴轰炸得疲惫不堪——此为现代心疾高发之重要外因。"
+"修行者当学会\"节视\"——少刷手机、少看短视频、少看负面新闻、少看争斗攻击之内容。"
+"代之以\"养眼\"——多看自然景色（青山绿水、日月星辰、花鸟虫鱼——此等自然景物中蕴有天地之清气，"
+"久视之可净化心神）。每日至少半小时不看任何电子屏幕（睡前一小时尤应远离屏幕），"
+"闭目养神或看窗外自然景物皆可。第三善法曰\"节欲\"——非仅指男女之欲（此欲之节制固已重要），"
+"更指一切\"贪求之欲\"——贪美食、贪华服、贪财物、贪名位、贪他人之认可、"
+"贪事事如意。贪求越多则不得越多，不得越多则心越苦。修行者当学会\"节欲\"——"
+"非禁欲（禁欲易致反彈），而是逐渐降低自己的欲望阈值。从一件小事做起——"
+"比如原本每餐必须有三个菜才满意，现在两菜一汤即可；原本一定要穿名牌才自信，"
+"现在朴素整洁即可。欲望降低一分，内心的自由就增加一分。第四善法曰\"节思\"——"
+"每日减少无益之思虑。思虑本身不是坏事（思考问题是人类之重要能力），"
+"但大量思虑属于\"无效思虑\"——翻来覆去思考同一件无法改变的事（反刍思维）、"
+"胡思乱想各种极端低概率的灾难场景（灾难化思维）、反复推测他人的心思和动机（读心术思维）、"
+"不断比较自己与别人之优劣（比较思维）。修行者当学会\"节思\"——识别无效思虑并及时\"关掉\"它。"
+"关掉的方法即是\"观心无常\"法中的\"暂停+观察\"——一旦觉察自己陷入了无效思虑，"
+"立刻暂停，以一个呼吸的时间将自己拉回当下，观察一下周围环境——"
+"\"现在我在哪里？我所坐的椅子是什么颜色？窗外有什么声音？\"——"+"以感官当下的真实体验替代无益的抽象思虑。以上节言、节视、节欲、节思——"
+"四\"节\"之法，看似消极（\"节\"即限制），实为积极之修养——如同江河之堤坝，"
+"堤坝限制了水的自由泛滥，却保障了水的有效利用。心神也是如此——限制心神的无序耗散，"
+"才能将心神集中用于正道修行。</p>"
+"<p style=\"line-height:2.2;\">"
+"<b>四、禳心修行之禁忌七条：</b>"
+"修禳心法门者，有七事需禁忌，犯之不但无益反而有害。一是切忌\"急求速效\"——"
+"心疾之形成非一日之寒，其痊愈亦非一日之功。有些人修了三天五天没见明显效果就放弃了，"
+"这等于播了种不待发芽就将土刨开。心疾的治疗需要时间——轻微者一二月可见效，"
+"中度者半年以上，严重者一年乃至数年。勿因一时未见速效而退失信心。二是切忌\"与别人比较\"——"
+"\"别人修了一个月就好了，我怎么三个月还不好？\"这个比较本身就是新一轮的焦虑与抑郁。"
+"每个人的心疾深浅不同、根器不同、修持的投入程度不同，康复速度自然不同。"
+"别人的进度与你无关，只管走自己的路，莫看别人的速。三是切忌\"完美主义\"——"
+"有些人因为在修行过程中偶尔放纵了一天——没静坐、没诵咒、发了脾气——"
+"就觉得自己\"破功了\"\"白修了\"，于是破罐子破摔完全放弃。这是心疾患者常见的\"非黑即白\"思维——"
+"\"要么做到完美，要么完全不做。\"灵宝天尊开示：修行是循序渐进的，偶尔的退步是正常且不可避免的。"
+"今天没做好，明天继续做就是；不必因为一次退步就否定之前累积之进步。四是切忌\"修而不养\"——"
+"有些人每日按时静坐持咒（修），但日常生活中心态毫无改变（不养），"
+"修是修、养是养，修时收敛心神、修后放纵任性——如此修行犹如以漏卮盛水，永不满也。"
+"真正的修行是将静坐中\"觉知\"\"平静\"\"无执\"的状态带入日常生活的每一刻——"
+"走路时保持觉知，吃饭时保持觉知，工作时保持觉知，与人交谈时保持觉知。"
+"修是\"充电\"，养是\"保电\"，唯有修养结合方能真正得益。五是切忌\"执于法门\"——"
+"有些人一旦选择了某个方法（如专修禳忧清心符），就执着认为只有这个方法是好的，"
+"排斥其他方法，甚至排斥医药治疗。这是错解了方法的意义。灵宝天尊赐下多种方法，"
+"正是因为众生根器不同、心疾不同、适合的方法也不同——方法是为人的需要而设，"
+"不是人为方法服务。如果某个方法修了一段时间感觉没有进展，不妨尝试另一个方法或组合方法。"
+"如果心疾已经严重到影响正常生活、出现自杀念头，不要犹豫立即寻求医学干预——"
+"道法不排斥医学，医学也可以与道法相辅相成。六是切忌\"恃法自傲\"——"
+"修了此经法，有了一点心得体会，就觉得自己的心疾比别人好、自己的方法比别人高、"
+"自己比别人有智慧。傲慢本身即是心疾（狂妄之疾）之一种精微表现——"
+"修法反而助长了另一种心疾，这是最为可惜之事。永远保持一颗谦卑的心——"
+"所修之法是灵宝天尊所赐，非自己之功劳；所得之进步是诸天尊护佑之力，非自己之能耐。"
+"七是切忌\"秘而不传\"——有些人得了效验却不肯告知他人，希望\"独享\"此法之利。"
+"这是小乘心态，与大乘道教普度众生之宗旨相违背。自己受益了，理应将此法推荐给其他有需要的人，"
+"造福更多的同病相怜者。这不是\"炫耀\"，而是\"分享\"——如一人从黑暗中发现了一盏灯，"
+"理应呼喊周围的同伴也到灯光中来。而且，越是分享、越是利他，自心的光明也越增长——"
+"赠人玫瑰手有余香，是之谓也。</p>"
+"<h2 style=\"color:#8b1a1a;border-bottom:2px solid #e8ddd0;padding-bottom:8px;font-size:22px;margin-top:28px;\">"
+"卷六 · 证验功德与究竟解脱</h2>"
+"<p style=\"line-height:2.2;\">"
+"<b>一、禳心修行证验十二征——行者自验是否进步：</b>"
+"灵宝天尊为令行者能够客观检验自己修行的进展程度，免于自欺或自疑，特开示证验十二征。"
+"此十二征分为身心二层：心层六征——即心理层面的改善迹象；身层六征——即身体层面的相伴改善。"
+"行者可据此自评，有则加勉，无则改进。心层第一征曰\"忧念减轻\"——从前终日忧心之事，"
+"如今虽然还会想到，但不再像从前那样控制不住地反复忧虑；能够对自己说\"我已经想了这个问题，"
+"现在不想了\"，而且能够做到\"真的不想\"。心层第二征曰\"睡眠改善\"——入睡时间缩短，"
+"夜间醒来次数减少，噩梦减少，晨起时感到精力有所恢复而非更加疲惫。睡眠是心神之镜——"
+"心神安则睡眠佳，睡眠佳则心神更安，良性循环就此建立。心层第三征曰\"脾气好转\"——"
+"从前一点小事就暴跳如雷，现在虽然还会生气，但\"爆炸\"的阈值提高了，发作的强度降低了，"
+"恢复的时间缩短了。能觉察到\"我在生气\"而不再被生气完全控制。心层第四征曰"
+"\"社交改善\"——从前因心疾而封闭自我、逃避社交，现在逐渐愿意与人交往，"
+"在人群中也能够相对放松，不再时刻觉得\"别人都在看我、都在评价我\"。"
+"心层第五征曰\"兴趣恢复\"——从前对一切都失去兴趣（抑郁之核心症状），"
+"现在对某些曾经的爱好重新燃起了热情——想看书了、想散步了、想听音乐了、想做饭了——"
+"这些都是生命力恢复的表现。心层第六征曰\"意义感回归\"——从前觉得人生毫无意义，"
+"现在隐约感到人生或许有某种自己尚未完全理解的意义；从前觉得活着没意思，"
+"现在至少愿意\"再等等看看\"。这个\"再等等看看\"极其重要——它是希望之萌芽，"
+"是在无意义感深井中找到的第一根绳索。身层第一征曰\"饮食改善\"——从前食不甘味，"
+"现在吃饭有了滋味；从前不思饮食，现在胃口渐开；从前暴饮暴食（借食解忧），"
+"现在食量回归正常。身层第二征曰\"体力恢复\"——从前稍微一动就疲惫不堪（心疾耗气所致），"
+"现在体力有所恢复，愿意动、能动了。身层第三征曰\"面色好转\"——从前面色萎黄晦暗（心神暗耗之象），"
+"现在面色渐渐红润、光泽重现。身层第四征曰\"头痛胸闷减轻\"——心疾最常见身体症状——"
+"胸闷如压石、头痛如紧箍——这些症状在修行之后逐渐减轻乃至消失。心疾之\"气\"郁结于胸，"
+"观心修行使气机通畅，胸闷随之缓解。身层第五征曰\"消化改善\"——从前因心疾而消化不良、"
+"胃痛腹胀、腹泻或便秘交替，现在消化系统趋于正常。此因心神安则脾胃和，脾主意心主神，"
+"心脾相生，心安则脾健。身层第六征曰\"旧病不药而愈\"——有些与心疾相关的身体疾病——"
+"如因长期焦虑引起的\"神经性皮炎\"、因长期抑郁引起的\"免疫力下降反复感冒\"、"
+"因长期恐惧引起的\"不明原因腰痛尿频\"——在修行有效之后不药而愈（或药物减量后亦能控制）。"
+"此即\"治心可达治身\"之明证——心为君主之官，君主安则百官称职，诸疾自愈。</p>"
+"<p style=\"line-height:2.2;\">"
+"<b>二、修行功德利益——禳心之福报：</b>"
+"修持此《禳心疾经》不仅可疗愈自身心疾，尚有诸多功德利益，灵宝天尊一一宣说如下。"
+"第一利益曰\"定力增长\"——通过长期观心无常之练习，行者的定力（专注力与稳定性）大幅增长，"
+"不仅有益于修道，亦有益于世间学业、事业——专注力强的人无论学什么做什么都事半功倍。"
+"此是因心疾而得修行，因修行而得定力，因定力而益世间——祸福转化不可思议。"
+"第二利益曰\"智慧开发\"——心疾者多善于内省，内省的习惯一旦与正法结合，"
+"即能产生超越常人之智慧。灵宝天尊说：\"曾经深度痛苦的人，一旦走出来，对人生之理解往往比"
+"一帆风顺之人深刻得多。\"此即\"知苦为道\"之后所开发之智慧——对人性有更深的理解，"
+"对生命有更真的感悟，对道有更切的体会。第三利益曰\"慈悲心生\"——自己经历过心疾之痛苦，"
+"对别人的痛苦就更加感同身受。从前或许是冷漠自利之人，修行此经之后，同情心与利他心自然增长。"
+"此即\"苦能生慈\"之义——受过寒冷的人更愿意给他人送去温暖。"
+"第四利益曰\"谦德养成\"——心疾使人深感自己的无力与渺小，打破昔日之傲慢。"
+"傲慢是修行之大敌，心疾反而成为对治傲慢的逆增上缘——经历心疾之人，"
+"往往比一帆风顺之人更加谦卑、更加懂得感恩、更加珍惜每一个平凡的日子。"
+"第五利益曰\"道缘增胜\"——修持此经者，与灵宝天尊结下深厚法缘，为来世继续修行种下善根。"
+"而且修行过程中，会有更多闻正法、遇明师、得善友的机缘自然出现——"
+"这就是\"道缘增胜\"的体现——不是你刻意去找，而是缘自己来找你。"
+"第六利益曰\"福泽眷属\"——个人修心禳疾，受益的不仅是自己。心疾痊愈之人，"
+"家庭关系随之改善——不再对家人无缘无故发脾气、不再因心疾而忽视家人之需求、"
+"不再以负面情绪感染全家。一个人变了，全家都因之而受益。这就是\"修一人而安一家\"。"
+"第七利益曰\"究竟解脱\"——最终极之功德利益，是\"道果\"——从根本上了断一切心病，"
+"不是\"压抑\"也不是\"转移\"，而是彻底看破、彻底放下、彻底清净。此时行者已经超越了心疾之层面，"
+"进入修道之正轨，向最终解脱（成仙了道）迈进。灵宝天尊说：\"此经名为《禳心疾》，"
+"然其最终目的非仅禳疾而已，而是以禳疾为契机引人入道。犹如以药引治标而诱人服补药之治本——"
+"先以禳心之法解除众生眼前心疾之苦，众生因切身受益而生信心，由信心而精进修道，"
+"由修道而究竟解脱。此灵宝天尊普度众生之善巧方便也。\"</p>"
+"<p style=\"line-height:2.2;\">"
+"<b>三、究竟说——心疾之终极超越：</b>"
+"灵宝天尊于经末慈悲宣说心疾之究竟超越，此为全经之最高义理、画龙点睛之笔。\""
+"一切心疾，究其根本，无非'执幻为实、认假为真'八个字而已。众生将无常变幻之心念执为真实，"
+"将刹那生灭之情绪视为永恒，将一个假设之'我'当成实体——于是幻中生幻，假中造假，"
+"无事生非，自寻烦恼。若论心疾之最根本治疗，唯有四字：'明心见性'。什么是明心？"
+"明心者，透彻地认知自心之运作机制——念头如何生灭、情绪如何起伏、执著如何产生、"
+"痛苦如何持续。这一切看得清清楚楚之后，心不再是谜团，而是可以理解的规律——"
+"从'我不知道自己为什么会这样'到'我明白了自己为什么会这样'——这就是'明心'。"
+"什么是见性？见性者，透过意识心之表象，见到意识心背后那个清净、不动、永恒之本性（或称元神、"
+"或称道性、或称真我）。此本性如虚空——虚空中可以有云来云去（念头生灭）、可以有风起风息（情绪变化）、"
+"可以有雷有雨（痛苦袭来），但虚空本身不因云来而增、不因云去而减，不因风起而动、不因风息而静，"
+"不因雷雨而伤、不因晴空而喜。见性之后，行者即以此本性为'我'，而不再以意识心之种种状态为'我'——"
+"这就是从根本上超越了心疾。灵宝天尊最后宣说四句究竟偈曰——'心本无疾，因执成病。"
+"观空遣执，本来清净。知苦即道，转识成智。明心见性，究竟解脱。'此四句偈，"
+"前两句揭示心疾之本质（心本无疾——心之本性清净无病，因执著故而成病），"
+"中间一句开示治心二法门（观空遣执——以观心无常破执著；知苦即道——以知苦为道转烦恼），"
+"最后一句指向究竟目标（明心见性——从根底上解脱一切心病）。行者若能参透此偈并依之修行，"
+"则一切心疾不治而治，一切烦恼不除而除。此即本经最核心、最精华、最究竟之奥义所在。\"</p>"
+"<p style=\"line-height:2.2;\">"
+"<b>四、流通分——嘱累传持：</b>"
+"灵宝天尊说此经已，十方无量仙众，闻经欢喜，皆大赞叹。救苦真人从座而起，顶礼天尊，"
+"白言：\"天尊慈悲，说此禳心疾无上妙法，利益无量众生。我等誓当护持此经，广为流布，"
+"令未来世间一切心病众生，得闻此法而获解脱。若有人至心持诵此经，依教奉行者，"
+"我等当率诸天神将，隐形守护其左右，令其修行无障、心疾速愈、道心坚固、早证道果。"
+"若有人诽谤此经、阻碍流布、或以之牟取私利者，我等当依律减其福算、加其病苦，"
+"令知敬畏，不敢轻法。\"灵宝天尊赞言：\"善哉善哉，汝等能发此护法大愿，"
+"功德不可思议。吾今以此经付嘱于汝，汝当善加守护，传于有缘，勿令断绝。"
+"未来世中，若有善男子善女人，闻此经名心生欢喜，受持读诵，如法修行，"
+"当知此人已于无始劫来种诸善根，非仅一世之修行。此人命终之后，不经地狱饿鬼畜生三途之苦，"
+"直生灵宝天尊座前，闻法修行，速得道果。若有医师、心理咨询师、社会工作者及一切以助人疗心为职业者，"
+"能读此经，依经之义指导求助者，虽其自身未必修行，而利他之心已与道合，"
+"亦获无量功德，命终之后生于善处，值遇正法。\"灵宝天尊说此语已，大众皆大欢喜，"
+"顶礼天尊，信受奉行，各还本处。此《太上洞玄灵宝天尊说禳心疾经》于是流通于三界十方，"
+"为一切心病众生之无上良药，亘古至今利益无量，至今犹为道门疗心之根本经典。</p>"
