+"<h2 style=\"color:#8b1a1a;border-bottom:2px solid #e8ddd0;padding-bottom:8px;font-size:22px;\">"
+"卷一 · 心疾本原</h2>"
+"<p style=\"line-height:2.2;\">"
+"<b>一、经题名义：</b>"
+"此经全称《太上洞玄灵宝天尊说禳心疾经》。\"太上\"者，至尊无上之号，表明此经为最高天尊金口亲宣，非凡俗之作。\"洞玄\"者，三洞之一，灵宝部之总称，灵宝天尊所主，"
+"以济度众生、禳灾解厄为宗。\"灵宝天尊\"者，道教三清之第二位尊神，居上清境禹余天上清宫，主司济度无量众生，大悲大愿与众生疾苦最为相应。"
+"\"说\"者，金口亲宣，遍告十方，非文字记录之谓，而是天尊于法会上当机开示。\"禳\"者，祈请解除、禳除灾患之义，道教禳法为消灾解厄之重要科仪。"
+"\"心疾\"者，非肉体心脏之器质性疾病，而是心灵、精神、情志层面之病患——忧虑、烦恼、恐惧、嗔怒、抑郁、躁狂、妄想、执著等一切心理精神之疾的总称。"
+"\"经\"者，常也、法也，亘古不变之真理，修道者所当依循之常法。合而释之：至尊无上之灵宝天尊，于清微天上为济度众生，金口亲宣此禳除心疾之无上妙法，"
+"令一切为心病所苦之众生依此修行，得以解脱烦恼、复归清净。此经蕴义甚深，涵盖道教对心灵疾病之完整认知与系统治疗方案，是道教\"道医\"体系中关于心理健康之最根本经典。</p>"
+"<p style=\"line-height:2.2;\">"
+"<b>二、说经因缘：</b>"
+"昔元始天尊于大罗天上七宝玄台说法之时，十方无量仙众围绕听法。忽有一真人从座而起，名曰\"救苦真人\"，稽首礼拜，白元始天尊言："
+"\"天尊在上，臣观世间众生，有种种心病烦恼——或忧思过度而精神恍惚，或恐惧不安而寝食俱废，或嗔怒炽盛而伤人害己，或悲哀欲绝而形销骨立，"
+"或痴迷执著而颠倒妄想，或躁动不宁而无片刻安。此等心疾，世间良医以药石针灸治之不能愈，以言语劝解开导不能解。众生因此心疾，"
+"辗转呻吟，生不如死，乃至轻生自弃者不可胜计。唯愿天尊慈悲，为诸众生说治心之无上妙法，令一切心病众生得闻此法而获解脱。\""
+"元始天尊告救苦真人言：\"善哉善哉，汝为众生发此大悲心。此治心禳疾之法，非我所说，乃灵宝天尊之专司。汝可往清微天上禹余宫中，"
+"启请灵宝天尊为汝及未来世间一切心病众生宣说此法。\"救苦真人承元始天尊之教敕，即与诸大众往诣清微天上禹余宫中，顶礼灵宝天尊，具述前缘。"
+"灵宝天尊默然良久，然后告言：\"汝等谛听，吾今为汝及未来世间一切心病众生，说此《禳心疾》无上妙法。此法甚深，不可思议，"
+"能令一切心病众生闻法即解、依教即愈。汝等当至心谛受，广为流布，勿令断绝。\"于是灵宝天尊于禹余宫中，放五色光明，出大音声，说此禳心疾经。</p>"
+"<p style=\"line-height:2.2;\">"
+"<b>三、心疾总论——何为心疾：</b>"
+"灵宝天尊告诸大众曰：\"心疾者，非一病也，乃百千种心病之总名。吾今为汝等一一分别，令知病相，然后知治病之方。\""
+"心疾在道教体系中，是指一切由心神失调所引发之病患。人之心神，本如明镜——朗照十方，无尘无垢，澄澈清净。"
+"然为七情六欲所扰、外缘内境所牵，明镜渐渐蒙尘，光明渐渐晦暗，于是种种心疾随之而生。心疾不同于身疾——"
+"身疾者，风寒暑湿、饮食劳倦所伤，病在皮肉筋骨脏腑血脉，良医以望闻问切四诊合参，以药石针灸推拿诸法可治。"
+"而心疾者，病在心神，无形无相，无影无踪，医者看不见摸不着，药石无法直接作用于心神，针灸无法刺入心灵深处——"
+"此所以寻常医术不能治心疾也。心疾之治，唯道可达。道者，宇宙之本体，生命之本源，心神之归宿。以道治心，"
+"犹如以清水洗尘镜——尘垢虽厚，清水能净；明镜虽蒙，本性不失。此即\"道医\"之义——以大道为医，治众生心病。</p>"
+"<p style=\"line-height:2.2;\">"
+"<b>四、心疾源流——从何而来：</b>"
+"心疾之来源，灵宝天尊说有三根本、六助缘。三根本者：一曰无明——不达道体，不识自性，于清净心中妄起分别，"
+"于平等法中妄生人我，于虚幻境中认假为真。此无明为一切心疾之总根源。二曰执著——于虚妄之法起实有想，"
+"于无常之境起恒常想，于无我之中起我我所想，执之不舍，如蚕作茧自缚其中。执著越深，心疾越重。"
+"三曰业力——从无始劫来，六道轮回中种种恶业积聚于心识田中，遇缘则发，如种子得水土而生芽。宿世所造杀盗淫妄等业，"
+"今世虽不记忆，然其负面能量潜伏于心，成为心疾之远因。六助缘者：一者外境逼迫——遭遇天灾人祸、贫困疾病、"
+"亲人亡故、事业挫折等外在打击，内心难以承受，引发心疾。二者人际关系——父子不和、夫妇反目、朋友背叛、"
+"上下欺凌，种种人事之冲突磨擦，令心不安。三者妄想纷飞——不待外缘，自心中妄念如流水般连绵不断，"
+"想过去、忧未来、计现在，一念未灭一念又生，终至心神疲惫。四者过度思虑——思虑本身非病，"
+"但思虑过度则伤神耗气。如学者穷研苦思、商人算计不休、官员权衡反复，思虑过度则失眠、健忘、烦躁、"
+"抑郁之疾随之而生。五者欲望炽盛——贪财、贪色、贪名、贪食、贪睡，五欲如火，愈烧愈旺，"
+"求之不得则忧，得之又患失之，患得患失之间心疾已深。六者不知调摄——不知劳逸结合、不知动静相宜、"
+"不知喜怒哀乐之节度，任情放纵、率性而为，久而久之，心神暗耗、心疾丛生。</p>"
+"<p style=\"line-height:2.2;\">"
+"<b>五、心疾九类分说：</b>"
+"心疾虽千变万化，然归纳之可分为九大类。灵宝天尊一一明示如下。第一类曰忧疾——忧者，虑也，愁也。"
+"忧疾之人，终日戚戚，眉头不展，心中如压巨石。或忧家道中落、或忧子女不成、或忧事业无成、或忧人言可畏。"
+"忧久则伤肺，肺伤则气短；忧久亦伤脾，脾伤则食少。忧疾最深者，虽处顺境亦常怀忧戚，所谓\"杞人忧天\"者是也——"
+"天本不塌而忧其塌，塌本无害于我而我先自苦。忧疾之根源在于对未来的不确定感过分放大，患得患失之心过重。"
+"第二类曰烦疾——烦者，躁也，乱也。心烦之人，坐立不安，心绪纷乱如麻，千头万绪纠缠不清。"
+"或烦家务琐事、或烦工作繁重、或烦人际纷扰、或烦环境嘈杂。烦久则伤肝，肝伤则易怒；烦久亦伤心，心伤则失眠。"
+"烦疾之特征在于\"剪不断、理还乱\"——明知多想无益而偏要想，明知求全责备不可能而偏要求。第三类曰恐疾——"
+"恐者，惧也，畏也。恐惧之人，心神不宁，如临深渊、如履薄冰。或恐生病、或恐死亡、或恐失业、"
+"或恐失爱、或恐鬼神、或恐雷電。恐久则伤肾，肾伤则腰酸尿频；恐久亦伤胆，胆伤则惊悸多疑。"
+"恐疾最深者，草木皆兵、杯弓蛇影，无事而自生恐怖。恐疾之根源在于对安全感的病态需求与对未知的过度恐惧。"
+"第四类曰嗔疾——嗔者，怒也，恚也。嗔怒之人，心火炽盛，一语不合则暴跳如雷，一事不顺则怒火中烧。"
+"嗔怒发作时气血上涌，面红耳赤，失去理智，出言伤人甚至动手毁物。嗔怒过后虽后悔，然下次遇缘又发，"
+"如此反复无止。嗔久则伤肝，肝伤则胁痛头晕；嗔久亦伤心，心伤则心悸胸痛。嗔疾之根源在于我执过重——"
+"以自我为中心，凡不顺我意者皆视为冒犯。第五类曰悲疾——悲者，哀也，痛也。悲哀之人，以泪洗面，"
+"心中创痛如刀割针刺。或因亲人亡故而悲不自胜，或因爱情破灭而哀毁骨立，或因事业失败而意气消沉。"
+"悲久则伤肺，肺伤则咳嗽气短；悲久亦伤心，心伤则怔忡健忘。悲疾最深者，虽悲伤之事已过去多年，"
+"仍然沉浸于悲伤之中无法自拔，如祥林嫂之反复诉说，旁人早已听厌而自己浑然不觉——此即\"悲结\"未解之故。"
+"第六类曰郁疾——郁者，结也，闷也。抑郁之人，心如死灰，对一切丧失兴趣，觉得人生无意义、无价值、无希望。"
+"抑郁不同于一般之悲伤——悲伤有具体对象，抑郁则弥漫无端；悲伤有宣泄之途，抑郁则闷在心中无法排遣。"
+"郁久则气滞血瘀，百病由此而生。郁疾之根源在于生命力受阻——如江河被壅塞，水流不通而发臭。"
+"郁疾患者需疏而非堵、导而非压。第七类曰痴疾——痴者，迷也，惑也。痴迷之人，或沉迷于某种嗜好无法自拔，"
+"如痴迷赌博倾家荡产、痴迷游戏荒废正业、痴迷色欲损身败德；或思想僵化执迷不悟，一种错误观念深入骨髓，"
+"他人百般劝说皆如耳旁风。痴久则伤脾，脾伤则思维迟钝；痴久亦伤肾，肾伤则意志消沉。"
+"痴疾之根源在于智慧未开、道眼未明，以假为真、以非为是。第八类曰狂疾——狂者，躁也，乱也。"
+"躁狂之人，精神亢奋，言语滔滔不绝，思维跳跃不定，行为冲动不计后果。或突然决定重大事项而不考虑风险，"
+"或挥霍钱财一掷千金而不计日后，或彻夜不眠精力充沛异常而后又突然崩溃。狂久则伤心，心伤则神不守舍；"
+"狂久亦伤肝，肝伤则魂不归位。狂疾之根源在于阴阳失衡——阳亢而阴不制之，如火无薪而自焚。"
+"第九类曰妄疾——妄者，虚也，假也。妄想之人，精神恍惚，或幻听幻视、或疑神疑鬼、或妄想自己是某位大人物、"
+"或妄想有人要害自己。妄想不同于一般之胡思——胡思乱想尚知自己在想，妄想则认假为真，完全失去现实感。"
+"妄久则伤肾，肾伤则精髓枯竭；妄久亦伤心，心伤则神明昏乱。妄疾之根源在于神不守舍——心神不能安住于本位，"
+"如主人离家而盗贼入室。以上九类心疾，或单独出现，或数类并存，或交替发作，"
+"灵宝天尊说此九类已经涵盖世间一切心病之大概。治此九类心疾各有侧重之法，然其总纲不外\"观心无常、知苦为道\"八字而已。</p>"
+"<p style=\"line-height:2.2;\">"
+"<b>六、心身不二——心疾与身疾之内在关联：</b>"
+"灵宝天尊特别开示：心疾与身疾并非二事，而是同一疾病之两个方面。道教心身一元论认为，形与神犹如烛与焰——"
+"烛为形、焰为神，烛尽则焰灭，形坏则神离。心疾必影响身体——忧烦伤肺，恐惧伤肾，嗔怒伤肝，"
+"悲哀伤肺，抑郁伤脾，痴迷伤心，躁狂伤肝，妄想伤肾。反之，身疾亦影响心神——久病卧床之人，"
+"最易产生恐惧、抑郁、烦躁等心病；疼痛之人，情绪多不稳定；气血虚弱之人，心神自然不宁。"
+"所以治心疾时不可忽视身体——饮食有节、起居有常、运动有度、劳逸结合，皆辅治心疾之必要条件。"
+"同理，治身疾时亦不可忽视心神——心态乐观、情绪稳定、神志清明之人，身体自愈能力远强于忧心忡忡之人。"
+"换言之：治心可治身，治身可辅心，心身同治方为最上乘之医道。此即《黄帝内经》所谓\"形与神俱\"\"精神内守病安从来\"之义也。</p>"
+"<p style=\"line-height:2.2;\">"
+"<b>七、药石之局限——为何药物不能治心疾：</b>"
+"灵宝天尊进一步阐明药石对心疾之局限，其义甚深。药物者，以草木金石之气味偏性，纠正人体阴阳气血之偏颇——"
+"寒者热之，热者寒之，虚者补之，实者泻之。此对于器质性病变确有良效。然心疾之根源在于\"神明\"层面——"
+"忧、烦、恐、嗔、悲、郁、痴、狂、妄，以上九疾之根本，非阴阳气血之偏颇（虽然必伴有此类偏颇），"
+"而是元神层面的污染与蒙蔽。药物可以暂时调节气血——如以镇静安神之药使狂躁者安静，以理气开郁之药使抑郁者舒畅——"
+"然这只是\"治标\"，未能触及心疾之根本。药力过后，原病复作，甚至需要不断加大剂量方能维持效果，"
+"终至药石罔效。更有一重原因：心疾之根源在于\"认知\"与\"执著\"——错误的思想、偏执的观念、无明的蒙蔽。"
+"这些属于\"智慧\"层面的问题，非药物所能改变。一个人若执著于\"天下人都要害我\"这一偏执妄想，"
+"即使服遍天下安神定志之药，此偏执妄想亦不会因此消除。故知：药石对于心疾，可以辅助而不可依赖，"
+"可以从标入手而不可作为根本。治心疾之根本在于\"道\"——以道之智慧破除无明，以道之方法净化心神，"
+"以道之力量化解执著。此即\"心病还须心药医，道力能消万劫疑\"之真义。</p>"
+"<p style=\"line-height:2.2;\">"
+"<b>八、历代心疾证案——印证道治之必要：</b>"
+"灵宝天尊列举自古以来以道治心之典型案例以坚听众信心。第一证案：古有居士姓张名平叔（即后世之紫阳真人张伯端），"
+"少年时博学多才而心高气傲，科举不第、仕途蹭蹬，遂患严重抑郁之疾——终日闭门不出、不思饮食、形容枯槁、"
+"数度欲自尽。遍求名医服药无数，皆不见效。后遇一道人——即刘海蟾祖师——与之言道，"
+"教以\"观心\"之法：每日静坐，观看自己心念之起灭，不加干涉、不加评判，任其来去如流水。"
+"张平叔依教修持，初坐时妄念纷飞如万马奔腾，坚持三月后妄念渐渐稀少，半载后心地豁然开朗，"
+"如云开日出、暗室燃灯。抑郁之疾不药而愈。此后张平叔精进修道，终成金丹大道一代宗师，"
+"著《悟真篇》传世。紫阳真人自身之经历，即是最有力之\"道治心疾\"证验。第二证案："
+"唐时有贵妇人王氏，因子夭折而悲痛欲绝，三年之中日日以泪洗面，渐至神志恍惚、哭泣不已、不分昼夜，"
+"家人以为疯癫。遍请名医百方无效。后请道士设坛诵《常清静经》，并授以\"知苦为道\"之法——"
+"教其观想天下母亲皆曾经历丧子之痛，此苦非自己一人独受；进而观想苦本身即是道之显现，"
+"苦中蕴藏觉悟之机。王氏依教修持，逐渐从悲痛中走出，三月后不再哭泣，半载后恢复如常，"
+"更因经历此苦而豁然看破生死，晚年出家修道，终成正果。第三证案：宋时一书生姓陈，"
+"因怀才不遇而终日愤懑不平，见人富贵则嫉妒，见人得志则嗔恨，心中如火焚烧，以致失眠、头痛、口苦、"
+"目赤，群医束手。后读《道德经》\"知足者富\"\"知足不辱\"之语，突然醒悟：昔日之苦非他人所致，"
+"乃自己贪求无厌之心所造；从此改变心态，知足常乐，不再比较攀缘。一年之后诸症悉消，"
+"不仅心病痊愈，身体亦恢复健康。以上三案足证——心疾非药石能治，唯道可医。道医之道，"
+"不在草木金石，而在智慧光明、在心性修持、在觉悟解脱。</p>"
+"<h2 style=\"color:#8b1a1a;border-bottom:2px solid #e8ddd0;padding-bottom:8px;font-size:22px;margin-top:28px;\">"
+"卷二 · 观心无常法</h2>"
+"<p style=\"line-height:2.2;\">"
+"<b>一、观心无常——治心疾之第一法门：</b>"
+"灵宝天尊说：\"心疾万端，治之匪易。然有一法，能治一切心疾——此法名曰'观心无常'。汝等谛听，吾为详说。\""
+"\"观心无常\"四字，乃此经之核心法门，其义甚深，其用甚广，其效如神。四字分解如下："
+"\"观\"者，内观、觉照、省察之意，非以肉眼看，乃以智慧眼向内观照自心之状态。\"心\"者，"
+"非指心脏之肉团，乃指能思能虑能忧能喜之意识心，及此意识心背后之清净本性。\"无常\"者，"
+"变化不居、刹那生灭、无有常住之意。合而言之——以智慧向内观照，如实了知自心之一切状态（忧、烦、恐、嗔、悲、郁、痴、狂、妄）"
+"皆是无常变化的，不执着于任何一种心境，不认任何一种心境为\"我\"。此法看似简单，实则力量巨大——"
+"一切心疾之所以能折磨人，皆因患者\"执着\"于当前之负面心境，以为此心境真实不虚、永久不变、代表\"我\"之全部。"
+"一旦通过\"观心无常\"之修持，切实体证到\"这一切都会过去、这一切都不是真实的我\"，则心疾自然失去其控制力。</p>"
+"<p style=\"line-height:2.2;\">"
+"<b>二、观心无常之四重观法：</b>"
+"第一重观曰\"观念无常\"——观照心中念头、思绪、情感之生生灭灭。修行者于静坐中或日常生活中，细心观察自心之一切活动："
+"一个念头生起，不久即灭；另一个念头生起，又灭。忧念生起，持续片刻，被杂念打断；忧念再生，又被其他念头替代。"
+"如此反复观察，修行者会发现：原来\"我\"的忧郁并非一个固定的实体，而是一连串\"忧念\"的相续生灭。"
+"当修行者不再把这些相续生灭的忧念认同为\"我\"时，忧郁的力量便大大减弱。如同坐在河边看流水——"
+"水流不断，但我不是水流，我只是观水者。念头如水流，来者自来、去者自去，而\"观者\"始终清净不动。"
+"此即《清静经》\"能遣之者，内观其心，心无其心\"之真义——内观自心时，发现所谓\"心\"不过是一串无常变化之念头而已，"
+"并无一个固定不变之\"心\"可得。第二重观曰\"观受无常\"——观照心中感受、情绪之苦乐变化。心中的感受如同天气——"
+"有时晴空万里（快乐），有时乌云密布（忧郁），有时狂风暴雨（愤怒），有时细雨蒙蒙（惆怅）。但无论何种天气，"
+"天空本身始终不变。修行者学会区分\"情绪\"与\"觉知情绪的那个觉知\"——情绪是无常变化的，"
+"而觉知本身是稳定的。当负面情绪来时，不抗拒、不逃避、不沉溺；只是如实观察：\"哦，忧郁来了。\""
+"\"哦，愤怒来了。\"\"哦，忧郁正在变化。\"\"哦，忧郁正在消散。\"以旁观者的态度看待自己的情绪，"
+"不与之认同，则情绪的杀伤力大幅降低。第三重观曰\"观身无常\"——观照身体感受与心疾之关联。"
+"心疾发作时身体必有反应——忧郁时胸闷气短、焦虑时手心出汗心跳加速、愤怒时面红耳赤肌肉紧张。"
+"修行者学习观察这些身体感受，发现它们也是无常变化的——胸闷过一会儿可能减轻，出汗过一会儿可能停止。"
+"身体感受的无常性进一步印证了心疾的无常性——连身体层面的反应都会过去，何况心理层面的感受？"
+"第四重观曰\"观我无常\"——观照\"我执\"本身之虚妄。心疾患者常有强烈之\"我执\"——\"我病了\"\"我痛苦\"\"我活不下去了\"\"没人理解我\"。"
+"修行者深入探究：这个\"我\"究竟是什么？是身体？身体每分每秒都在新陈代谢变化之中，十年前的身体跟今天的身体已完全不同。"
+"是思想？思想更是刹那变化，早上这样想，下午那样想。是情绪？情绪更是变化无常。"
+"逐一审查，竟找不到一个固定的、不变的、独立的\"我\"可以执著。既然\"我\"尚且无常不可得，"
+"则依附于\"我\"之上的\"我的心疾\"又如何能够常存？此观最为锋利——直破\"我执\"之根本，"
+"令一切心疾失去所依。</p>"
+"<p style=\"line-height:2.2;\">"
+"<b>三、观心无常之静坐实修九步：</b>"
+"灵宝天尊授予具体实用的静坐观心方法，分为九个步骤，修行者可循序渐进。第一步：择地择时——择一安静不受打扰之室，"
+"每日清晨（卯时5-7时）或夜晚（亥时21-23时）为最佳修持时段。初始每日十五分钟即可，逐步增至半小时乃至一小时。"
+"第二步：调身——端坐于椅或蒲团之上，脊柱自然竖直不可僵硬挺直，头正颈松，下颌微收，眼微闭，"
+"两手相叠置于小腹之前（左手在下右手在上，大拇指轻轻相触），舌抵上腭（即\"搭鹊桥\"以通任督二脉），"
+"全身放松，从头顶到脚底逐一放松——松眉头、松牙关、松肩膀、松胸背、松腰腹、松腿脚。"
+"第三步：调息——鼻吸鼻呼，深长细匀而自然，不可憋气，不可急促。初习者可先数呼吸——"
+"吸气时心中默念\"一\"，呼气时默念\"二\"，如此\"一二、一二\"地数，令心神逐渐安定。"
+"数息约三至五分钟后，心已稍静，即可进入下一步。注意：数息只是为了静心之方便，不是目的；"
+"心一旦稍静，即放下数息，进入正观。第四步：观念——注意力轻轻放在\"心中念头之生灭\"上。"
+"不要刻意寻找念头，也不要刻意压制念头。念头来时，知道\"念头来了\"；念头去时，知道\"念头去了\"。"
+"不跟随念头——不顺着念头想下去；不抗拒念头——不试图把念头赶走。只是如实地\"看\"着念头来去，"
+"如同一个旁观者。如果发现自己在跟随念头（即已经开始顺着某个念头深入思考），立刻觉察\"哦，我跟进去了\"，"
+"然后轻轻将注意力拉回\"观察者\"的位置。初习时可能每几秒就被念头带走一次，这是正常的，不要沮丧；"
+"每次觉察到被带走就轻轻回来，日积月累功夫自然纯熟。第五步：观受——当静坐中感受到某种情绪浮现时——"
+"可能是焦虑、可能是烦躁、可能是无聊、可能是平静——将注意力从\"念头\"转向\"情绪感受\"。"
+"给情绪\"标注\"——不是用语言评判它，而是默默识别它：\"这是焦虑\"\"这是烦躁\"\"这是无聊\"。"
+"然后观察这个情绪在身体上的表现——焦虑时胸口是什么感觉？烦躁时肩膀是什么感觉？无聊时呼吸是什么变化？"
+"你会发现：所有情绪都伴随着身体感受，而身体感受本身也是无常变化的。第六步：观身——"
+"将注意力逐一扫描全身各部位，从头到脚，感受每一个部位的冷暖、松紧、轻重、麻胀。"
+"如果某个部位有特别明显的感觉（如胸闷、头痛、肩紧），就在那个部位多停留一会儿，"
+"单纯地\"感受\"那种感觉而不加评判。你可能会发现：很多负面情绪其实就是这些身体感觉加上\"我不喜欢这个感觉\"的判断。"
+"如果去掉\"我不喜欢\"的判断，单纯地\"感受\"身体感觉本身——其实并没有那么难受。第七步：观我——"
+"在心中默默问自己三个问题：\"感觉到这些念头的'我'在哪里？\"\"觉知到这些情绪的'我'是什么？\""
+"\"当我观察念头和情绪时，'观察者'本身可以被观察到吗？\"不要试图用思维回答这些问题——"
+"问题本身就像一把利剑，斩断一切思维缠绕。在问完问题之后的沉默中，保持觉知，答案会自己显现。"
+"这个\"答案\"不是语言文字的答案，而是一种\"豁然洞明\"的直接体验——原来没有一个固定的\"我\"，"
+"\"我\"只是心识流动的一个假名而已。第八步：回光——当静坐接近尾声时，不要猛然起座。"
+"先轻轻将意识从内在观照中收回，慢慢地动一动手指、脚趾，慢慢地搓一搓手使手掌发热，"
+"以热手搓揉面部（从下往上）、双耳、后颈，然后缓缓睁开双眼——先看近处地面，再慢慢看远处。"
+"静坐完毕之后，保持静坐中那份\"觉知\"的心态进入日常生活——走路时觉知自己在走路，"
+"吃饭时觉知自己在吃饭，说话时觉知自己在说话。这种在日常生活中保持觉知的状态，称为\"动中定\"，"
+"是比静坐中定力更为重要之功夫——静中修得十分定力，动中能有一分算是功夫。第九步：日常行持——"
+"除每日固定静坐外，修行者当在日常生活中随时运用\"观心无常\"之法。每当感到忧烦恐嗔悲郁等负面情绪来袭时，"
+"立刻在心中默念\"这是无常的\"，然后以一个呼吸的时间（约五六秒）暂停一切言语行动，"
+"单纯地感受当下一刻的呼吸，将注意力从\"被情绪控制\"切换到\"观察情绪\"。这个简单的操作——"
+"\"暂停+观察\"——往往能在关键时刻阻止坏情绪的蔓延与恶化。如驾驶汽车时发现即将追尾而紧急刹车——"
+"\"观心无常\"就是一念之间的\"心理刹车\"。</p>"
+"<p style=\"line-height:2.2;\">"
+"<b>四、观心无常之递进四阶——从初学至深悟：</b>"
+"灵宝天尊开示观心无常法门修持过程中经历四个阶段，学者可据此自验修持之深浅次第，莫自欺亦莫自疑。"
+"第一阶曰\"见念\"——初修之时，不观不知道，一观吓一跳：原来自己的心这么乱！念头纷飞如瀑布，"
+"一个接一个几乎没有间隙。以前不观心时不觉得，现在一观才发现自心居然如此喧嚣混乱。"
+"初次\"见念\"者往往会有挫败感——\"我怎么越修越退步了？心反而更乱了？\"其实这是极大的误解——"
+"不是心更乱了，而是因为你开始\"看见\"心了。以前心乱而不知道心乱，现在知道心乱了，这就是进步的第一步。"
+"灵宝天尊特别告诫：见此情景莫退初心——恰如浑浊之水，以前一直搅动不停，故看不到泥沙；"
+"现在停止搅动了，方见泥沙翻腾——这恰是水将澄清之前兆。继续静观，泥沙终将沉淀，清水终将显现。"
+"第二阶曰\"间隙\"——修持有日之后，念头与念头之间的\"间隙\"开始出现。从前念头密不透风如瀑布连绵；"
+"现在瀑布之中开始出现\"空档\"——此念已灭、彼念未生之间的那个短暂的\"空白\"。这个空白起初可能只有半秒一秒，"
+"但已经足够让修行者瞥见：原来心还有\"无念\"的状态！这一瞥极其重要——它打破了\"心永远在乱\"的错误认知，"
+"给了修行者继续修下去的信心。随着功夫加深，此间隙越来越长、越来越清晰，修行者可以在间隙中体验到一种"
+"深层的宁静——不同于昏沉或空白，而是一种清醒而空旷的觉知状态。第三阶曰\"即照即空\"——"
+"功夫进一步深化，修行者发现：不必等念头过后才感知其无常，而是在念头刚起之时即已\"看透\"它是无常的、是无我的；"
+"因为看透了，所以不再被念头牵着走。就像防火技术高明之人——火星刚起即刻觉察而熄灭，不待其燎原。"
+"此时修行者的心态较之从前已有质的改变——从前是\"被情绪控制\"，现在是\"情绪出现但无法控制我\"。"
+"忧念仍会出现，但不再是\"我忧郁了\"，而是\"有一个忧念出现了\"——\"我\"与\"忧念\"之间拉开了距离。"
+"这个\"距离\"是心理健康与心理疾病的根本分界线。第四阶曰\"寂照同时\"——最高阶段，"
+"修行者再无心疾之困扰，非谓\"念头永不生起\"，而是念头虽有生灭而觉照如如不动；"
+"犹如明镜照物——物来则现、物去则空，明镜本身不增不减。此即灵宝天尊所说\"心无其心，物无其物，"
+"空无所空，寂无所寂\"的境界。至此观心无常法门已经圆满，修行者从根本上超越了心疾——"
+"不是\"战胜\"了心疾（战胜意味着对抗，对抗本身即是紧张），而是\"看破\"了心疾（看破意味着理解，理解带来释然）。"
+"此即观心无常法门之究竟妙用——不治而治，不除而除。</p>"
+"<h2 style=\"color:#8b1a1a;border-bottom:2px solid #e8ddd0;padding-bottom:8px;font-size:22px;margin-top:28px;\">"
+"卷三 · 知苦为道法</h2>"
+"<p style=\"line-height:2.2;\">"
+"<b>一、知苦为道——转烦恼为智慧之无上心法：</b>"
+"灵宝天尊说：\"观心无常能令行者出离心病之缠缚，然犹有更深一层法要——名曰'知苦为道'。若只会'出离'而不会'转化'，"
+"则心病虽去，智慧未开；若能转烦恼为智慧，则不仅心病痊愈，更可因祸得福、因疾成道。\"知苦为道\"四字，"
+"是道教对人生苦难之最正面、最积极之态度。\"知\"者，如实体认、深切理解；\"苦\"者，不仅指心疾之苦，"
+"泛指人生一切痛苦、挫折、磨难、不幸；\"为\"者，转化、成为；\"道\"者，觉悟之路、解脱之门。"
+"合而言之：如实认知痛苦之本质，将痛苦转化为觉悟之资粮，使痛苦成为通向解脱之道路。此即老子所谓\"祸兮福之所倚\"——"
+"看似灾祸，其中蕴藏福报；看似苦难，其中藏有道机。灵宝天尊特别强调：心疾之苦，如果只是被动承受，"
+"则苦上加苦，纯为不幸；如果能主动转化，以苦为镜、以苦为师，则苦非苦也，乃道之助缘。</p>"
+"<p style=\"line-height:2.2;\">"
+"<b>二、苦之本质——灵宝天尊说苦谛：</b>"
+"灵宝天尊首先开示苦之本质，令行者对\"苦\"有一根本性的正确认知，方能在此基础上转苦为道。"
+"第一义：苦是生命之常态而非异常。众生无不在苦中——生苦、老苦、病苦、死苦、爱别离苦、怨憎会苦、求不得苦、"
+"五阴炽盛苦。八苦交煎，无一人能免。心疾之苦只是此八苦中\"求不得苦\"\"五阴炽盛苦\"\"怨憎会苦\"等苦之具体表现。"
+"认清这一点很重要——你不是\"唯独你受苦\"的那个不幸者，你是与一切众生共同受苦的众生之一。"
+"这个认知可以破除\"我是天底下最不幸之人\"的偏执，使心量从狭隘的自我中打开。第二义：苦从何来？"
+"苦之根源在于\"渴爱\"与\"执著\"——渴求欢愉而欢愉不长久，故苦；执著自我而自我不可得，故苦；"
+"追求永恒而一切无常，故苦。心疾之苦尤其如此——抑郁症患者执著于\"我应该快乐\"而快乐不来，"
+"故焦虑抑郁；焦虑症患者执著于\"一切都要在掌控中\"而世界不可控，故焦虑。苦的根源不在外境，"
+"而在内心之渴爱与执著——这一点认知至关重要，因为它意味着：虽然外境不可改变，"
+"但内心之渴爱与执著是可以改变的——苦之根源是可以消除的。第三义：苦有\"逼迫苦\"与\"转化苦\"之区别。"
+"逼迫苦是被动承受的苦——苦来了，你只能忍受，毫无自主权，苦中无希望、无光明、无出路——这是凡夫之常态。"
+"转化苦是主动面对的苦——苦来了，你以它为老师、为镜子、为磨刀石，从苦中学习、成长、升华——"
+"这是修行者的态度。同样的苦，被动承受是地狱，主动转化是道场。犹如同样一块铁矿石——"
+"凡夫视之为废石弃之不顾，智者以高温冶炼之而得精钢。心疾之苦犹如铁矿石，修\"知苦为道\"法者犹如冶炼之智者。</p>"
+"<p style=\"line-height:2.2;\">"
+"<b>三、知苦为道五重转化次第：</b>"
+"灵宝天尊细说转苦为道之五个层次递进，行者依此次第修持，可将心疾之苦逐步转化直至究竟解脱。"
+"第一重转化曰\"认苦\"——从逃避转为面对。心疾患者之第一反应往往是逃避：忽视它、否认它、麻醉它。"
+"有人以工作麻醉自己——拼命工作以忘记烦恼；有人以娱乐麻醉自己——不停刷手机看视频以逃避孤独；"
+"有人以药物酒精麻醉自己——借酒浇愁、借药安眠。种种逃避之法皆属\"鸵鸟政策\"——"
+"头埋进沙堆以为自己看不见危险，其实危险依然存在。知苦为道第一重要之步骤即是从逃避转为面对："
+"不再逃跑，转身直面自己的痛苦。大胆地对自己说：\"是的，我抑郁了。\"\"是的，我很焦虑。\"\"是的，我很愤怒。\""
+"这个\"承认\"本身就是巨大力量的开始——犹如失眠者一旦放弃\"我必须睡着\"的执念，反而很快入睡。"
+"第二重转化曰\"观苦\"——从\"我是受苦者\"转为\"我观苦\"。一般受苦者之心态是：\"我\"和\"苦\"合为一体——"
+"\"我忧郁\"\"我焦虑\"\"我痛苦\"，完全认同于苦。转\"知苦为道\"的行者则将\"我\"与\"苦\"拉开距离——"
+"不是\"我忧郁\"，而是\"忧郁正在发生\"；不是\"我是焦虑的人\"，而是\"此刻焦虑正在经过我的心\"。"
+"这个微妙的语言改变反映的是根本的心态转变——从\"我就是苦\"到\"我观察到苦\"。此即运用前述\"观心无常\"之功夫，"
+"但此处特别强调以\"苦\"为观照对象。修行者于每次心疾发作时，不以\"我很苦\"之心态沉溺其中，"
+"而以\"有个苦正在发生，我来观察它\"之心态退后一步观察。第三重转化曰\"问苦\"——主动向苦提问。"
+"当焦虑来临时，平和地问它：\"焦虑，你想告诉我什么？\"\"焦虑，你从哪里来？\"\"焦虑，你希望我做什么？\""
+"当抑郁来临时，平和地问它：\"抑郁，你为何缠着我？\"\"抑郁，你背后隐藏着什么？\""
+"不要带着对抗的情绪问，而是像医生问病人、老师问学生那样带着关怀与好奇心问。灵宝天尊说："
+"'苦'不是你的敌人，'苦'是你生命中那个用粗暴方式提醒你的信使。\"每一种心疾背后，"
+"都可能隐藏着一个长期被忽视的\"内在需求\"——焦虑可能提示你对自己要求过高、活得太累；"
+"抑郁可能提示你生活中的某些重要方面已被长期忽略、需要调整；愤怒可能提示你的边界被侵犯、"
+"需要学会保护自己。听懂\"苦\"的语言，你就能化苦为宝。第四重转化曰\"谢苦\"——"
+"进一步以感恩之心面对痛苦。这一步极为高深——一般人只会对快乐感恩，对痛苦只有怨恨。"
+"而知苦为道者则能更进一步：感谢痛苦。因为正是痛苦让你警醒——如果没有痛苦，你可能会在错误的生活轨道上越走越远；"
+"正是痛苦逼迫你走上修道之路——如果没有痛苦，你可能会在红尘享乐中虚度一生，永远不会去想\"人生到底是怎么回事\"。"
+"灵宝天尊特别指出：古今多少修道有成者，其入道之因缘正是心疾之苦——"
+"紫阳真人因抑郁而修道，白玉蟾因失意而寻仙，吕洞宾因科举不第而入终南。如果没有当时的\"苦\"，"
+"就没有后来的\"道\"。如此看来，苦实为道之逆增上缘——以反面方式推你一把，让你走上正途。"
+"第五重转化曰\"化苦\"——最终将痛苦完全转化为道力与智慧。\"化\"不同于\"消灭\"——消灭是对立的、暴力的；"
+"化是融合的、自然的。犹如冰化为水——冰与水外观不同而本质相同，只需加温即可融化。"
+"苦与乐也是如此——苦与乐本质皆是心之波动，苦只是冻结的乐，乐只是融化的苦。修行到极深处，"
+"冰即是水、水即是冰，苦即是乐、乐即是苦，二者不再有对立分别。此时行者面对一切境界——"
+"顺境逆境、苦境乐境——皆能平等对待，心中不起分别执著。此即庄子所谓\"安时而处顺，哀乐不能入也\"——"
+"不是没有哀乐，而是哀乐来去自如，不再能进入内心深处扰动平静。到达此境，知苦为道法门即臻圆满。</p>"
+"<p style=\"line-height:2.2;\">"
+"<b>四、转九疾为九慧——对治法要：</b>"
+"灵宝天尊进一步将九种心疾与九种智慧一一对应，开示\"转疾为慧\"之具体对治方法。行者可依自身所患之疾，"
+"选修对应之慧，此为\"对症修道\"之法——犹如良医对症下药，比泛泛修行更为直接高效。"
+"第一：忧疾转\"预智\"——忧虑者过多思虑未来之不确定，其心虽有百害，亦有一利：思虑周密、善于规划。"
+"若能将忧虑之中\"过度恐惧\"的成分剥离，保留\"前瞻思考\"的能力，则忧疾可转为\"预智\"——"
+"未雨绸缪、防患未然之智慧，此乃圣人之智，非庸人之忧。第二：烦疾转\"敏智\"——烦躁者心思活跃、"
+"反应敏捷，对周围环境中之琐碎事物皆能敏锐察觉。若能将烦躁之中\"躁动不安\"的成分剥离，"
+"保留\"敏锐感知\"的能力，则烦疾转为\"敏智\"——洞察幽微、明察秋毫之智慧。第三：恐疾转\"慎智\"——"
+"恐惧者格外重视安全、敬畏危险，其警惕性与防备意识远高于常人。若能将恐惧之中\"杯弓蛇影\"的成分剥离，"
+"保留\"谨慎小心\"的能力，则恐疾转为\"慎智\"——如临深渊如履薄冰、敬小慎微之智慧。第四：嗔疾转\"勇智\"——"
+"嗔怒者气血旺盛、行动力强、不甘受辱。若能将嗔怒之中\"伤害他人\"的成分剥离，"
+"保留\"强烈正义感与行动力\"的能力，则嗔疾转为\"勇智\"——见义勇为、不畏强暴、护法伏魔之智慧。"
+"第五：悲疾转\"慈智\"——悲哀者感受深刻、富有同情心，能体会他人之痛苦。若能将悲哀之中\"无力自拔\"的成分剥离，"
+"保留\"感同身受\"的能力，则悲疾转为\"慈智\"——大悲悯众生、愿代众生受苦之智慧。第六：郁疾转\"深智\"——"
+"抑郁者内向沉思、深度思考，常触及人生之根本问题（如意义、价值、生死）。若能将抑郁之中\"丧失活力\"的成分剥离，"
+"保留\"深度思考\"的能力，则郁疾转为\"深智\"——探究宇宙人生根本真理之智慧。第七：痴疾转\"专智\"——"
+"痴迷者专注力极强，一旦投入某事则全神贯注，不受外界干扰。若能将痴迷之中\"执迷不悟\"的成分剥离，"
+"保留\"极度专注\"的能力，则将痴疾转为\"专智\"——制心一处、无事不办之智慧。第八：狂疾转\"逸智\"——"
+"躁狂者思维奔逸、联想丰富、不拘一格、创意泉涌。若能将躁狂之中\"失控\"的成分剥离，"
+"保留\"思维活跃与创造力\"的能力，则狂疾转为\"逸智\"——天马行空、创意无穷、逍遥自在之智慧。"
+"第九：妄疾转\"妙智\"——妄想者超越现实之限制，在精神世界中自由驰骋。若能将妄想之中\"脱离现实\"的成分剥离，"
+"保留\"超越常轨思维\"的能力，则妄疾转为\"妙智\"——不可思议、出人意表、妙契道真之智慧。"
+"灵宝天尊总结：\"九疾即九慧，非二物也。犹如同一块璞玉——就其含石而言是瑕疵，就其内玉而言是珍宝。"
+"识得此理，则心疾非但不足为患，反而成为修道之资粮、开慧之工具。此即'烦恼即菩提'之真义也。\"</p>"
+"<p style=\"line-height:2.2;\">"
+"<b>五、知苦为道之困境突破：</b>"
+"灵宝天尊慈悲，预知行者修行此\"知苦为道\"法门时必然遭遇内在与外在之双重困境，故预先开示突破之法。"
+"第一困境：\"理论我都懂，但就是做不到。\"头脑理解\"知苦为道\"之道理，但每次痛苦来袭时依然沉溺其中、"
+"无力转化——此为修行者最常见之困境。灵宝天尊开示：此非能力不足，而是功夫不熟。犹如学习游泳——"
+"在岸上讲一万遍理论，下水时仍然手忙脚乱。解决之道在于反复练习——每次痛苦来临时，哪怕只有一秒钟做到了"
+"\"观察而不是沉溺\"，就是一次胜利。积少成多，久而久之反应模式自然改变。切莫因一次做不到就全盘否定自己——"
+"你已经在改变的路上了，只是需要一个过程。第二困境：\"转苦为道之后，别人说我冷血无情。\""
+"当修行者不再如从前那样情绪激烈时，身边亲友可能感到不适——\"你以前为我伤心欲绝，现在怎么这么平静？"
+"你是不是不爱我了？\"灵宝天尊开示：平静不是冷血，正如同深潭之表面平静而底下蕴藏巨大能量。"
+"修行者的\"平静\"是对自己情绪的驾驭能力增强了，不是对他人冷漠了。以平静之心关爱他人，"
+"比以焦虑之心关爱他人更为有力——焦虑者之关爱往往夹杂控制，平静者之关爱才是纯粹的给予。"
+"第三困境：\"转化不了怎么办？特别是痛苦太深太重的时候。\"灵宝天尊开示：痛苦太深之时，"
+"不必强求\"转化\"。可以暂时回到\"观心无常\"法门——不强求转化，只是观察。如同重伤之人，"
+"不必急于下床锻炼，先卧床静养等待伤口愈合。太深的痛苦需要一个\"被允许存在\"的阶段——"
+"允许自己痛苦、允许自己暂时做不到转化、允许自己需要一个过程。这个\"允许\"本身就是一种转化——"
+"从\"我与痛苦对抗\"转化到\"我允许痛苦存在\"，对抗的张力一旦消失，痛苦本身的强度也会下降。</p>"
+"<h2 style=\"color:#8b1a1a;border-bottom:2px solid #e8ddd0;padding-bottom:8px;font-size:22px;margin-top:28px;\">"
+"卷四 · 道医禳心符咒法诀</h2>"
+"<p style=\"line-height:2.2;\">"
+"<b>一、禳心符箓总论——灵宝禳心九符：</b>"
+"灵宝天尊说：\"观心无常与知苦为道，此二法为治心疾之内修根本。然众生根器不同——有上根者可纯以内观而得愈，"
+"有中下根者需内外兼修、以符咒辅之方能奏效。故吾今传禳心符箓九道，与内修配合，如鸟之双翼、车之两轮，"
+"相辅相成，效益倍增。\"禳心九符，依九种心疾各制一道灵符，每符配合特定咒语与存思方法，"
+"专治对应之心疾。制符之法统摄如下：择甲子日、庚申日、三元日或本命日之清晨（日出前后半个时辰内），"
+"于静室之中面东而立，叩齿三十六通，存想灵宝天尊现金色身于面前虚空——高一丈六尺，"
+"顶有圆光如日轮，身着九色离罗之帔，手持碧玉拂尘，面容慈悲含笑。存想清楚后，"
+"取朱砂一钱以自身舌尖血三滴调和（取血前须以净水漱口三遍），以新笔蘸之，书符于黄素绢上。"
+"书符时屏息凝神，一气呵成，不可中断，不可与他人言语。符成之后折叠为三角形，以五色丝线系之，"
+"悬于胸前膻中穴位置，日夜不离身（沐浴时暂取）。符若日久破损，择吉日焚化于净炉中，灰撒清流，"
+"再依前法新制。以下逐一宣说九道禳心灵符之具体法式。</p>"
+"<p style=\"line-height:2.2;\">"
+"<b>二、第一符——禳忧清心符：</b>"
+"专治忧疾（过度忧虑、多思多愁、杞人忧天）。符形长方（象\"安\"字之基），中央朱书一\"安\"字，"
+"\"安\"字之上以云篆书\"无忧\"二字，左书\"心\"右书\"宁\"，符胆书\"乐\"字。配合咒语曰："
+"太上台星，应变无停。驱除忧虑，还我清宁。心神安泰，智慧光明。三魂永久，魄无丧倾。急急如律令。\""
+"此咒共三十二字，取八八六十四卦之半数——半者未满，忧疾即因未满而忧，故以半数之咒对治之。"
+"诵咒配合存思：闭目观想自身心中有一片阴沉乌云（象征忧虑），灵宝天尊从虚空中以拂尘轻轻一拂，"
+"乌云即刻转为白云，白云渐散现出蓝天，蓝天之中日出东方，光芒万丈——心中的一切忧愁随乌云消散殆尽。"
+"此符咒每日早晚各诵七遍（应北斗七星，七星为运转之枢纽，忧疾亦因心之\"运转\"失调，故以七星数调之），"
+"诵时手掐\"寅\"诀（寅为木旺之时，主生发舒畅之气，对治忧之收敛郁结），诵毕以鼻深吸气一口，"
+"意想吸入金色光明（灵宝天尊之法气），缓缓呼出灰色浊气（心中之忧浊）。坚持四十九日为一个周期。</p>"
+"<p style=\"line-height:2.2;\">"
+"<b>三、第二符——禳烦定心符：</b>"
+"专治烦疾（心烦意乱、坐立不安、思绪纷乱）。符形六角（象雪花——雪落无声，取其宁静之意），"
+"中央朱书一\"静\"字，\"静\"字周围以云篆环书\"心澄意净万念归空\"八字，符胆书\"寂\"字。配合咒语曰："
+"灵宝天尊，安慰心神。千烦万扰，一化微尘。意如止水，心似明灯。内外澄澈，烦恼不侵。急急如律令。\""
+"此咒三十二字配符形六角——三十二暗合四八之数（四季配八卦），六角应六合，总摄一切空间之烦扰归于宁静。"
+"存思配合：闭目观想自身心中如一团乱麻（千头万绪纠缠不清），灵宝天尊手指间放出一道清凉如月光之白光，"
+"白光射入心中乱麻，白光所照之处乱麻自然解开，一根一根理顺，最终整齐如经线排列。"
+"诵咒每日午时（中午11-1时，阴阳交替之时，最易心烦，故择此时诵之最利）及子时（夜11-1时，一阳来复之时）"
+"各诵九遍（九九八十一，乃阳数之极，足以克制一切阴邪烦扰）。手掐\"午\"诀（午为火旺，以火之阳刚克心中阴柔之烦乱）。"
+"又：烦疾患者宜于书桌或工作之处贴此符一张（以黄纸朱书，不必用血和朱砂，朱墨即可），面对此符工作，"
+"烦乱来时可暂息片刻注视符中\"静\"字，心神即能归位。</p>"
+"<p style=\"line-height:2.2;\">"
+"<b>四、第三符——禳恐安神符：</b>"
+"专治恐疾（恐惧不安、惊悸多疑、缺乏安全感）。符形五芒（象星——北极星为众星之中、不动不摇，象征安住），"
+"中央朱书一\"镇\"字，\"镇\"字之上以云篆书\"无畏\"二字，下书\"安\"字，符胆书\"定\"字。配合咒语曰："
+"北方黑帝，太微之精。镇我心神，安我魂灵。百邪不侵，万鬼遁形。身如金刚，心若太清。急急如律令。\""
+"此咒配合黑帝（北方之帝，主肾，肾藏志，志强者不恐），故以北方黑帝为护法神。存思配合："
+"闭目观想自身被一团温暖金光笼罩，金光之外四方各立一尊护法神——东立青童君，南立赤精君，"
+"西立皓灵君，北立玄冥君——四神各高一丈，威严不动，守护四方，一切恐惧之源皆被挡在金光之外无法靠近。"
+"每日早晚各诵二十一遍（三七之数），诵时手掐\"子\"诀（子为水旺，水主肾，肾强则恐惧自消）。"
+"又：恐疾患者在睡梦中尤其恐惧（噩梦、惊悸、盗汗等），可将此符悬于床头，配合睡前服\"禳恐符水\"——"
+"以净水一碗，焚此符化灰入水，以指尖蘸水点眉心（天目穴）、膻中穴、手心劳宫穴、脚心涌泉穴各三滴，"
+"然后饮下剩余之水三分之一，余水洒于卧室四角。此法甚验，尤其对于噩梦恐惧及不明原因之夜间惊悸。</p>"
+"<p style=\"line-height:2.2;\">"
+"<b>五、第四符——禳嗔平气符：</b>"
+"专治嗔疾（易怒暴躁、心火炽盛、伤人害己）。符形四方（象大地之平正——地能含藏万物而不怒，"
+"可以此为镜平息自心之怒火），中央朱书一\"忍\"字，\"忍\"字乃心上一把刀——刀悬于心上而不落，"
+"即是\"忍\"之功夫。\"忍\"字之下以云篆书\"息怒\"二字，符胆书\"平\"字。配合咒语曰："
+"南方赤帝，制伏火星。怒火顿息，清凉自生。血气和顺，肝木不焚。柔和忍辱，道气长存。急急如律令。\""
+"存思配合：闭目观想自身胸中一团熊熊烈火（象征嗔怒），灵宝天尊从净瓶中倾出一股清凉甘露，"
+"甘露浇于烈火之上，火势逐渐减弱熄灭，余烬之上长出青青绿草，一片清凉境界。"
+"每日午时（火旺之时，以火制火）诵十二遍（十二应地支，主一年十二月天天用忍）。手掐\"巳\"诀"
+"（巳为火之临官位，以火制火——犹如以兵止兵）。又：此符之\"忍\"字有一特殊修法——"
+"当嗔怒即将爆发时，即刻以右手食指在左手掌心虚写此符一遍（不需要纸笔墨，空气书写即可），"
+"然后握紧左拳，以右手拇指按住左手虎口（合谷穴），心中默诵咒语三遍，深呼吸三次——"
+"嗔怒之火往往在此十秒之内被压下去。待冷静之后再思考问题，会理性许多。此即\"急时急救法\"，"
+"虽不能根治嗔疾，然可避免因一时冲动而酿成不可挽回之恶果，故极为实用。</p>"
+"<p style=\"line-height:2.2;\">"
+"<b>六、第五符——禳悲舒郁符：</b>"
+"专治悲疾与郁疾（二疾往往相伴而生——悲久则郁，郁久则悲，故合用一符而分两种存思法）。"
+"符形椭圆（象满月——月有阴晴圆缺，悲郁如月缺，修此符则如月由缺而复圆），中央朱书一\"舒\"字，"
+"\"舒\"字左\"舍\"右\"予\"——舍者放下也，予者给予也；放下悲郁，给予自己新的可能。"
+"以云篆书\"天朗气清\"四字环绕于\"舒\"字四周，符胆书\"畅\"字。配合咒语曰："
+"西方皓灵，太白之精。扫除阴霾，舒我郁情。悲结解散，心月复明。惠风和畅，万类向荣。急急如律令。\""
+"存思配合有二：针对悲疾——闭目观想自身心中一片凄风苦雨（象征悲伤），灵宝天尊放出红日一轮，"
+"红日温暖之光芒普照心中，风雨顿息，彩虹出现，大地回春，百花齐放。针对郁疾——闭目观想自身心中"
+"一片冰封湖面（象征抑郁——生命力被冻结），灵宝天尊放出春日暖阳，冰面渐渐融化，"
+"化为春水，水中有鱼游动（生命力恢复之象），湖边长出新绿。每日酉时（下午5-7时，日落之时，"
+"悲郁之人最易在此刻加重病感，故择此最难受之时修法最能对治）诵十四遍（二七之数，"
+"二七十四乃满月之后一日，月虽稍缺而圆光犹在，象征悲郁虽在而希望未远）。手掐\"申\"诀"
+"（申为金旺，金主肺，悲忧伤肺故以金制之，此为\"以其道还治其身\"之法）。"
+"又：悲郁患者宜同时配合\"行善法\"——每日刻意行一小善（帮助别人做一件事、说一句温暖的话、"
+"捐一点小钱、拣起路上垃圾），不为积德，只为在行善的过程中\"给予\"，\"给予\"本身即是\"舒\"——"
+"舍予之间，郁结自解。此符之外行法虽简，然与符咒配合效益更佳。</p>"
+"<p style=\"line-height:2.2;\">"
+"<b>七、第六符——禳痴开慧符：</b>"
+"专治痴疾（执迷不悟、愚痴暗钝、智慧不开）。符形三角（象△——乃\"火\"之形，火主光明，"
+"光明能破黑暗，智慧能破愚痴），中央朱书一\"觉\"字，\"觉\"字从\"學\"省而见——学习而后能见真理是为觉。"
+"\"觉\"字以云篆书\"破迷开悟\"四字环绕，符胆书\"慧\"字。配合咒语曰："
+"天尊说经，开我智门。破除迷暗，朗照乾坤。真实不虚，了了分明。智慧如海，万法皆通。急急如律令。\""
+"存思配合：闭目观想自身头中一片黑暗（象征愚痴无明），灵宝天尊于虚空中放出一道极白极亮之光，"
+"从头顶百会穴灌入，光在脑中如明灯照亮暗室——黑暗角落一一被照亮，尘埃蜘蛛网（错误观念与执著）"
+"一一暴露无遗。光由脑向下照亮全身五脏六腑四肢百骸，通体光明透亮，一切暗昧尽除。"
+"每日寅时（凌晨3-5时，寅为一日之始、阳气初生，此时头脑最为清醒，诵此符最易开慧）诵九遍。"
+"手掐\"卯\"诀（卯为日出之时，正如智慧之日出破暗昧）。又：痴疾患者多因\"不闻正法\"而迷——"
+"故除修此符外，还须多读道经以增长正见、多参明师以开示正路、多自反省以觉察迷执。"
+"符咒是助缘，正见是根本，二者缺一不可。灵宝天尊特别寓示：\"执迷最深者，常是聪明人——"
+"聪明人易陷于自己构造之理论体系而不能自拔。故'痴疾'非愚者之病，乃聪明人之陷阱。"
+"破此痴疾，不需更聪明，而需放下聪明——此即'绝圣弃智'之真义。\"</p>"
+"<p style=\"line-height:2.2;\">"
+"<b>八、第七符——禳狂归元符：</b>"
+"专治狂疾（躁狂亢奋、精神失控、行为失度）。符形圆形（象太极——太极圆转，阴阳平衡，狂疾乃阴阳失衡之症），"
+"中央朱书一\"和\"字，\"和\"字左\"禾\"右\"口\"——禾者谷物，口者言语，谷物入腹而生和气，"
+"躁狂之语化为平和之言。\"和\"字以云篆书\"阴阳和合\"四字环列上下左右四方，"
+"符胆书\"均\"字（均者平衡也）。配合咒语曰："
+"太极圆转，阴阳均衡。躁火下降，真水上腾。龙虎交媾，铅汞合并。狂心顿歇，复归清宁。急急如律令。\""
+"存思配合：闭目观想自身中有一股烈火从下向上冲（象征躁狂之火上炎），"
+"同时有一股清泉从头顶向下灌溉（灵宝天尊以净瓶之水灌顶），水火在胸中\"黄庭\"（中丹田位置）"
+"交汇——水火交融，化为温热之气（不寒不热之中和之气），这股中和之气向全身扩散，"
+"四肢百骸皆得中和之滋养。狂躁之火得真水而降，冰凉之身（狂后抑郁之象）得真火而温，"
+"阴阳重归平衡。每日午时与子时各诵九遍（子午乃阴阳交替之二时辰，狂疾乃阴阳失调之症，"
+"故于二时诵之最为对症），手掐\"辰\"诀（辰为龙，龙能大能小能升能降——修此符亦当学龙之自在变化，"
+"该升则升该降则降，不偏不倚，是谓中和）。又：狂疾发作期不宜强行静坐——越压抑越反弹。"
+"此时宜以\"动中求静\"——缓慢散步配合深呼吸，行步时默诵咒语，手掐辰诀，步伐不急不缓，"
+"一步一呼吸。如此行持半小时至一小时，亢奋之气自然渐渐平息。此即\"以动制动\"之妙法。</p>"
+"<p style=\"line-height:2.2;\">"
+"<b>九、第八符——禳妄还真符：</b>"
+"专治妄疾（妄想幻觉、脱离现实、精神恍惚）。符形八角（象八卦——八卦为天地万物之基本秩序，"
+"妄想乃偏离秩序之思维，以八卦复其秩序），中央朱书一\"真\"字，\"真\"字以云篆书\"返妄归真\"四字环绕，"
+"\"真\"字四角各书一\"正\"字（四正镇四方），符胆书\"实\"字。配合咒语曰："
+"八卦列位，四正分明。邪思退散，正念归心。虚者返实，假者还真。精神内守，神明自清。急急如律令。\""
+"存思配合：闭目观想自身心神如一团散乱的萤火虫（游移不定不能集中），灵宝天尊放出一颗明珠——"
+"大如鸡卵，光明圆润——悬于心窝正中，明珠之光如磁石吸引萤火，散乱的萤火一一向明珠归附，"
+"最终凝结为一团稳定而明亮的光球，整个身心由此安稳。每日卯时（日出时，阳升而阴降，"
+"取\"正大光明\"之气）和酉时（日落时，阳降而阴升，取\"收摄归元\"之气）各诵三十六遍"
+"（三十六乃天罡之数，天罡为北斗之柄，能正一切不正），手掐\"寅\"诀（寅为三阳开泰，"
+"阳气充足则阴邪妄想不能干）。又：妄疾多与睡眠障碍相伴——睡眠不足则神不守舍，"
+"妄念乘虚而入。故治妄疾必须同时调理睡眠：睡前以热水泡脚至微微出汗（引火下行），"
+"然后坐于床上，以此符悬于床头，默诵咒语二十一遍，诵毕以右手掌心按于右脚涌泉穴，"
+"左手掌心按于左脚涌泉穴，各按揉三十六圈（顺逆各半），然后躺下，侧卧（右侧卧为佳——"
+"左手自然置于左胯、右手屈肘托右侧面颊，双腿微屈，即\"吉祥卧\"），心念系于呼吸。此法坚持七日，"
+"睡眠质量必有明显改善，睡眠一好，妄想自然减少大半。</p>"
+"<p style=\"line-height:2.2;\">"
+"<b>十、第九符——禳心总符：</b>"
+"前列八符各治一疾，此第九符为\"禳心总符\"——总治一切心疾，兼有预防保健之功。"
+"无病者可佩之以防心病，有病者可与对症之符合用以增效力。符形九叠云篆（九为阳数之极，"
+"叠为符箓之密——非画符之\"画\"，而是九重云篆重叠而成，如九重天叠加），中央为一大\"道\"字，"
+"\"道\"字分九层环绕：第一层\"清\"、第二层\"静\"、第三层\"定\"、第四层\"慧\"、第五层\"安\"、"
+"第六层\"和\"、第七层\"明\"、第八层\"宁\"、第九层\"真\"——此九字合为\"清静定慧安和明宁真\"，"
+"乃禳治一切心疾之九字真言。总符配合总咒曰："
+"灵宝天尊，大慈大悲。九字真言，禳心妙谛。清净定慧，安和明宁。一切心疾，化为微尘。"
+"神清气爽，智慧圆明。道气长存，万病不侵。急急如太上灵宝天尊律令敕。\""
+"此咒共五十六字，暗合七八之数（七月七日乃灵宝天尊圣诞后第七日之相关吉日），取义圆满。"
+"存思配合：闭目观想灵宝天尊立于面前虚空中——高一丈六尺，通体放出九色光明（赤橙黄绿青蓝紫黑白）——"
+"九色光明如九道彩虹，一一从行者顶门贯入，充盈全身。每一道光对应一个心疾的消除——"
+"赤光消忧愁，橙光消烦躁，黄光消恐惧，绿光消悲郁，青光消嗔怒，蓝光消痴迷，紫光消躁狂，"
+"黑光消妄想，白光总消一切心病及根本无明。九光入体后融合为一团金色光球在丹田中缓慢旋转，"
+"温暖舒适，光明润泽。此光球即是\"道种\"——日后一切修行皆从此道种生根发芽。"
+"每日不拘时诵此总咒二十一遍（三七之数），手掐\"子\"诀（子为十二支之首，象征一切修行之起点，"
+"万法皆从子起）。此符可与他符合用——先诵总符总咒以奠定气场，再诵对症符咒以精确疗愈。"
+"总符为体，分符为用，体用兼备，方为完整。</p>"
+"<p style=\"line-height:2.2;\">"
+"<b>十一、禳心符水——内外兼修之妙法：</b>"
+"符力虽强，若能配合符水服用，则效力倍增——符为外力加持，水为内服入体，"
+"内外夹攻，病邪无所遁形。禳心符水之制用方法统摄如下：取清晨井华水一碗（或山泉水、"
+"矿泉水，不可用自来水——自来水有化学添加，不利符力之发挥），置于静室南面案上。"
+"焚檀香或降真香三炷（一达三清、二达诸真、三达司命），向水碗诵对症之咒七遍，诵时存想"
+"灵宝天尊手执杨柳枝，蘸净瓶甘露洒入水碗——甘露入水，水中放出柔和金光。诵毕，"
+"取对症灵符一道，以左手剑诀夹符，于香上顺时针绕三匝（借三香真火之力净化加持），"
+"然后焚化于水碗之上，令符灰尽入水中不可散落碗外。以右手剑诀指向碗中水，再诵咒一遍作最后加持。"
+"然后取解——先以左手三山诀托碗，以右手剑诀蘸符水，洒于自身：一洒百会（头顶正中），"
+"二洒天目（眉心），三洒膻中（两乳之间），四洒气海（脐下一寸三分），五洒至阳（后背与膻中对应之处）。"
+"洒毕，取碗中符水三分之一缓缓饮下——不宜一饮而尽，宜三口咽下（一口应上元天官、"
+"二口中元地官、三口下元水官）。咽时存想所咽之水化为金光，从食道入胃再渗透全身。"
+"剩余符水洒于室内四角及门口（由内向外洒，令病气从此门出不复入）。此法每七日行一次——"
+"太过频繁反而耗气，七天一次恰到好处，配合日常诵咒持符，连续七个七次（即四十九日），"
+"各项心疾应有显著好转。若四十九日后仍旧无改善，当反省三点：一者至诚心可足？二者持符期间可曾犯戒？"
+"三者是否边治边造——一面修符水一面放纵旧习？对症改之，再行一个四十九日周期。</p>"
