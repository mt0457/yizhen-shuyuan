寅月（正月）：立春雨水，余寒凛冽。虽名为春，实则寒凝未解。调候以丙火为首，解冻回春。丙火如初春之阳，虽微而生机已动。甲木以癸水润根，丙癸并透为上。庚金以丙火暖局，丙甲并透为佳。壬水以庚金发源，庚丙并透为贵。此月所生，首重火之暖局。

卯月（二月）：惊蛰春分，阳和日暖。余寒渐消，木气正旺。调候以火泄秀为主，水润为辅。甲木以庚金斫削为主，丙火泄秀为次。乙木以丙癸并济。庚金以丁火炼金。壬水以庚金发源。此月所生，重在木火通明。

辰月（三月）：清明谷雨，辰土当权。木有余气而土已进气，湿土当权。调候首重润土——壬癸水润泽辰土为急。甲以庚壬并透为上，庚金制木，壬水润土。乙以癸水为首。丙以壬甲并济。此月所生，重在润土。

巳月（四月）：立夏小满，火炎土燥。丙火临官，火势已旺。调候以水为第一急务。甲木癸水润根，庚金生水。丙火壬水既济。戊土癸水调候。辛金壬水淬炼。此月所生，无水则万物焦枯。

午月（五月）：芒种夏至，火旺之极。丁火帝旺，烈火熊熊。调候用水最为急迫。甲木癸水为尊。丙火壬庚为要。戊土壬癸等润。辛金壬癸淬炼。壬水庚癸发源。此月所生，无水即夭。

未月（六月）：小暑大暑，火土燥烈。未为燥土又为火之余气。调候以壬水为急。甲木先壬后庚。乙木癸丙并济。庚金壬水淬炼。丁火甲壬为要。此月所生，润土为第一。

申月（七月）：立秋处暑，金神司令。庚金当权。秋气初至，余暑未消。调候以水火并济。甲木丁火制金。丙火甲木生扶。庚金丁火炼金。壬水戊土堤防。此月所生，重在制金护木。

酉月（八月）：白露秋分，金旺之极。辛金当权。秋高气爽，寒凉渐生。调候以火暖局又需水泄金。甲木丙丁为先。乙木丁癸并济。丙火甲木为要。庚金丁丙锻炼。此月所生，火为尊神。

戌月（九月）：寒露霜降，戌土当权。燥土司令，金有余气。调候以润土为先，暖局次之。甲木先壬后庚。乙木癸水润泽。庚金壬水淘洗。丁火甲庚为要。此月所生，重在壬水润土。

亥月（十月）：立冬小雪，水冷木寒。壬水当权。冬气已至，天地寒凝。调候以火为第一急务。甲木庚丁为要。乙木丙火暖局。丙火甲木生扶。庚金丙火解冻。壬水戊丙为要。此月所生，无火则寒。

子月（十一月）：大雪冬至，水旺之极。癸水当权。天寒地冻，一阳初生。调候以火为最急。甲木先丁后庚。乙木丙火为尊。丙火甲木为先。庚金丙丁为要。壬水戊丙并济。此月所生，丙火为宝。

丑月（十二月）：小寒大寒，丑土当权。湿土司令，金水皆寒。调候以火暖局解冻为先。丙火为尊，丁火次之。甲木丙丁庚并透为上。乙木丙火为先。庚金丙丁为要。此月所生，得火则生，无火则死。

