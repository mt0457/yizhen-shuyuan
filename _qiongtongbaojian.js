《穷通宝鉴》原名《栏江网》，清代余春台据明代手抄本整理编纂。此书专论五行调候，以十干配十二月，逐月论其喜忌用神，为八字命理调候派之最高经典。与《滴天髓》《渊海子平》《三命通会》并称命学四大经典。

