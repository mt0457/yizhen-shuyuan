<b>元始天尊，大慈大悲。说此禳厄，广度群迷。九厄八难，各有法持。符咒斋醮，经功善德。至心修诵，厄难冰释。变灾为祥，转祸为福。夭者得寿，病者得康。贫者得富，讼者得和。一切厄中，悉得解脱。皈命元始天尊大慈悲父。皈命太上洞真元始天尊说禳命厄经法。皈命十方三界一切传经演教度人无量天尊。不可思议功德。志心称念，禳厄解灾天尊，福生无量天尊。</b>
