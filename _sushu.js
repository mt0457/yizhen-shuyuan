汉司马迁《史记·太史公自序》:"运筹帷幄之中，制胜于无形，子房计谋其事。无知名，无勇功，图难于易，为大于细。"

宋司马光《资治通鉴》论留侯:"张良为汉谋臣，运筹决胜，功最高。然未尝有战斗功，高帝自择齐三万户，良愿封留足矣。及天下已定，托于神仙，弃人间事，此其明哲保身之术，非独功成不居而已。"

宋真德秀《大学衍义》:"留侯一生得力在一忍字。方其狙擊秦皇，匹夫之勇耳。及圯上老人折辱之，于是变刚为柔，化锐为钝，而帝师之业成矣。夫忍之一字，岂独留侯终身行之？古今天下成大事者，未有不从忍中来也。"

明王守仁《传习录》论子房:"子房之智，非独在于谋略也，更在于知进退存亡而不失其正。功成身退，天之道也。子房能之，故曰人杰。"

清曾国藩《求阙斋读书录》:"余读《素书》，叹其言简而旨远。张良以此佐汉高成帝业，而终能超然远引，免于韩、彭之祸。盖不独得用世之略，更得全身之道也。《素书》曰:畏危者安，畏亡者存。留侯有焉。"

清王夫之《读通鉴论》:"张良之智，不为天下先而能应天下之变。其学出于黄老，而能以柔道御天下。汉高之兴，良之功为多。然功成之后，托于仙游，是能以道自全者。"

现代钱穆《国史大纲》论张良:"张良为汉初三杰之一，其功在于运筹帷幄，非战阵之劳。观其少年狙秦，意气慷慨；壮年佐汉，谋略深沉；晚年辟谷，超然物外。一生变化如此，非深于道家之学，安能至此？黄石公所授，盖即道家处世用世之秘要也。"

