素书·求人之志章第三

绝嗜禁欲，所以除累。抑非损恶，所以禳过。贬酒阙色，所以无污。避嫌远疑，所以不误。博学切问，所以广知。高行微言，所以修身。恭俭谦约，所以自守。深计远虑，所以不穷。亲仁友直，所以扶颠。近恕笃行，所以接人。任材使能，所以济务。殚恶斥谗，所以止乱。推古验今，所以不惑。先揆后度，所以应卒。设变致权，所以解结。括囊顺会，所以无咎。橛橛梗梗，所以立功。孜孜淑淑，所以保终。

