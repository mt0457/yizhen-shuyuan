素书·正道章第二

德足以怀远，信足以一异，义足以得众，才足以鉴古，明足以照下，此人之俊也。行足以为仪表，智足以决嫌疑，信可以使守约，廉可以使分财，此人之豪也。守职而不废，处义而不回，见嫌而不苟免，见利而不苟得，此人之杰也。

