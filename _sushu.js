素书·本德宗道章第四

夫志心笃行之术：长莫长于博谋，安莫安于忍辱，先莫先于修德，乐莫乐于好善，神莫神于至诚，明莫明于体物，吉莫吉于知足。

本德宗道，君子之行也。本德者，以德为本，以仁为根，以义为干，以礼为枝，以智为叶，以信为花，以诚为实。宗道者，以道为宗，以天为法，以地为则，以时为序，以变为通。故曰：道德仁义礼，五者一体也。

夫道者，人之所蹈也。蹈道而行者，天下归心。德者，人之所得也。得德而守者，万物自宾。仁者，人之所亲也。亲仁而爱者，众皆悦服。义者，人之所宜也。行义而宜者，功必成矣。礼者，人之所履也。履礼而敬者，名必立矣。

君子知五者之要，则天下可得而理矣。不知五者之要，则身不能保，国不能治。故曰：欲修其身者，先正其心。欲正其心者，先诚其意。欲诚其意者，先致其知。致知在格物。物格而后知至，知至而后意诚，意诚而后心正，心正而后身修，身修而后家齐，家齐而后国治，国治而后天下平。此谓本德宗道之序也。

素书·遵义章第五

以明示下者暗，有过不知者蔽，迷而不返者惑，以言取怨者祸，令与心乖者废，后令缪前者毁，怒而无威者犯，好众辱人者殃，戮辱所任者危，慢其所敬者凶，貌合心离者孤，亲谗远忠者亡，近色远贤者昏，女谒公行者乱，私人以官者浮，凌下取胜者侵，名不胜实者耗。

略己而责人者不治，自厚而薄人者弃。以过弃功者损，群下外异者沦。既用不任者疏，行赏吝色者沮，多许少与者怨，既迎而拒者乖。薄施厚望者不报，贵而忘贱者不久。念旧恶而弃新功者凶，用人不正者殆，强用人者不畜，为人择官者乱，失其所强者弱，决策于不仁者险，阴计外泄者败，厚敛薄施者凋。

战士贫而游士富者衰，货赂公行者昧。闻善忽略、记过不忘者暴。所任不可信、所信不可任者浊。牧人以德者集，绳人以刑者散。小功不赏，则大功不立。小怨不赦，则大怨必生。赏不服人、罚不甘心者叛。赏及无功、罚及无罪者酷。听谗而美、闻谏而仇者亡。能有其有者安，贪人之有者残。

素书·安礼章第六

怨在不舍小过，患在不预定谋。福在积善，祸在积恶。饥在贱农，寒在惰织。安在得人，危在失士。富在迎来，贫在弃时。上无常操，下多疑心。轻上生罪，侮下无亲。近臣不重，远臣轻之。自疑不信人，自信不疑人。枉士无正友，曲上无直下。危国无贤人，乱政无善人。

爱人深者求贤急，乐得贤者养人厚。国将霸者士皆归，邦将亡者贤先避。地薄者大物不产，水浅者大鱼不游，树秃者大禽不栖，林疏者大兽不居。山峭者崩，泽满者溢。

弃玉取石者盲，羊质虎皮者辱。衣不举领者倒，走不视地者颠。柱弱者屋坏，辅弱者国倾。足寒伤心，民怨伤国。山将崩者下先隳，国将衰者人先弊。根枯枝朽，民困国残。

与覆车同轨者倾，与亡国同事者灭。见已往，慎将来，察其始，知其终。见已生者慎将生，恶其迹者预避之。畏危者安，畏亡者存。夫人之所行，有道则吉，无道则凶。吉者百福所归，凶者百祸所攻。非其神圣，自然所钟。

务善策者无恶事，无远虑者有近忧。同志相得，同仁相忧，同恶相党，同爱相求，同美相妒，同智相谋，同贵相害，同利相忌，同声相应，同气相感，同类相依，同义相亲，同难相济，同道相成，同艺相窥，同巧相胜。此乃数之所得，不可与理违。

释己以教人者逆，正己以化人者顺。逆者难从，顺者易行，难从则乱，易行则理。如此理身、理家、理国，可也。

