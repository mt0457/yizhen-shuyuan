留侯张良者，其先韩人也。大父开地，相韩昭侯、宣惠王、襄哀王。父平，相厘王、悼惠王。悼惠王二十三年，平卒。卒二十岁，秦灭韩。良年少，未宦事韩。韩破，良家僮三百人，弟死不葬，悉以家财求客刺秦王，为韩报仇，以大父、父五世相韩故。

良尝学礼淮阳。东见仓海君。得力士，为铁椎重百二十斤。秦皇帝东游，良与客狙击秦皇帝博浪沙中，误中副车。秦皇帝大怒，大索天下，求贼甚急，为张良故也。良乃更名姓，亡匿下邳。

