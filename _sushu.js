《黄石公记》，又称《黄石公三略》，与《素书》同出黄石公名下。分上略、中略、下略三卷。兹录其要：

夫主将之法，务揽英雄之心。赏禄有功，通志于众。故与众同好靡不成，与众同恶靡不倾。治国安家，得人也。亡国破家，失人也。含气之类，咸愿得其志。

《军谶》曰：柔能制刚，弱能制强。柔者德也，刚者贼也。弱者人之所助，强者怨之所攻。柔有所设，刚有所施，弱有所用，强有所加。兼此四者而制其宜。

端末未见，人莫能知。天地神明，与物推移。变动无常，因敌转化。不为事先，动而辄随。故能图制无疆，扶成天威，匡正八极，密定九夷。如此谋者，为帝王师。

故曰：莫不贪强，鲜能守微。若能守微，乃保其生。圣人存之，动应事机。舒之弥四海，卷之不盈怀。居之不以室宅，守之不以城郭。藏之胸臆，而敌国服。

《军谶》曰：能柔能刚，其国弥光。能弱能强，其国弥彰。纯柔纯弱，其国必削。纯刚纯强，其国必亡。

夫为国之道，恃贤与民。信贤如腹心，使民如四肢，则策无遗。所适如支体相随，骨节相救。天道自然，其巧无间。

军国之要，察众心、施百务。危者安之，惧者欢之，叛者还之，冤者原之，诉者察之，卑者贵之，强者抑之，敌者残之，贪者丰之，欲者使之，畏者隐之，谋者近之，谗者覆之，毁者复之，反者废之，横者挫之，满者损之，归者招之，服者居之，降者脱之。

获固守之，获厄塞之，获难屯之。获城割之，获地裂之，获财散之。敌动伺之，敌近备之，敌强下之，敌佚去之，敌陵待之，敌暴绥之，敌悖义之，敌睦携之。顺举挫之，因势破之，放言过之，四网罗之。

得而勿有，居而勿守，拔而勿久，立而勿取。为者则己，有者则士，焉知利之所在。彼为诸侯，己为天子。使城自保，令士自取。

世能祖祖，鲜能下下。祖祖为亲，下下为君。下下者，务耕桑不夺其时，薄赋敛不匮其财，罕徭役不使其劳。则国富而家娱，然后选士以司牧之。

夫所谓士者，英雄也。故曰：罗其英雄，则敌国穷。英雄者，国之干。庶民者，国之本。得其干，收其本，则政行而无怨。

夫用兵之要，在崇礼而重禄。礼崇则智士至，禄重则义士轻死。故禄贤不爱财，赏功不逾时，则下力并而敌国削。夫用人之道，尊以爵，赡以财，则士自来。接以礼，励以义，则士死之。

夫将帅者，必与士卒同滋味而共安危，敌乃可加。故兵有全胜，敌有全因。昔者良将之用兵，有馈箪醪者，使投诸河，与士卒同流而饮。夫一箪之醪，不能味一河之水，而三军之士思为致死者，以滋味之及己也。

《军谶》曰：军井未达，将不言渴。军幕未办，将不言倦。军灶未炊，将不言饥。冬不服裘，夏不操扇，雨不张盖。是谓将礼。与之安，与之危，故其众可合而不可离，可用而不可疲。以其恩素蓄，谋素和也。故曰：蓄恩不倦，以一取万。

《军谶》曰：将之所以为威者，号令也。战之所以全胜者，军政也。士之所以轻战者，用命也。故将无还令，赏罚必信。如天如地，乃可御人。士卒用命，乃可越境。

夫统军持势者，将也。制胜破敌者，众也。故乱将不可使保军，乖众不可使伐人。攻城则不拔，图邑则不废。二者无功，则士力疲弊。士力疲弊，则将孤众悖。以守则不固，以战则奔北。是谓老兵。兵老则将威不行。

将无虑则谋士去，将无勇则吏士恐，将妄动则军不重，将迁怒则一军惧。《军谶》曰：虑也、勇也，将之所重。动也、怒也，将之所用。此四者，将之明诫也。

《军谶》曰：军无财，士不来。军无赏，士不往。《军谶》曰：香饵之下，必有悬鱼。重赏之下，必有死夫。故礼者，士之所归。赏者，士之所死。招其所归，示其所死，则所求者至。故礼而后悔者，士不止。赏而后悔者，士不使。礼赏不倦，则士争死。

《军谶》曰：兴师之国，务先隆恩。攻取之国，务先养民。以寡胜众者，恩也。以弱胜强者，民也。故良将之养士，不易于身。故能使三军如一心，则其胜可全。

《军谶》曰：用兵之要，必先察敌情。视其仓库，度其粮食，卜其强弱，察其天地，伺其空隙。故国无军旅之难而运粮者，虚也。民菜色者，穷也。千里馈粮，民有饥色。樵苏后爨，师不宿饱。夫运粮百里，无一年之食。二百里，无二年之食。三百里，无三年之食。是国虚。国虚则民贫，民贫则上下不亲。敌攻其外，民盗其内。是谓必溃。

《军谶》曰：将谋欲密，士众欲一，攻敌欲疾。将谋密则奸心闭，士众一则军心结，攻敌疾则备不及设。军有此三者，则计不夺。将谋泄则军无势，外窥内则祸不制，财入营则众奸会。将有此三者，军必败。

将无虑则谋士去，将无勇则吏士恐，将妄动则军不重，将迁怒则一军惧。虑也、勇也，将之所重。动也、怒也，将之所用。

夫高鸟死，良弓藏。敌国灭，谋臣亡。亡者，非丧其身也，谓夺其威、废其权也。封之于朝，极人臣之位，以显其功。中州善国，以富其家。美色珍玩，以说其心。夫人众一合而不可卒离，威权一与而不可卒移。还师罢军，存亡之阶。故弱之以位，夺之以国，是谓霸者之略。故霸者之作，其论驳也。存社稷、罗英雄者，中略之势也。故世主秘焉。

