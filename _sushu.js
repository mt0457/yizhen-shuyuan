《素书》自宋张商英作注后，历代注本不下十余种。兹举其要者：

宋·张商英注本——最早注本，随文释义，发明章旨，为后世各本之祖。收入《道藏》《百川学海》《廿二子》等丛书。

元·王氏注本——元人注，姓名不详。以道家义理解素书，多引《老子》《庄子》为证。今存《道藏》本。

明·慎懋赏《素书解》——分章疏解，每句皆有注解，问以史事印证。收入《四库全书存目》。

明·张居正《素书直解》——传为张居正为万历帝讲读时所著，文辞简明，多举历代帝王得失为鉴。

清·俞樾《素书平议》——以训诂方法校订文字，辨证旧注之失。收于《诸子平议补录》。

民国·黄元炳《素书新注》——民国二十三年铅印本，以现代眼光阐释素书，融会儒释道三家义理。

以上诸本，张商英注最早，最得作者本意。学者当以此本为主，参以各家，以求深入。
