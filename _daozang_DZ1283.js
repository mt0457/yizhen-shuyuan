太极真人曰：修灵宝飞行三界之道，当行太初。常以月一日、三日、五日、十五日、二十五日、甲午、丙午、戊午日，平日一入斋堂，东向日，至日中正南坐。亦可被发俯心，咒曰：太一小童玉女，常居绛宫。瞑目念心中赤炁，上与日精同光，日精赤炁来下，入鼻口中，咽之三九而止。又咒曰：日君太阳，神乎神乎。还归绛宫，与我合德。俱养绛宫小童。毕。
