自南北朝以来，历代高道凡遇水旱之灾，皆依此经建斋设醮、诵咒书符，感应如响，灵验昭彰。
经中洞渊三十六咒，乃洞渊一派之根本密咒，一字一句皆暗合天地间水炁运行之玄机，非寻常咒语可比。
