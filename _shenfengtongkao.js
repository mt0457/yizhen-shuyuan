张楠临终训子曰：吾一生论命，以病药为宗。病药二字，可通天地万物，岂止论命而已。

治国亦如治病。朝政之弊为病，贤臣良将为药。药到则国治，药去则国乱。齐家亦如治病。家风之偏为病，家规家教为药。修身亦如治病。自身之短为病，克己复礼为药。

