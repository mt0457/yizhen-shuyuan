其地位如同《易经》之《系辞传》、佛教之《心经》——
浓缩全部精华，导归终极一乘。
若修《大洞真经》三十九章而不修回风混合帝一之道，
则如种禾而不收、登山而不至顶，功亏一篑，不能究竟。
