一章主五神（五藏之神）……各章之间层层递进，
从外而内、从粗而精、从散而聚、从多而一。
修持者每日依次存思一章之神，三十九日为一个完整周期。
存思之法极为精详——修持者须先叩齿、咽液、诵咒，
然后在心中观想对应神灵之名字、服色、形状、居处，
