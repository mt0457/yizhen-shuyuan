大禹行水，随山刊木，定高山大川。伯益与伯翳主驱禽兽，命山川，类草木，别水土。四岳佐之，以周四方。内别五方之山，外分八方之海。纪其珍宝奇物，异方之所生，水土草木禽兽昆虫麟凤之所止，祯祥之所隐，及四海之外，绝域之国，殊类之人。铸九鼎而象百物，使民知神奸，入川泽山林，不逢不若。此《山海经》之所由作也。

夫天地之大也，何所不有？宇宙之广也，何所不包？《山海经》者，非徒志怪之书也，实乃中华地理之祖、神话之源、博物之始也。其载山川道里、飞走鳞介、金石矿产、神祇祭祀，无所不包。读之者，可以知先民之智慧，可以窥上古之风物，可以证三代之文明。是书也，可以观，可以识，可以考，可以证，实乃炎黄子孙之根脉，华夏文化之瑰宝也。

