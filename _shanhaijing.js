又东三十五里曰葱聋之山。其中多大谷。
又东十五里曰涹山。其上多赤铜，其阴多铁。
又东七十里曰脱扈之山。有草焉，其状如葵叶而赤华，名曰植楮，可以已癙。
又东二十里曰金星之山。多天婴，可以已痤。
又东七十里曰泰威之山。其中有谷曰枭谷，其中多铁。
又东十五里曰橿谷之山。其中多赤铜。
又东百二十里曰吴林之山。其中多葌草。
又北三十里曰牛首之山。有草焉，名曰鬼草，服之不忧。劳水出焉，是多飞鱼，食之已痔衕。
又北四十里曰霍山。有兽焉，其状如狸而白尾有鬣，名曰朏朏，养之可以已忧。
又北五十二里曰合谷之山。是多薝棘。
又北三十五里曰阴山。少水出焉，其中多雕棠，食之已聋。

中次二经济山之首曰辉诸之山。又西南二百里曰发视之山。又西三百里曰豪山。又西三百里曰鲜山。其中多鸣蛇，其状如蛇而四翼，其音如磬，见则其邑大旱。又西三百里曰阳山。其中多化蛇，其状如人面而豺身，鸟翼而蛇行，见则其邑大水。又西二百里曰昆吾之山，其上多赤铜。又西百二十里曰葌山。有木焉，名曰芒草，可以毒鱼。又西二百里曰蔓渠之山。伊水出焉，而东流注于洛。有兽焉，其名曰马腹，其状如人面虎身，其音如婴儿，是食人。

中次三经萯山之首曰敖岸之山。神熏池居之。有兽焉，其状如白鹿而四角，名曰夫诸，见则其邑大水。又东十里曰青要之山，实惟帝之密都。有草焉，其状如葌，而方茎黄华赤实，名曰荀草，服之美人色。又东十里曰騩山。正回之水出焉，其中多飞鱼，其状如豚而赤文，服之不畏雷，可以御兵。又东四十里曰宜苏之山。又东二十里曰和山。吉神泰逢司之，其状如人而虎尾，出入有光，泰逢神动天地气也。

中次四经厘山之首曰鹿蹄之山。又西五十里曰扶猪之山。有兽焉，其状如貉而人目。又西一百二十里曰厘山。有兽焉，其状如牛，苍身，其音如婴儿，是食人，其名曰犀渠。又西二百里曰箕尾之山。又西二百五十里曰柄山。又西二百里曰白边之山。又西二百里曰熊耳之山。其中多水玉，多人鱼。又西三百里曰牡山。又西三百五十里曰欢举之山。洛水出焉。

中次五经薄山之首曰苟床之山。东三百里曰首山。其阴有谷曰机谷，多𩿜鸟，其状如枭而三目，有耳，食之已垫。又东三百里曰县斸之山。又东三百里曰葱聋之山。又东五百里曰条谷之山。又北十里曰超山。又东五百里曰成侯之山。又东五百里曰朝歌之山。又东五百里曰槐山。又东十里曰历山。又东十里曰尸山。又东十里曰良余之山。又东南十里曰蛊尾之山。又东北二十里曰升山。又东十二里曰阳虚之山。

中次六经缟羝山之首曰平逢之山。有神焉，其状如人而二首，名曰骄虫，是为螫虫，实惟蜂蜜之庐。西十里曰缟羝之山。又西十里曰廆山。有鸟焉，状如山鸡而长尾，赤如丹火而青喙，名曰鸰䳩，服之不眯。又西三十里曰瞻诸之山。又西三十里曰娄涿之山。又西四十里曰白石之山。又西五十里曰谷山。又西七十二里曰密山。其中多旋龟，其状鸟首而鳖尾。又西百里曰长石之山。又西一百四十里曰傅山。又西五十里曰橐山。又西九十里曰常烝之山。又西九十里曰夸父之山。其北有林焉，名曰桃林，广员三百里，其中多马。又西九十里曰阳华之山。

中次七经苦山之首曰休与之山。有石焉，名曰帝台之棋，五色而文，所以祷百神者也。东三百里曰鼓钟之山，帝台之所以觞百神也。又东二百里曰姑媱之山。帝女死焉，化为䔄草，服之媚于人。又东二十里曰苦山。有兽焉，名曰山膏，其状如逐，赤若丹火，善詈。又东二十七里曰堵山。神天愚居之，是多怪风雨。又东五十二里曰放皋之山。有兽焉，其状如蜂，枝尾而反舌，名曰文文。又东五十七里曰大𩇵之山。有草焉，名曰牛伤，可以御兵。其中多三足龟，食者无大疾，可以已肿。又东七十里曰半石之山。有草焉，名曰嘉荣，服之者不霆。又东五十里曰少室之山。有木焉，名曰帝休，服者不怒。又东三十里曰泰室之山。有木焉，名曰栯木，服者不妒。有草焉，名曰䔄草，服之不昧。又北三十里曰讲山。有木焉，名曰帝屋，可以御凶。又北三十里曰婴梁之山。又东三十里曰浮戏之山。又东四十里曰少陉之山。有草焉，名曰𦱌草，食之不愚。又东南十里曰太山。又东二十里曰末山。又东二十五里曰役山。又东三十五里曰敏山。有木焉，名曰葪柏，服者不寒。又东三十里曰大騩之山。有草焉，其状如蓍而毛，青华而白实，其名曰𦵧，服之不夭。

中次八经荆山之首曰景山。东北百里曰荆山。其中多牦牛，多豹虎，多橘櫾。漳水出焉，其中多黄金，多鲛鱼。又东北百五十里曰骄山。神𧕛围处之，其状如人面，羊角虎爪，恒游于睢漳之渊，出入有光。又东北百二十里曰女几之山。又东北二百里曰宜诸之山。又东北三百五十里曰纶山。又东百三十里曰光山。神计蒙处之，其状人身而龙首，出入必有飘风暴雨。又东百五十里曰岐山。神涉𧕛处之。又东百三十里曰铜山。又东北百里曰美山。又东北百里曰大尧之山。又东北三百里曰灵山。又东北七十里曰龙山。又东南五十里曰衡山。又东南七十里曰石山。又南百二十里曰若山。又东南一百二十里曰彘山。又东南一百五十里曰玉山。又东南七十里曰灌山。又东北百五十里曰仁举之山。又东五十里曰师每之山。又东南二百里曰琴鼓之山。其兽多豕鹿，多白犀，其鸟多鸩。

中次九经岷山之首曰女几之山。又东北三百里曰岷山。江水出焉，东北流注于海，其中多良龟，多鼍。其兽多犀象，多夔牛。又东北一百四十里曰崃山。又东一百五十里曰崌山。又东三百里曰高梁之山。又东四百里曰蛇山。又东五百里曰鬲山。其兽多犀象熊罴，多猨蜼。又东北三百里曰隅阳之山。又东二百五十里曰岐山。又东三百里曰勾檷之山。又东一百五十里曰风雨之山。又东北二百里曰玉山。又东一百五十里曰熊山。有穴焉，熊之穴，恒出神人，夏启而冬闭。又东一百四十里曰騩山。又东二百里曰葛山。又东一百七十里曰贾超之山。

中次十经之首曰首阳之山。又西五十里曰虎尾之山。又西南五十里曰繁缋之山。又西南二十里曰勇石之山。又西二十里曰复州之山。有鸟焉，其状如鸮，而一足彘尾，其名曰跂踵，见则其国大疫。又西三十里曰楮山。又西二十里曰又原之山。又西五十里曰涿山。又西七十里曰丙山。

中次十一经荆山之首曰翼望之山。湍水出焉，东流注于济。贶水出焉，东南流注于汉，其中多蛟。又东北一百五十里曰朝歌之山。又东南二百里曰帝囷之山。又东南五十里曰视山。有井焉，名曰天井，夏有水，冬竭。又东南二百里曰前山。又东南三百里曰丰山。有兽焉，其状如蝯，赤目赤喙黄身，名曰雍和，见则国有大恐。神耕父处之，常游清泠之渊，出入有光。有九钟焉，是知霜鸣。又东北八百里曰兔床之山。又东六十里曰皮山。又东六十里曰瑶碧之山。有鸟焉，其状如雉，恒食蜚，名曰鸩。又东四十里曰支离之山。有鸟焉，其名曰婴勺，其状如鹊，赤目赤喙白身，其尾若勺。又西北一百里曰堇理之山。有鸟焉，其状如鹊，青身白喙白目白尾，名曰青耕，可以御疫。又东南三十里曰依轱之山。有兽焉，其状如犬，虎爪有甲，其名曰獜，食者不风。又东南四十里曰鸡山。又东南五十里曰高前之山。其上有水焉，甚寒而清，帝台之浆也，饮之者不心痛。又东南三十里曰游戏之山。又东南三十里曰婴䃌之山。又东南三十里曰毕山。又东南二十里曰乐马之山。有兽焉，其状如彙，赤如丹火，其名曰𤟑，见则其国大疫。又东四十里曰婴山。又东三十里曰虎首之山。又东二十里曰婴侯之山。又东五十里曰大孰之山。又东四十里曰卑山。又东三十里曰倚帝之山。有兽焉，状如鼣鼠，名曰狙如，见则其国有大兵。又东三十里曰鲵山。又东三十里曰雅山。又东五十五里曰宣山。其上有桑焉，大五十尺，其枝四衢，其叶大尺余，赤理黄华青柎，名曰帝女之桑。又东四十五里曰衡山。又东四十里曰丰山。又东七十里曰妪山。又东三十里曰鲜山。有兽焉，其状如膜犬，赤喙赤目白尾，见则其邑有火，名曰𤝻即。又东三十里曰章山。又东二十五里曰大支之山。又东五十里曰区吴之山。又东五十里曰声匈之山。又东五十里曰大騩之山。又东十里曰踵臼之山。又东北七十里曰历石之山。有兽焉，其状如狸而白首虎爪，名曰梁渠，见则其国有大兵。又东南一百里曰求山。又东二百里曰丑阳之山。有鸟焉，其状如乌而赤足，名曰𩾵䳜，可以御火。又东三百里曰奥山。又东三十五里曰服山。又东百十里曰杳山。又东三百五十里曰几山。有兽焉，其状如彘，黄身白头白尾，名曰闻獜，见则天下大风。

中次十二经洞庭山之首曰篇遇之山。又东南五十里曰云山。有桂竹，甚毒，伤人必死。又东南一百三十里曰龟山。又东七十里曰丙山。又东南五十里曰风伯之山。又东一百五十里曰夫夫之山。神于儿居之，其状人身而身操两蛇，常游于江渊，出入有光。又东南一百二十里曰洞庭之山。帝之二女居之，是常游于江渊。澧沅之风，交潇湘之渊，是在九江之间，出入必以飘风暴雨。又东南一百八十里曰暴山。又东南二百里曰即公之山。有兽焉，其状如龟，而白身赤首，名曰蛫，是可以御火。又东南一百五十九里曰尧山。又东南一百里曰江浮之山。又东二百里曰真陵之山。又东南一百二十里曰阳帝之山。又南九十里曰柴桑之山。多白蛇飞蛇。又东二百三十里曰荣余之山。
凡洞庭山之首，自篇遇之山至于荣余之山，凡十五山，二千八百里。
右中经之山志，大凡百九十七山，二万一千三百七十一里。

大凡天下名山五千三百七十，居地大凡六万四千五十六里。

