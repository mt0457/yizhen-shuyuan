南山经之首曰鹊山。其首曰招摇之山，临于西海之上，多桂，多金玉。有草焉，其状如韭而青华，其名曰祝余，食之不饥。有木焉，其状如谷而黑理，其华四照，其名曰迷谷，佩之不迷。有兽焉，其状如禺而白耳，伏行人走，其名曰狌狌，食之善走。丽麂之水出焉，而西流注于海，其中多育沛，佩之无瘕疾。

又东三百里，曰堂庭之山，多棪木，多白猿，多水玉，多黄金。

又东三百八十里，曰猿翼之山，其中多怪兽，水多怪鱼，多白玉，多蝮虫，多怪蛇，多怪木，不可以上。

又东三百七十里，曰杻阳之山，其阳多赤金，其阴多白金。有兽焉，其状如马而白首，其文如虎而赤尾，其音如谣，其名曰鹿蜀，佩之宜子孙。怪水出焉，而东流注于宪翼之水。其中多玄龟，其状如龟而鸟首虺尾，其名曰旋龟，其音如判木，佩之不聋，可以为底。

又东三百里，曰青丘之山，其阳多玉，其阴多青雘。有兽焉，其状如狐而九尾，其音如婴儿，能食人，食者不蛊。有鸟焉，其状如鸠，其音若呵，名曰灌灌，佩之不惑。英水出焉，南流注于即翼之泽。其中多赤鱬，其状如鱼而人面，其音如鸳鸯，食之不疥。

山海经·西山经第二

西山经华山之首，曰钱来之山，其上多松，其下多洗石。有兽焉，其状如羊而马尾，名曰羬羊，其脂可以已腊。

又西四十五里，曰松果之山。濩水出焉，北流注于渭，其中多铜。有鸟焉，其名曰䳋渠，其状如山鸡，黑身赤足，可以已曝。

又西六十里，曰太华之山，削成而四方，其高五千仞，其广十里，鸟兽莫居。有蛇焉，名曰肥遗，六足四翼，见则天下大旱。

又西八十里，曰小华之山，其木多荆杞，其兽多㸲牛，其阴多磬石，其阳多㻬琈之玉。鸟多赤鷩，可以御火。其草有萆荔，状如乌韭，而生于石上，亦缘木而生，食之已心痛。

又西三百五十里，曰玉山，是西王母所居也。西王母其状如人，豹尾虎齿而善啸，蓬发戴胜，是司天之厉及五残。有兽焉，其状如犬而豹文，其角如牛，其名曰狡，其音如吠犬，见则其国大穰。有鸟焉，其状如翟而赤，名曰胜遇，是食鱼，其音如鹿，见则其国大水。

又西二百八十里，曰昆仑之丘，是实惟帝之下都，神陆吾司之。其神状虎身而九尾，人面而虎爪。是神也，司天之九部及帝之囿时。有兽焉，其状如羊而四角，名曰土蝼，是食人。有鸟焉，其状如蜂，大如鸳鸯，名曰钦原，蜇鸟兽则死，蜇木则枯。有木焉，其状如棠，黄华赤实，其味如李而无核，名曰沙棠，可以御水，食之使人不溺。有草焉，名曰薲草，其状如葵，其味如葱，食之已劳。

山海经·北山经第三

北山经之首，曰单狐之山，多机木，其上多华草。漨水出焉，而西流注于泑水，其中多芘石文石。

又北二百五十里，曰求如之山，其上多铜，其下多玉，无草木。滑水出焉，而西流注于诸毗之水。其中多滑鱼，其状如鳝，赤背，其音如梧，食之已疣。其中多水马，其状如马，文臂牛尾，其音如呼。

又北三百里，曰北岳之山，多枳棘刚木。有兽焉，其状如牛，而四角、人目、彘耳，其名曰诸怀，其音如鸣雁，是食人。

又北三百八十里，曰虢山，其上多漆，其下多桐椐。其阳多玉，其阴多铁。伊水出焉，西流注于河。其兽多橐驼，其鸟多寓，状如鼠而鸟翼，其音如羊，可以御兵。

又北二百里，曰发鸠之山，其上多柘木。有鸟焉，其状如乌，文首、白喙、赤足，名曰精卫，其鸣自詨。是炎帝之少女名曰女娃，女娃游于东海，溺而不返，故为精卫。常衔西山之木石，以堙于东海。

山海经·东山经第四

东山经之首，曰樕䘄之山，北临乾昧。食水出焉，而东北流注于海。其中多鳙鳙之鱼，其状如犁牛，其音如彘鸣。

又南三百里，曰泰山，其上多玉，其下多金。有兽焉，其状如豚而有珠，名曰狪狪，其鸣自叫。环水出焉，东流注于江，其中多水玉。

又南三百里，曰竹山，錞于江，无草木，多瑶碧。激水出焉，而东南流注于娶檀之水，其中多茈羸。

山海经·中山经第五

中山经薄山之首，曰甘枣之山。共水出焉，而西流注于河。其上多杻木，其下有草焉，葵本而杏叶，黄华而荚实，名曰箨，可以已瞢。有兽焉，其状如𤠱鼠而文题，其名曰㔮，食之已瘿。

又东二十里，曰历儿之山，其上多橿，多杤木，是木也，方茎而员叶，黄华而毛，其实如拣，服之不忘。

又东十五里，曰金星之山，多天婴，其状如龙骨，可以已痤。

又东七十里，曰泰威之山，其中有谷，曰枭谷，其中多铁。

中次六经缟羝山之首，曰平逢之山，南望伊洛，东望谷城之山，无草木，无水，多沙石。有神焉，其状如人而二首，名曰骄虫，是为螫虫，实惟蜂蜜之庐。

山海经·海外南经第六

海外自西南陬至东南陬者。结匈国在其西南，其为人结匈。南山在其东南，自此山来，虫为蛇，蛇号为鱼。比翼鸟在其东，其为鸟青、赤，两鸟比翼。羽民国在其东南，其为人长头，身生羽。毕方鸟在其东，青水西，其为鸟人面一脚。讙头国在其南，其为人人面有翼，鸟喙，方捕鱼。

羿与凿齿战于寿华之野，羿射杀之。在昆仑虚东。羿持弓矢，凿齿持盾。一曰戈。三首国在其东，其为人一身三首。周饶国在其东，其为人短小，冠带。长臂国在其东，捕鱼水中，两手各操一鱼。

不死民在其东，其为人黑色，寿，不死。歧舌国在其东。昆仑虚在其东，虚四方。羿与凿齿战于寿华之野，羿射杀之。羿持弓矢，凿齿持盾。

山海经·海外西经第七

海外自西南陬至西北陬者。灭蒙鸟在结匈国北，为鸟青，赤尾。大运山高三百仞，在灭蒙鸟北。夏后启于此儛九代，乘两龙，云盖三层。左手操翳，右手操环，佩玉璜。三身国在夏后启北，一首而三身。一臂国在其北，一臂、一目、一鼻孔。有黄马虎文，一目而一手。奇肱之国在其北，其人一臂三目，有阴有阳，乘文马。有鸟焉，两头，赤黄色，在其旁。

刑天与帝至此争神，帝断其首，葬之常羊之山。乃以乳为目，以脐为口，操干戚以舞。

山海经·海外北经第八

海外自东北陬至西北陬者。无䏿之国在长股东，为人无䏿。烛阴在无䏿国东，其为物人面蛇身，赤色，居钟山下。一目国在其东，一目中其面而居。柔利国在一目东，为人一手一足，反膝，曲足居上。夸父与日逐走，入日。渴欲得饮，饮于河渭，河渭不足，北饮大泽。未至，道渴而死。弃其杖，化为邓林。禹所积石之山在其东，河水所入。寻木长千里，在拘缨南，生河上西北。跂踵国在拘缨东，其为人大，两足亦大。一曰大踵。欧丝之野在大踵东，一女子跪据树欧丝。

山海经·海外东经第九

海外自东南陬至东北陬者。𨲠丘，爰有遗玉、青马、视肉、杨柳、甘柤、甘华，百果所生。在东海，两山夹丘，上有树木。一曰嗟丘。大人国在其北，为人大，坐而削船。奢比之尸在其北，兽身、人面、大耳，珥两青蛇。君子国在其北，衣冠带剑，食兽，使二大虎在旁，其人好让不争。有薰华草，朝生夕死。

青丘国在其北，其狐四足九尾。一曰在朝阳北。黑齿国在其北，为人黑，食稻啖蛇，一赤一青，在其旁。汤谷上有扶桑，十日所浴，在黑齿北。居水中，有大木，九日居下枝，一日居上枝。

山海经·海内南经第十

海内东南陬以西者。瓯居海中。闽在海中，其西北有山。一曰闽中山在海中。三天子鄣山在闽西海北。一曰在海中。桂林八树在番隅东。伯虑国、离耳国、雕题国、北朐国皆在郁水南。兕在舜葬东，湘水南。其状如牛，苍黑，一角。巴蛇食象，三岁而出其骨，君子服之，无心腹之疾。其为蛇青黄赤黑。一曰黑蛇青首，在犀牛西。

山海经·海内西经第十一

海内西南陬以北者。贰负之臣曰危，危与贰负杀窫窳。帝乃梏之疏属之山，桎其右足，反缚两手与发，系之山上木。在开题西北。昆仑南渊深三百仞。开明兽身大类虎而九首，皆人面，东向立昆仑上。开明西有凤凰、鸾鸟，皆戴蛇践蛇，膺有赤蛇。开明北有视肉、珠树、文玉树、玗琪树、不死树。凤凰、鸾鸟皆戴瞂。又有离朱、木禾、柏树、甘水、圣木曼兑。开明东有巫彭、巫抵、巫阳、巫履、巫凡、巫相，夹窫窳之尸，皆操不死之药以距之。

山海经·海内北经第十二

海内西北陬以东者。蛇巫之山，上有人操柸而东向立。一曰龟山。西王母梯几而戴胜。其南有三青鸟，为西王母取食。在昆仑虚北。帝尧台、帝喾台、帝丹朱台、帝舜台，各二台，台四方，在昆仑东北。大蜂其状如螽。朱蛾其状如蛾。蟜，其为人虎文，胫有䏿，在穷奇东。一曰状如人，昆仑虚北所有。阘非，人面而兽身，青色。据比之尸，其为人折颈披发，无一手。环狗，其为人兽首人身。一曰猬状如狗，黄色。袜，其为物人身黑首从目。

山海经·海内东经第十三

海内东北陬以南者。钜燕在东北陬。国在流沙中者埻端、玺㬇，在昆仑虚东南。一曰海内之郡，不为郡县，在流沙中。国在流沙外者，大夏、竖沙、居繇、月支之国。西胡白玉山在大夏东，苍梧在白玉山西南，皆在流沙西，昆仑虚东南。昆仑山在西胡西，皆在西北。

山海经·大荒东经第十四

东海之外有大壑，少昊之国。少昊孺帝颛顼于此，弃其琴瑟。大荒之中，有山名曰合虚，日月所出。有中容之国。帝俊生中容，中容人食兽、木实，使四鸟：豹、虎、熊、罴。有司幽之国。有白民之国。帝俊生帝鸿，帝鸿生白民，白民销姓，黍食，使四鸟：豹、虎、熊、罴。

有青丘之国，有狐，九尾。有柔仆民，是维嬴土之国。有黑齿之国。帝俊生黑齿，姜姓，黍食，使四鸟。大荒之中，有山名曰鞠陵于天、东极、离瞀，日月所出。名曰折丹，东方曰折，来风曰俊，处东极以出入风。

山海经·大荒南经第十五

南海之外，赤水之西，流沙之东，有兽，左右有首，名曰䟣踢。有三青兽相并，名曰双双。有阿山者。南海之中，有泛天之山，赤水穷焉。有荣山，荣水出焉。黑水之南，有玄蛇，食麈。有巫山者，西有黄鸟，帝药八斋。黄鸟于巫山，司此玄蛇。

大荒之中有山，名曰融天，海水南入焉。有人曰凿齿，羿杀之。有蜮山者，有蜮民之国，桑姓，食黍，射蜮是食。有人方扞弓射黄蛇，名曰蜮人。有宋山者，有赤蛇，名曰育蛇。有木生山上，名曰枫木。枫木，蚩尤所弃其桎梏，是为枫木。

山海经·大荒西经第十六

西北海之外，大荒之隅，有山而不合，名曰不周负子，有两黄兽守之。有禹攻共工国山。有女子方浴月。帝俊妻常羲，生月十有二，此始浴之。有玄丹之山。有五色之鸟，人面有发。爰有青鴍、黄鷔、青鸟、黄鸟，其所集者其国亡。有西王母之山、壑山、海山。有神，人面虎身，有文有尾，皆白，处之。其下有弱水之渊环之，其外有炎火之山，投物辄然。有人戴胜，虎齿，有豹尾，穴处，名曰西王母。

山海经·大荒北经第十七

东北海之外，大荒之中，河水之间，附禺之山。有儋耳之国，任姓，禺号子，食谷。有牛黎之国。有人无骨，儋耳之子。有继无民，继无民任姓，无骨子，食气、鱼。西北海外，流沙之东，有国曰中䡢，颛顼之子，食黍。有山名曰北极天柜，海水北注焉。有神，九首人面鸟身，名曰九凤。大荒之中，有山名曰衡天。有先民之山。有盘木千里。

有叔歜国，颛顼之子，黍食，使四鸟：虎、豹、熊、罴。有黑虫如熊状，名曰猎猎。有北齐之国，姜姓，使虎、豹、熊、罴。大荒之中，有山名曰融父山，顺水入焉。有人名曰犬戎。黄帝生苗龙，苗龙生融吾，融吾生弄明，弄明生白犬，白犬有牝牡，是为犬戎，肉食。

山海经·海内经第十八

东海之内，北海之隅，有国名曰朝鲜。天毒，其人水居，偎人爱之。西海之内，流沙之中，有国名曰壑市。西海之内，流沙之西，有国名曰泛叶。流沙之西，有鸟山者，三水出焉。爰有黄金、璇瑰、丹货、银铁，皆流于此中。又有淮山，好水出焉。

南海之内，黑水青水之间，有木名曰若木，若水出焉。有禺中之国。有列襄之国。有灵山，有赤蛇在木上，名曰蝡蛇，木食。有盐长之国。有人焉鸟首，名曰鸟民。有九丘，以水络之：名曰陶唐之丘、有叔得之丘、孟盈之丘、昆吾之丘、黑白之丘、赤望之丘、参卫之丘、武夫之丘、神民之丘。

炎帝之妻，赤水之子听訞生炎居，炎居生节并，节并生戏器，戏器生祝融。祝融降处于江水，生共工。共工生术器，术器首方颠，是复土穰，以处江水。共工生后土，后土生噎鸣，噎鸣生岁十有二。洪水滔天。鲧窃帝之息壤以堙洪水，不待帝命。帝令祝融杀鲧于羽郊。鲧复生禹。帝乃命禹卒布土以定九州。
