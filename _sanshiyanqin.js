六两：一朝金榜快题名，显祖荣宗大器成。衣禄定然原裕足，田园财帛更丰盈。
——金榜题名光宗耀祖，衣禄充裕田园丰盈。此为极品文贵之格，位极人臣。

六两一钱：不作朝中金榜客，定为世上大富翁。聪明天赋经书熟，名显高科自是荣。
——不是朝中金榜题名的贵人，也必定是世间的大富翁。天资聪颖饱读经书，名显科场自然荣显。

六两二钱：此命生来福不穷，读书必定显亲宗。紫衣金带为卿相，富贵荣华孰与同。
——生来福气无穷，读书必定光宗耀祖。紫衣金带位至卿相，富贵荣华无人能及。

六两三钱：命主为官福禄长，得来富贵实非常。名题金塔传金榜，定中高科天下扬。
——为官之人福禄长久，得来的富贵非同寻常。名题雁塔金榜题名，高中科举天下扬名。

六两四钱：此格威权不可当，紫袍金带坐高堂。荣华富贵谁能及，万古留名姓氏扬。
——威权不可抵挡，紫袍金带高坐大堂。荣华富贵谁能比及？万古留名姓氏远扬。帝王将相之格。

六两五钱：细推此命福非轻，富贵荣华孰与争。定国安邦人极品，威声显赫震寰瀛。
——细细推究此命福气不轻，富贵荣华无人能争。定国安邦之人中极品，威声显赫震动天下。

六两六钱：此格人间一福人，堆金积玉满堂春。从来富贵由天定，正笏垂绅谒圣君。
——人间第一大福之人，堆金积玉满堂如春。从来富贵由天而定，手持笏板垂绅晋谒圣君。

六两七钱：此命生来福自宏，田园家业最高隆。平生衣禄盈丰足，一世荣华万事通。
——生来福气宏大，田园家业最为兴隆。平生衣禄丰盈满足，一生荣华万事亨通。

六两八钱：富贵由天莫苦求，万金家计不须谋。十年不比前番事，祖业根基千古留。
——富贵由天莫去强求，万贯家财不须费心谋取。十年之间境况大变，祖业根基千古遗留。

六两九钱：君是人间衣禄星，一生富贵众人钦。总然福禄由天定，安享荣华过一生。
——君是人间之衣禄星，一生富贵众人钦敬。纵然福禄由天而定，亦可安享荣华度过一生。

七两：此命推来福不轻，何须愁虑苦劳心。荣华富贵已天定，正笏垂绅拜紫宸。
——福气深重不必愁虑劳心，荣华富贵已然天定。手持笏板垂绅拜见天子。极品大臣之格。

七两一钱：此命生成大不同，公侯卿相在其中。一生自有逍遥福，富贵荣华极品隆。
——生来便与常人不同，公侯卿相之命格。一生自有逍遥之福，富贵荣华达到极品。

七两二钱：此格世界罕有生，十代积善产此人。天上紫微星照命，统治万民乐太平。
——此格局世间罕有，是十代积善才产生此人。天上紫微星照临其命，统治万民安享太平——帝王之格。

