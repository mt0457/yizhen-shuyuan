（正旦云）相公说哪里话。自古寒门出贵子，白屋出公卿。妾身既嫁与相公，便随相公去那破窑中居住，有何不可！

【第二折·居窑】

（吕蒙正、刘月娥居破窑中。风雪交加。正旦唱）

【南吕·一枝花】朔风狂，彤云密布；大雪飘，四野模糊。破瓦寒窑难遮护，冷飕飕风透衣裾。饥无食，寒无炉，腹中饥馁向谁诉。

【梁州第七】俺这里破窑中冷似冰，他那里富家暖阁拥红炉。想当日彩楼前绣球抛中，指望夫妇和谐、永效于飞。谁承望父嫌贫贱，把亲骨肉做了陌路殊途。

（吕蒙正云）小姐且自忍耐。待小生上朝取应，定要夺个状元回来，方不负小姐一片冰心。

（正旦云）相公此去，须要保重。妾身在这破窑之中，专等相公佳音。

【第三折·及第】

（吕蒙正状元及第，授本处县令。衣锦还乡，先着人往破窑中报喜。正旦闻讯，唱）

【中吕·粉蝶儿】十载寒窗无人问，一举成名天下知。我只道破窑中挨不过这穷日子，谁承望枯木逢春也发新枝。

（吕蒙正着官服见正旦，夫妻相认。同往刘员外家。刘员外惭，认女及婿。吕蒙正不计前嫌，一家团圆。）

