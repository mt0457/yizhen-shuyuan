（做抛绣球科，绣球正中吕蒙正。刘员外见吕蒙正衣衫褴褛，怒云）此人一贫如洗，如何做得我家女婿！左右，将那绣球夺回！（正旦云）父亲，绣球既已抛中，便是天定姻缘。女儿情愿嫁与此人，虽贫不悔。

