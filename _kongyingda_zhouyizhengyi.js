孔颖达（574—648），字冲远，冀州衡水（今河北衡水）人。生于北齐，隋末举明经，入唐为秦王府文学馆学士。贞观年间，奉唐太宗敕主持编纂《五经正义》。《周易正义》为其一，采王弼、韩康伯注为本，兼取诸家之说，详为之疏。书成，诏颁天下，明经取士皆以此为准。自贞观至清末，一千三百年间，学者传习、科举命题，莫不宗之。

《周易正义》之体例：经文之下为王弼注（六十四卦及彖象文言）或韩康伯注（系辞说卦序卦杂卦），注下为孔颖达疏。疏者，疏通证明之义，解经文之旨趣，阐注文之幽微，旁征博引，以求贯通。卷首冠以《八论》，总述易学源流及编纂大旨。

