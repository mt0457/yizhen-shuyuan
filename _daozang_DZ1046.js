<p style="font-size:16px;color:#8b1a1a;line-height:2.2;margin:0;">
<b>道法自然，自然而然。日出月没，非推非牵。寒往暑来，非召非延。春生秋杀，非令非宣。人法自然，与道合真。逆自然者，灾祸临身。观天之道，执天之行。顺其自然，长生久视。皈依太上老君，皈依自然大道，皈依三洞经教。自然常清静天尊。</b>
</p>
