金圣叹评曰：天下之文章，无有出水浒右者。天下格物君子，无有出施耐庵先生右者。
学者诚能澄怀格物，发皇文章，不独赏其叙事之妙，更须悟其劝惩之意。
一部大书，七十回后便成恶札。然则天下文章当以水浒为第一。

后人有《水浒》总赞：
梁山泊里聚群雄，替天行道杏黄旌。
三打祝家庄上震，两赢童贯阵前惊。
征辽大破混天阵，讨腊伤残子弟兵。
千古忠魂蓼儿洼，残阳如血照天明。

附：水浒传经典诗词选录

【开篇词】
纷纷五代乱离间，一旦云开复见天。
草木百年新雨露，车书万里旧江山。
寻常巷陌陈罗绮，几处楼台奏管弦。
人乐太平无事日，莺花无限日高眠。

【林冲题壁诗】
仗义是林冲，为人最朴忠。
江湖驰誉望，京国显英雄。
身世悲浮梗，功名类转蓬。
他年若得志，威镇泰山东。

【宋江浔阳楼反诗】
自幼曾攻经史，长成亦有权谋。
恰如猛虎卧荒丘，潜伏爪牙忍受。
不幸刺文双颊，那堪配在江州。
他年若得报冤仇，血染浔阳江口。

【宋江续诗】
心在山东身在吴，飘蓬江海漫嗟吁。
他时若遂凌云志，敢笑黄巢不丈夫。

【鲁智深坐化颂】
平生不修善果，只爱杀人放火。
忽地顿开金绳，这里扯断玉锁。
咦！钱塘江上潮信来，今日方知我是我。

【燕青别主辞】
雁序分飞自可惊，纳还官诰不求荣。
身边自有君王赦，脱却风尘过此生。

【李逵诀别辞】
生时服侍哥哥，死了也只是哥哥部下一个小鬼。

【吴用花荣自缢前题壁】
堪羡宋江忠义，安邦定国扶君。
谁知今日遭冤死，一梦绕孤坟。

【百回本结尾诗】
莫把行藏怨老天，韩彭当日亦堪怜。
一心征腊摧锋日，百战擒辽破敌年。
煞曜罡星今已矣，谗臣贼相尚依然。
早知鸩毒埋黄壤，学取鸱夷泛钓船。

