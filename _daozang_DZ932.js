<p style="line-height:2.2;">
现存主要版本：明《正统道藏》正一部本文类所收本，《万历续道藏》所收本，清代《道藏辑要》所收本，三本文字大同小异。近代以来，此经广泛流传于各地道观及民间信仰中。
</p>

