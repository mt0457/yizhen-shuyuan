韩非子·显学第五十

世之显学，儒、墨也。儒之所至，孔丘也。墨之所至，墨翟也。自孔子之死也，有子张之儒，有子思之儒，有颜氏之儒，有孟氏之儒，有漆雕氏之儒，有仲良氏之儒，有孙氏之儒，有乐正氏之儒。自墨子之死也，有相里氏之墨，有相夫氏之墨，有邓陵氏之墨。故孔、墨之后，儒分为八，墨离为三，取舍相反不同，而皆自谓真孔、墨。孔、墨不可复生，将谁使定后世之学乎？孔子、墨子俱道尧、舜，而取舍不同，皆自谓真尧、舜。尧、舜不复生，将谁使定儒、墨之诚乎？无参验而必之者，愚也；弗能必而据之者，诬也。故明据先王，必定尧、舜者，非愚则诬也。

韩非子·孤愤第十一

智术之士，必远见而明察，不明察不能烛私；能法之士，必强毅而劲直，不劲直不能矫奸。人臣循令而从事，案法而治官，非谓重人也。重人也者，无令而擅为，亏法以利私，耗国以便家，力能得其君，此所为重人也。智术之士明察，听用，且烛重人之阴情；能法之士劲直，听用，且矫重人之奸行。故智术能法之士用，则贵重之臣必在绳之外矣。是智法之士与当涂之人，不可两存之仇也。

韩非子·说难第十二

凡说之难：非吾知之有以说之之难也，又非吾辩之能明吾意之难也，又非吾敢横失而能尽之难也。凡说之难，在知所说之心，可以吾说当之。所说出于为名高者也，而说之以厚利，则见下节而遇卑贱，必弃远矣。所说出于厚利者也，而说之以名高，则见无心而远事情，必不收矣。所说阴为厚利而显为名高者也，而说之以名高，则阳收其身而实疏之；说之以厚利，则阴用其言显弃其身矣。此不可不察也。

夫事以密成，语以泄败。未必其身泄之也，而语及所匿之事，如此者身危。彼显有所出事，而乃以成他故，说者不徒知所出而已矣，又知其所以为，如此者身危。规异事而当，知者揣之外而得之，事泄于外，必以为己也，如此者身危。周泽未渥也，而语极知，说行而有功则德忘，说不行而有败则见疑，如此者身危。贵人有过端，而说者明言礼义以挑其恶，如此者身危。贵人或得计而欲自以为功，说者与知焉，如此者身危。

韩非子·内储说上七术

主之所用也七术，所察也六微。七术：一曰众端参观，二曰必罚明威，三曰信赏尽能，四曰一听责下，五曰疑诏诡使，六曰挟知而问，七曰倒言反事。此七者，主之所用也。

