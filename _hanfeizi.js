《韩非子》为战国末期韩非所著，共五十五篇十余万言，是法家思想的集大成之作。
韩非（约前280年—前233年），韩国公子，与李斯同师事荀子。喜刑名法术之学，而归本于黄老。
韩非口吃，不善言谈，而善著书。见韩之削弱，数以书谏韩王，韩王不能用。
于是韩非疾治国不务修明其法制，执势以御其臣下，富国强兵而以求人任贤，反举浮淫之蠹而加之于功实之上。
