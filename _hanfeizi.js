上古之世，人民少而禽兽众，人民不胜禽兽虫蛇。有圣人作，构木为巢以避群害，而民悦之，使王天下，号之曰有巢氏。民食果蓏蚌蛤，腥臊恶臭而伤害腹胃，民多疾病。有圣人作，钻燧取火以化腥臊，而民说之，使王天下，号之曰燧人氏。中古之世，天下大水，而鲧、禹决渎。近古之世，桀、纣暴乱，而汤、武征伐。今有构木钻燧于夏后氏之世者，必为鲧、禹笑矣；有决渎于殷、周之世者，必为汤、武笑矣。然则今有美尧、舜、汤、武、禹之道于当今之世者，必为新圣笑矣。是以圣人不期修古，不法常可，论世之事，因为之备。

