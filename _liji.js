王者之制禄爵，公侯伯子男，凡五等。诸侯之上大夫卿，下大夫，上士中士下士，凡五等。天子之田方千里，公侯田方百里，伯七十里，子男五十里。不能五十里者，不合于天子，附于诸侯曰附庸。天子之三公之田视公侯，天子之卿视伯，天子之大夫视子男，天子之元士视附庸。

制：农田百亩。百亩之分：上农夫食九人，上次食八人，其次食七人，其次食六人；下农夫食五人。庶人在官者，其禄以是为差也。诸侯之下士视上农夫，禄足以代其耕也。中士倍下士，上士倍中士，下大夫倍上士；卿，四大夫禄；君，十卿禄。次国之卿，三大夫禄；君，十卿禄。小国之卿，倍大夫禄，君十卿禄。

次国之上卿，位当大国之中，中当其下，下当其上大夫。小国之上卿，位当大国之下卿，中当其上大夫，下当其下大夫。其有中士下士者，数各居其上之三分。

凡四海之内九州，州方千里。州，建百里之国三十，七十里之国六十，五十里之国百有二十，凡二百一十国；名山大泽不以封，其余以为附庸闲田。八州，州二百一十国。天子之县内，方百里之国九，七十里之国二十有一，五十里之国六十有三，凡九十三国；名山大泽不以朌，其余以禄士，以为闲田。凡九州，千七百七十三国。天子之元士、诸侯之附庸不与。

天子百里之内以共官，千里之内以为御。千里之外，设方伯。五国以为属，属有长。十国以为连，连有帅。三十国以为卒，卒有正。二百一十国以为州，州有伯。八州八伯，五十六正，百六十八帅，三百三十六长。八伯各以其属，属于天子之老二人，分天下以为左右，曰二伯。

天子无事与诸侯相见曰朝。考礼正刑一德，以尊于天子。天子赐诸侯乐，则以柷将之；赐伯子男乐，则以鼗将之。诸侯，赐弓矢然后征，赐鈇钺然后杀，赐圭瓒然后为鬯。未赐圭瓒，则资鬯于天子。

天子命之教然后为学。小学在公宫南之左，大学在郊。天子曰辟雍，诸侯曰頖宫。天子将出征，类乎上帝，宜乎社，造乎祢，祃于所征之地。受命于祖，受成于学。出征，执有罪；反，释奠于学，以讯馘告。

天子诸侯宗庙之祭：春曰礿，夏曰禘，秋曰尝，冬曰烝。天子祭天地，诸侯祭社稷，大夫祭五祀。天子祭天下名山大川：五岳视三公，四渎视诸侯。诸侯祭名山大川之在其地者。天子诸侯祭因国之在其地而无主后者。

天子社稷皆大牢，诸侯社稷皆少牢。大夫士宗庙之祭，有田则祭，无田则荐。庶人春荐韭，夏荐麦，秋荐黍，冬荐稻。韭以卵，麦以鱼，黍以豚，稻以雁。

祭天地之牛，角茧栗；宗庙之牛，角握；宾客之牛，角尺。诸侯无故不杀牛，大夫无故不杀羊，士无故不杀犬豕，庶人无故不食珍。庶羞不逾牲，燕衣不逾祭服，寝不逾庙。

古者公田，藉而不税。市，廛而不税。关，讥而不征。林麓川泽，以时入而不禁。夫圭田无征。用民之力，岁不过三日。田里不粥，墓地不请。

司空执度度地，居民山川沮泽，时四时。量地远近，兴事任力。凡使民：任老者之事，食壮者之食。凡居民材，必因天地寒暖燥湿，广谷大川异制。民生其间者异俗：刚柔轻重迟速异齐，五味异和，器械异制，衣服异宜。修其教，不易其俗；齐其政，不易其宜。

中国戎夷，五方之民，皆有性也，不可推移。东方曰夷，被发文身，有不火食者矣。南方曰蛮，雕题交趾，有不火食者矣。西方曰戎，被发衣皮，有不粒食者矣。北方曰狄，衣羽毛穴居，有不粒食者矣。中国、夷、蛮、戎、狄，皆有安居、和味、宜服、利用、备器，五方之民，言语不通，嗜欲不同。达其志，通其欲：东方曰寄，南方曰象，西方曰狄鞮，北方曰译。

