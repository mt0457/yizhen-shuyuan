《司马法》本一百五十五篇，今仅存五篇。以下为历代类书、注疏中所引佚文：

春不东征，秋不西伐。月食班师，所以省战也。

上多前虏。上多前虏则下不服，下不服则战不力。

善者，忻民之善，闭民之恶。

国中之听，必得其情；军旅之听，必得其宜。

天下虽安，忘战必危。天下既平，天子大恺。

一人之禁，无过瞬息。

将军死绥。有前一尺，无却一寸。

军中之乐，鼓笛为上，使士卒知将意也。

见敌作誓，瞻功行赏。

军赏不逾月，欲民速得为善之利也。

将者，人之司命，三军与之俱治，与之俱乱。得贤将者，兵强国昌；不得贤将者，兵弱国亡。

凡战之道，教人为善，而后罚其恶。先赏而后罚，则士卒劝。

兵者，诡道也。故能而示之不能，用而示之不用。

凡战，鼓以旌旗为耳目，三军视听如一，则胜。

将谋欲密，士众欲一，攻敌欲疾。

凡战，智者为谋主，勇者为斗主，能者为事主。

将之所麾，莫不心移；将之所指，莫不前死。

