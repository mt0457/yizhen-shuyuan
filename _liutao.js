宋神宗元丰三年，诏命国子监司业朱服、武学博士何去非等校定《孙子》《吴子》《司马法》《六韬》《尉缭子》《三略》《李卫公问对》七部兵书，刻版印行，颁之武学，号为《武经七书》。此为我国古代第一部官方军事教科书体系，是古代兵学之最高经典集合。

七书中，《孙子》十三篇为兵学之冠，言简意赅，博大精深，论战争之道与兵家权谋，影响最巨。《吴子》六篇为吴起所著，论治兵选将，以仁为本，文德武备兼备。《司马法》五篇为齐国司马穰苴兵书，存三代军礼古制，仁义为本而权诈为末。《六韬》六卷六十篇，体系最全，包罗万象，论治国用兵之全貌。《尉缭子》五卷二十四篇，论法制严明，编伍训练，与商鞅耕战之法一脉相承。《三略》三卷，又称《黄石公三略》，论战略韬略，多道家之言，上略设礼赏、中略差德行、下略陈道德。《李卫公问对》三卷为唐太宗与李靖论兵之语录，探微发隐，于各家兵说多有精辟辨析。

七书各有侧重，合而观之，则中国古代军事思想之全貌尽见。历代兵家奉为圭臬，科举武科必考之书，对中国历史与军事文化影响极为深远。其中《六韬》以其体系的完整性与论述的深度，居七书之枢纽地位，上承《司马法》古制，下启《孙子》权谋，实为兵学承前启后之巨著。

