《六韬》又称《太公六韬》《太公兵法》，传为周初太公望（姜尚）所著。全书以太公与周文王、周武王问答形式写成，共六卷六十篇。卷一《文韬》十二篇，论治国安民之术；卷二《武韬》五篇，论用兵伐敌之道；卷三《龙韬》十三篇，论军事组织与将帅之道；卷四《虎韬》十二篇，论军需装备与战术布阵；卷五《豹韬》八篇，论特种地形作战；卷六《犬韬》十篇，论教战练兵与诸兵种协同。此书为《武经七书》之一，集先秦军事思想之大成，涵盖治国、用兵、阵法、器械、选将、练士诸方面，体系完备，气象宏大。司马迁《史记》载张良于下邳圯上得太公兵法，即此书也。

