周礼·地官司徒第二

惟王建国，辨方正位，体国经野，设官分职，以为民极。乃立地官司徒，使帅其属而掌邦教，以佐王安扰邦国。教官之属：大司徒，卿一人。小司徒，中大夫二人。乡师，下大夫四人、上士八人、中士十有六人、旅下士三十有二人、府六人、史十有二人、胥十有二人、徒百有二十人。

大司徒之职，掌建邦之土地之图与其人民之数，以佐王安扰邦国。以天下土地之图，周知九州之地域广轮之数，辨其山林、川泽、丘陵、坟衍、原隰之名物。而辨其邦国都鄙之数，制其畿疆而沟封之。设其社稷之壝而树之田主，各以其野之所宜木，遂以名其社与其野。

以上会之法辨五地之物生：一曰山林，其动物宜毛物，其植物宜皂物，其民毛而方。二曰川泽，其动物宜鳞物，其植物宜膏物，其民黑而津。三曰丘陵，其动物宜羽物，其植物宜核物，其民专而长。四曰坟衍，其动物宜介物，其植物宜荚物，其民皙而瘠。五曰原隰，其动物宜裸物，其植物宜丛物，其民丰肉而庳。

以土宜之法辨十有二土之名物，以相民宅而知其利害，以阜人民，以蕃鸟兽，以毓草木，以任土事。辨十有二壤之物而知其种，以教稼穑树艺。以土均之法辨五物九等，制天下之地征，以作民职，以令地贡，以敛财赋，以均齐天下之政。

以乡三物教万民而宾兴之：一曰六德，知、仁、圣、义、忠、和。二曰六行，孝、友、睦、姻、任、恤。三曰六艺，礼、乐、射、御、书、数。

以乡八刑纠万民：一曰不孝之刑，二曰不睦之刑，三曰不姻之刑，四曰不弟之刑，五曰不任之刑，六曰不恤之刑，七曰造言之刑，八曰乱民之刑。

以五礼防万民之伪，而教之中。以六乐防万民之情，而教之和。凡万民之不服教而有狱讼者，与有地治者听而断之；其附于刑者归于士。

周礼·春官宗伯第三

惟王建国，辨方正位，体国经野，设官分职，以为民极。乃立春官宗伯，使帅其属而掌邦礼，以佐王和邦国。礼官之属：大宗伯，卿一人。小宗伯，中大夫二人。

大宗伯之职，掌建邦之天神、人鬼、地示之礼，以佐王建保邦国。以吉礼事邦国之鬼神示，以禋祀祀昊天上帝，以实柴祀日、月、星辰，以槱燎祀司中、司命、飌师、雨师。以血祭祭社稷、五祀、五岳，以狸沈祭山林川泽，以疈辜祭四方百物。以肆献裸享先王，以馈食享先王，以祠春享先王，以禴夏享先王，以尝秋享先王，以烝冬享先王。

以凶礼哀邦国之忧，以丧礼哀死亡，以荒礼哀凶札，以吊礼哀祸灾，以禬礼哀围败，以恤礼哀寇乱。以宾礼亲邦国，春见曰朝，夏见曰宗，秋见曰觐，冬见曰遇，时见曰会，殷见曰同。以军礼同邦国，大师之礼，用众也；大均之礼，恤众也；大田之礼，简众也；大役之礼，任众也；大封之礼，合众也。以嘉礼亲万民，以饮食之礼亲宗族兄弟，以婚冠之礼亲成男女，以宾射之礼亲故旧朋友，以飨燕之礼亲四方之宾客，以脤膰之礼亲兄弟之国，以贺庆之礼亲异姓之国。

小宗伯之职，掌建国之神位，右社稷，左宗庙。兆五帝于四郊，四望、四类亦如之。兆山川丘陵坟衍，各因其方。掌五礼之禁令与其用等。辨庙祧之昭穆。掌三吉凶之五服、车旗、宫室之禁。

周礼·夏官司马第四

惟王建国，辨方正位，体国经野，设官分职，以为民极。乃立夏官司马，使帅其属而掌邦政，以佐王平邦国。政官之属：大司马，卿一人。小司马，中大夫二人。军司马，下大夫四人。舆司马，上士八人。行司马，中士十有六人、旅下士三十有二人。府六人，史十有二人，胥十有二人，徒百有二十人。

大司马之职，掌建邦国之九法，以佐王平邦国。制畿封国以正邦国，设仪辨位以等邦国，进贤兴功以作邦国，建牧立监以维邦国，制军诘禁以纠邦国，施贡分职以任邦国，简稽乡民以用邦国，均守平则以安邦国，比小事大以和邦国。以九伐之法正邦国，冯弱犯寡则眚之，贼贤害民则伐之，暴内陵外则坛之，野荒民散则削之，负固不服则侵之，贼杀其亲则正之，放弑其君则残之，犯令陵政则杜之，外内乱、鸟兽行则灭之。

中春教振旅，司马以旗致民，平列陈，如战之陈。辨鼓铎镯铙之用：王执路鼓，诸侯执贲鼓，军将执晋鼓，师帅执提，旅帅执鼙，卒长执铙，两司马执铎，公司马执镯。以教坐作进退疾徐疏数之节。遂以搜田，有司表貉，誓民，鼓，遂围禁。火弊，献禽以祭社。

凡制军，万有二千五百人为军，王六军，大国三军，次国二军，小国一军，军将皆命卿。二千有五百人为师，师帅皆中大夫。五百人为旅，旅帅皆下大夫。百人为卒，卒长皆上士。二十五人为两，两司马皆中士。五人为伍，伍皆有长。

周礼·秋官司寇第五

惟王建国，辨方正位，体国经野，设官分职，以为民极。乃立秋官司寇，使帅其属而掌邦禁，以佐王刑邦国。刑官之属：大司寇，卿一人。小司寇，中大夫二人。士师，下大夫四人。乡士，上士八人、中士十有六人、旅下士三十有二人。府六人，史十有二人，胥十有二人，徒百有二十人。

大司寇之职，掌建邦之三典，以佐王刑邦国，诘四方。一曰刑新国用轻典，二曰刑平国用中典，三曰刑乱国用重典。以五刑纠万民：一曰野刑，上功纠力；二曰军刑，上命纠守；三曰乡刑，上德纠孝；四曰官刑，上能纠职；五曰国刑，上愿纠暴。以圜土聚教罢民，凡害人者，置之圜土而施职事焉，以明刑耻之。其能改者，反于中国，不齿三年。其不能改而出圜土者，杀。

以两造禁民讼，入束矢于朝，然后听之。以两剂禁民狱，入钧金，三日乃致于朝，然后听之。以嘉石平罢民，凡万民之有罪过而未丽于法而害于州里者，桎梏而坐诸嘉石，役诸司空。重罪旬有三日坐，期役；其次九日坐，九月役；其次七日坐，七月役；其次五日坐，五月役；其下罪三日坐，三月役。以肺石达穷民，凡远近茕独老幼之欲有复于上而其长弗达者，立于肺石三日，士听其辞，以告于上而罪其长。

小司寇之职，掌外朝之政，以致万民而询焉。一曰询国危，二曰询国迁，三曰询立君。其位：王南乡，三公及州长、百姓北面，群臣西面，群吏东面。小司寇摈以叙进而问焉，以众辅志而弊谋。以五刑听万民之狱讼，附于刑，用情讯之。至于旬，乃弊之，读书则用法。

周礼·冬官考工记第六

国有六职，百工与居一焉。或坐而论道，或作而行之，或审曲面势，以饬五材，以辨民器，或通四方之珍异以资之，或饬力以长地财，或治丝麻以成之。坐而论道，谓之王公；作而行之，谓之士大夫；审曲面势，以饬五材，以辨民器，谓之百工；通四方之珍异以资之，谓之商旅；饬力以长地财，谓之农夫；治丝麻以成之，谓之妇功。

知者创物，巧者述之，守之世，谓之工。百工之事，皆圣人之作也。烁金以为刃，凝土以为器，作车以行陆，作舟以行水，此皆圣人之所作也。天有时，地有气，材有美，工有巧，合此四者，然后可以为良。材美工巧，然而不良，则不时，不得地气也。橘逾淮而北为枳，鸜鹆不逾济，貉逾汶则死，此地气然也。郑之刀，宋之斤，鲁之削，吴粤之剑，迁乎其地而弗能为良，地气然也。燕之角，荆之干，妢胡之笴，吴粤之金锡，此材之美者也。天有时以生，有时以杀；草木有时以生，有时以死；石有时以泐；水有时以凝，有时以泽；此天时也。

凡攻木之工七，攻金之工六，攻皮之工五，设色之工五，刮摩之工五，搏埴之工二。攻木之工：轮、舆、弓、庐、匠、车、梓。攻金之工：筑、冶、凫、栗、段、桃。攻皮之工：函、鲍、韗、韦、裘。设色之工：画、缋、钟、筐、荒。刮摩之工：玉、栉、雕、矢、磬。搏埴之工：陶、瓬。

有虞氏上陶，夏后氏上匠，殷人上梓，周人上舆。故一器而工聚焉者，车为多。车有六等之数：车轸四尺，谓之一等；戈柲六尺有六寸，既建而迤，崇于轸四尺，谓之二等；人长八尺，崇于戈四尺，谓之三等；殳长寻有四尺，崇于人四尺，谓之四等；戟常崇于殳四尺，谓之五等；矛常有四尺，崇于戟四尺，谓之六等。车谓之六等之数。

凡察车之道，必自载于地者始也，是故察车自轮始。凡察车之道，欲其朴属而微至。不朴属，无以为完久也；不微至，无以为戚速也。轮已崇，则人不能登也；轮已庳，则于马终古登阤也。故兵车之轮六尺有六寸，田车之轮六尺有三寸，乘车之轮六尺有六寸。六尺有六寸之轮，轵崇三尺有三寸也，加轸与轐焉，四尺也。人长八尺，登下以为节。
