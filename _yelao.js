野老·天象占·五星占篇

五星者，岁星、荧惑、镇星、太白、辰星是也。岁星者，东方木星，仁德之象。其色明润，其行顺轨，则五谷丰登，天下和平。岁星变色则饥，退行则乱，停留则兵。岁星入月则天下无道。岁星昼见则臣强君弱。岁星守心则年丰，守房则谷贵，守角则虫灾。荧惑者，南方火星，刑罚之象。其色赤而光明，其行无常，所至则有兵乱。荧惑守心，则天子有忧。荧惑入北斗，则天下乱。荧惑与太白斗，则大战。荧惑色变白则为旱，变黑则为水。镇星者，中央土星，稼穑之象。其色黄，其行二十八年一周天。镇星居其所而众星从之，则天下安。镇星失次，则地动山崩。镇星守南斗，则岁大熟。镇星守牵牛，则谷贵民饥。太白者，西方金星，兵革之象。其色白，晨出为启明，昏见为长庚。太白当出不出、当入不入，则天下兵起。太白昼见，则强国弱、弱国强。太白经天，则天下革政。太白与月相掩，则大将死。辰星者，北方水星，刑罚之象。其行近太阳，不出四仲之月。辰星春见则水少，夏见则旱，秋见则霜早，冬见则寒甚。辰星色白则为旱，色赤则为兵，色黄则为丰。五星聚于一舍，则圣人出，天下归心。五星皆逆行，则天下大乱。五星变色，则各以其类为灾。故观五星之行度、色相、迟速、顺逆、留守、犯掩、合散，可以知天下之治乱兴衰。

野老·天象占·二十八宿占篇

二十八宿者，天之舍也。东方七宿：角、亢、氐、房、心、尾、箕，为青龙之象。北方七宿：斗、牛、女、虚、危、室、壁，为玄武之象。西方七宿：奎、娄、胃、昴、毕、觜、参，为白虎之象。南方七宿：井、鬼、柳、星、张、翼、轸，为朱雀之象。角宿明则天下太平，暗则将帅有忧。角星动摇，则兵起。亢宿明则贤臣进，暗则佞臣用。亢星跃则大水至。氐宿明则民安，暗则民流。氐星散则后妃有疾。房宿明则君明臣良，暗则君昏臣乱。房星间见，则兵起四方。心宿明则天下丰稔，暗则天子失位。心星前星不明则太子忧，后星不明则庶子忧。尾宿明则后宫安宁，暗则后宫有乱。尾星聚则大水至。箕宿明则谷贵，暗则谷贱。箕星动则有风灾。斗宿明则君寿，暗则君忧。斗星变则爵禄不均。牛宿明则五谷熟，暗则牺牲不备。牛星移则天下大疫。女宿明则女工兴，暗则丝帛贵。女星微则妃后争宠。虚宿明则天下安，暗则天下虚耗。危宿明则国泰，暗则国有大丧。室宿明则宫室成，暗则土木兴。壁宿明则文章盛，暗则典籍散。奎宿明则将军勇，暗则兵甲不用。娄宿明则郊祀得礼，暗则祭祀不敬。胃宿明则仓廪实，暗则仓廪虚。昴宿明则胡兵起，暗则边境安。毕宿明则田猎兴，暗则弋猎无度。觜宿明则军威振，暗则军旅废。参宿明则刑罚中，暗则刑法滥。井宿明则水泉溢，暗则水旱不均。鬼宿明则鬼神安，暗则鬼神为祟。柳宿明则庖厨丰，暗则饮食不继。星宿明则衣服备，暗则衣裳不足。张宿明则礼乐兴，暗则礼仪废。翼宿明则远方来宾，暗则远人不服。轸宿明则车骑盛，暗则车马不足。凡二十八宿，各有其度，各有其色，各有其占。守常则吉，失常则凶。

野老·天象占·杂星篇

杂星者，瑞星、妖星、客星、流星、彗星之类也。瑞星有五：一曰景星，王者德至天则景星见。二曰周伯星，黄色煌煌然，所见之国大昌。三曰含誉星，光耀似彗，有德者昌。四曰格泽星，如炎火之状，见则不种而获。五曰归邪星，如星非星，如云非云，归国者昌。妖星有六：一曰彗星，光芒四射如彗，见则兵起。二曰孛星，光芒短而色白，见则内乱。三曰天棓星，状如大星而有尾，见则争地。四曰天枪星，左右有芒角，见则兵丧。五曰天欃星，状如扫帚，见则天下乱。六曰蚩尤旗，类彗而曲，见则王者征伐四方。客星者，非常之星，忽见忽没。客星出角宿则兵起，出亢宿则大水，出氐宿则大疫，出房宿则大臣死，出心宿则天子忧，出尾宿则后宫乱，出箕宿则风灾，出斗宿则谷贵，出牛宿则人多死，出女宿则女工废，出虚宿则天下虚，出危宿则国危，出室宿则宫室焚，出壁宿则文人死，出奎宿则兵乱，出娄宿则祭祀废，出胃宿则仓廪空，出昴宿则胡兵至，出毕宿则边兵起，出觜宿则军败，出参宿则刑法酷，出井宿则水泉竭，出鬼宿则鬼神乱，出柳宿则饥馑至，出星宿则衣帛贵，出张宿则礼废，出翼宿则远人叛，出轸宿则车骑损。流星者，自上而降曰流，自下而升曰飞，大者曰奔。流星色赤则将叛，色白则大将死，色黄则喜事至，色青则疫病行，色黑则死丧之事。流星入紫微垣，则天子有忧。流星入太微垣，则朝廷有变。流星入天市垣，则百姓流徙。流星大如瓮，则王者失地。流星如月，则大臣叛。流星如日，则天子易位。彗星者，扫除之象也。彗星出东方则齐楚有兵，出西方则秦晋有乱，出南方则吴越有灾，出北方则燕赵有丧。彗星长竟天，则天下大乱，兵革四起，王者死之。

野老·风云占·风占篇

风者，天地之号令也。王者之德及于四方，则八风应时。立春艮气至，条风从东北来。春分震气至，明庶风从东来。立夏巽气至，清明风从东南来。夏至离气至，景风从南来。立秋坤气至，凉风从西南来。秋分兑气至，阊阖风从西来。立冬乾气至，不周风从西北来。冬至坎气至，广莫风从北来。风从其所居之乡来则为实风，主生长万物。风从冲后来则为虚风，伤人者也。风从北方来名曰大刚风，其伤人也内舍于肾，外在于骨与肩背之膂。风从东北来名曰凶风，其伤人也内舍于大肠，外在于两胁腋臂骨下及肢节。风从东方来名曰婴儿风，其伤人也内舍于肝，外在于筋纽。风从东南来名曰弱风，其伤人也内舍于胃，外在于肌肉。风从南方来名曰大弱风，其伤人也内舍于心，外在于脉。风从西南来名曰谋风，其伤人也内舍于脾，外在于肌。风从西方来名曰刚风，其伤人也内舍于肺，外在于皮肤。风从西北来名曰折风，其伤人也内舍于小肠，外在于手太阳脉。凡占风之法，先辨其方，次审其时，再察其势。王者当顺四时八风之理而行政令。春风带湿则百草萌生，春风带燥则春旱伤苗。夏风自南来则暑气正，夏风自北来则寒暑不时。秋风自西来则天气肃杀，秋风自东来则秋雨连绵。冬风自北来则寒气正，冬风自南来则冬暖无雪，来年多虫。凡暴风卒至，必有异事。风从敌来而扬沙，则敌兵将至。风从军后来而温和，则我军必胜。风从军中起而旋绕，则有伏兵。黑风从北方来，则大水至。赤风从南方来，则大火起。青风从东方来，则虫蝗生。白风从西方来，则兵革兴。黄风从中央起，则土功大兴。风拔木发屋，则为大臣专权之象。风扬尘蔽天，则为兵乱将至之征。风无时而作，则为政令不时之兆。

野老·风云占·云占篇

云者，山川之气也。其状不同，其占各异。青云主虫灾，赤云主兵旱，黄云主丰稔，白云主丧乱，黑云主水涝。云如龙形，则为天子得贤。云如虎形，则将有战伐。云如鱼鳞，则明日大风。云如羊群，则数日不雨。云如车盖，则使臣得归。云如旌旗，则兵事将起。云如华盖覆日，则为天子之瑞。云如紫气东来，则为圣人之祥。云如山阜，则为水灾。云如波涛，则为洪水。云如楼台，则为兵乱。云如仙人衣，则为瘟疫。凡候云之法，当于清晨日出时观之。日初出时有云如黄气覆之，是谓黄云捧日，其年大稔。日初出时有青云夹日，是谓青云扶日，其年多雨。日初出时赤云蔽日，是谓赤云贯日，其年大旱。日入时有黑云遮日，明日必有风雨。四方有云：东方有青云如树木状，则东方有兵起。南方有赤云如火焰状，则南方有火灾。西方有白云如刀剑状，则西方有战事。北方有黑云如流水状，则北方有水患。中央有黄云如城阙状，则五谷丰登。韩云如布，赵云如牛，楚云如日，宋云如车，鲁云如马，卫云如犬，周云如轮，秦云如行人，魏云如鼠，郑云如绛衣，越云如龙，蜀云如囷。云气入军营，自敌来则敌兵将至，自我往则我军当进。云气如猪入营，则营中有疫。云气如鸡入营，则营中有乱。云气如犬入营，则营中有盗。云气如蛇入营，则将军失计。云气如凤入营，则将军得胜。

野老·岁时占·四时占篇

四时者，春夏秋冬也。春者，阳气始上，万物萌动。春行夏令则雨水不时，草木早落；春行秋令则大疫流行，疾风暴雨数至；春行冬令则水潦为败，雪霜大挚，首种不入。正月东风解冻，蛰虫始振，鱼上冰，獭祭鱼，鸿雁来。若风不解冻，则号令不行；蛰虫不振，则阴气奸阳；鱼不上冰，则甲胄私藏；獭不祭鱼，则国多盗贼；鸿雁不来，则远人不服。夏者，阳气大盛，万物繁茂。夏行春令则蝗虫为灾，暴风来格；夏行秋令则丘隰水潦，禾稼不熟；夏行冬令则草木早落，后乃大水。四月蝼蝈鸣，蚯蚓出，王瓜生。若蝼蝈不鸣，则水潦淫漫；蚯蚓不出，则嬖妾夺后；王瓜不生，则困于百姓。秋者，阴气始下，万物收成。秋行春令则暖风来至，民气懈惰；秋行夏令则国多火灾，寒热不节；秋行冬令则风灾数起，收雷先行，草木早死。七月凉风至，白露降，寒蝉鸣。若凉风不至，则国无宽政；白露不降，则民多邪病；寒蝉不鸣，则人臣力争。冬者，阴气大盛，万物闭藏。冬行春令则冻闭不密，地气上泄；冬行夏令则暴风发屋，冬雷震震；冬行秋令则霜雪不时，小兵时起。十月水始冰，地始冻，雉入大水为蜃。若水不冰，则为阳失其所；地不冻，则咎征在宫；雉不入大水，则国多淫妇。

野老·岁时占·二十四气占候篇

立春之日，东风解冻。若风从乾来则年丰，从坎来则多雨，从艮来则多疫，从震来则多风，从巽来则多虫，从离来则多旱，从坤来则多霜，从兑来则多兵。占立春日：天气晴明，则一岁丰稔；阴雨则一岁多涝。雨水之日，獭祭鱼。若獭不祭鱼，则国多盗贼。惊蛰之日，桃始华。若不华，则阳气不畅，五谷不实。春分之日，玄鸟至。若不至，则妇人不娠。清明之日，桐始华。若不华，则岁有大寒。谷雨之日，萍始生。若萍不生，则阴气盛而多水。立夏之日，蝼蝈鸣。若不鸣，则水潦为灾。小满之日，苦菜秀。若不秀，则贤人潜伏。芒种之日，螳螂生。若不生，则阴气慝盛。夏至之日，鹿角解。若不角解，则政令不行。小暑之日，温风至。若温风不至，则国无宽政。大暑之日，腐草为萤。若草不腐，则刑法不当。立秋之日，凉风至。若凉风不至，则政令严苛。处暑之日，鹰乃祭鸟。若不祭鸟，则师旅无功。白露之日，鸿雁来。若鸿雁不来，则远人叛。秋分之日，雷始收声。若雷不收声，则诸侯失德。寒露之日，菊有黄华。若菊不华，则土不稼穑。霜降之日，豺乃祭兽。若不祭兽，则民多盗贼。立冬之日，水始冰。若不冰，则为阴失其节。小雪之日，虹藏不见。若虹不藏，则妇不专一。大雪之日，鹖鴠不鸣。若不鸣，则臣下专恣。冬至之日，蚯蚓结。若不结，则君政不行。小寒之日，雁北乡。若不北乡，则民不怀土。大寒之日，鸡始乳。若不乳，则淫女乱政。凡此二十四气，各有所候，各有所占。当至而至则和平，当至而不至则来岁有殃，不当至而至则当岁有变。

野老·岁时占·七十二候占篇

夫七十二候者，五日为一候，三候为一气，六气为一时，四时为一岁，各从其治焉。冬至初候蚯蚓结，次候麋角解，末候水泉动。若不结则政不行，不解则兵不戢，不动则阴不藏。小寒初候雁北乡，次候鹊始巢，末候雉始雊。若不北乡则民不怀土，不巢则盗贼将兴，不雊则国多谣言。大寒初候鸡始乳，次候征鸟厉疾，末候水泽腹坚。若不乳则宫中有乱，不厉疾则将帅不勇，不腹坚则政令不行。立春初候东风解冻，次候蛰虫始振，末候鱼上冰。若不解冻则万物不苏，不振则春令不行，不上冰则庶民有怨。雨水初候獭祭鱼，次候鸿雁来，末候草木萌动。若不祭鱼则民争利，不雁来则远人不服，不萌动则五谷不蕃。惊蛰初候桃始华，次候仓庚鸣，末候鹰化为鸠。若不华则阳气郁，不鸣则臣下不言，不化则为奸人在位。春分初候玄鸟至，次候雷乃发声，末候始电。若不至则妇人不孕，不发则号令不行，不电则君威不振。清明初候桐始华，次候田鼠化为鴽，末候虹始见。若不华则百官废职，不化则小人道长，不见则妇人有乱。谷雨初候萍始生，次候鸣鸠拂其羽，末候戴胜降于桑。若不生则民多流亡，不拂羽则武备不修，不降桑则蚕事不举。立夏初候蝼蝈鸣，次候蚯蚓出，末候王瓜生。若不鸣则政令失时，不出则地气不通，不生则庖厨不备。小满初候苦菜秀，次候靡草死，末候小暑至。若不秀则贤人不用，不死则阴气不伏，不至则暑气失节。芒种初候螳螂生，次候鵙始鸣，末候反舌无声。若不生则五谷不实，不鸣则佞臣在侧，不无声则谗言不止。夏至初候鹿角解，次候蜩始鸣，末候半夏生。若不角解则贤士退隐，不鸣则百姓怨嗟，不生则药草不备。小暑初候温风至，次候蟋蟀居壁，末候鹰乃学习。若温风不至则国无恩泽，不居壁则民失其所，不学习则武臣不训。大暑初候腐草为萤，次候土润溽暑，末候大雨时行。若不萤则阴不化阳，不溽暑则秋禾不茂，不大雨则岁旱民饥。立秋初候凉风至，次候白露降，末候寒蝉鸣。若不至则政暴令急，不降则民多热病，不鸣则朝有谗臣。处暑初候鹰乃祭鸟，次候天地始肃，末候禾乃登。若不祭则兵出无功，不肃则阴气不杀，不登则五谷失时。白露初候鸿雁来，次候玄鸟归，末候群鸟养羞。若不来则远人不至，不归则人民流散，不养羞则臣下僭侈。秋分初候雷始收声，次候蛰虫坯户，末候水始涸。若不收声则君威不肃，不坯户则民不有储，不涸则河渠不治。寒露初候鸿雁来宾，次候雀入大水为蛤，末候菊有黄华。若不来则远方不通，不入水则盗贼多有，不华则地气不实。霜降初候豺乃祭兽，次候草木黄落，末候蛰虫咸俯。若不祭兽则将士骄纵，不黄落则阳气不敛，不咸俯则民气不藏。立冬初候水始冰，次候地始冻，末候雉入大水为蜃。若不冰则来年多疫，不冻则蛰虫不藏，不入水则国多淫佚。小雪初候虹藏不见，次候天气上腾地气下降，末候闭塞而成冬。若不藏则淫妇擅权，不升降则阴阳不交，不闭塞则冬令不行。大雪初候鹖鴠不鸣，次候虎始交，末候荔挺出。若鹖鴠鸣则臣下喧争，不交则阴不感阳，不出则兰草不芳。凡七十二候，顺则为祥，逆则为咎，详而察之，可以知岁之丰歉，时之治乱矣。

野老·物候占·草木篇

草木者，天地之毛发也。观草木之荣枯，可以知岁之丰歉、气之顺逆。正月梅始华，若梅不华则寒气不退，春耕宜迟。杏始华则春气正，可种百谷。桃花盛则阳气盛，宜种秔稻。李花白则雨水调匀，可种黍稷。二月柳始芽，若柳不芽则春寒不解。榆钱生则贫者得食，槐芽出则春气大通。桑叶发则蚕事可兴。三月桐始华，若桐不华则岁有霜灾。牡丹开则百花开，天气清明。芍药发则谷雨时至，宜种豆菽。四月槐花开则夏气至，可种夏谷。榴花红则暑气盛，不宜再种。五月荷花放则暑气正，菱芡生则水泽丰。艾蒿长则阳气极，菖蒲秀则端午至。六月茉莉香则湿热盛，稻花扬则秋有望。七月凤仙开则秋气至，鸡冠花放则霜期近。桂始华则八月将至，百谷当收。八月菊始华则秋气正，芙蓉开则秋深露重。荻花白则秋风劲，芦苇老则秋水寒。九月蓼花红则寒气至，芙蓉落则冬已近。十月梅始胎则一阳来复，山茶开则冬气正。水仙出则腊月近，兰始萌则春不远。十一月枇杷花开则冬暖，瑞香含蕊则春信至。十二月腊梅开则岁已尽，迎春发则新年近。凡草木之应时，各以其类。应时而发则为祥瑞，先时而发则为太过，后时而发则为不及。太过则阳气泄而多灾，不及则阴气凝而多寒。观草木者，俯察之要也。

野老·物候占·鸟兽篇

鸟兽者，天地之灵气也。观鸟兽之动静，可知气运之顺逆。正月雁北归，若雁不北归则春寒不解。鹊始巢，若鹊不巢则盗贼将起。雉始鸣，若雉不鸣则宫中有忧。二月仓庚鸣，若不鸣则时令不正。鹰化为鸠，若不化则小人当道。燕至，若不至则妇人不孕。三月田鼠化为鴽，若不化则阴阳不调。虹始见，若不见则淫乱生。四月蝼蝈鸣，若不鸣则水潦为灾。蚯蚓出，若不出则地气不通。五月螳螂生，若不生则虫灾将起。鵙始鸣，若不鸣则谗言入耳。蝉始鸣，若不鸣则政令不宣。六月鹰乃学习，若不学则武备不修。蟋蟀居壁，若不居壁则民不安居。七月寒蝉鸣，若不鸣则朝有奸臣。鹰祭鸟，若不祭则兵事不利。八月鸿雁来，若不来则远人不服。玄鸟归，若不归则民人流散。九月豺祭兽，若不祭则贪官横行。雀入水为蛤，若不化则盗贼多有。十月雉入水为蜃，若不化则淫乱不止。鹊巢高则风多，巢低则雨多。蚁封户则大雨至。蚯蚓出地则久雨将晴。蛇横道则地动之兆。鼠群迁则水患将至。鸡栖于埘而鸣，则天气将变。犬嘷而不止，则有盗贼之忧。牛喘于夜，则明日大热。马惊于槽，则军旅将动。凡观鸟兽者，察其常与变。常则吉，变则凶。此物候占之大略也。

野老·人事占·行军占篇

行军占候者，将帅所以决胜千里之术也。凡出军之日，先观天象。日中有晕则不可出师。月有晕则夜战可胜。星动摇则军心不定。风从后来则追击必胜。风从前来则我军不利。云气如龙形则王师必胜。云气如虎形则敌兵勇敢。云气如豕形则敌有埋伏。云气如蛇形则行军不利。凡军营中，夜有黑气覆营，则敌兵将至。夜有光气如电，则有伏兵在近。营门无故自开，则奸细在内。旗杆无故自折，则大将不利。旌旗自相缠绕，则军心不一。军器无故自鸣，则战事将起。马无故嘶鸣，则敌人夜袭。牛无故惊奔，则战阵将乱。鼙鼓无声而自鸣，则军中有异。号角不吹而自响，则将有奇功。凡行军之时，日晕而风，则不可渡水。月晕而雨，则不可攻城。雷起于营上，则敌军将退。电起于营中，则将帅有忧。虹贯军营，则大将有难。雹降营中，则士卒多伤。雾起自营内，则不可出战。雾自敌来，则可出奇兵。雪降营中而积，则围城宜急。霜降营中而厚，则战事宜速。凡此皆行军占候之要术也。

野老·人事占·农事占篇

农事占候者，农夫所以测岁知时之术也。凡立春日天气晴和，则一岁太平，五谷丰登。立春日有雪则夏旱。立春日有雨则春雨调匀。正月初一日晴，则岁中多晴。正月初一日雨，则岁中多雨。正月初七日为人日，是日晴则人安，阴则人多病。正月初八日为谷日，是日晴则五谷丰，阴则歉收。正月十五日为上元，是日晴则春少雨，阴则春多雨。二月二日为龙抬头，是日晴则春旱，雨则春雨足。惊蛰日闻雷声，则年丰而物无灾。春分日东风来，则麦收有望。清明日晴，则夏秋多晴。清明日雨，则夏秋多雨。谷雨日雨，则五谷丰收。谷雨日晴，则夏旱少雨。立夏日晴，则夏多晴。立夏日阴，则夏多雨。小满日雨，则河水满而稻丰。芒种日晴，则麦收顺利。夏至日雨，则秋旱。夏至日晴，则秋雨多。小暑日热，则秋后多雨。大暑日热，则冬无大雪。立秋日雨，则秋多雨而谷贵。立秋日晴，则秋风调而谷贱。处暑日晴，则秋禾丰收。白露日阴，则秋雨连绵。秋分日晴，则来岁丰收。寒露日无霜，则冬暖。霜降日霜，则冬寒而雪多。立冬日晴，则一冬晴暖。立冬日阴，则一冬多雪。小雪日雪，则冬雪适宜。大雪日雪，则来年麦丰。冬至日晴，则来年雨多。冬至日雪，则来年旱。小寒日寒，则来年春暖。大寒日寒，则来年虫少。凡此皆农家日用占候之大法也。

野老·择日篇·总论

择日者，选择吉日良辰以行事之术也。古者圣人作甲子，以纪岁月日时。天干有十：甲、乙、丙、丁、戊、己、庚、辛、壬、癸。地支有十二：子、丑、寅、卯、辰、巳、午、未、申、酉、戌、亥。干支相配，六十日而一周。建除家曰：建日宜出行谒贵，除日宜除旧布新，满日宜开仓入货，平日宜整饰墙垣，定日宜婚嫁定盟，执日宜捕猎擒贼，破日宜破屋坏垣，危日宜安抚边境，成日宜入学赴任，收日宜收纳财物，开日宜开市交易，闭日宜修筑堤防。凡十二建星，各有宜忌，不可不审也。

野老·择日篇·建除十二神

