娄宿明则郊祀得礼，暗则祭祀不敬。
胃宿明则仓廪实，暗则仓廪虚。
昴宿明则胡兵起，暗则边境安。
毕宿明则田猎兴，暗则弋猎无度。
觜宿明则军威振，暗则军旅废。
