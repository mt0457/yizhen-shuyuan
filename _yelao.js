荧惑者，南方火星，刑罚之象。
其色赤而光明，其行无常，所至则有兵乱。
荧惑守心，则天子有忧。
荧惑入北斗，则天下乱。
荧惑与太白斗，则大战。
荧惑色变白则为旱，变黑则为水。
镇星者，中央土星，稼穑之象。
其色黄，其行二十八年一周天。
镇星居其所而众星从之，则天下安。
镇星失次，则地动山崩。
镇星守南斗，则岁大熟。
镇星守牵牛，则谷贵民饥。
太白者，西方金星，兵革之象。
其色白，晨出为启明，昏见为长庚。
太白当出不出、当入不入，则天下兵起。
太白昼见，则强国弱、弱国强。
太白经天，则天下革政。
太白与月相掩，则大将死。
辰星者，北方水星，刑罚之象。
其行近太阳，不出四仲之月。
辰星春见则水少，夏见则旱，秋见则霜早，冬见则寒甚。
辰星色白则为旱，色赤则为兵，色黄则为丰。
五星聚于一舍，则圣人出，天下归心。
五星皆逆行，则天下大乱。
五星变色，则各以其类为灾。
故观五星之行度、色相、迟速、顺逆、留守、犯掩、合散，可以知天下之治乱兴衰。

野老·天象占·二十八宿占篇

二十八宿者，天之舍也。
东方七宿：角、亢、氐、房、心、尾、箕，为青龙之象。
北方七宿：斗、牛、女、虚、危、室、壁，为玄武之象。
西方七宿：奎、娄、胃、昴、毕、觜、参，为白虎之象。
南方七宿：井、鬼、柳、星、张、翼、轸，为朱雀之象。
角宿明则天下太平，暗则将帅有忧。
角星动摇，则兵起。
亢宿明则贤臣进，暗则佞臣用。
亢星跃则大水至。
氐宿明则民安，暗则民流。
氐星散则后妃有疾。
房宿明则君明臣良，暗则君昏臣乱。
房星间见，则兵起四方。
心宿明则天下丰稔，暗则天子失位。
心星前星不明则太子忧，后星不明则庶子忧。
尾宿明则后宫安宁，暗则后宫有乱。
尾星聚则大水至。
箕宿明则谷贵，暗则谷贱。
箕星动则有风灾。
斗宿明则君寿，暗则君忧。
斗星变则爵禄不均。
牛宿明则五谷熟，暗则牺牲不备。
牛星移则天下大疫。
女宿明则女工兴，暗则丝帛贵。
女星微则妃后争宠。
虚宿明则天下安，暗则天下虚耗。
危宿明则国泰，暗则国有大丧。
室宿明则宫室成，暗则土木兴。
