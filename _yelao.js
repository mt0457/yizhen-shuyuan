野老·择日篇·五行择日法

五行者，金木水火土也。
春属木，色青，宜用甲乙日。
夏属火，色赤，宜用丙丁日。
秋属金，色白，宜用庚辛日。
冬属水，色黑，宜用壬癸日。
四季之末各十八日属土，色黄，宜用戊己日。
修造之事，各以其方配五行。
东方属木，宜用木日修造，忌金日。
南方属火，宜用火日修造，忌水日。
西方属金，宜用金日修造，忌火日。
北方属水，宜用水日修造，忌土日。
中央属土，宜用土日修造，忌木日。
凡相生之日则吉，相克之日则凶。
木生火，火生土，土生金，金生水，水生木，此五行相生也。
木克土，土克水，水克火，火克金，金克木，此五行相克也。
择日者当取相生之日，避相克之日。
又当合年命而论之，不可一概而论也。

野老·择日篇·黄道吉日

黄道者，日所行之道也。
青龙、明堂、金匮、天德、玉堂、司命，此六神为黄道，值日则吉。
天刑、朱雀、白虎、天牢、玄武、勾陈，此六神为黑道，值日则凶。
青龙值日：宜出行、嫁娶、修造、开市，百事大吉。
明堂值日：宜入学、赴任、修造、祭祀，诸事皆宜。
金匮值日：宜纳财、开仓、立券、交易，求财大吉。
天德值日：宜祭祀、祈福、婚嫁、出行，百福骈臻。
玉堂值日：宜修造、入宅、婚嫁、出行，万事顺遂。
司命值日：宜赴任、出行、修造、入学，官禄升迁。
天刑值日：大凶，不宜出行、婚嫁、开市，犯之有刑伤。
朱雀值日：大凶，不宜词讼、出行、婚嫁，犯之有口舌。
白虎值日：大凶，不宜出行、婚嫁、修造，犯之有血光。
天牢值日：大凶，不宜出行、赴任、婚嫁，犯之有牢狱。
玄武值日：大凶，不宜出行、婚嫁、开市，犯之有盗贼。
勾陈值日：大凶，不宜出行、婚嫁、修造，犯之有牵连。
凡择日者，必求黄道吉日，避黑道凶日。
黄道日中尤以天德、司命为最吉，青龙、明堂次之，金匮、玉堂又次之。
得黄道日而复得天德月德，则大吉大利，万无一失也。

