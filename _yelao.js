野老·天象占·杂星篇

杂星者，瑞星、妖星、客星、流星、彗星之类也。
瑞星有五：一曰景星，王者德至天则景星见。
二曰周伯星，黄色煌煌然，所见之国大昌。
三曰含誉星，光耀似彗，有德者昌。
四曰格泽星，如炎火之状，见则不种而获。
五曰归邪星，如星非星，如云非云，归国者昌。
妖星有六：一曰彗星，光芒四射如彗，见则兵起。
二曰孛星，光芒短而色白，见则内乱。
三曰天棓星，状如大星而有尾，见则争地。
四曰天枪星，左右有芒角，见则兵丧。
五曰天欃星，状如扫帚，见则天下乱。
六曰蚩尤旗，类彗而曲，见则王者征伐四方。
客星者，非常之星，忽见忽没。
客星出角宿则兵起，出亢宿则大水，出氐宿则大疫，出房宿则大臣死，出心宿则天子忧，出尾宿则后宫乱，出箕宿则风灾，出斗宿则谷贵，出牛宿则人多死，出女宿则女工废，出虚宿则天下虚，出危宿则国危，出室宿则宫室焚，出壁宿则文人死，出奎宿则兵乱，出娄宿则祭祀废，出胃宿则仓廪空，出昴宿则胡兵至，出毕宿则边兵起，出觜宿则军败，出参宿则刑法酷，出井宿则水泉竭，出鬼宿则鬼神乱，出柳宿则饥馑至，出星宿则衣帛贵，出张宿则礼废，出翼宿则远人叛，出轸宿则车骑损。
流星者，自上而降曰流，自下而升曰飞，大者曰奔。
流星色赤则将叛，色白则大将死，色黄则喜事至，色青则疫病行，色黑则死丧之事。
流星入紫微垣，则天子有忧。
流星入太微垣，则朝廷有变。
流星入天市垣，则百姓流徙。
流星大如瓮，则王者失地。
流星如月，则大臣叛。
流星如日，则天子易位。
彗星者，扫除之象也。
彗星出东方则齐楚有兵，出西方则秦晋有乱，出南方则吴越有灾，出北方则燕赵有丧。
彗星长竟天，则天下大乱，兵革四起，王者死之。

野老·风云占·风占篇

风者，天地之号令也。
王者之德及于四方，则八风应时。
立春艮气至，条风从东北来。
春分震气至，明庶风从东来。
立夏巽气至，清明风从东南来。
夏至离气至，景风从南来。
立秋坤气至，凉风从西南来。
秋分兑气至，阊阖风从西来。
立冬乾气至，不周风从西北来。
冬至坎气至，广莫风从北来。
风从其所居之乡来则为实风，主生长万物。
风从冲后来则为虚风，伤人者也。
风从北方来名曰大刚风，其伤人也内舍于肾，外在于骨与肩背之膂。
风从东北来名曰凶风，其伤人也内舍于大肠，外在于两胁腋臂骨下及肢节。
风从东方来名曰婴儿风，其伤人也内舍于肝，外在于筋纽。
风从东南来名曰弱风，其伤人也内舍于胃，外在于肌肉。
风从南方来名曰大弱风，其伤人也内舍于心，外在于脉。
风从西南来名曰谋风，其伤人也内舍于脾，外在于肌。
风从西方来名曰刚风，其伤人也内舍于肺，外在于皮肤。
风从西北来名曰折风，其伤人也内舍于小肠，外在于手太阳脉。
凡占风之法，先辨其方，次审其时，再察其势。
王者当顺四时八风之理而行政令。
春风带湿则百草萌生，春风带燥则春旱伤苗。
夏风自南来则暑气正，夏风自北来则寒暑不时。
秋风自西来则天气肃杀，秋风自东来则秋雨连绵。
冬风自北来则寒气正，冬风自南来则冬暖无雪，来年多虫。
凡暴风卒至，必有异事。
风从敌来而扬沙，则敌兵将至。
风从军后来而温和，则我军必胜。
风从军中起而旋绕，则有伏兵。
黑风从北方来，则大水至。
赤风从南方来，则大火起。
青风从东方来，则虫蝗生。
白风从西方来，则兵革兴。
黄风从中央起，则土功大兴。
风拔木发屋，则为大臣专权之象。
风扬尘蔽天，则为兵乱将至之征。
风无时而作，则为政令不时之兆。

野老·风云占·云占篇

云者，山川之气也。
其状不同，其占各异。
青云主虫灾，赤云主兵旱，黄云主丰稔，白云主丧乱，黑云主水涝。
云如龙形，则为天子得贤。
云如虎形，则将有战伐。
云如鱼鳞，则明日大风。
云如羊群，则数日不雨。
云如车盖，则使臣得归。
云如旌旗，则兵事将起。
云如华盖覆日，则为天子之瑞。
云如紫气东来，则为圣人之祥。
云如山阜，则为水灾。
云如波涛，则为洪水。
云如楼台，则为兵乱。
云如仙人衣，则为瘟疫。
凡候云之法，当于清晨日出时观之。
日初出时有云如黄气覆之，是谓黄云捧日，其年大稔。
日初出时有青云夹日，是谓青云扶日，其年多雨。
日初出时赤云蔽日，是谓赤云贯日，其年大旱。
日入时有黑云遮日，明日必有风雨。
四方有云：东方有青云如树木状，则东方有兵起。
南方有赤云如火焰状，则南方有火灾。
西方有白云如刀剑状，则西方有战事。
北方有黑云如流水状，则北方有水患。
中央有黄云如城阙状，则五谷丰登。
韩云如布，赵云如牛，楚云如日，宋云如车，鲁云如马，卫云如犬，周云如轮，秦云如行人，魏云如鼠，郑云如绛衣，越云如龙，蜀云如囷。
云气入军营，自敌来则敌兵将至，自我往则我军当进。
云气如猪入营，则营中有疫。
云气如鸡入营，则营中有乱。
云气如犬入营，则营中有盗。
云气如蛇入营，则将军失计。
云气如凤入营，则将军得胜。

野老·岁时占·四时占篇

四时者，春夏秋冬也。
春者，阳气始上，万物萌动。
春行夏令则雨水不时，草木早落；春行秋令则大疫流行，疾风暴雨数至；春行冬令则水潦为败，雪霜大挚，首种不入。
正月东风解冻，蛰虫始振，鱼上冰，獭祭鱼，鸿雁来。
若风不解冻，则号令不行；蛰虫不振，则阴气奸阳；鱼不上冰，则甲胄私藏；獭不祭鱼，则国多盗贼；鸿雁不来，则远人不服。
夏者，阳气大盛，万物繁茂。
夏行春令则蝗虫为灾，暴风来格；夏行秋令则丘隰水潦，禾稼不熟；夏行冬令则草木早落，后乃大水。
四月蝼蝈鸣，蚯蚓出，王瓜生。
若蝼蝈不鸣，则水潦淫漫；蚯蚓不出，则嬖妾夺后；王瓜不生，则困于百姓。
秋者，阴气始下，万物收成。
秋行春令则暖风来至，民气懈惰；秋行夏令则国多火灾，寒热不节；秋行冬令则风灾数起，收雷先行，草木早死。
七月凉风至，白露降，寒蝉鸣。
若凉风不至，则国无宽政；白露不降，则民多邪病；寒蝉不鸣，则人臣力争。
冬者，阴气大盛，万物闭藏。
冬行春令则冻闭不密，地气上泄；冬行夏令则暴风发屋，冬雷震震；冬行秋令则霜雪不时，小兵时起。
十月水始冰，地始冻，雉入大水为蜃。
若水不冰，则为阳失其所；地不冻，则咎征在宫；雉不入大水，则国多淫妇。

野老·岁时占·二十四气占候篇

立春之日，东风解冻。
若风从乾来则年丰，从坎来则多雨，从艮来则多疫，从震来则多风，从巽来则多虫，从离来则多旱，从坤来则多霜，从兑来则多兵。
占立春日：天气晴明，则一岁丰稔；阴雨则一岁多涝。
雨水之日，獭祭鱼。
若獭不祭鱼，则国多盗贼。
惊蛰之日，桃始华。
若不华，则阳气不畅，五谷不实。
春分之日，玄鸟至。
若不至，则妇人不娠。
清明之日，桐始华。
若不华，则岁有大寒。
谷雨之日，萍始生。
若萍不生，则阴气盛而多水。
立夏之日，蝼蝈鸣。
若不鸣，则水潦为灾。
小满之日，苦菜秀。
若不秀，则贤人潜伏。
芒种之日，螳螂生。
若不生，则阴气慝盛。
夏至之日，鹿角解。
若不角解，则政令不行。
小暑之日，温风至。
若温风不至，则国无宽政。
大暑之日，腐草为萤。
若草不腐，则刑法不当。
立秋之日，凉风至。
若凉风不至，则政令严苛。
处暑之日，鹰乃祭鸟。
若不祭鸟，则师旅无功。
白露之日，鸿雁来。
若鸿雁不来，则远人叛。
秋分之日，雷始收声。
若雷不收声，则诸侯失德。
寒露之日，菊有黄华。
若菊不华，则土不稼穑。
霜降之日，豺乃祭兽。
若不祭兽，则民多盗贼。
立冬之日，水始冰。
若不冰，则为阴失其节。
小雪之日，虹藏不见。
若虹不藏，则妇不专一。
大雪之日，鹖鴠不鸣。
若不鸣，则臣下专恣。
冬至之日，蚯蚓结。
若不结，则君政不行。
小寒之日，雁北乡。
若不北乡，则民不怀土。
大寒之日，鸡始乳。
若不乳，则淫女乱政。
凡此二十四气，各有所候，各有所占。
当至而至则和平，当至而不至则来岁有殃，不当至而至则当岁有变。

野老·岁时占·七十二候占篇

夫七十二候者，五日为一候，三候为一气，六气为一时，四时为一岁，各从其治焉。
冬至初候蚯蚓结，次候麋角解，末候水泉动。
若不结则政不行，不解则兵不戢，不动则阴不藏。
小寒初候雁北乡，次候鹊始巢，末候雉始雊。
若不北乡则民不怀土，不巢则盗贼将兴，不雊则国多谣言。
大寒初候鸡始乳，次候征鸟厉疾，末候水泽腹坚。
若不乳则宫中有乱，不厉疾则将帅不勇，不腹坚则政令不行。
立春初候东风解冻，次候蛰虫始振，末候鱼上冰。
若不解冻则万物不苏，不振则春令不行，不上冰则庶民有怨。
雨水初候獭祭鱼，次候鸿雁来，末候草木萌动。
若不祭鱼则民争利，不雁来则远人不服，不萌动则五谷不蕃。
惊蛰初候桃始华，次候仓庚鸣，末候鹰化为鸠。
若不华则阳气郁，不鸣则臣下不言，不化则为奸人在位。
春分初候玄鸟至，次候雷乃发声，末候始电。
若不至则妇人不孕，不发则号令不行，不电则君威不振。
清明初候桐始华，次候田鼠化为鴽，末候虹始见。
若不华则百官废职，不化则小人道长，不见则妇人有乱。
谷雨初候萍始生，次候鸣鸠拂其羽，末候戴胜降于桑。
若不生则民多流亡，不拂羽则武备不修，不降桑则蚕事不举。
立夏初候蝼蝈鸣，次候蚯蚓出，末候王瓜生。
若不鸣则政令失时，不出则地气不通，不生则庖厨不备。
小满初候苦菜秀，次候靡草死，末候小暑至。
若不秀则贤人不用，不死则阴气不伏，不至则暑气失节。
芒种初候螳螂生，次候鵙始鸣，末候反舌无声。
若不生则五谷不实，不鸣则佞臣在侧，不无声则谗言不止。
夏至初候鹿角解，次候蜩始鸣，末候半夏生。
若不角解则贤士退隐，不鸣则百姓怨嗟，不生则药草不备。
小暑初候温风至，次候蟋蟀居壁，末候鹰乃学习。
若温风不至则国无恩泽，不居壁则民失其所，不学习则武臣不训。
大暑初候腐草为萤，次候土润溽暑，末候大雨时行。
若不萤则阴不化阳，不溽暑则秋禾不茂，不大雨则岁旱民饥。
立秋初候凉风至，次候白露降，末候寒蝉鸣。
若不至则政暴令急，不降则民多热病，不鸣则朝有谗臣。
处暑初候鹰乃祭鸟，次候天地始肃，末候禾乃登。
若不祭则兵出无功，不肃则阴气不杀，不登则五谷失时。
白露初候鸿雁来，次候玄鸟归，末候群鸟养羞。
若不来则远人不至，不归则人民流散，不养羞则臣下僭侈。
秋分初候雷始收声，次候蛰虫坯户，末候水始涸。
若不收声则君威不肃，不坯户则民不有储，不涸则河渠不治。
寒露初候鸿雁来宾，次候雀入大水为蛤，末候菊有黄华。
若不来则远方不通，不入水则盗贼多有，不华则地气不实。
霜降初候豺乃祭兽，次候草木黄落，末候蛰虫咸俯。
若不祭兽则将士骄纵，不黄落则阳气不敛，不咸俯则民气不藏。
立冬初候水始冰，次候地始冻，末候雉入大水为蜃。
若不冰则来年多疫，不冻则蛰虫不藏，不入水则国多淫佚。
小雪初候虹藏不见，次候天气上腾地气下降，末候闭塞而成冬。
若不藏则淫妇擅权，不升降则阴阳不交，不闭塞则冬令不行。
大雪初候鹖鴠不鸣，次候虎始交，末候荔挺出。
若鹖鴠鸣则臣下喧争，不交则阴不感阳，不出则兰草不芳。
凡七十二候，顺则为祥，逆则为咎，详而察之，可以知岁之丰歉，时之治乱矣。

野老·物候占·草木篇

