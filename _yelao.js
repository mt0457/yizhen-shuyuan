野老·择日篇·总论

择日者，选择吉日良辰以行事之术也。
古者圣人作甲子，以纪岁月日时。
天干有十：甲、乙、丙、丁、戊、己、庚、辛、壬、癸。
地支有十二：子、丑、寅、卯、辰、巳、午、未、申、酉、戌、亥。
