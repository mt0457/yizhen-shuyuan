建除家曰：建日宜出行谒贵，除日宜除旧布新，满日宜开仓入货，平日宜整饰墙垣，定日宜婚嫁定盟，执日宜捕猎擒贼，破日宜破屋坏垣，危日宜安抚边境，成日宜入学赴任，收日宜收纳财物，开日宜开市交易，闭日宜修筑堤防。
