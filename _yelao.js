野老·择日篇·五行择日法

五行者，金木水火土也。春属木，色青，宜用甲乙日。夏属火，色赤，宜用丙丁日。秋属金，色白，宜用庚辛日。冬属水，色黑，宜用壬癸日。四季之末各十八日属土，色黄，宜用戊己日。修造之事，各以其方配五行。东方属木，宜用木日修造，忌金日。南方属火，宜用火日修造，忌水日。西方属金，宜用金日修造，忌火日。北方属水，宜用水日修造，忌土日。中央属土，宜用土日修造，忌木日。凡相生之日则吉，相克之日则凶。木生火，火生土，土生金，金生水，水生木，此五行相生也。木克土，土克水，水克火，火克金，金克木，此五行相克也。择日者当取相生之日，避相克之日。又当合年命而论之，不可一概而论也。

