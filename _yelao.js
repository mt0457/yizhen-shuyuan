野老·占候综述篇

占候者，观天象、察物类、审气数以知吉凶之术也。
古者圣王治世，必设灵台之官，仰观天文，俯察地理，以明天道，以授民时。
昔伏羲氏仰观象于天，俯观法于地，观鸟兽之文与地之宜，近取诸身，远取诸物，于是始作八卦，以通神明之德，以类万物之情。
此占候之始也。
黄帝命羲和占日，常仪占月，臾区占星气，大挠作甲子，容成造历法。
是以观乎天文，以察时变；观乎人文，以化成天下。
自三代以来，占候之学代有传承。
周有保章氏，掌天星以志星辰日月之变动，以观天下之迁，辨其吉凶。
又有冯相氏，掌十有二岁、十有二月、十有二辰、十日、二十有八星之位，辨其叙事，以会天位。
秦有甘公石申，楚有唐昧，赵有尹皋，魏有孙膑，皆以占候名世。
汉兴，司马迁作天官书，详列星官，论其占验。
张衡制浑天仪，精测天象，著灵宪，开占候之新局。
其后李淳风作乙巳占，瞿昙悉达辑开元占经，庾季才著灵台秘苑，历代相承，蔚为大观。
占候之学，大要有五：一曰天象占，观日月五星二十八宿之变动；二曰风云占，察四方云气风色之异同；三曰岁时占，候四时八节二十四气七十二候之正变；四曰物候占，审草木鸟兽虫鱼之应时；五曰人事占，参人事之顺逆以合天道。
五者兼备，则可以见微知著，防患未然。
故曰：知天者圣，知时者明。
观天之道，执天之行，尽矣。

