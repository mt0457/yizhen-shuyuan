天人焉有两般义，道不虚行只在人。

【清夜吟】
月到天心处，风来水面时。
一般清意味，料得少人知。

【冬至吟】
冬至子之半，天心无改移。
一阳初动处，万物未生时。
玄酒味方淡，大音声正希。
此言如不信，更请问庖牺。

【首尾吟】
尧夫非是爱吟诗，诗是尧夫尽性时。
若圣与人吾岂敢，不忧不惧是男儿。

【安乐窝中自贻】
安乐窝中快活人，闲来四物幸相亲。
一编诗逸收花月，一部书严惊鬼神。
一炷香清冲宇泰，一樽酒美湛天真。
太平自庆何多也，唯愿君王寿万春。

