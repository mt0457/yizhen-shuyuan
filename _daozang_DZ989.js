北辰之上，紫微宫中。中斗大魁，注算尊崇。善恶为凭，算有减增。行善延寿，作恶夭终。七星照命，五斗朝宗。至诚礼斗，感通星宫。延寿益算，消灾免凶。福禄增崇，智慧开通。命自我立，福自我隆。精勤修持，与道合融。皈依道经师三宝。志心称念：中天大圣北斗中宫大魁注算星君，中斗延寿益算天尊。大魁注算不可思议功德。中斗度人无量天尊。
