炼丹之目的在长生——长生者，生生不息之道也，
故以面向东方为最佳朝向——东方为日出之方、青灵始炁之所在、一切生机之源头。
面向东方静坐，可以吸收东方生发之炁以滋养自身之生机。
若东方不便（如房间窗户向西），面向南方亦可——南方赤帝丹灵之炁主长养，有助于丹火之燃烧。
一般忌讳面向北方静坐——北方黑帝五灵之炁主收藏（近乎死寂），对炼丹之生机活泼有抑制之虞。
至于西方主收敛，亦不甚适宜——收敛者杀伐之气，不利丹道之生生之意。
若实在无法选择朝向，可面朝房间中光线最充足之方向——光明属阳、阴暗属阴，炼丹是阳生之事，宜向阳。
