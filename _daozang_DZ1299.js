<p style="line-height:2.2;">
本经末附正一道三十六种大科总目，以资索检：（1）玉皇大斋（2）黄箓大斋（3）九幽大醮（4）罗天大醮（5）周天大醮（6）普天大醮（7）三官法忏（8）礼斗大科（9）文昌大醮（10）药王大醮（11）城隍大醮（12）社稷大醮（13）祈晴大醮（14）祷雨大醮（15）禳蝗大醮（16）禳疫大醮（17）禳火大醮（18）禳星大醮（19）授箓大科（20）传度大科（21）奏职大科（22）水火炼度（23）血湖大醮（24）破狱大科（25）施食大科（26）安龙奠土（27）开光大科（28）封山大科（29）祭天大科（30）通天大醮（31）度桥大醮（32）放生大科（33）还愿大醮（34）谢土大科（35）祭江大醮（36）普度大醮。以上三十六种大科，每一科皆有其完整之坛场规制、法器配备、经咒疏文、存思诀法、音乐步虚等详细科范——因其篇幅浩大，本经限于体例只详述其要义，各科之完整科范备载于正一道各山宫观之《科仪本》中，学道者可就近参阅师传秘本。
</p>

