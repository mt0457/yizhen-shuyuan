<p style="font-size:16px;color:#8b1a1a;line-height:2.2;margin:0;">
<b>九晨在天为星斗，在法为飞步，在身为关窍，在道为根本。
踏其罡以合其轨，诵其咒以感其灵，存其光以应其明，服其炁以纳其精。
四步合一，久而通神。魂朝北斗，名列长生。星辉护体，万邪不侵。
灾消厄解，智慧开明。身心康泰，福报日增。临终接引，永离幽冥。
修道有成，飞升太清。稽首皈依，北斗九晨。至心朝礼，九星星君。
九晨飞行天尊。中天大圣北斗九星星君。不可思议功德。</b>
</p>
