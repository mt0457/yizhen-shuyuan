【楔子】

（卜儿蔡婆上，诗云）花有重开日，人无再少年。不须长富贵，安乐是神仙。老身蔡婆婆是也。楚州人氏，嫡亲三口儿家属。不幸夫主亡逝已过，止有一个孩儿，年长八岁。俺娘儿两个，过其日月。家中颇有些钱财。这里一个窦秀才，从去年问我借了二十两银子，如今本利该银四十两。我数次索取，那窦秀才只说贫难，没得还我。他有一个女儿，今年七岁，生得可喜，长得可爱。我有心看上他，与我家做个媳妇，就准了这四十两银子，岂不两得其便。他说今日好日辰，亲送女儿到我家来。老身且不索钱去，专在家中等候。这早晚窦秀才敢待来也。

（冲末扮窦天章，引正旦扮端云上，诗云）读尽缥缃万卷书，可怜贫煞马相如。汉庭一日承恩召，不说当垆说子虚。小生姓窦，名天章，祖贯长安京兆人也。幼习儒业，饱有文章。争奈时运不通，功名未遂。不幸浑家亡化已过，撇下这个女孩儿，小字端云。从三岁上亡了他母亲，如今孩儿七岁了也。小生一贫如洗，流落在这楚州居住。此间一个蔡婆婆，他家广有钱物。小生因无盘缠，曾借了他二十两银子，到今本利该还他四十两。他数次问小生索取。教我把甚么还他？谁想蔡婆婆常常着人来说，要小生女孩儿做他儿媳妇。况如今春榜动，选场开，正待上朝取应，又苦盘缠缺少。小生出于无奈，只得将女孩儿端云送与蔡婆婆做儿媳妇去。（做叹科，云）嗨！这个那里是做媳妇？分明是卖与他一般。就准了他那先借的四十两银子，分外但得些少东西，勾小生应举之费，便也过望了。说话之间，早来到他家门首。婆婆在家么？

（卜儿上，云）秀才，请家里坐，老身等候多时也。（做相见科，窦天章云）小生今日一径的将女孩儿送来与婆婆，怎敢说做媳妇，只与婆婆早晚使用。小生目下就要上朝进取功名去，留下女孩儿在此，只望婆婆看觑则个！（卜儿云）这等，你是我亲家了。你本利少我四十两银子，兀的是借钱的文书还了你，再送与你十两银子做盘缠。亲家，你休嫌轻少。（窦天章做谢科，云）多谢了婆婆！先少你许多银子，都不要我还了，今又送我盘缠，此恩异日必当重报。婆婆，女孩儿早晚呆痴，看小生薄面，看觑女孩儿咱。（卜儿云）亲家，这不消你嘱付。令爱到我家，就做亲女儿一般看承他，你只管放心的去。（窦天章云）婆婆，端云孩儿该打呵，看小生面则骂几句；当骂呵，则处分几句。孩儿，你也不比在我跟前，我是你亲爷，将就的你。你如今在这里，早晚若顽劣呵，你只讨那打骂吃。儿嚛，我也是出于无奈！（做悲科，唱）

【仙吕·赏花时】我也只为无计营生四壁贫，因此上割舍得亲儿在两处分。从今日远践洛阳尘，又不知归期定准，则落的无语闇消魂。（下）

（卜儿云）窦秀才留下他这女孩儿与我做媳妇儿，他一径上朝应举去了。（正旦做悲科，云）爹爹，你直下的撇了我孩儿去也！（卜儿云）媳妇儿，你在我家，我是亲婆，你是亲媳妇，只当自家骨肉一般。你不要啼哭，跟着老身前后执料去来。（同下）

