立冬、冬至八个节气——皆可行此忏法。凡以至诚心礼忏者，能消灾延寿、解厄度亡、增福添算、保命长生。
全忏以太上道君说经为缘起，详述东岳大帝之神职威德、众生罪业之根源种类、忏悔之方法与仪轨、
礼拜之功德与利益，为道教东岳信仰中最为重要的忏法经典之一。
