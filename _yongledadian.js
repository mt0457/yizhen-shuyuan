朕惟昔者圣王之法天下也，文武并用，一张一弛。文以治天下，武以定祸乱。朕承天命，统御万方，宵旰忧勤，罔敢暇逸。思以文德绥海内，以武威服四夷。尝观《韵府群玉》《回溪史韵》诸书，事虽有统，而采摘不广，纪载太略。尔等其尚体朕怀，毋惮繁剧，毋忽细微。凡书契以来，经史子集百家之书，至于天文、地志、阴阳、医卜、僧道、技艺之言，备辑为一书。毋厌浩繁，毋惮搜采。庶几因韵以考字，因字以求事，开卷而古今之事，一览可见。昔孔子删述六经，以垂教万世。朕法其意，集诸子百家之言，以成一书，名曰《永乐大典》。庶几有裨于治道，有补于世教。凡我子孙臣庶，其敬承之。故序。

永乐五年十一月乙丑

