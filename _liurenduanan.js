【案卅八·占求子】甲戌日，子将，卯时，夫妻占能否得子。四课：干上卯（六合），支上子（天后）。三传：卯、子、午。断曰：六合为子嗣之象，天后为母。卯为桃花子息，子为水润木生。子午虽冲而卯木通关。子年可得子。果子年生一男。

【案卅九·占孕安】己丑日，巳将，戌时，占孕中安否。四课：干上戌（天空），支上巳（螣蛇）。三传：戌、丑、午。断曰：天空为虚，螣蛇为惊。孕妇有虚惊之象。三传戌丑午，午为末传火旺。南方避之（火旺之地）。后果有惊无险，顺产。

【案四十·占子息】壬寅日，申将，子时，占子女未来如何。四课：干上子（天后），支上申（白虎）。三传：子、申、辰。断曰：天后为母，子息旺盛之象。三传子申辰合水局，水主智慧。子女聪明有才。后子果科举有成。

