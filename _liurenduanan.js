【案廿八·占行人归】庚寅日，亥将，午时，家占外出经商者何时归。四课：干上午（朱雀），支上亥（玄武）。三传：午、戌、寅。断曰：马星在寅，初传为午——马星未显在三传之初。寅为末传，寅月可归。果次年正月（寅月）归家。

【案廿九·占行人安否】壬子日，辰将，申时，家占远行之子是否平安。四课：干上申（白虎），支上辰（勾陈）。三传：申、子、辰。断曰：白虎临干，旅途有险。三传申子辰合水局，申金生水，水为流通。已过险境，平安无事。后果平安归家。

【案三十·占音信】丁卯日，酉将，巳时，占远方亲人何时有音信。四课：干上巳（螣蛇），支上酉（太阴）。三传：巳、酉、丑。断曰：太阴为文书音信，螣蛇为信息虚惊。三传巳酉丑合金局。酉月（八月）当有信至。果八月得家书。

