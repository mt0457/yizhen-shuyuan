【正月·登明亥将】亥为正月将，属水，其神为登明。登明主文书、阴私、沟渠、猪畜。正月占事，亥将临宫，水旺则事主流动变化。亥加寅卯为水木相生，主文书吉利。亥加巳午为水火既济，事有转机。亥加申酉为金生水，得贵人助。亥加亥子丑为三会水局，事多反复难定。登明临干百事吉，临支家宅有阴私之事。

【二月·河魁戌将】戌为二月将，属土，其神为河魁。河魁主欺诈、牢狱、旧事、犬畜。二月占事，戌将临宫，土旺则事主迟滞。戌加寅卯为土木相克，事有阻隔。戌加巳午为火土相生，经努力可成。戌加申酉为土生金泄气，付出多而得少。戌加辰为天罗地网，讼事不利。河魁临干防欺诈，临支家宅有旧事未了。

【三月·从魁酉将】酉为三月将，属金，其神为从魁。从魁主阴私、婚姻、金银、鸡禽。三月占事，酉将临宫，金旺则事主决断。酉加寅卯为金克木，事多竞争。酉加巳午火克金，女命防口舌。酉加亥子为金生水，阴事暗成。巳酉丑合金局则阴人成事。从魁临干婚姻可就，临支家中有阴私之事。

【四月·传送申将】申为四月将，属金，其神为传送。传送主道路、驿马、迁移、猴兽。四月占事，申将临宫，金旺则事主变动迁移。申加寅卯为金克木，出行有阻。申加巳午火克金，旅途小心火盗。申加亥子为金生水，行船有利。申子辰合水局则迁徙可成。传送临干出行吉，临支家中有迁徙之议。

【五月·小吉未将】未为五月将，属土，其神为小吉。小吉主宴饮、医药、酒食、羊畜。五月占事，未将临宫，土旺则事主和合。未加寅卯为木克土，宴席有变。未加巳午为火土相生，饮食丰盛。未加巳酉丑合金为土生金，酒食破财。亥卯未合木局则医药有效。小吉临干宴饮吉，临支家中有病人服药。

【六月·胜光午将】午为六月将，属火，其神为胜光。胜光主文书、光明、眼目、马畜。六月占事，午将临宫，火旺则事主迅速。午加寅卯木生火，文事亨通。午加申酉火克金，官司口舌。寅午戌合火局则文书上达天听。午加亥子水火冲则事有反复。胜光临干求名吉，临支家中有文书纷争。

【七月·太乙巳将】巳为七月将，属火，其神为太乙。太乙主口舌、怪异、炉灶、蛇虫。七月占事，巳将临宫，火旺金囚则事主变化多端。巳加寅卯火得木生，有贵人扶助。巳加申酉火克金，防金属之伤。巳酉丑合金局而巳在其中，以火炼金，技艺有成。巳加亥为巳亥冲，事多变故。

【八月·天罡辰将】辰为八月将，属土，其神为天罡。天罡主争斗、牢狱、山岭、龙鱼。八月占事，辰将临宫，土旺金相则事主刚猛。辰加寅卯木克土，竞争激烈。辰加巳午火土相生，讼事得解。寅卯辰会木局则天罡失势，主争斗失利。辰加戌为辰戌冲，官非必至。天罡临干防争斗，临支家宅有争讼。

【九月·太冲卯将】卯为九月将，属土，其神为太冲。太冲主舟车、盗贼、门户、兔狐。九月占事，卯将临宫，木旺则事主迅速变动。卯加巳午木生火，文事可成。卯加申酉金克木，出行有阻、防盗贼。卯加亥子水生木，舟车有利。亥卯未合木局则迁移大利。太冲临干出行吉，临支门户防贼。

【十月·功曹寅将】寅为十月将，属木，其神为功曹。功曹主官禄、文书、驿马、虎豹。十月占事，寅将临宫，木旺则事主上升。寅加巳午木生火，官职擢升。寅加申酉金克木，升迁有阻。寅午戌合火局则官禄文书顺利。寅加亥子水生木，文书得批复。功曹临干求官吉，临支家中有人调动。

【十一月·大吉丑将】丑为十一月将，属土，其神为大吉。大吉主贵人、田宅、将军、牛畜。十一月占事，丑将临宫，土旺水相则事主稳重。丑加寅卯木克土，贵人失势。丑加巳酉合金为土生金，贵人相助得财。巳酉丑合金局则贵人得力。丑加未为丑未冲，田宅有变。大吉临干贵人助，临支田宅有喜。

【十二月·神后子将】子为十二月将，属水，其神为神后。神后主妇女、暗昧、淫泆、鼠窃。十二月占事，子将临宫，水旺则事主暗昧。子加寅卯水生木，妇女有喜。子加巳午水克火，妇女有灾。申子辰合水局则阴事全成。子加午为子午冲，妇女口舌。神后临干妇女吉，临支家中有阴私之事。

