【案五十一·占谒贵】庚子日，巳将，午时，占拜访贵人是否得见。四课：干上午（朱雀），支上巳（螣蛇）。三传：午、子、卯。断曰：贵人丑未未显，朱雀为文书先通。螣蛇巳火临支，贵人处有客需等。午日去可见。果午日得见。

【案五十二·占访友】乙巳日，申将，辰时，占访友是否在家。四课：干上辰（勾陈），支上申（白虎）。三传：辰、酉、寅。断曰：勾陈为停留，白虎为不在。友不在家，酉日再去方见。果当日不在，三日后（酉日）得见。

【案五十三·占托人】丁丑日，亥将，巳时，占托人办事是否可靠。四课：干上巳（螣蛇），支上亥（玄武）。三传：巳、酉、丑。断曰：螣蛇虚惊，玄武暗昧。所托之人不可靠。三传巳酉丑合金局，酉为太阴主算计。果被所托之人坑骗。

【案五十四·占合伙】戊辰日，午将，辰时，占与某人合伙是否可行。四课：干上辰（勾陈），支上午（朱雀）。三传：辰、午、申。断曰：勾陈为合伙，朱雀为口舌。地支同勾（辰辰），合伙中有争执之象。三传辰午申，末传申金克干（戊土），合伙结局不佳。劝勿合伙。后果因财争吵散伙。

【案五十五·占佣人】甲午日，酉将，申时，占雇佣人是否勤恳。四课：干上申（白虎），支上酉（太阴）。三传：申、亥、寅。断曰：白虎临干，佣人性刚。太阴临支，有隐藏之事。三传申亥寅，亥水通关。佣人可用但需防。后果雇一能吏但后贪小利。

【案五十六·占师徒】辛巳日，丑将，卯时，占拜师学艺是否适宜。四课：干上卯（六合），支上丑（贵人）。三传：卯、巳、未。断曰：六合为和合，贵人为名师。支上贵人丑，师父有德望。三传卯巳未顺生，学业有成。果拜师后技艺精进。

【案五十七·占出行方向】壬午日，辰将，寅时，占出行应往何方向。四课：干上寅（青龙驿马），支上辰（勾陈）。三传：寅、午、戌。断曰：青龙临干驿马发动，出行大利。寅为东方青龙本位，宜向东方。果向东方出行得利。

【案五十八·占渡江】乙酉日，巳将，午时，占渡江是否安全。四课：干上午（朱雀），支上巳（螣蛇）。三传：午、丑、申。断曰：巳火为螣蛇，午火朱雀，火旺生土克水。虽有风波而不足为患。末传申白虎金生水，午后风平。果午后渡江安全。

【案五十九·占出师】庚申日，卯将，申时，将军占出兵吉凶。四课：干上申（白虎），支上卯（六合）。三传：申、子、辰。断曰：白虎临干加申金本位，杀气极重。地支申白虎支上卯六合——敌有防备。三传申子辰合水局泄金气。不宜出兵。果未听而败。

【案六十·占选将】丙子日，午将，辰时，占选何人为将。四课：干上辰（勾陈），支上午（朱雀）。三传：辰、申、子。断曰：勾陈为将，朱雀为名。三传辰申子合水局，水克火日主。宜选北方之人（水旺之方）。果选北将为胜。

