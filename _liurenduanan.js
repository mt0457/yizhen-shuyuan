【占天时歌】朱雀螣蛇火为晴，天后玄武水雨临。六合青龙风伯至，勾陈太乙土主阴。白虎传送雷霹雳，太阴从魁霜雪侵。天空河魁多阴晦，登明神后水淋淋。功曹太冲多风起，胜光光明大晴明。天罡大吉多阴雨，占时配合自分明。

【占婚姻歌】六合太阴婚姻主，天后青龙女貌妍。干上神生支上吉，支上神生干上贤。三传合局婚姻就，贵人临课福禄全。桃花并玄武私约，朱雀并螣蛇口舌。白虎临干支刑克，两处相伤婚不成。

【占求财歌】青龙贵人财禄星，太常小吉酒食盈。干上神生支上利，支上神生干上赢。三传顺生财不断，末传见财终有成。玄武临课防盗贼，天空欺诈财落空。

【占出行歌】驿马临课身将动，青龙六合宜出行。白虎临干防道路，螣蛇朱雀恐虚惊。玄武防失天空阻，劫煞亡神不可行。干上生支归期近，支上生干去未停。

【占疾病歌】白虎死神病沉重，青龙六合医有功。日干受伤病难起，日支受克宅不安。三传见墓防归计，末传逢生可望安。玄武为祟多阴症，螣蛇为病怪异缠。

