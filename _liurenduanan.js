【案卅一·占失马】甲午日，子将，卯时，占失马去向。四课：干上卯（六合），支上子（天后）。三传：卯、子、午。断曰：六合为藏匿，天后为北方。马向北方逃走。午为末传逢冲，午日可寻回。果于北方午日寻回。

【案卅二·占失银】丙寅日，酉将，辰时，商人占失银能否找回。四课：干上辰（勾陈），支上酉（太阴）。三传：辰、酉、寅。断曰：勾陈为守藏，太阴为隐蔽。银未被远盗。酉方（西）辰方（东南）寻之。果在店中东南角柜底寻回。

【案卅三·占失窃】戊戌日，午将，子时，占家遭窃贼去向。四课：干上子（天后），支上午（朱雀）。三传：子、午、卯。断曰：玄武未显而天后在干，窃贼为女性或内贼。卯为六合桃花，贼有同伙。向东方追。果在东方邻村捕获。

【案卅四·占遗失文书】乙丑日，巳将，辰时，占遗失之文书何处寻。四课：干上辰（勾陈），支上巳（螣蛇）。三传：辰、巳、午。断曰：勾陈为文书，螣蛇为虚惊。文书未失，在东南方高处。果于书架上寻得。

