【德神临课】甲德在寅，乙德在申，丙德在巳，丁德在亥，戊德在巳，己德在寅，庚德在申，辛德在巳，壬德在亥，癸德在巳。凡课传中见日德，百事皆吉，逢凶化吉，遇难呈祥。德神临干自身有德，临支家宅有德。德神加于官鬼则官讼得解，加于白虎则灾祸减轻。

【合神应用】甲合己，乙合庚，丙合辛，丁合壬，戊合癸。子合丑，寅合亥，卯合戌，辰合酉，巳合申，午合未。凡课传中见合，主和合、成就、聚合。三合局则事有定局，六合则人事和谐。合多则事有牵连不已。

【驿马发动】寅午戌见申，申子辰见寅，巳酉丑见亥，亥卯未见巳。马星临课传主出行变动。马星在初传即日动身，在中传近日出行，在末传远期有动。马星加干上自己主动出行，加支上他人催促出行。马星逢冲则出发在即，马星逢合则出行有阻。

【羊刃警示】甲刃在卯，乙刃在寅，丙戌刃在午，丁己刃在未，庚刃在酉，辛刃在申，壬刃在子，癸刃在亥。刃为劫财，又为血光。刃临干上防破财伤身，临支上家中有血光之灾。刃加白虎血光必见，刃加玄武盗贼劫财。刃逢冲则灾立至，刃逢合则灾可缓。

【桃花显象】申子辰在酉，寅午戌在卯，亥卯未在子，巳酉丑在午。桃花临课主婚姻、情爱、酒色之事。桃花在干上自己主动，在支上对方有意。桃花加青龙为良缘，加玄武为私情，加朱雀为口舌因色起，加白虎为因色致祸。

【天喜星临】正月起戌顺行十二支。天喜临课传主喜庆，占婚姻大吉，占子嗣有喜，占官禄升迁。天喜加六合天作之合，加青龙双喜临门，加太常宴饮庆贺。

【天赦日】春戊寅、夏甲午、秋戊申、冬甲子。天赦日占事，逢凶化吉，百无禁忌。天赦日占讼必得赦免，占病有救星，占出行无阻。

