【求财类】青龙为财帛星，贵人主得财有助。太常主饮食之财，小吉主酒食交易。三传顺生财源滚滚，末传见青龙终有大利。玄武临课防劫财，天空临课防诈骗。
【官禄类】贵人主升迁，青龙主官禄。朱雀主文书告身，勾陈主印绶。干上神生太岁为君主赏识，支上神克太岁为遭贬谪。驿马临课调动在即。
【出行类】青龙驿马宜行，白虎拦路勿出。玄武在途防盗，天空在途防虚。干上克支上归心似箭，支上生干上去程迢迢。
【疾病类】白虎为病神，青龙为医星。死神临课病沉重，生气临课病可愈。三传见墓防不测，末传见生有望安。日干受克病在己，日支受克病在家。
【行人归期】驿马发动人已行，三传见归期在即。末传见马远期归，初传见马即日到。干上克支归期近，支上克干尚未归。伏吟不动无消息。
【失物类】玄武为盗星，勾陈为藏处。干上神为失主，支上神为失物所在。三传顺生可寻觅，逆克则失物已远。天空为内贼，螣蛇为虚惊失物自还。
【官司类】朱雀为诉状，勾陈为审判。白虎主刑伤，贵人主调解。干上克支上我理胜，支上克干上彼理直。末传克初传后发制人。
【子嗣类】六合主子息，天后主孕育。青龙主男丁，太阴主女嗣。干上生支上孕育顺，支上克干上防胎动。桃花加青龙得子必贤。

