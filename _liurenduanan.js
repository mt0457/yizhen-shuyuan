【案廿四·占病情】戊午日，酉将，午时，占母病吉凶。四课：干上午（朱雀），支上申（白虎）。三传：午、戌、寅。断曰：白虎临支加申金，病势沉重。朱雀午火临干，心火旺盛与病相冲。三传午戌寅合火局，火旺克金（白虎金）。医在东方寅位寻。果于寅方请得名医，服药后病情好转。

【案廿五·占医效】甲申日，丑将，申时，占某医是否可治此病。四课：干上申（白虎），支上寅（青龙）。三传：申、亥、寅。断曰：白虎为病，青龙为医。青龙临支寅位，此医可治。三传申亥寅，亥为水通关金木之战。亥日求医最佳。果于亥日请医，药到病除。

【案廿六·占寿元】癸巳日，子将，亥时，老年占寿元。四课：干上亥（玄武），支上子（天后）。三传：亥、子、丑。断曰：玄武主阴，天后主水。三传亥子丑三会水局，冬月水旺。癸水日主得三会水局，寿元尚长。但丑为墓库，逢丑年需防。果后活至八十余岁，卒于丑年冬月。

【案廿七·占瘟病】丙申日，巳将，午时，村中瘟疫占吉凶。四课：干上午（朱雀），支上巳（螣蛇）。三传：午、戌、申。断曰：朱雀为火疫，螣蛇为怪异。三传午戌申，申为白虎末传，瘟疫将过去。半月后瘟止。后果半月后瘟疫消退。

