【贵人临宫诀】贵人临子名解纷，临丑名升堂，临寅名凭几，临卯名登车，临辰名天狱，临巳名趋朝，临午名乘轩，临未名列席，临申名移途，临酉名入室，临戌名入狱，临亥名登舟。贵人顺治则万事吉昌，逆行则减力三分。升堂、凭几、登车、乘轩、列席、入室为贵人得地，所谋皆遂。天狱、入狱为贵人失位，求助无门。

【青龙临宫诀】青龙临子名人庙，临丑名蟠泥，临寅名乘云，临卯名驱雷，临辰名入海，临巳名飞天，临午名烧身，临未名在陆，临申名伤鳞，临酉名摧角，临戌名登天，临亥名游江。乘云、驱雷、入海、飞天、游江为青龙得地，财喜双至。烧身、伤鳞、摧角为青龙受制，财喜减半。

【白虎临宫诀】白虎临子名溺水，临丑名在野，临寅名登山，临卯名临门，临辰名噬人，临巳名焚身，临午名衔刀，临未名在野，临申名当路，临酉名出林，临戌名落阱，临亥名渡河。溺水、焚身、落阱、渡河为白虎失势，凶而不凶。登山、临门、噬人、衔刀、当路、出林为白虎得势，凶祸必至。凡白虎临支加于卯酉上名白虎临门，家有丧祸。白虎加于墓神上则孝服。

【玄武临宫诀】玄武临子名入海，临丑名升堂，临寅名入林，临卯名窥户，临辰名失路，临巳名反顾，临午名截路，临未名在野，临申名折足，临酉名拔刃，临戌名遭囚，临亥名归渊。入海、入林、窥户、归渊为玄武得地，盗贼猖獗。失路、折足、遭囚为玄武受制，盗气消弭。

【朱雀临宫诀】朱雀临子名投江，临丑名掩目，临寅名安巢，临卯名巢户，临辰名敛翼，临巳名昼翔，临午名衔符，临未名临坟，临申名励嘴，临酉名夜噪，临戌名投网，临亥名入水。投江、掩目、敛翼、投网、入水为朱雀受制，口舌可解。安巢、昼翔、衔符、励嘴为朱雀得地，口舌文书有利。

【螣蛇临宫诀】螣蛇临子名入井，临丑名盘龟，临寅名生角，临卯名当门，临辰名象龙，临巳名乘雾，临午名飞空，临未名入林，临申名衔剑，临酉名化龙，临戌名入冢，临亥名堕水。入井、入冢、堕水为螣蛇受制，虚惊可解。生角、飞空、衔剑、化龙为螣蛇得势，怪异非常。

