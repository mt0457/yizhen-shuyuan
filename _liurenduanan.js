元首课上克下事由天定，重审课下克上事需审慎。知一课比用取传方向明，涉害课涉害取传事有阻。遥克课遥克取传事在远，昴星课昴星取传事隐晦。别责课别责取传需外力，八专业课八专取传事宜专。伏吟课伏吟不动事迟滞，返吟课返吟相冲事反复。

三交课三传皆克层层阻，乱首课无一克事停滞。赘婿课均上克下受支配，度厄课均下克上需奋抗。无禄课无财星占财不利，绝嗣课无子孙后嗣难继。侵害课克多生少防受损，刑伤课刑多合少防官非。

青龙动主财喜至，贵人动主官禄升。六合动主婚姻就，天后动主妇女吉。太常动主宴饮会，太阴动主谋略成。白虎动主灾丧临，玄武动主盗失惊。朱雀动主口舌起，螣蛇动主虚怪异。勾陈动主争讼连，天空动主欺诈行。

驿马动主出行，桃花现主婚缘。羊刃见防血光，墓神逢主困滞。德神临百事吉，合神到诸事谐。刑冲破害为忌，三合六合为吉。

