【邵雍占迁居】壬辰日，午将，辰时，人占迁居洛城吉凶。干上辰，支上午。三传辰午申。断曰：天罡加辰本位，人宅相安。胜光午火在支为文明之地。申为传送驿马，迁居则动中得吉。洛城在西方申位，大吉。验：迁居洛阳后著书立说，名垂千古。

【管辂占射覆】丁卯日，卯将，辰时。干上辰，支上酉。三传辰酉寅。盒中何物？断曰：酉为金为从魁，其形圆而白。辰为天罡为土，其色黄。寅为功曹为木，其形长。此物圆而色黄，中有木柄，铜镜也。验：启盒果为铜镜。

【郭璞占逃难】甲申日，子将，寅时。干上寅，支上子。三传寅申亥。断曰：白虎申金加干支冲，兵祸将至。驿马寅在干上，宜速向南行。亥为天门末传，渡江南下可免。验：果渡江得免于难。

【袁天罡占国运】戊辰日，子将，午时。干上午，支上子。三传午子卯。断曰：子午为天地之冲，午为帝座子为后宫。卯为六合主叛乱。三传午子卯为轩盖课，主帝王有难。验：后值安史之乱。

【李淳风占日食】丙午日，午将，午时。干上午，支上午。三传午午午伏吟课。断曰：胜光重重，午为太阳伏吟不动。三传皆午太阳过旺，阳极阴生。午月午日午时必日食。验：果日食。

【张良占鸿门】癸亥日，丑将，戌时。干上戌，支上丑。三传戌丑午。断曰：天空戌为虚诈，大吉丑为贵人。午火克酉金（日支酉？癸寄丑宫）。虚惊中有贵人相助，赴宴无妨。验：鸿门宴果得项伯相助脱险。

【陈抟占龙脉】壬子日，辰将，子时。干上子，支上辰。三传子辰申。断曰：子为帝座，辰为龙穴，申为传送。水局通流，龙脉自昆仑而来，结穴于华山。验：后华山为道家第四洞天。

【一行占历法】甲子日，子将，子时。干上子，支上子。三传子子子伏吟。断曰：子为贞元，为历法起算之始。甲子日子将子时，天上地下同一甲子。历法修订必以甲子为元。验：大衍历以甲子为元，万古不废。

