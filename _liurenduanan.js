【案卅五·占讼胜负】辛酉日，午将，午时，占官司胜负。四课：干上午（朱雀），支上卯（六合）。三传：午、卯、子。断曰：朱雀为口舌文书，六合为调解。三传午卯子，午火克酉金（日干辛寄戌？辛寄辰宫），对方强势。劝其和解。后经人调解平息。

【案卅六·占牢狱】庚辰日，丑将，戌时，家占入狱亲人何时释。四课：干上戌（天空），支上丑（贵人）。三传：戌、丑、午。断曰：天空为狱，贵人为救。丑为贵人末传之后中传见贵人。春月（丑为十二月）贵人得力。果腊月释放。

【案卅七·占诉讼】丙午日，卯将，申时，占诉讼是否应提起。四课：干上申（白虎），支上卯（六合）。三传：申、亥、寅。断曰：白虎临干加申金，诉讼凶险。六合临支，对方愿和解。三传申亥寅，亥为水通关。劝其和解，后双方和解成功。

