【案二十·占出行】丙子日，寅将，午时，占出行是否顺利。四课：干上午（朱雀），支上寅（青龙驿马）。三传：寅、午、戌。断曰：青龙驿马并临，出行大利。三传寅午戌合火局，火为光明。出行方向宜南。果出行南方，一路顺遂。

【案廿一·占归期】辛酉日，酉将，子时，家中占行人何时归。四课：干上子（天后），支上卯（六合）。三传：子、卯、午。断曰：驿马未动，三传无马星。六合卯在中传，卯日可归。果卯日归家。

【案廿二·占行船】壬辰日，午将，辰时，舟子占行船安否。四课：干上辰（勾陈），支上午（朱雀）。三传：辰、午、申。断曰：辰为水库，午为火，水火相激有风浪之虞。申为白虎，末传不利。劝停一日。果当日下午忽起大风，幸未出航得免于难。

【案廿三·占迁居】戊寅日，卯将，巳时，占迁居新地吉凶。四课：干上巳（螣蛇），支上卯（六合）。三传：巳、酉、丑。断曰：六合临支，新居有和合之象。螣蛇临干，搬家过程中有虚惊。三传巳酉丑合金局，西方为宜。果迁居西方新镇，后家业兴旺。

