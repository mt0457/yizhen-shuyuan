诸葛亮（181年—234年），字孔明，号卧龙，琅琊阳都（今山东沂南）人。三国时期蜀汉丞相，杰出的政治家、军事家、文学家。章武三年（223年）受刘备托孤，辅佐后主刘禅，鞠躬尽瘁，死而后已。建兴十二年（234年）病卒于五丈原军中，年五十四。谥忠武侯。

