【女命专论】女命骨髓赋法另有侧重。女命以夫妻宫为夫，子女宫为子。女命紫微坐命——贵妇之命，然紫微孤高宜配年长之夫。女命太阴坐命——温柔贤淑，相夫教子。女命天府坐命——持家有道，旺夫益子。女命贪狼坐命——貌美多才，然桃花过重恐有风月是非。女命七杀破军坐命——性情刚烈，宜晚婚。女命化忌入夫妻宫——感情困扰，婚姻不顺。女命看夫子二星：夫星看夫妻宫之主星及官禄宫对照。子星看子女宫之主星及田宅宫对照。夫子二宫俱吉，为贤妻良母之命。

【小儿命专论】小儿命以命宫为根基，父母宫为成长环境。小儿命宫吉星庙旺——易养成人。小儿命宫煞星陷地——多病多灾。小儿父母宫煞忌冲——幼年父母缘薄。小儿疾厄宫吉星守——体健少病。小儿未起大限前看小限，每岁一宫，吉星守则为平安之年。小儿关煞：命宫见羊陀——防跌伤。迁移宫见火铃——防水火之灾。官禄宫见空劫——学业多阻。田宅宫见化忌——居家多病。

【僧道命专论】命宫华盖加空劫——出世之志。命宫天梁加空亡——宜修行。命宫紫微加地空地劫——帝王入空门。福德宫空劫重——精神追求超越世俗。僧道之命，不以富贵论，而以清修为高。妻财子禄四宫俱空者，方为真修行之命。僧道命不忌孤——孤为清。不忌空——空为净。然僧道中亦有大德者——紫微入庙加文昌天梁，高僧大德之命。

【残疾命专论】疾厄宫煞星重重加化忌——先天残疾之象。命宫擎羊陀罗夹之——外伤致残。迁移宫火铃加天马——出行意外致残。先天残疾与后天残疾有别：先天在疾厄宫，后天在迁移宫及流年。羊陀夹疾厄——手术之象。火铃夹疾厄——急症致残。

【刑狱命专论】命宫廉贞化忌加擎羊——官非牢狱之象。交友宫巨门化忌——被朋友牵连入狱。官禄宫七杀加陀罗——职场犯罪。流年命宫廉贞化忌加煞——当年需防官非。古法刑狱命宜多行善事、远离是非、避免合伙经营。

【横死命专论】命宫七杀破军加羊陀火铃——横死之象。迁移宫擎羊加天马——出行意外（马头带箭）。疾厄宫廉贞化忌——重病不治。流年迁移宫火铃加天马加化忌——当年出行需格外小心。古法告诫此类命格之主宜多积德行善、避免高危行为、逢凶年宜守不宜冲。

