《太上正一北极真武佑圣真君宝诰》，又名《北极真武宝诰》《玄天上帝宝诰》，一卷，收入明《正统道藏》正一部。宝诰者，道教赞颂神明之神圣文体也——上达天真，下通幽冥，诵之则神明鉴临，灾厄消散。此宝诰为正一派朝礼北极真武佑圣真君（即玄天上帝、真武大帝）之根本诰文。真武大帝乃北极四圣之一，镇守北方，主掌雷霆，统领六丁六甲、五雷神将，专司降魔伏妖、荡除邪秽。凡遇邪祟侵扰、妖魔作怪、家宅不宁、噩梦连连者，至心诵此宝诰，真武大帝即遣天兵神将前来护佑。又真武为北方水神，主掌水府之事——凡航运、水利、防洪、求雨、治水等事，皆在其职司之内。自唐宋以来，真武信仰遍及天下，道观宫庙处处皆见真武圣像。此宝诰文辞古雅，义理精深，将真武大帝之神格、职司、功德、灵应一一赞颂，自古被奉为朝礼真武之圭臬。修真之士每日晨课诵此宝诰，可感召真武大帝之护佑，增福延寿，消灾解厄，降魔除秽，所求如意。
