<p style="margin:8px 0 0 0;line-height:2;">《太上洞玄灵宝八史真形图》，一卷，撰人不详，约出于魏晋南北朝时期，为灵宝派存思修真之秘图经典，收录于明《正统道藏》洞玄部灵图类。</p>
