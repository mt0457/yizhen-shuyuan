<p style="line-height:2.2;">
<b>白帝白招拒详述：</b>白帝白招拒，全称为"西方白帝七炁天君白招拒"，又名"皓灵皇老七炁天君"，居西方七炁白天之中，其宫阙名曰"皓灵玉阙"，以白玉为阶、银霜为瓦、白虎雄踞。白帝之服色：头戴白玉通天冠，身着白云虎纹袍，腰佩皓英宝剑，足踏七炁白云。白帝之侍卫：右有白虎大将监兵神君（持白矛）、左有西岳华山神君（持玉简），统率西方七炁神兵七万七千众。白帝之圣诞为立秋日（或八月初一日），是日诵白帝名号、佩白帝符最为应验。感通白帝之征兆：佩带白帝符或诵念白帝名号时，若感到胸肺（肺区）清爽舒畅、呼吸深长有力，或于梦中见白色光明、白虎巡山、金气清肃之象，即为白帝感通之征兆。</p>

