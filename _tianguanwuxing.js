一宫命宫——头部、面貌。
二宫财帛宫——颈部、咽喉。
三宫兄弟宫——肩部、手臂、肺。
四宫田宅宫——胸部、胃。
五宫男女宫——心脏、背部。
六宫奴仆宫——腹部、肠道。
七宫夫妻宫——腰部、肾脏。
八宫疾厄宫——生殖系统、肛门。
九宫迁移宫——大腿、肝脏。
十宫官禄宫——膝盖、骨骼。
十一宫福德宫——小腿、血液循环。
十二宫相貌宫——足部、精神。

