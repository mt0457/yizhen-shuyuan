【译】鲮鱼在什么地方？鬿堆又居于何处？
羿焉彃日？乌焉解羽？
【译】后羿怎样射下九日？金乌之羽如何散落？

【第三段：问夏代兴衰】
——屈原追述夏朝历史，从启到桀，问兴亡之由——

禹之力献功，降省下土四方。
【译】大禹竭力奉献功业，降临视察天下四方。
焉得彼涂山女，而通之于台桑？
【译】怎样得到涂山氏之女，在台桑与她私通？
闵妃匹合，厥身是继。
【译】怜爱涂山氏结为配偶，为延续自身血脉。
胡维嗜不同味，而快鼌饱？
【译】为何口味嗜好不同，却贪图一时之快而求饱足？
启代益作后，卒然离蠥。
【译】启取代益成为君主，却突然遭遇祸难。
