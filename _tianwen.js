【译】元气充盈惟存影像，如何辨识其本相？
明明暗暗，惟时何为？
【译】白昼光明黑夜昏暗，为何如此安排？
阴阳三合，何本何化？
【译】阴阳二气参合和合，何为本源何是化生？
圜则九重，孰营度之？
【译】天穹圆盖共有九层，是谁规划度量而成？
惟兹何功，孰初作之？
【译】如此浩大工程，是谁最初开创？
斡维焉系？天极焉加？
【译】天轴转动的枢纽系于何处？天极又架在何方？
