【译】鲧死后化为黄熊，巫师怎能使他复活？
咸播秬黍，莆雚是营。
【译】鲧教百姓播种黑黍，又经营水草蒲苇之地。
何由并投，而鲧疾修盈？
【译】为何鲧被众人共同摒弃，而恶名却长久流传？
