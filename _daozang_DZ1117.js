<b>灵宝天尊大慈悲，正一度人妙法开。十二真符度群品，经符合修上玉阶。三洞度人鼎足立，灵宝为上清正一侪。诵经书符两不废，度人功德满九垓。皈命灵宝天尊。皈命正一真人张道陵天师。皈命十二度人神将一切护法。正一传度，利济存亡。不可思议功德。</b>
