+"<h2 style=\"color:#8b1a1a;border-bottom:2px solid #e8ddd0;"
+"padding-bottom:8px;font-size:22px;\">卷一 · 冻疮总论</h2>"
+"<p style=\"line-height:2.2;\">"
+"太上老君于太清境大赤天宫中，放大光明照彻十方，集会诸天真人、"
+"十方圣众、三界神祇、五方寒暑之神、四海风雨之伯，慈悲告曰："
+"天地之间，四时更迭，寒暑往来，此天道之常也。"
+"然寒气过甚或人身正气不足，则寒邪乘虚而入，客于肌肤，凝于血脉，"
+"结于肢末，发为冻疮。冻疮之生非独天时之寒，亦有内外二因相交而成。"
+"外因者天时酷寒、风雪侵凌、湿冷久渍是也；"
+"内因者元气不足、卫阳不固、气血虚弱、经脉瘀滞是也。"
+"二者相合则寒邪深入，冻疮乃生。</p>"
+"<p style=\"line-height:2.2;\">"
+"此经乃太上老君观北方苦寒之地众生受冻疮之苦，大发慈悲之心，"
+"亲口宣说禳解冻疮之秘法。老君曰：冻疮虽为小疾，然其苦不堪——"
+"轻则红肿痛痒彻夜难眠，重则皮肉溃烂筋骨暴露，乃至指趾脱落终身残疾。"
+"更有甚者，严寒之地冻死者年以万计。天心至慈大道好生，"
+"岂忍见众生受此冻疮冻死之苦？故于洞神部中特说此经，"
+"使世人知禳解之法、行防冻之道、受温暖之福。"
+"经中所述之法，上承三清道祖之慈旨，中合天地阴阳寒暑之运化，"
+"下合人身气血经脉之周流，乃道门禳冻疮之第一经典。"
+"凡善男子善女人得遇此经，当生难遭之想，珍重受持，不可轻慢。</p>"
+"<p style=\"line-height:2.2;\"><b>冻疮之源流考辨：</b>"
+"考诸医典及历代修真之士所传，冻疮之源约有十端："
+"一曰天时酷寒——冬月严寒朔风凛冽，寒邪自皮毛而入，"
+"此为冻疮最直接之外因。"
+"二曰湿冷相搏——冰雪融化湿气浸淫加之低温，"
+"寒湿二邪相合为害尤烈，所谓\"寒易防而湿难避，寒湿相合冻疮必成\"。"
+"三曰气血虚弱——素体阳气不足、气血亏虚者，卫外不固，"
+"寒邪最易乘虚而入。"
+"四曰经脉瘀滞——气血运行不畅四肢末端尤甚，"
+"寒邪入侵后气血凝滞更甚，瘀而生疮。"
+"五曰衣着不周——冬月衣裳单薄不能御寒，"
+"或鞋袜湿透未及时更换，寒从足下生。"
+"六曰久坐不动——冬日畏寒蜷缩不动，气血运行益缓，"
+"四肢末端更易冻伤。"
+"七曰饮食失宜——冬日不食温热之品而食寒凉之物，"
+"内寒外寒相感召。"
+"八曰劳累过度——体力消耗过多汗出当风，腠理开泄寒邪直入。"
+"九曰旧伤复发——往年曾生冻疮之处，局部气血已伤，"
+"来年更易复发。"
+"十曰禀赋薄弱——天生阳气不足、皮肉娇嫩者，"
+"最易为寒邪所伤。知此十端，则可对症施治，"
+"因人因时因地而行禳解之法。</p>"
+"<p style=\"line-height:2.2;\"><b>冻疮之辨证与分型：</b>"
+"冻疮之证非一，轻重有别，深浅各异，须详加辨证方可对症施治。"
+"依其症状轻重可分为五度：一度曰<b>红肿型</b>——"
+"局部皮肤发红微肿，触之有冷感，遇热则瘙痒刺痛，"
+"此时寒邪仅在肌肤之表，未入血脉，最为易治。"
+"二度曰<b>水疱型</b>——红肿之上起水疱或血疱，"
+"疱液清稀或带血色，疼痛加剧，此寒邪已入血脉，气血瘀滞较甚。"
+"三度曰<b>溃烂型</b>——水疱破后形成溃疡，"
+"疮面暗红或紫黑，渗液不止，痛如针刺，"
+"此寒邪已伤肌肉，气血凝滞严重。"
+"四度曰<b>坏疽型</b>——局部皮肤肌肉变黑坏死，"
+"感觉丧失不觉疼痛，此寒邪已深入筋骨，气血完全断绝，"
+"最为危重，有脱落之虞。"
+"五度曰<b>全身冻僵型</b>——非止局部冻疮，"
+"乃全身受寒过甚，体若冰棍神识昏迷，"
+"此乃寒邪直中脏腑，阳气欲绝之危候，若不急救顷刻毙命。"
+"五度之中，前三度可依本经之法禳解调治，"
+"四度须兼以手术去腐生肌，"
+"五度须以回阳救逆之急救大法先复阳气再行禳冻之法。"
+"又依其邪气性质可分为三型："
+"一曰<b>寒凝型</b>——以冷痛、青紫、僵硬为主，宜温经散寒。"
+"二曰<b>湿滞型</b>——以肿胀、水疱、渗液为主，宜化湿通络。"
+"三曰<b>瘀阻型</b>——以紫暗、硬结、溃烂为主，宜活血化瘀。"
+"三者常相兼为病，辨清主次方可有的放矢。</p>"
+"<p style=\"line-height:2.2;\"><b>禳冻疮之根本五要：</b>"
+"禳解冻疮虽有万法，归根结底不外五要。"
+"一要曰<b>温阳固表</b>——阳气为身之太阳，"
+"阳气充足则卫外为固，寒邪不得而入。"
+"温阳之法在食温热之品、衣温暖之服、居温煦之室、行温运之功。"
+"阳气者若天与日，失其所则折寿而不彰。"
+"养得一分阳气即多一分抗寒之力。"
+"二要曰<b>活血通脉</b>——血得温则行得寒则凝，"
+"冻疮之病理核心在\"寒凝血瘀\"四字。"
+"活血之法在按摩导引、温经通络、行气化瘀，"
+"使气血周流不息，寒邪无所停滞。"
+"三要曰<b>燥湿敛疮</b>——湿性黏滞最易与寒邪相合，"
+"寒湿相合如油入面难以分解。"
+"燥湿之法在保持局部干燥、外敷敛湿之药、内服化湿之品。"
+"四要曰<b>避寒就温</b>——此为预防冻疮之第一要义。"
+"冬日出行须穿戴厚暖，尤其手足耳鼻等末端部位须特别保护。"
+"居室宜温暖干燥，避免久坐寒冷潮湿之地。"
+"五要曰<b>内养正气</b>——正气存内邪不可干。"
+"养正之法在饮食有节、起居有常、不妄作劳、精神内守。"
+"此五要者，乃禳冻疮之根本大法，万法不出其外。</p>"
+"<p style=\"line-height:2.2;\"><b>冻疮与脏腑之关系：</b>"
+"冻疮虽发于体表四肢，然与内在脏腑密切相关。医道同源，道医一理。"
+"心主血脉——心阳不足则血脉运行无力，"
+"四肢末端最易失于温养而生冻疮。"
+"肺主皮毛——肺气虚弱则皮毛腠理不固，"
+"寒邪最易从皮毛而入。"
+"脾主肌肉四肢——脾阳不足则四肢不温、肌肉失养，"
+"冻疮多发于手足。"
+"肾为先天之本内藏元阳——肾阳亏虚则一身之阳皆衰，"
+"最易为寒邪所伤。"
+"肝主筋爪——肝血不足则爪甲枯槁、筋脉拘挛，"
+"冻疮后期常见筋脉损伤。"
+"故禳冻疮不可仅治局部，须五脏同调、整体论治。"
+"温心阳以促血行、补肺气以固皮毛、"
+"健脾胃以实肌肉四肢、温肾阳以壮一身之根本、"
+"养肝血以柔筋脉爪甲。五脏调和则正气充盛，"
+"正气充盛则虽处严寒之地亦不生冻疮矣。</p>"
+"<p style=\"line-height:2.2;\"><b>冻疮与修真之关系：</b>"
+"或问：修真之士既已修炼，何故尚须防冻疮？"
+"答曰：修真之士虽修内丹养真气，然在未成大道之前身躯仍是血肉之躯，"
+"仍须顺应四时、防护外邪。且修真者常居深山道观，山高风寒，"
+"冬日尤甚——所谓\"高处不胜寒\"也。"
+"昔有修真之士于雪山之巅苦修，因未谙防冻之法，"
+"手足俱冻溃烂，不得已中断修行下山求医，遂误数年之功。"
+"又有修士冬日闭关打坐，因久坐不动气血凝滞，"
+"双足冻伤而不自知，待出关时双足已成坏疽。"
+"故知防冻护体非但为世俗之人所须，亦为修真之士必修之课。"
+"仙经云：欲修天仙，先修地仙；欲修地仙，先修人仙；"
+"欲修人仙，先保此身。身之不存道将焉附？"
+"故老君特说此经，使修真之士亦知防冻护体之要，"
+"得以安心办道，早证真果。</p>"
