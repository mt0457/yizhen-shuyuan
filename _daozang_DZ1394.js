+"然须谨记：符之灵验以书符者之道行为根本——"
+"道高则符灵，德浅则符虚。故欲符灵，先修道行；"
+"欲符验，先积阴功。不可舍本逐末徒恃符法。</p>"
+"<p style=\"line-height:2.2;\"><b>书符总诀：</b>"
+"凡书禳冻疮符，书符者须斋戒三日，期间不食荤酒辛辣，不近女色。"
+"书符之日清晨卯时沐浴更衣，以生姜汤净手净面——姜性温热可助阳气。"
