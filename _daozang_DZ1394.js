+"冬日出行宜备一套干燥内衣和袜子以便更换。"
+"鞋袜若被雪水浸湿应立即更换干燥鞋袜并以干毛巾擦干双足。"
+"四宜<b>松紧适度</b>——鞋带袜口腰带袖口等不宜过紧，"
+"过紧则阻碍血液循环反而增加冻疮风险。"
+"五忌<b>衣着单薄冒寒出行</b>——冬日出门前须根据气温和风力"
+"穿着足够保暖之衣物，不可因\"只是出去一会儿\"而衣着单薄。"
+"六忌<b>饮酒后赤身外出</b>——酒后毛孔舒张血管扩张体表散热加快，"
+"此时外出虽自觉温暖实则散热极快极易冻伤甚至冻死，"
+"古语\"酒后不外出、外出不饮酒\"即此理也。"
+"七忌<b>以雪搓冻伤之处</b>——民间有\"以雪搓冻疮\"之误传，"
+"此法大错！雪搓冻伤处不仅不能治疗反而会使局部温度更低"
+"加重冻伤，且雪中若有冰晶颗粒会划伤皮肤增加感染风险。"
+"冻伤之处只宜以温水或温暖之手缓缓加温，"
+"不可用雪搓、不可用火烤、不可用热水烫。</p>"
+"<p style=\"line-height:2.2;\"><b>饮食之宜忌：</b>"
+"饮食为内养之根本。"
+"一宜<b>多食温热性食物</b>——冬季宜多食羊肉、牛肉、鸡肉、"
+"鹿肉等温补肉类；多食生姜、大葱、大蒜、花椒、桂皮、"
+"八角、辣椒等辛温调味品；多食核桃、栗子、松子、腰果等坚果类食品；"
+"多食红枣、桂圆、荔枝干、枸杞等温补干果；"
+"多饮姜茶、红糖水、热汤等温热饮品。"
+"二宜<b>三餐温热</b>——冬日饮食宜趁热食用，不宜吃冷饭冷菜。"
+"早餐尤其重要——一份热腾腾的早餐可为一整天的阳气生发打下基础。"
+"三宜<b>适当增加热量摄入</b>——冬季人体需要更多热量来维持体温，"
+"不可过度节食。"
+"四宜<b>多饮温水</b>——冬日虽不易觉渴然仍须保证充足饮水，"
+"以温水为佳，少量多次。充足的水分有助血液循环和新陈代谢。"
+"五忌<b>过食寒凉生冷之物</b>——冰水冷饮冰淇淋等寒凉之品伤脾胃阳气，"
+"脾胃阳气一伤则四肢更易不温。冬日尤须忌食生冷。"
+"六忌<b>空腹饮酒御寒</b>——空腹饮酒虽能一时感觉温暖，"
+"然酒性发散之后反而更冷，且空腹饮酒伤胃。"
+"若欲饮酒御寒宜先吃饱温热食物再少量饮用温热之黄酒或米酒。"
+"七忌<b>过度节食减肥</b>——冬季刻意大幅减少饮食摄入会导致热量不足、"
+"气血亏虚、抗寒能力下降，冻疮更易发生。</p>"
+"<p style=\"line-height:2.2;\"><b>居处之宜忌：</b>"
+"居处为安身之所。"
+"一宜<b>居室温暖干燥</b>——冬季室内温度宜保持在适宜之范围"
+"（体感舒适不冷不热），室内湿度宜适中不可过于潮湿——"
+"湿冷比干冷更易导致冻疮。可于室内放置炭火盆或取暖器具，"
+"但须注意通风以防一氧化碳中毒。"
+"二宜<b>被褥温暖蓬松</b>——冬被宜厚实蓬松，"
+"睡前可以热水袋或暖炉预热被窝。"
+"被褥须经常晾晒以保持干燥蓬松——"
+"阳光晒过的被子又暖又软保暖效果最佳。"
+"三宜<b>睡前泡脚</b>——每晚临睡前以热水泡脚十五至二十分钟，"
+"水溫以能耐受之较高温度为佳但不可烫伤，"
+"泡至全身微微出汗为度。"
+"泡脚水中可加生姜数片、艾叶一把、花椒数十粒以增温经散寒之效。"
+"泡脚后立即擦干双足穿上干净暖袜，然后上床就寝。"
+"此一习惯若能坚持整个冬季，则双足温暖冻疮不生。"
+"四宜<b>门窗密封防寒风</b>——检查门窗缝隙以纸条或密封条堵塞"
+"寒风直入之处。然亦不可密封过死完全不通风——"
+"每日宜开窗通风一至两次每次数分钟，以保持室内空气新鲜。"
+"开窗通风时人宜暂离该室或穿戴暖和。"
+"五忌<b>居室阴冷潮湿</b>——地下室、背阴之室、临水之室"
+"湿气重寒气深，不宜作为冬日起居主要场所。"
+"若不得不居于此类环境则须加强取暖除湿。"
+"六忌<b>久坐不动</b>——冬日畏寒久坐不动则气血运行益缓，"
+"双脚最易冻伤。宜每坐半个时辰起身活动片刻，"
+"做几节踮脚、踏步、伸展之动作促进血液循环。"
+"七忌<b>以煤炉或炭火取暖不加通风</b>——"
+"密闭室内燃煤或木炭取暖会产生一氧化碳，"
+"无色无味不知不觉间致人中毒死亡，此类悲剧冬季时有发生。"
+"取暖必须保持室内通风，睡前须将炭火移至室外。</p>"
+"<p style=\"line-height:2.2;\"><b>出行之宜忌：</b>"
+"出行在外防护尤须周详。"
+"一宜<b>出行前查看天气</b>——冬日出行前须了解当日气温、"
+"风力、降雪等情况，据此准备合适衣着和装备。"
+"极寒或暴风雪天气尽量避免出行。"
+"二宜<b>随身携带防寒应急之物</b>——冬日长途出行宜随身携带："
+"备用干燥袜子一双、暖手炉或暖宝宝数个、"
+"高热量零食若干（巧克力、坚果、牛肉干等）、"
+"保温杯装热姜茶一瓶。若于雪地或冰面行走还宜携带防滑鞋链。"
+"三宜<b>雪地行走注意防滑防湿</b>——"
+"雪地行走宜穿防滑防水之鞋，步幅宜小速度宜缓。"
+"若不慎滑倒须先检查是否有骨折再移动。"
+"鞋内进雪须及时清除以免雪化湿冷导致足部冻伤。"
+"四宜<b>寒风之中保护面部</b>——严寒大风天气出行须以围巾或面罩"
+"保护面部及口鼻，眼部宜戴防风镜。"
+"面部皮肤薄血运丰富散热快，面部冻伤为冬季常见损害。"
+"五忌<b>疲劳或饥饿时冒寒出行</b>——"
+"疲劳或饥饿时身体产热能力下降抗寒能力降低，"
+"此时出行更易冻伤。出发前须吃饱休息充足。"
+"六忌<b>醉酒后独自出行</b>——醉酒后判断力下降体温调节能力降低，"
+"曾有醉汉冬夜倒在路边冻毙之惨剧，切记不可醉酒后独自外出。"
+"七忌<b>手脚麻木时继续暴露于寒冷中</b>——"
+"若在寒冷的户外感到手脚麻木失去知觉，"
+"此为冻伤之早期信号不可掉以轻心，"
+"应立即进入温暖室内或采取保暖措施，以温水或体温缓缓复温。</p>"
+"<p style=\"line-height:2.2;\"><b>冻疮发作期之特别宜忌：</b>"
+"若冻疮已发，除依本经前述诸法治疗外尚有以下特别宜忌须遵守。"
+"一宜<b>保持患处清洁干燥</b>——每日以温甘草汤或淡盐水清洗患处，"
+"洗后以干净柔软毛巾轻轻吸干水分（不可用力揉搓），"
+"保持局部清洁干燥以防感染。"
+"二宜<b>避免搔抓</b>——冻疮发作时常有剧烈瘙痒，"
+"此时须极力克制不可搔抓。"
+"搔抓会破坏皮肤屏障加重损伤甚至引起感染。"
+"若瘙痒难忍可以手掌轻拍或冷敷（以凉水而非冰水）暂时缓解，"
+"或涂抹止痒药膏。"
+"三宜<b>适度活动患处</b>——在保暖的前提下适度活动患处"
+"（如手指冻疮则做手指屈伸运动），"
+"可促进局部血液循环加速愈合。但活动不可过度剧烈以免加重损伤。"
+"四宜<b>抬高患处</b>——休息时或将患肢垫高以利血液回流减轻肿胀。"
+"五忌<b>以极热之水烫洗冻疮</b>——"
+"冻疮患处对温度感觉迟钝，以过热之水烫洗虽能一时止痒"
+"但会造成烫伤且可能加重组织损伤。"
+"洗冻疮之水以略高于体温（40度左右）为宜。"
+"六忌<b>自行挑破水疱</b>——冻疮水疱内有保护性疱液，"
+"自行挑破会增加感染风险。"
+"若水疱自行破裂则须以消毒液清洗后以无菌敷料包扎。"
+"七忌<b>冻疮患处直接烤火</b>——将冻疮患处直接靠近火炉或暖气片烤热"
+"虽能快速温暖但患处血管因冻伤后调节功能失常，"
+"快速加热会导致血管急剧扩张渗出增加反而加重肿胀甚至组织坏死。"
+"正确之法是以体温或温水缓缓复温——"
+"如将冻伤之手放入自己腋下或他人怀中以体温温暖之。</p>"
+"<p style=\"line-height:2.2;\"><b>小儿与老人之特别禳冻法：</b>"
+"小儿气血未充、老人阳气已衰，此二者为冻疮最易受害之人群，"
+"须特别留心防护。"
+"小儿禳冻之要：一须注意随气温变化及时增减衣物——"
+"小儿活泼好动易出汗，汗后当风最易受寒，须及时擦干汗水更换干衣。"
+"二须注意小儿手足保暖——小儿童鞋童袜不可过小过紧，"
+"须留一定空间以便脚趾活动促进血液循环。"
+"三须教育小儿冬季不可玩雪太久——小儿贪玩不知寒冷，"
+"玩雪过久手被冻伤而不自知，家长须适时提醒和干预。"
+"四须注意小儿面颊耳郭之保暖——可以凡士林或绵羊油薄涂于"
+"小儿面颊耳郭，既润肤又有一定防寒作用。"
+"老人禳冻之要：一须特别注意夜间保暖——"
+"老人夜间体温调节能力下降，被褥须足够温暖，"
+"必要时使用电热毯或热水袋（须注意防低温烫伤）。"
+"二须注意晨起保暖——老人晨起时体温最低阳气初升，"
+"此时最需保暖。晨起后宜先在被窝中活动手足片刻再起身，"
+"起身后立即穿上保暖衣物。"
+"三须预防跌倒——老人冬季出行除防冻疮外还须特别防跌，"
+"冰雪路面宜拄拐杖或由人搀扶。"
+"老人一旦跌倒骨折卧床，则冻疮、褥疮、肺炎诸并发症接踵而至，"
+"后患无穷。"
+"四须注重饮食温补——老人脾胃虚弱吸收不良，"
+"冬季温补宜选择易消化之品如羊肉粥、当归生姜羊肉汤、山药粥等，"
+"不可骤然进补大辛大热之品以免虚不受补。</p>"
+"<p style=\"line-height:2.2;\"><b>冻疮愈后之防复发要诀：</b>"
+"冻疮有一特性——今年生冻疮之处来年在同样气候条件下极易复发，"
+"此为\"冻疮之记忆\"——局部气血已伤元气未复之故。"
+"故冻疮痊愈之后仍须持续禳冻至少一年以巩固疗效防止复发。"
+"防复发之要诀有四：一要<b>坚持三伏养阳</b>——"
+"利用三伏天阳气最旺之时以三伏贴、三伏灸等法温补阳气，"
+"此为冬病夏治之精华，可从根本上改变阳虚体质减少冻疮复发。"
+"二要<b>提前一个节气开始防冻</b>——往年冻疮何时开始发作？"
+"于该节气前一个节气即开始全面防冻——"
+"如往年于大雪节气开始生冻疮，则于小雪节气即开始泡脚、服药、"
+"佩戴防冻符等预防措施，提前阻断冻疮之发生链条。"
+"三要<b>旧患之处特别保护</b>——往年冻疮发作之处来年须加倍保护——"
+"该处局部气血已留下薄弱之烙印。可在入秋后即开始于旧患处"
+"每日涂擦姜汁或冻疮膏并轻轻按摩以增强局部之气血循环和抗寒能力。"
+"四要<b>坚持全年锻炼</b>——体质改善非一朝一夕，"
+"须坚持全年锻炼增强体质。"
+"尤其推荐冷水浴或冷热交替浴（自夏季开始循序渐进，冬季不可骤然开始）"
+"——可增强血管舒缩能力和抗寒能力。"
+"但此非人人适合，体弱多病者不宜。</p>"
