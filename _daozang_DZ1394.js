+"<p style=\"line-height:2.2;\"><b>春季节气六符要义：</b>"
+"春季节气六符——自立春至谷雨，总诀在\"护阳防寒\"四字。"
+"春天阳气初生如婴儿之弱，此时防寒尤须谨慎。"
+"立春符以朱砂书于黄纸，正面书\"敕令立春护阳\"六字雷篆，"
+"背面书斋主姓名生辰，于立春日卯时焚于宅之东方，"
+"召东方青帝护持初生之阳。"
+"雨水符加干姜汁书之，重在燥湿防寒，贴于鞋袜之内或鞋柜之上。"
+"惊蛰符以辛温之桂枝煎汤调朱砂书之，取桂枝温经通阳之功，"
+"此符随身佩戴可防乍暖还寒之冻伤。"
+"春分符书时面向东方叩齿九通，以阴阳平衡之日书之最为灵验。"
+"清明符以柳枝蘸符水书之——柳枝为清明之物取其生机，"
+"贴于鞋垫之下外出踏青扫墓时保护双足。"
+"谷雨符以新茶汁调朱砂书之，谷雨茶得春气最全，"
+"以此茶汁和朱砂书符可防春夏之交的倒春寒。"
+"春符六道施用得当，则整个春季阳气顺利生长，"
+"为一年禳冻打下良好基础。</p>"
+"<p style=\"line-height:2.2;\"><b>夏季节气六符要义：</b>"
+"夏季节气六符——自立夏至大暑，总诀在\"养阳祛寒\"四字。"
+"夏季阳气最盛，此时养阳可收事半功倍之效——"
+"所谓\"春夏养阳\"是也。"
+"立夏符以艾叶汁调朱砂书之，艾为纯阳之草最能补阳，"
+"于立夏日午时书符效果最佳。"
+"小满符重在防范湿邪，以苍术粉调朱砂书之，"
+"苍术燥湿健脾为治湿之要药。"
+"芒种符以藿香汁调朱砂——藿香芳香化湿辟秽，"
+"梅雨季节佩之可防湿寒。"
+"夏至符以午时太阳晒热之净水调朱砂，取阳极之炁，"
+"此符为一年中阳气最旺之日所书，佩之可蓄阳于内以备冬寒。"
+"小暑符较为特殊——重在防暑热之时过度贪凉，"
+"以薄荷汁调朱砂书之，既清热又不伤阳。"
+"大暑符以三伏贴之原理配合符法——先以姜汁调白芥子粉涂于大椎、"
+"肺俞、肾俞、足三里等穴位，再以符化灰合蜂蜜敷于穴位之上，"
+"以三伏天时之热引药力符力入里祛除体内沉寒痼冷。"
+"此即\"冬病夏治\"在禳冻疮中之运用——"
+"夏天治冬天易生冻疮之体质，此为上医治未病之法，最须珍视。</p>"
+"<p style=\"line-height:2.2;\"><b>秋季节气六符要义：</b>"
+"秋季节气六符——自立秋至霜降，总诀在\"收敛防寒\"四字。"
+"秋天气机收敛，须顺应天时将阳气收归于内，"
+"并以渐增之防护迎接即将到来之寒冬。"
+"立秋符以乌梅汁调朱砂书之——乌梅味酸主收敛，助阳气内收。"
+"处暑符以百合汁调朱砂书之——百合润肺养阴，"
+"防秋燥与寒相合损伤肺气。"
+"白露符重防早晚寒气，以桂花露调朱砂书之——"
+"桂花秋日之花得秋金之气，能温肺散寒。"
+"秋分符与春分符同为阴阳平衡之日所书，"
+"但秋分重在\"收\"而春分重在\"生\"。"
+"秋分日面朝西方叩齿七通，存想肺中白气化为白虎镇守西方以御冬寒。"
+"寒露符以菊花酒调朱砂书之——"
+"菊花秋令之花经霜不凋有耐寒之性，酒性温热能助符力。"
+"霜降符为秋季最后一符亦为入冬前之预备符，"
+"以山茱萸汁调朱砂书之——"
+"山茱萸温补肝肾固涩精气，为冬季藏精御寒做好最后准备。"
+"秋符六道施用得当，则秋季阳气顺利归藏，"
+"如仓廪充实足以度过严冬。</p>"
+"<p style=\"line-height:2.2;\"><b>冬季节气六符要义：</b>"
+"冬季节气六符——自立冬至大寒，总诀在\"御寒护阳\"四字。"
+"冬季寒气当令，禳冻疮之法在此期间最为紧要。"
+"立冬符为入冬第一符，以附子汁调朱砂书之——"
+"附子大热纯阳为回阳救逆第一品药，"
+"取微量附子和入朱砂以增符之温热之力。"
+"此符贴于贴身衣物之内近心口处，"
+"可保一日之中阳气不衰寒气不侵。"
+"小雪符以肉桂粉调朱砂书之——"
+"肉桂温补肾阳引火归元，为冬季温补之要药。"
+"大雪符为一年中最冷时段之一所用之符，"
+"以鹿角胶汁调朱砂书之——鹿为纯阳之兽其角更得阳气之全，"
+"以此胶和朱砂书符温阳之力最雄。"
+"冬至符乃二十四符中最关键之一符——"
+"冬至阴极阳生，如种子在地下蓄势待发。"
+"是日以冬至子时之井华水（此时之水秉阴尽阳生之炁）调朱砂，"
+"于子时面朝北方叩齿十二通，"
+"存想北海之下一点真阳如明珠升起直入丹田，然后书符。"
+"此符可佩带整个冬三月，为冬季禳冻之根本符。"
+"小寒符以干姜汁调朱砂——姜为呕家圣药亦为温中散寒之要品，"
+"以其汁和朱砂增符之散寒力。"
+"大寒符为冬季最后一符亦为全年最后一符，"
+"以当归汁调朱砂——当归温润补血活血，"
+"可使冬季禳冻之阳气顺利过渡至立春之新生阳气。"
+"冬符六道施用得当，则整个冬季虽天寒地冻而身常温煦，"
+"冻疮无从生矣。</p>"
+"<p style=\"line-height:2.2;\"><b>禳冻疮五道特别符法：</b>"
+"除二十四道节气符外，尚有五道特别符法为应急之用。"
+"一曰<b>速效禳冻符</b>——适用于已生冻疮红肿痛痒之时，"
+"以蒜汁调朱砂书于黄纸（大蒜辛温走窜能开毛窍引药力符力入里），"
+"贴于患处或患处所在经脉之近端穴位。"
+"符中画\"三昧真火融寒化冻\"八字雷篆，左右各画一火焰形。"
+"书符时存想符化为一团烈火直入冻疮之处，融冰化雪活血通脉。"
+"贴符后一炷香时间内即可感到患处发热瘙痒减轻，红肿渐退。"
+"二曰<b>溃烂收口符</b>——适用于冻疮已溃烂渗液不收口者，"
+"以白及粉调朱砂书于棉布之上"
+"（白及为敛疮生肌之要药），"
+"贴于溃烂处周围（不可直接覆盖溃烂面以免影响排脓）。"
+"符中画\"生肌敛疮收口愈合\"八字雷篆。"
+"书符时存想患处生出新鲜肉芽如春草破土，糜烂逐渐收敛干燥。"
+"三曰<b>回阳救逆符</b>——适用于全身冻僵神识昏迷之危候，"
+"此为急救之符不可轻用。"
+"以麝香少许调朱砂书于黄绢之上"
+"（麝香辛温走窜力极强能开窍醒神回阳救逆），"
+"放于患者心口膻中穴及头顶百会穴。"
+"同时以艾条重灸关元气海命门三穴以回垂绝之阳。"
+"四曰<b>预防冻疮根本符</b>——"
+"适用于每年必发冻疮之体质者，"
+"于夏至日或冬至日书之，"
+"以三年以上陈艾绒汁调朱砂书于黄绢，"
+"折叠成三角形以红线系之随身佩戴一整年，"
+"可从根本上改善体质减少冻疮复发。"
+"五曰<b>冻疮愈后防疤符</b>——"
+"冻疮愈合后遗留紫暗疤痕或硬结不散者，"
+"以丹参汁调朱砂书之（丹参养血活血化瘀消癥），"
+"贴于疤痕处，每日一换连续四十九日，"
+"可使疤痕软化色泽转淡。</p>"
+"<p style=\"line-height:2.2;\"><b>符法之四宜四忌：</b>"
+"禳冻疮符法施用有四宜四忌。"
+"四宜——一宜择天晴日暖之日书符，寒湿阴雨之日不宜书符"
+"因寒湿之气会影响符之灵效。"
+"二宜书符前以热水泡手使双手温暖灵活，手僵指冷时不可书符。"
+"三宜符成后以温酒一杯敬符神——酒性温热助符力运行。"
+"四宜贴符之处先以姜片摩擦至皮肤微红微热再贴符，"
+"以开毛窍助符力透入。"
+"四忌——一忌书符时门窗大开寒风直入，书符之室须温暖无风。"
+"二忌符贴于患处过久至皮肤过敏——每日更换观察皮肤反应。"
+"三忌以此符法牟取暴利乘人之危——"
+"道法济人原为慈悲，若变为敛财之具则符法全失且遭天谴。"
+"四忌贴符后立即以火烤或热水烫患处——"
+"冻疮患处宜缓缓加温不宜骤热，骤热则寒热相激反伤皮肉。"
+"此四忌切须谨记不可违犯。</p>"
+"<h2 style=\"color:#8b1a1a;border-bottom:2px solid #e8ddd0;"
+"padding-bottom:8px;font-size:22px;margin-top:28px;\">"
+"卷三 · 禳冻疮丹药方剂</h2>"
+"<p style=\"line-height:2.2;\">"
+"丹药者，道门历代祖师采集天地精华炼制之灵药也。"
+"禳冻疮之丹药方剂，分为内服温养与外敷治疗两大类。"
+"内服以温阳散寒、益气养血为主；外敷以消肿止痛、生肌敛疮为要。"
+"内外兼治则冻疮可愈，体质可强，复发可防。</p>"
+"<p style=\"line-height:2.2;\"><b>内服温养方剂：</b>"
+"内服之方重在温养阳气、充养气血，使正气内存寒邪不侵。"
+"第一方<b>温阳御寒汤</b>——附子三钱（先煎一个时辰以去其毒）、"
+"干姜三钱、肉桂二钱、炙甘草三钱、黄芪一两、当归五钱、"
+"桂枝三钱、白芍四钱、红枣十枚、生姜五片。"
+"以水八碗煎至三碗，去渣分三次温服，每日一剂。"
+"此方以四逆汤合黄芪建中汤化裁，温阳散寒益气养血，"
+"适用于素体阳虚、手足不温、每年必发冻疮者。"
+"冬至后开始服用，连服四十九日为一个疗程。"
+"附子须用炮附子且先煎久煎，不可生用。"
+"第二方<b>当归四逆加味汤</b>——当归五钱、桂枝三钱、"
+"白芍四钱、细辛一钱、通草二钱、炙甘草三钱、大枣十枚、"
+"吴茱萸二钱、生姜五片。以水六碗煎至二碗，去渣分两次温服，每日一剂。"
+"此方为《伤寒论》当归四逆汤加吴茱萸生姜而成，"
+"专治血虚寒凝、手足厥冷，为冻疮治疗之经典方剂。"
+"第三方<b>十全大补汤加减</b>——人参三钱（或党参一两代）、"
+"白术四钱、茯苓五钱、炙甘草三钱、当归五钱、川芎三钱、"
+"白芍四钱、熟地五钱、黄芪一两、肉桂二钱、"
+"鹿角胶三钱（烊化冲服）。"
+"以水八碗煎至三碗，去渣分三次温服，每日一剂。"
+"此方气血双补兼温阳，适用于气血两虚、四肢不温、"
+"冻疮反复发作之体质虚弱者。"
+"第四方<b>独活寄生汤化裁</b>——独活三钱、桑寄生五钱、"
+"秦艽三钱、防风二钱、细辛一钱、当归五钱、川芎三钱、"
+"熟地五钱、白芍四钱、桂枝三钱、杜仲四钱、牛膝三钱、"
+"人参二钱、炙甘草二钱。以水六碗煎至二碗，去渣分两次温服。"
+"此方原治风寒湿痹，化裁后温经散寒、养血通络，"
+"适用于冻疮兼有风寒湿痹痛者。"
+"第五方<b>简易姜枣红糖汤</b>——生姜一两（切片不去皮）、"
+"红枣二十枚（劈开）、红糖二两。以水四碗煮至二碗，"
+"去渣代茶频饮。此方最为平和简便，生姜散寒、红枣养血、红糖温中，"
+"三味合一温暖周身，不拘体质人人可服，"
+"为冬季日常防冻之食疗第一汤。</p>"
+"<p style=\"line-height:2.2;\"><b>外用涂敷方剂：</b>"
+"外用之方直接作用于冻疮患处，药力直达病所取效迅捷。"
+"第一方<b>冻疮消肿止痛膏</b>——猪脂四两（炼净）、"
+"肉桂粉五钱、干姜粉五钱、花椒粉三钱、乳香粉三钱、"
+"没药粉三钱、血竭粉二钱、樟脑一钱。"
+"将猪脂化开微温时放入诸药粉末搅匀成膏，贮瓷瓶中密封备用。"
+"用时取适量涂于患处轻轻按摩至发热，每日二至三次。"
+"此膏温经散寒、活血止痛，适用于冻疮红肿疼痛尚未溃烂者。"
+"第二方<b>冻疮溃烂生肌散</b>——煅石膏一两、黄柏五钱、"
+"大黄五钱、白及一两、血竭三钱、冰片一钱、"
+"珍珠粉二钱（若无可以煅龙骨代）。"
+"共研极细末过二百目筛，贮瓶中密封备用。"
+"用时先以甘草汤清洗疮面，然后以药粉薄撒于疮面，"
+"外以消毒纱布包扎，每日换药一至二次。"
+"此散清热解毒、祛腐生肌，适用于冻疮已溃烂渗液者。"
+"第三方<b>冻疮浸泡汤</b>——艾叶一两、花椒五钱、"
+"生姜一两（拍碎）、桂枝五钱、红花三钱、透骨草一两、"
+"伸筋草一两、川芎三钱。"
+"以水五碗煎煮半个时辰，去渣取汁倒入盆中，"
+"待温度降至适宜时（不可过热）将患处浸泡于药液中，"
+"每次一炷香时间（约二十分钟），每日一至二次。"
+"此汤温经散寒、活血通络，适用于手足冻疮红肿痛痒者。"
+"第四方<b>冻疮皲裂润肤油</b>——芝麻油四两、当归五钱、"
+"紫草三钱、白芷三钱、生地五钱、黄蜡五钱。"
+"将芝麻油与当归、紫草、白芷、生地一同文火慢熬至药枯，"
+"去渣后加入黄蜡融化搅匀，候冷成膏。每日涂抹患处数次。"
+"此油养血润燥、生肌润肤，适用于冻疮愈合后皮肤干燥皲裂者。"
+"第五方<b>冻疮急救温通酒</b>——干姜一两、花椒五钱、"
+"樟脑二钱、冰片一钱、白酒一斤。"
+"将干姜花椒研粗末与樟脑冰片一同浸入白酒中密封浸泡七日，"
+"去渣取酒备用。用时以棉签蘸药酒涂擦于冻疮未溃之处，"
+"或以纱布浸药酒后湿敷。"
+"此酒专为冻疮初起急救之用——辛温走窜力极强，"
+"涂擦后数分钟内即可感到局部发热血液循环加速。"
+"但须注意：冻疮已溃烂者不可用此酒直接涂疮面，"
+"只可涂擦于溃烂周围之正常皮肤。"
+"第六方<b>冻疮预防三九贴</b>——白芥子五钱、延胡索五钱、"
+"甘遂二钱、细辛二钱、肉桂二钱、"
+"麝香少许（或以冰片代）。"
+"共研细末以生姜汁调成糊状，于冬至日开始贴敷——"
+"取穴大椎、肺俞、心俞、膈俞、肾俞、命门，"
+"每次贴敷半个时辰取下，每九日一次，"
+"共贴三次（一九、二九、三九各一次）。"
+"此法借三九严寒之极阴生阳之机，"
+"以辛温之药敷于背俞穴以激发阳气运行周身，"
+"为预防冻疮之根本大法。</p>"
+"<p style=\"line-height:2.2;\"><b>丹药炼制秘法：</b>"
+"道门丹药之炼制非同寻常，须择天时、合地利、应人和。"
+"炼禳冻丹药之总诀在\"借天地之阳以培人身之阳\"。"
+"一曰<b>三阳暖身丹</b>——取端午日午时所采艾叶（得天阳）、"
+"夏至日午时所采菖蒲（得地阳）、"
+"三伏天午时所采生姜（得人阳），"
+"三味各等分阴干为末。再取冬至日子时之雪水调合药末为丸"
+"如梧桐子大，朱砂为衣。"
+"此丹集一年中三个阳气最盛时点之三味阳性药材，"
+"又以冬至阴极阳生之水调和，取\"阳中生阳\"之意。"
+"每日子时以温酒送服七丸，"
+"服后静坐存想丹田有一轮红日升起遍照周身。"
+"此丹为禳冻疮丹药之首，服之能温补全身阳气，增强抗寒能力。"
+"二曰<b>九阳暖心丹</b>——取九种纯阳药材各三钱"
+"（附子、肉桂、干姜、吴茱萸、蜀椒、细辛、丁香、高良姜、荜茇），"
+"各以酒浸一宿后微火焙干，共研细末，"
+"以炼蜜为丸如龙眼核大，每丸重一钱。"
+"每晨空腹以淡盐水送服一丸。"
+"此丹以大热纯阳之品直入少阴心肾二经，"
+"专补心肾阳气，适用于心肾阳虚、手足厥冷、"
+"脉微欲绝之重症冻疮体质者。"
+"然此丹热性极强，非大寒之体不可轻服，且不可久服以防伤阴。"
+"三曰<b>太一暖身香</b>——取檀香、沉香、降真香、丁香、乳香、"
