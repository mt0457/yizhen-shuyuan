<b>混元一炁，化现龙王。天尊敕旨，镇守四方。东海敖广青帝主，南海敖钦赤帝王，西海敖闰白帝镇，北海敖顺黑帝当。五湖四渎各有主，九江八河各龙藏。洞庭柳毅传书远，鄱阳石钟涛声长，太湖烟雨蚕桑茂，洪泽高堰固金汤，巢湖陷州警后世，长江万里贯八荒，黄河九曲屡迁徙，淮河借道不改王，济水潜行三隐现，清流入海永流芳。兴云布雨润枯槁，驱旱逐魃救饥荒。宝诰诵时风乍起，至心恳处雨自降。风不覆舟于险浪，浪不崩堤于秋江。水德五善修大道——柔而克刚、净而不染、平而无欺、容而无碍、恒而无断。诵诰即是修水德，修水德即是悟大道，悟大道即是归混元。以此功德皆回向——愿天下风调雨顺、五谷丰登、河清海晏、万民安乐。至心皈命礼。十方万灵一切龙王行雨辅化天尊。福生无量天尊。</b>
