经中所谓“八景”者，八节之景也——立春、春分、立夏、夏至、立秋、秋分、立冬、冬至，此八节者，乃一年之中阴阳消长、天地气交之关键节点；“飞经”者，飞神之经也——修道者于八节之日依法存思，则能魂魄飞升、与神同游于八极之表。
