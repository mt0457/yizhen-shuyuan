【案十三·占诉讼】因田产与人打官司。得雷天大壮䷡，世爻午火应爻子水。应克世——对方势强。官鬼爻持世本有利，然月建为亥水克世。断曰：此案我方理亏，不如和解。其人不信，果败诉。

【案十四·占寻人】张氏寻失散多年的兄长。得山水蒙䷃，兄弟爻子水动化申金回头生。兄弟为用神，子水动化申金回头生——用神旺动且得生，人尚在世。申为西北方城市。断曰：兄在西北方向，大城镇中。后三年，果在西安寻得。

【案十五·占盗贼】家被窃，占盗贼去向。得水火既济䷾变火泽睽䷥。官鬼爻戌土动。官鬼为盗贼，戌土临玄武。玄武为阴私之人，戌为西北方。戌化酉金（退神）——盗贼已向西北逃遁，力量渐衰。断曰：二日内可获。报官后二日果捕得，盗贼正欲逃往西北邻县。

【案十六·占梦】人梦大水惊恐而醒，占梦兆。得坎为水䷜。坎水重叠，六爻俱静。断曰：梦水为财（坎为水，水生财），非凶兆也。旬内当有意外之财。后果七日得赠银二十两。

【案十七·占兵事】时值战乱，占城中安危。得坤为地䷁，六爻俱静。坤为安稳、包容之象，六爻安静——断曰：城池无恙，百姓可安。后贼兵果绕城而遁。

【案十八·占经商选址】商人占两处店铺何者为佳。先占东店得风雷益䷩，妻财辰土旺相。后占西店得火泽睽䷥，妻财酉金旬空。断曰：东店财旺，西店空亡不可用。果在东店开张后生意兴隆，西店后为他人所开，不久倒闭。

【案十九·占年运】年底问来年运势。得地天泰䷊，世爻辰土得月建生。泰为通泰之象，辰土旺相得生——断曰：明年家宅平安，财有增益。果来年风调雨顺，家业小有发展。

【案二十·占风水】问祖坟风水吉否。得山风蛊䷨，父母爻戌土为坟。戌土月在午月（火生土）——得生，旺相。然二爻巽木克土（木克土），巽为风，主风水有损。断曰：坟地本好，但近树木根穿，宜清理。后人清理大树根须，重修坟冢，后家运转好。

【案二十一·占股票盈亏】商人欲入股，占吉凶。得火雷噬嗑䷔，妻财爻丑土持世。丑土当月令（午火月生土）——得生，旺相。子孙爻巳火动生在旁——财源有力。断曰：此股可入，冬至后获利。果冬至后股价大涨，获利三成。

【案二十二·占寻犬】人家养之犬走失，占可归否。得山火贲䷕，子孙爻申金为犬（宠物为子孙）。申金旬空（甲寅旬子丑空…申不空，假设在甲戌旬则申酉空）——值旬空为犬走失之象。然申金为用神旺相，虽空不空。断曰：犬未远去，速往西方寺庙或高处寻。果在城西庙中寻得。

【案二十三·占船运安危】货主问船运能否平安抵达。得水风井䷯，世爻戌土，应爻辰土。世应皆土，比和无克。官鬼爻酉金安静不动。父母爻亥水为船——旺相得应爻辰土之库。断曰：船行平安，三日后到埠。果三日后船安抵。

【案二十四·占父寿】人问老父寿数。得天雷无妄䷘，父母爻子水休囚，被月建午火冲破（子午冲）。月破者当月无用，且午月火旺水囚。断曰：今冬子月当慎（子水值月可暂时得力，过则复衰）。果其父于腊月病逝（子月为十一月，腊月为丑月。子月力暂强，过子月入丑月则子水彻底衰败）。

【案二十五·占坟地迁移】人问祖坟可否迁移。得泽水困䷮，父母爻辰土为旧坟，未土为新坟地。辰土动化丑土（进神）。动父进神主旧不如新。断曰：旧坟龙气已衰（辰为水墓，水主龙脉而辰土克水），新地吉，宜速迁。后迁至未方（西南）新地，三年后家业渐兴。

