大哉正一，肇自天师。老君亲授，法脉流慈。
传度之仪，千载不息。二十四治，法坛林立。
三盟三誓，天地为证。法箓为凭，天曹有名。
口诀心印，六耳不闻。法剑镇邪，万魔遁形。
法印为信，将吏遵令。法职正名，代天行道。

非人不传，非时不传。唯德是授，唯器是甄。
此仪此范，道门之本。失此则散，得此则存。
学者观此，当生恭敬。修道之士，当知来处。
法脉渊源，薪火可继。道炁长存，永世不替。

至心稽首，太上正一传度仪范。皈命正一天师，皈命太上老君，皈命三清道祖，皈命一切圣真。传度功德，普及于一切。弟子受度，皆共成道。度人无量天尊！

