舟行道里昼夜殊，佳士恨不久与俱。峡山行尽见平楚，舍舟登岸身无虞。念君治所近吾庐，步屧往来常与俱。君才敏赡兼百夫，朝作千篇日未晡。朅来湖上得佳句，从此不看西湖湖。知君过我慰我愚，欲去不及空踟蹰。

