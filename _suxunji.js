云兴于山，霿霿为雾。匪山不仁，天实不顾。山川我享，为我百诉。岂不畏天，哀此下土。班班鸣鸠，谷谷晨号。天乎未雨，余不告劳。既耕且种，既耘且耨。既获且簸，既春且馏。炊之饙之，以祭我稻。先祖是皇，孝孙是保。

