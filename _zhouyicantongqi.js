魏伯阳，会稽上虞人。修真潜默，养志虚无。博赡文词，通诸纬候。恬淡守素，唯道是从。每视轩裳，如糠秕焉。不知师授谁氏，得古人《龙虎经》，尽获妙旨。乃约《周易》，撰《参同契》三篇。复作《补塞遗脱》一篇。所述多以寓言借事，隐显异文。密示青州徐从事，徐乃隐名而注之。至后汉孝桓帝时，公复传授与同郡淳于叔通，遂行于世。

公撰《参同契》者，谓修丹与天地造化同途，故托易象而论之。莫不假借君臣以彰内外，叙离坎直指汞铅，列乾坤奠量鼎器，明父母系以始终，合夫妇显其滋孕，分爻象导之节符。本之天地，配以阴阳。览之者冀达玄功，行之者期成至道。其书三卷，都为一帙。上卷言修丹之本，中卷言修丹之法，下卷言修丹之鼎。大旨以乾坤为鼎器，以坎离为药物，以六十卦为火候。言不苟造，理不虚设。引验见效，校度神明。推类结字，原理为征。真契道要，故曰参同契。

