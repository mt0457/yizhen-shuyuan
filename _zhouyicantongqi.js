乾坤刚柔，配合相包。阳禀阴受，雌雄相须。须以造化，精气乃舒。坎离冠首，光耀垂敷。玄冥难测，不可画图。圣人揆度，参序元基。四者混沌，径入虚无。六十卦周，张布为舆。龙马就驾，明君御时。和则随从，路平不邪。邪道险阻，倾危国家。

君子居其室，出其言善，则千里之外应之。谓万乘之主，处九重之室。发号出令，顺阴阳节。藏器待时，勿违卦月。屯以子申，蒙用寅戌。余六十卦，各自有日。聊陈两象，未能究悉。立义设刑，当仁施德。逆之者凶，顺之者吉。

按历法令，至诚专密。谨候日辰，审察消息。纤芥不正，悔吝为贼。二至改度，乖错委曲。隆冬大暑，盛夏霜雪。二分纵横，不应漏刻。风雨不节，水旱相伐。蝗虫涌沸，群异旁出。天见其怪，山崩地裂。孝子用心，感动皇极。近出己口，远流殊域。或以招祸，或以致福。或兴太平，或造兵革。四者之来，由乎胸臆。

动静有常，奉其绳墨。四时顺宜，与气相得。刚柔断矣，不相涉入。五行守界，不妄盈缩。易行周流，屈伸反复。

晦朔之间，合符行中。混沌鸿蒙，牝牡相从。滋液润泽，施化流通。天地神明，不可度量。利用安身，隐形而藏。始于东北，箕斗之乡。旋而右转，呕轮吐萌。潜潭见象，发散精光。昴毕之上，震出为征。阳气造端，初九潜龙。阳以三立，阴以八通。故三日震动，八日兑行。九二见龙，和平有明。三五德就，乾体乃成。九三夕惕，亏折神符。盛衰渐革，终还其初。巽继其统，固济操持。九四或跃，进退道危。艮主进止，不得逾时。二十三日，典守弦期。九五飞龙，天位加喜。六五坤承，结括终始。韫养众子，世为类母。上九亢龙，战德于野。用九翩翩，为道规矩。阳数已讫，讫则复起。推情合性，转而相与。循环璇玑，升降上下。周流六爻，难可察睹。故无常位，为易宗祖。

