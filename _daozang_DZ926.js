<p style="font-size:16px;color:#8b1a1a;line-height:2.2;margin:0;">
<b>灵宝天尊，大慈大悲。哀悯众生，宣说真经。八灾度厄，万世梯航。诚心诵持，灾厄不侵。水火风震，虫疫兵饥。外禳灾难，内禳心魔。不求免灾，但求无惧。不求无厄，但求有道。若能内禳自心，外在灾厄如浮云过太空——不能伤其分毫。真正禳灾，以心为本。至心皈命，灵宝天尊。大慈大悲，随感赴应。消除灾厄，庇护群生。皈依道经师三宝。禳灾度厄天尊。灵宝无量度人天尊。</b>
</p>
