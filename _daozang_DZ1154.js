地皇内文者，地皇所说之秘文也。此文出于天地始分之际，结于乾坤定位之初。
山岳未峙，此文已镇于下；江海未通，此文已贯于中；万物未生，此文已育于内。
故地皇内文为安镇大地之本、召劾地祇之符、摄制百鬼之法。
得此文者，入山不逢虎狼，入水不遭蛟龙，入林不遇邪魅，入土不触煞气。
山川林泽一切地祇，见此文者莫不敬仰，来者稽首，去者顶礼，顺者受福，逆者受诛。
此文与天皇内文相为表里，天皇主天、主阳、主生发，地皇主地、主阴、主收藏，天地阴阳交泰，然后万物得以生成。
修道者当兼修天地二皇内文，使体内之阴阳二炁得以平衡，此为长生久视之根基也。
