吸满七口气后，闭气片刻，令紫炁在体内周行一周。
然后缓缓呼出体内浊气，观想浊气化为黑烟从脚底涌泉穴排出，入地三尺，永不再返。
此为天皇朝日采炁之法，日日行之，一年之后面色光润如童子，三年之后疾病不侵，九年之后身轻如羽，可以日行千里而不倦。
