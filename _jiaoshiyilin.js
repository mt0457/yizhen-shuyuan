巽为风（巽之巽）：温山松柏，常茂不落。鸾凤以庇，得其欢乐。温山松柏之安稳。占事长久吉昌。
巽之乾：采唐沬乡，要我桑中。失信不会，忧思约带。采唐失信之思。占事有约不践。
巽之坤：有鸟飞来，集于宫树。鸣声可畏，主将出去。鸟鸣可畏之兆。占事有警告。
巽之屯：仁政之德，参参日息。成都就邑，入受福禄。仁政日盛之吉。占事业兴旺。
巽之蒙：他山之石，错攻其玉。和璧既琢，光辉满室。他山攻玉之成。占事有成。
巽之需：赍贝赎狸，不听我辞。系于虎须，牵不得来。以贝赎狸反遭虎困。占事无谓损失。
巽之师：薄行搔尾，逐云除水。污泥为陆，下田宜稷。改水为田之利。占事有改造之益。
巽之比：天门九重，深不可彻。蒺藜绞罚，横加卒毒。天门深闭之困。占求见不通。
巽之泰：天门大开，牢户寥廓。桎梏解脱，拘囚纵释。天门大开之解放。占事先困后亨。
巽之否：争鸡失羊，亡其金囊。利不得得，忧恐惶惶。争鸡失羊之失。占因小失大。
巽之同人：天旱水涸，枯槁无泽。未有所获，困于无食。天旱水涸之困。占求财无得。
巽之大有：陶朱白圭，善贾息资。三致千金，德施乡里。陶朱善贾之富。占经商大吉。
巽之谦：三伏极阴，昆虫藏匿。草木零落，伤我稼穡。三伏极阴之寒。占防灾害。
巽之豫：黄鸟采蓄，既嫁不答。念我父兄，思复邦国。远嫁思乡之情。占婚姻有憾。
巽之随：田鼠野鸡，意常欲逃。拘制笼槛，不得动摇。田鼠被拘之困。占事不自由。
巽之蛊：平国不君，夏氏作乱。乌号窃发，灵公殒命。君臣失道之乱。占防政变。
巽之临：巨蛇大鳅，战于国郊。上下隔绝，主君走逃。巨蛇大战之乱。占防大变。
巽之观：谗言乱国，覆是为非。伯奇乖离，恭子忧哀。谗言乱国之祸。占防小人。
巽之噬嗑：郁怏不明，为阴所伤。众雾积聚，共夺日光。阴雾蔽日之暗。占事不明。
巽之贲：望城抱子，见邑不殆。公孙上堂，大君欢喜。望城抱子之喜。占事有获。
巽之剥：三虫为蛊，刳迹无与。胜母盗泉，君子弗处。三虫为蛊之害。占防小人。
巽之复：车驰人逐，卷甲相仇。齐鲁寇战，败于大丘。车驰相仇之乱。占防冲突。
巽之无妄：阴衰老极，阳建其德。履离戴光，天下昭明。阴极阳生之明。占事先暗后明。
巽之大畜：豹车出驾，乘时喜舞。英俊豪杰，俱入我宇。豹车出驾之荣。占事业有势。
巽之颐：阳伏在下，阴制其外。水火相搏，雷风交会。阴阳搏斗之斗。占事有冲突。
巽之大过：晨风文翰，大举就温。过我成邑，羿无所得。晨风大举之温。占出行有获。
巽之坎：白鸟衔饵，鸣呼其子。旋枝张翅，来从其母。白鸟育子之亲。占家事和睦。
巽之离：隐隐大雷，霶霈为雨。有女痴狂，惊骇邻里。大雷痴女之惊。占事有突发。
巽之咸：华薄实藁，衣敝如络。女巧不成，丝布为玉。华而不实之虚。占事有名无实。
巽之恒：破筐敝筥，弃捐于道。不复为宝，利得无有。破筐弃道之废。占财无得。
巽之遁：三鸡啄粟，十雏从食。饥鸢卒击，亡其两叔。雏鸡遭鸢之失。占防意外损失。
巽之大壮：乘车七百，以明文德。践土葵丘，齐晋受福。乘车明德之贵。占仕途大吉。
巽之晋：百足俱行，相辅为强。三圣翼事，王室宠光。百足相辅之强。占合作有力。
巽之明夷：典策法书，藏在兰台。虽遭乱溃，独不遇灾。典籍不毁之幸。占文书可保。
巽之家人：西诛不服，恃强负力。倍道趋敌，师走败覆。西诛不服之败。占竞争有失。
巽之睽：春阳生草，夏长条肄。万物蕃滋，充实益有。春夏万物蕃滋。占事兴旺。
巽之蹇：磝硗秃白，不生黍稷。无以供祭，只灵乏祀。硗秃不生之贫。占农事不利。
巽之解：褰衣涉河，水深渍衣。赖幸舟子，济脱无他。涉河遇险赖舟救。占事先危后安。
巽之损：宜行贾市，所求必倍。戴喜抱子，与利为友。行商得利之喜。占经商大吉。
巽之益：兄征东燕，弟伐辽西。克胜还归，封为君侯。兄弟出征大捷。占竞争获胜。
巽之夬：初虽惊惶，后乃无伤。受其福庆，永永其祥。初惊后福之喜。占事先惊后喜。
巽之姤：随风乘龙，与利相逢。田获三倍，商旅有功。随风乘龙之利。占求财大吉。
巽之萃：鱼扰水浊，桀乱我国。驾龙出游，东之乐土。鱼乱水浊之乱。占防小人。
巽之升：百蛮贡职，西见王母。献其良马，拜受福佑。百蛮朝贡之荣。占事业有大成。
巽之困：六目睽睽，各欲有至。专征未装，俟时旦明。六目各视之散。占事意见不一。
巽之井：山水暴怒，坏梁折柱。稽难行旅，留连愁苦。山洪坏桥之困。占出行大凶。
巽之革：使燕筑城，上下不亲。言而不信，亡其纪纲。筑城不亲之乱。占合作不力。
巽之鼎：矢石所射，襄为痍疾。奚子亚饭，腹大无节。矢石伤人之危。占防意外伤害。
巽之震：日月运行，一寒一暑。荣光赫赫，不可得保。日月运行之常。占事有起伏。
巽之艮：宫门愁鸣，臣围其君。不得东西，全闭牢门。宫门愁鸣之困。占被困。
巽之渐：戴盆望天，不见星辰。顾小失大，福逃于外。戴盆望天之愚。占事因小失大。
巽之归妹：天之所明，祸不遇家。反目相逐，终得和美。天佑不祸之家。占事先争后和。
巽之丰：仓唐奉使，中山以孝。文侯悦喜，击子征召。仓唐奉使之功。占出行有成。
巽之旅：嘉门福喜，增累盛炽。日就有德，宜民宜国。嘉门福喜之吉。占家国大吉。
巽之兑：南山之阳，华叶将将。嘉乐君子，为国宠光。南山华叶之荣。占事业显达。
巽之涣：画龙头角，文章未成。甘言美语，说辞无名。画龙未成之虚。占事未就。
巽之节：婴儿孩子，未有所识。狡童而争，乱我政事。婴儿争位之乱。占事不成熟。
巽之中孚：阴作大奸，欲伤我君。群飞蔽日，天无光辉。奸佞蔽日之暗。占防政变。
巽之小过：德之流行，利之四乡。雨师洒道，风伯逐殃。德流四方之善。占行善有报。
巽之既济：禹将为君，装入昆仑。稍进阳光，登见温汤。禹入昆仑之升。占事业进阶。
巽之未济：五岳四渎，含润为德。行不失理，民赖恩福。五岳四渎之德。占事有恩泽。

