乾为天（乾之乾）：道陟石阪，胡言连蹇。译喑且聋，莫使道通。登山涉险，语言不通之象。占事多阻，宜守不宜进。
乾之坤：招殃来螫，害我邦国。病伤手足，不得安息。天变地异，国有大灾。占事大凶，凡事谨慎。
乾之屯：阳孤亢极，多所恨惑。车倾盖亡，身常忧惶。亢龙有悔，高处不胜寒。占事宜退不宜进。
乾之蒙：鸱鸮娶妇，深目窈身。折腰不媚，与伯相背。以鸱鸮喻小人得志。占婚不吉，占事有诈。
乾之需：目瞤足动，喜如其愿。举家蒙宠，福禄自天。目跳足动之兆，好事将至。占事为吉兆。
乾之讼：龙马上山，绝无水泉。喉焦唇干，舌不能言。龙困浅滩之象。占事受阻，宜耐心等待。
乾之师：仓盈庾亿，宜稼黍稷。年丰岁熟，民人安息。五谷丰登，天下太平。占事大吉，农事尤利。
乾之比：中夜犬吠，盗在墙外。神明佑助，消散皆去。盗贼窥伺而神明护佑。占事虽有险而无碍。
乾之小畜：据斗运枢，顺天无忧。所行造德，与乐并居。顺应天道则无忧。占事顺势而为则吉。
乾之履：空拳握手，委地更起。富饶丰衍，快乐无已。空手起家终致富。占事宜努力进取。
乾之泰：不风不雨，白日皎皎。宜出驱驰，通理大道。风和日丽之象。占出行大吉。
乾之否：载日晶光，与月为双。五湖四海，照临万邦。日月同辉，光照四方。占事大吉，声名远扬。
乾之同人：子号索哺，母行求食。反见空巢，长息訾弋。母子离散，求食不得。占事有失落之象。
乾之大有：上帝之生，福佑日成。修德行善，子孙安宁。积善之家必有余庆。占事守德则吉。
乾之谦：山险难登，涧中多石。车驰軎击，重载伤轴。山高路险行车难。占事多阻，宜小心。
乾之豫：禹凿龙门，通利水源。东注沧海，民得安存。大禹治水之功。占事开创有成。
乾之随：乘龙上天，两蛇为辅。踊跃云中，游观沧海。飞龙在天之象。占事腾达有望。
乾之蛊：彭祖九子，据德不殆。南山松柏，长受嘉福。寿如彭祖，福如松柏。占事长寿有福。
乾之临：南山昊天，刺政闵身。悲愤填膺，忧心如焚。忧国忧民之心。占事多忧。
乾之观：江河淮海，天之奥府。众利所聚，可以富有。四海汇聚财富。占财大吉。
乾之噬嗑：坚冰黄鸟，终日悲鸣。不见甘露，独受酷刑。黄鸟悲鸣之象。占事困苦无援。
乾之贲：室如悬磬，既危且殆。早见之士，依山处谷。家徒四壁宜隐退。占事宜退隐守静。
乾之剥：大禹戒路，蚩尤除道。周匝万里，不危不殆。圣王开路，万里不危。占出行大吉。
乾之复：三人为旅，俱归北海。入门上堂，拜谒王母。三人同行归乡。占归家有喜。
乾之无妄：传言相误，非于径路。鸣鼓逐狐，不知迹处。误传信息逐狐不得。占事有误信之象。
乾之大畜：三羊争雌，相逐奔驰。终日不食，精气劳疲。三羊争偶徒劳无功。占事无谓竞争。
乾之颐：家给人足，颂声并作。四夷宾服，干戈卷阁。国泰民安之象。占事大吉太平。
乾之大过：桀跖并处，人民愁苦。拥兵荷粮，战于齐鲁。暴君乱世之象。占事多凶。
乾之坎：黄鸟采菉，既嫁不答。念我父兄，思复邦国。远嫁思乡之情。占婚姻有憾。
乾之离：胎生孚乳，长息成就。充满帝室，家国昌富。生生不息昌盛之象。占事兴旺。
乾之咸：三人求橘，反得丹穴。女贵以富，黄金银镒。意外得宝之象。占求财意外之喜。
乾之恒：东山西岳，会合俱食。百家送从，以成恩福。东西会合之吉。占合作有成。
乾之遁：朽舆瘦驷，不任御辔。君子服之，谈何容易。车朽马瘦难行远。占事力不从心。
乾之大壮：郤氏怀珠，不知其失。弃于沟渠，终不可得。怀珠而失之愚。占事有失宝之虞。
乾之晋：天之所予，福禄常在。不忧危殆，永受其庆。天赐福禄之象。占事大吉。
乾之明夷：弓矢俱张，把弹折弦。丸发不至，道遇害患。弓箭折弦弹不发。占事功亏一篑。
乾之家人：三女求夫，不见复关。伺候山隅，长思忧叹。三女待夫而不至。占等待之事难成。
乾之睽：阳旱炎炎，伤害禾谷。穑人无食，耕夫叹息。大旱伤农之象。占农事不吉。
乾之蹇：骑豚逐羊，不见所望。径涉虎穴，亡羊失羔。骑猪追羊入虎穴。占事方法不当反受损。
乾之解：暗昧冥语，相传诖误。鬼魅所居，谁知卧处。鬼魅暗昧之象。占事有欺诈。
乾之损：二人异路，东趋西步。千里之外，不相知处。分道扬镳各西东。占合作不成。
乾之益：公孙驾骊，载聘东齐。延陵说产，遗季纻衣。乘车聘齐之典。占出行有获。
乾之夬：孤竹之墟，失妇亡夫。伤于蒺藜，不见少妻。孤竹失偶之悲。占婚姻凶。
乾之姤：仁政不暴，凤凰来舍。四时顺节，民安其处。仁政感天凤凰来。占政事大吉。
乾之萃：任劣力薄，孱驽恐怯。如猬见鹊，不敢拒格。力弱势孤之象。占事无能为力。
乾之升：卫侯东游，惑于少姬。忘我考妣，久迷不来。卫侯迷于美色。占事因色失德。
乾之困：噂噂所言，莫知我垣。欢喜坚固，可以长安。众口纷纭而我自安。占事宜守己。
乾之井：鸱鸮破斧，邦人危殆。赖其忠德，转祸为福。鸱鸮虽凶而忠德可解。占事先凶后吉。
乾之革：玄黄虺隤，行者劳疲。役夫憔悴，逾时不归。行者劳苦之象。占出行多劳。
乾之鼎：弱足刖跟，不利出门。市贾不利，折亡为患。刖足难行不利出门。占出行及经商不利。
乾之震：悬貆素餐，居非其安。失舆剥庐，休坐徒患。不劳而获终非长久。占事宜守本分。
乾之艮：民怯城恶，奸人所伏。寇贼大至，入我邦郭。城防不固有贼寇。占防务不足。
乾之渐：阳低头，阴仰首。水为灾，伤我宝。阴阳失调水灾至。占防自然灾害。
乾之归妹：背北相憎，心意不同。如火与金，两不相容。水火不容之象。占合作婚姻不谐。
乾之丰：太微帝室，黄帝所直。藩屏周卫，不可得入。帝室森严不可入。占求见贵人不得。
乾之旅：茧栗牺牲，敬享鬼神。神嗜饮食，受福多孙。祭祀获福之象。占祭祀大吉。
乾之巽：出门逢恶，与祸为怨。更相击刺，伤我手臂。出门遇恶遭伤害。占出行大凶。
乾之兑：鹢飞中退，举事不遂。且守仁德，犹恐失坠。鹢鸟中退事不成。占事宜退守。
乾之涣：跛踦相随，日暮牛疲。陵迟后旅，失利亡雌。跛者相随牛困日暮。占事迟缓多失。
乾之节：龙角博颡，位至公卿。世禄久长，起动安宁。龙角博颡贵人之相。占官禄大吉。
乾之中孚：舜升大禹，石夷之野。征诣王庭，拜治水土。舜举大禹治水。占仕途有贵人提拔。
乾之小过：从风放火，荻芝俱死。三害集房，叔子中伤。放火烧山玉石俱焚。占事有池鱼之殃。
乾之既济：楩生荆山，命制输班。袍衣剥脱，夏热冬寒。良材遇良匠则成器。占事需待时机。
乾之未济：长面大鼻，来解己忧。遗吾福子，惠我嘉喜。长面大鼻之人来救。占事有贵人助。

