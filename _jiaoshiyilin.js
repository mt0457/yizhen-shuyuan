艮为山（艮之艮）：君孤独处，单弱无辅。名曰困苦，独坐空室。孤君独坐之困。占事无人相助。
艮之乾：忧惊已除，祸不为灾。安全以来，无忧无虑。忧除祸散之喜。占事先忧后喜。
艮之坤：穿绝桎梏，捩脱不去。与天相守，独坐空庐。桎梏难脱之困。占事束缚难解。
艮之屯：蹇牛折角，不能载粟。灾害不避，年岁无谷。牛折角年无谷。占农事不吉。
艮之蒙：邑将为墟，居之忧危。请命求安，脱免无患。城将为墟之危。占防家宅不宁。
艮之需：根刖残树，华叶落去。卒逢火焱，随风僵仆。树被刖又逢火。占事多灾。
艮之师：北山有枣，使叔寿考。东岭多栗，宜行贾市。北枣东栗之利。占经商有获。
艮之比：高原峻山，陆土少泉。草木林麓，嘉禾所灾。高山少泉禾受灾。占农事不利。
艮之泰：放衔委辔，奔乱不制。法度无常，君失其位。奔马失制君失位。占事失控。
艮之否：独坐西垣，莫与笑言。秋风多哀，使我心悲。独坐秋风之悲。占事孤独。
艮之同人：胫急股挛，不可出门。暮速归旅，必为身患。腿疾不能出门。占出行不利。
艮之大有：情伪难知，使我偏颇。小人在位，虽圣何咎。小人当道之困。占仕途有阻。
艮之谦：三人俱行，各别其道。一身五心，乱无所得。三人分道心乱。占合作不成。
艮之豫：公子王孙，把弹摄丸。发辄有获，室家饶足。王孙弹丸有获。占事有得。
艮之随：阴升阳伏，桀失其室。相餧不食，寄息空屋。阴阳失调之象。占事萧条。
艮之蛊：七窍龙身，造易八元。法天则地，顺时施恩。龙身造易之象。占事有创造。
艮之临：逐狐东山，水遏我前。深不可涉，失利后便。逐狐遇水失利。占求事有阻。
艮之观：衔命辱使，不堪其事。中坠落去，更为负载。辱命不堪之象。占事不能胜任。
艮之噬嗑：温仁君子，忠孝所在。八国为邻，祸灾不处。仁德君子之福。占守德则吉。
艮之贲：春多膏泽，夏润优渥。稼穑成熟，亩获百斛。风调雨顺丰收。占农事大吉。
艮之剥：二女共室，心不聊食。首发如蓬，忧常在中。二女同室心不和。占家宅不睦。
艮之复：筑关石颠，立木泉头。一钓连鳌，至于海湫。钓鳌得巨利。占事有大收获。
艮之无妄：欲避凶门，反与祸邻。颠覆不制，痛薰我心。欲避凶反遭祸。占事适得其反。
艮之大畜：踧行窃视，有所畏避。狸首伏藏，以夜为利。狸伏夜行以避害。占事宜隐秘。
艮之颐：八面九口，长舌为斧。斫破瑚琏，殷商绝后。长舌如斧破宝器。占防口舌是非。
艮之大过：和气相薄，膏泽津液。生我嘉谷，年丰大熟。和气生谷大丰收。占农事大吉。
艮之坎：消金铄石，破我弓镞。亡矢折镞，失其利禄。金石销毁之损。占财有失。
艮之离：秦仪机言，解其国患。一说燕下，齐相以权。苏秦张仪之辩才。占口才有功。
艮之咸：旦奭辅王，周德孔明。越裳献雉，万国咸宁。周公辅政之治。占仕途大吉。
艮之恒：弱足刖跟，不利出门。市贾不利，折亡为患。刖足难行不利商。占出行经商不利。
艮之遁：坚冰黄鸟，终日悲鸣。不见甘露，独受酷刑。黄鸟悲鸣之困。占事苦无援。
艮之大壮：魂微惙惙，属纩听绝。旷然大通，复更生活。死而复生之象。占事先死后活。
艮之晋：阴生麋鹿，鼠舞鬼哭。灵龟陆处，釜甑草生。怪异之象万物失序。占事有异变。
艮之明夷：凿井求玉，非卞氏宝。名困身辱，劳无所得。凿井求玉劳无得。占事徒劳。
艮之家人：山作天时，陆为海口。民不安处，覆其宗社。山崩海变之灾。占防自然灾害。
艮之睽：东风启户，隐伏欢喜。萌庶长养，华叶茂盛。春风启户万物生。占事新生有望。
艮之蹇：华灯百枝，消暗衰微。精光欲尽，奄如灰靡。华灯欲灭之象。占事将衰。
艮之解：三十无室，寄宿桑中。上宫长女，不得来同。三十无妻之困。占婚姻不吉。
艮之损：卵与石斗，糜碎无疑。动而有悔，出不得时。以卵击石之败。占竞争必败。
艮之益：秦兵争强，失其贞良。败于郩乡，师出逾时。秦兵败绩之鉴。占出师不利。
艮之夬：摧角不伤，虽折复起。秉德无愆，乃得长理。角摧复起之象。占事先损后复。
艮之姤：操笱搏狸，荷弓射鱼。非其器用，自令心劳。操非其器之劳。占事方法不当。
艮之萃：葵丘之盟，晋献会行。见太宰辞，复为还舆。会盟有成之象。占合作可成。
艮之升：膑诈庞子，夷灶尽毁。兵伏卒发，矢至如雨。孙膑破庞涓之策。占以智取胜。
艮之困：南行出城，世得大福。王姬归齐，赖其所欲。南行得福王姬归。占出行有喜。
艮之井：冬采薇兰，地冻坚冰。利走室北，暮无所得。冬采薇兰之无功。占事不合时宜。
艮之革：王乔无病，狗头不痛。亡屐失履，乏我送从。王乔无病之疏忽。占事有失。
艮之鼎：宛马疾步，盲师坐御。目不见路，中宵弗到。盲师驾马之危。占出行不利。
艮之震：求利难国，亡去我北。忧归其城，反为我贼。求利反失之象。占财有损。
艮之渐：比目四翼，安我邦国。上下无患，为我家福。比目四翼之祥瑞。占家国大吉。
艮之归妹：八材既登，以成嘉功。龙降庭坚，国无忧凶。八材成功之象。占事业有成。
艮之丰：消弊穿空，家莫为宗。奴婢逃走，子西父东。家破人散之象。占家宅大凶。
艮之旅：鸟舞国城，邑惧卒惊。仁德不修，为下所倾。鸟舞城惊之乱。占防民众不满。
艮之巽：五门四道，通利至源。南贩北贾，与福为邻。五门四道通利。占经商大吉。
艮之兑：春生夏长，秋收冬藏。时无不利，岁有余粮。四时顺遂丰收。占事大吉。
艮之涣：齐东郭庐，嫁于洛都。俊良美好，媒利过倍。嫁女得利之象。占婚姻有财。
艮之节：安床厚褥，不得久宿。弃我嘉宴，困于南国。安床不久之象。占事不长。
艮之中孚：内崩身伤，中乱无恒。虽有美粟，不得餐食。内伤中乱之困。占健康有忧。
艮之小过：出门逢患，与祸为怨。更有击刺，伤我指端。出门遭祸之象。占出行大凶。
艮之既济：出入节时，南北无忧。行者即至，在外归来。出入有节之吉。占出行平安。
艮之未济：公孙驾骊，载聘东齐。延陵说产，遗季纻衣。乘车聘齐之典。占出行有获。

