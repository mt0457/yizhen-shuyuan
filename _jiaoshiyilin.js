震之复：载金贩狗，利弃我走。藏匿渊底，折晦为咎。载金贩狗利弃去。占财有失。
震之无妄：日中为市，各抱所有。交易赀贿，函珠为市。日中开市交易。占商贾有成。
震之大畜：月步平趍，礼拜神仙。德泽洋溢，福禄来并。礼拜神仙福禄来。占祭祀大吉。
