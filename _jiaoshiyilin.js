离为火（离之离）：时乘六龙，为帝使东。达命宣旨，无所不通。六龙使者之通达。占仕途大吉。
离之乾：执辔四骊，王以为师。阴阳之明，载受东齐。四马之车王师出。占事业有权威。
离之坤：春秋祷祀，解祸除忧。君子无咎，与天相守。春秋祭祀解忧。占祭祀大吉。
离之屯：坐车乘轩，据国子民。虞叔受命，和合六亲。乘车治民之象。占仕途掌权。
离之蒙：开户下堂，与福相迎。禄于公门，至家以宁。开门迎福之象。占事业有福。
离之需：高木腐巢，漏湿难居。不去其居，终有祸忧。腐巢难居之象。占居所不安。
离之师：三虎搏狼，力不相当。摧折两败，为众所伤。虎狼相搏两败。占竞争两伤。
离之比：松柏枝叶，常茂不落。君子欢宁，日富安乐。松柏常青之象。占事长久安稳。
离之泰：奔轮脱辐，折轭摧辕。失其道里，不知所向。车轮脱辐之危。占出行大凶。
离之否：载璧秉圭，请命于河。周公克敏，冲人瘳愈。载璧请命之诚。占求助可成。
离之同人：素车伪马，不任重负。王侯出征，忧危为咎。伪马素车不任重。占事力不从心。
离之大有：大树之子，百条共母。当夏六月，枝叶盛茂。大树百条之盛。占家业兴旺。
离之谦：齐鲁争言，战于龙门。构怨结祸，三世不安。齐鲁相争之祸。占防长期纠纷。
离之豫：五岳四渎，润洽为德。行不失理，民赖恩福。五岳四渎之德。占事有恩泽。
离之随：驾一赛驴，与驽双驱。蹶跌伤损，结病无瘳。驾驴伤损之困。占事不利。
离之蛊：早霜晚雪，伤害禾麦。损功弃力，饥无所食。霜雪伤禾之灾。占农事大凶。
离之临：岐周海隅，独乐无忧。可以避难，全身保财。岐周乐土之象。占避难有方。
离之观：阴蔽其阳，目暗不明。君忧其国，求骐得黄。阴蔽阳暗之困。占事不明朗。
离之噬嗑：南国饥凶，民食糟糠。少子困捕，利无所得。南国饥荒之困。占求财无得。
离之贲：平公有疾，迎医秦国。和不能愈，晋人赴告。平公求医不愈。占疾病难治。
离之剥：戴尧扶禹，松乔彭祖。西过王母，道里夷易。圣贤扶助之吉。占出行有贵人。
离之复：羔羊皮革，君子朝服。辅政扶德，以合万国。君子朝服之象。占仕途有成。
离之无妄：升擢进用，巡狩北荒。至于玄水，受福为祥。升擢巡狩之吉。占仕途升迁。
离之大畜：南征大宛，北达幽燕。东西贸易，利得百倍。四方贸易之利。占经商大吉。
离之颐：鸟惊孤鸿，乱飞不宁。上弱下强，为阴所刑。鸟乱飞之不安。占事有动荡。
离之大过：六月采芑，征伐无道。张仲方叔，克胜饮酒。六月征伐克胜。占竞争获胜。
离之坎：六月采芑，征伐无道。张仲方叔，克胜饮酒。同上。占竞争获胜。
离之咸：白鸟衔饵，鸣呼其子。旋枝张翅，来从其母。白鸟衔饵育子。占家事和睦。
离之恒：东风解冻，河川流通。举帆张网，大鱼被蒙。东风解冻渔获丰。占事有转机。
离之遁：三狸搏鼠，遮遏前后。死于圜域，不得脱走。三狸捕鼠之困。占事被困。
离之大壮：绥德孔明，履禄久长。贵且有光，疾病忧伤。绥德履禄之象。占事有长久之福。
离之晋：三虎搏狼，力不相当。摧折两败，为众所伤。虎狼两败之象。占竞争两伤。
离之明夷：使伯采桑，恶不肯行。与叔争讼，更相毁伤。兄弟争讼之祸。占家事不和。
离之家人：抱空握虚，鸮惊我雏。利去不来，独坐空庐。抱空握虚之困。占求利不得。
离之睽：李华再实，鸿卵降集。仁德以兴，荫国受福。李花再开之祥。占事业复兴。
离之蹇：东山皋落，勇悍不服。金玦玩好，衣为身灾。皋落不服之患。占防远方有变。
离之解：飞蚊污身，为邪所率。青蝇分白，贞孝放逐。飞蚊污身之辱。占事有小人侵害。
离之损：南山大木，文身其目。制命出令，东里田亩。南山大木之材。占事业有根基。
离之益：泉起昆仑，东出玉门。流为九河，无有溺忧。昆仑泉水之利。占事源远流长。
离之夬：命短不长，中年夭伤。思若为哭，父母孔哀。中年夭伤之悲。占寿元不吉。
离之姤：君臣不和，上下失宜。宗子哀歌，失其宠姬。君臣不和之乱。占仕途有变。
离之萃：苛政日作，螟食华叶。割下啖上，民被其贼。苛政害民之象。占时运不济。
离之升：南行戴铠，登履九魁。车伤牛疲，日暮嗟叹。南行负重之困。占出行多劳。
离之困：春东夏南，随阳有功。与利相逢，富饶丰衍。随阳求利之富。占求财有利。
离之井：头尾颠倒，不知绪处。君失其国，臣失其序。头尾颠倒之乱。占事失序。
离之革：言无要约，不成券契。殷叔季姬，公孙争之。无约争姬之讼。占合作无凭。
离之鼎：缺破不成，胎卵不生。不见其形，失其道里。缺破不成之象。占事无成。
离之震：见蛇交卧，惜蚖畏恶。心怖不安，我兵退却。见蛇交卧之惧。占事有恐惧。
离之艮：河水孔穴，坏败我室。水深无涯，鱼鳖倾倒。河水坏室之灾。占防自然灾害。
离之渐：五岳四渎，地得以安。高而不危，敬慎不殆。五岳四渎之稳。占事安稳。
离之归妹：南至之日，阳消不息。北风烈寒，万物藏伏。冬至阳消之寒。占事宜伏藏。
离之丰：五利四福，俱田高邑。黍稷盛茂，多获藁稻。五利四福丰收。占农事大吉。
离之旅：公孙驾车，载游东齐。延陵说剑，遗我宝珠。驾车东游之乐。占出行有获。
离之巽：蛟螭当道，民困愁苦。望羊置群，长子在门。蛟螭当道之困。占前途有阻。
离之兑：金玉满堂，忠直乘危。三老冻饿，鬼夺我室。金玉满堂之危。占富而不安。
离之涣：日入明匿，阳精隐伏。小人心劳，求事不得。日入明匿之暗。占事不遂。
离之节：频逢招饮，失利后福。不如子息，旧居故处。频逢招饮之失。占事宜守旧。
离之中孚：南有嘉鱼，驾黄取游。鲂鱮诩诩，利来无忧。南有嘉鱼之乐。占出行有收获。
离之小过：黄裳建元，文德在身。禄佑洋溢，封为齐君。黄裳文德之贵。占仕途大吉。
离之既济：口不从心，欲东反西。与意乖违，动举失便。口不从心之悖。占事与愿违。
离之未济：虎狼之乡，日争凶讼。叨尔为仇，不可与游。虎狼之乡之危。占交友宜慎。

