震之鼎：体重飞难，未能越关。不离室垣，中心忧烦。体重大难飞。占出行不利。
震之艮：玄黄虺隤，行者劳疲。役夫憔悴，逾时不归。行者劳疲之象。占出行多劳。
震之渐：孔德如玉，出于幽谷。升高鼓翼，辉光照国。贤人出谷济世。占仕途有进。
