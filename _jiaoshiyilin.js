震之遁：背地相憎，心意不同。如火与金，两不相容。水火金不相容。占合作婚姻不谐。
震之大壮：夏台羑里，汤文厄处。鬼侯歏醢，岐人悦喜。汤文被囚之厄。占事先困后亨。
震之晋：牙孽生齿，螳螂启户。幽人利贞，鼓翼起舞。螳螂启户之象。占事有新生机。
震之明夷：烈女无夫，闵思苦忧。齐子无良，使我心愁。烈女无夫之苦。占婚姻不吉。
震之家人：践履危难，脱厄去患。入福喜门，见诲大君。脱险入福之象。占事先凶后吉。
震之睽：折臂接手，不能进酒。祈祀闲旷，神怒不喜。折臂不能进酒。占祭祀不吉。
震之蹇：蚁封户穴，大雨将集。鹊数起鸣，牝鸡叹室。蚁封穴雨将至。占防天气变化。
