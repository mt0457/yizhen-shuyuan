兑为泽（兑之兑）：班马还师，以息劳疲。役夫嘉喜，入户见妻。班师回朝之喜。占出行平安归来。
兑之乾：下堂出门，东至九山。逢福值喜，得其安闲。出门东行遇福。占出行大吉。
兑之坤：子鉏执麟，春秋作元。阴将以终，阳乃始焉。孔子获麟作春秋。占事有开创。
兑之屯：挟河为守，期至无死。虽危不殆，长安其居。挟河固守之安。占事宜坚守。
兑之蒙：天孙帝子，与日月处。光荣于世，福禄繁祉。天帝之孙之贵。占出身高贵。
兑之需：三年生狗，以戌为母。荆夷上侵，姬伯出走。怪异之象国不安。占防异变。
兑之师：早霜晚雪，伤害禾麦。损功弃力，饥无所食。霜雪伤禾之灾。占农事大凶。
兑之比：嵩融持戟，杜伯荷弩。降观下国，诛逐无道。持戟荷弩之威。占有武力可成。
兑之泰：子畏于匡，厄困陈蔡。明德不危，竟克免害。孔子困厄之鉴。占德可解厄。
兑之否：有两赤鹞，从五隼噪。操矢无筈，趣释尔射。赤鹞噪集之乱。占防小人。
兑之同人：当得自知，不逢凶灾。衰者复兴，终得福来。自知之明之吉。占事自省则吉。
兑之大有：三女为奸，俱游高园。背室夜行，与伯笑言。三女夜行之非。占防女色。
兑之谦：三妇共夫，志不相思。心怀不平，至老无子。三妇共夫之乱。占家宅不宁。
兑之豫：蔡侯朝楚，留连江滨。踰时历月，思其后君。蔡侯留楚之思。占出行不归。
兑之随：瞻白用弦，驽孱恐怯。任力随身，如猬见鹊。力弱势孤之困。占事无能为力。
兑之蛊：南巴六安，石斛戟天。所指不已，耋老复丁。南巴药物之效。占健康有救。
兑之临：东门坛墠，鼓舞而祀。神降福祉，受福无已。鼓舞祭祀之福。占祭祀大吉。
兑之观：桃夭少华，婚悦宜家。君子乐胥，长利止居。桃夭婚悦之喜。占婚大吉。
兑之噬嗑：随时逐利，不失其节。所求必得，欢乐无忧。随时逐利之顺。占求财可成。
兑之贲：公孫駕驪，載遊東齊。延陵說劍，遺我寶珠。驾车东游之乐。占出行有获。
兑之剥：乘舆八百，以明文德。践土葵丘，齐晋受福。乘车明德之贵。占仕途大吉。
兑之复：雄处弱水，雌在海滨。别离将食，哀悲于心。雌雄分离之哀。占婚姻离别。
兑之无妄：结网得鲜，受福安坐。终无祸患，为身康宝。结网得鱼之福。占事有收获。
兑之大畜：秋南春北，随时休息。反覆无有，所求不得。南北奔波无得。占求事落空。
兑之颐：启户闭门，巡狩释冤。夏台羑里，汤文悦喜。启户释冤之吉。占事先困后亨。
兑之大过：符左契右，相与合齿。乾坤利贞，乳生六子。符契相合之谐。占合作有成。
兑之坎：饥蚕作室，丝多乱绪。端不可得，不能为组。丝乱难织之困。占事杂乱无章。
兑之离：东壁余光，数暗不明。主母嫉妒，乱我事业。余光暗昧之扰。占事业有干扰。
兑之咸：白鸟衔饵，鸣呼其子。旋枝张翅，来从其母。白鸟育子之亲。占家事和睦。
兑之恒：范公陶夷，巧贾货资。东之营丘，易字子皮。范蠡善贾之富。占经商大吉。
兑之遁：三羖五牂，相随俱行。迷入空泽，经涉虎庐。羊群迷入虎穴。占出行大凶。
兑之大壮：晏饮不怠，醉饱行止。稽留历日，不得复返。饮酒过度之失。占事不可放纵。
兑之晋：公悦妪喜，子孙俱在。荣誉日登，福禄来处。公悦妪喜之乐。占家事有福。
兑之明夷：禄如周公，建国洛东。父子俱封，万世无穷。周公封建之功。占仕途有封。
兑之家人：安床厚褥，久不得宿。思其故处，弃我嘉谷。安床难宿之失。占事有变。
兑之睽：蓄积有余，粪土不居。利有所往，可以安居。蓄积有余之福。占财运稳当。
兑之蹇：心愿所喜，乃今逢时。我得利福，不离兵革。心愿得遂之喜。占事如愿。
兑之解：目不可合，忧来摇足。危惧之患，为鬼所射。夜不能寐之惧。占事有隐忧。
兑之损：福德之士，欢悦日喜。夷吾相桓，三归为臣。管仲相齐之功。占仕途有贵人。
兑之益：夏姬附耳，心听悦喜。利以博取，无言不许。夏姬悦耳之顺。占求事可成。
兑之夬：叔迎兄弟，遇恭在阳。君子季姬，并坐鼓簧。兄弟相遇之乐。占亲友团聚。
兑之姤：徙巢去家，南遇白鸟。东西受福，与喜相得。徙巢遇福之吉。占迁移有喜。
兑之萃：舜登大禹，石夷之野。征诣王庭，拜治水土。舜举大禹之功。占仕途有贵人。
兑之升：江河淮海，天之都市。商人受福，国家富有。四海贸易之富。占经商大吉。
兑之困：隐隐填填，火烧山崩。下民号呼，乃得安存。火烧山崩之灾。占防自然灾害。
兑之井：望幸阿衡，太宰周公。藩屏辅弼，福禄来同。贤相辅政之福。占仕途大吉。
兑之革：乌孙氏胡，深目黑眸。嗜欲不同，莫肯相从。异族嗜欲之异。占合作不谐。
兑之鼎：早霜晚雪，伤害禾麦。损功弃力，饥无所食。霜雪伤禾之灾。占农事大凶。
兑之震：营城洛邑，周公所作。世建三十，年历八百。周公营洛之功。占事业基业永固。
兑之艮：三人俱行，别离独宿。一身五心，反覆迷惑。三人分道之散。占合作不成。
兑之渐：三首六目，政多烦惑。皋陶瘖聋，乱不可从。政多烦惑之乱。占防政局不稳。
兑之归妹：养虎畜狼，还自贼伤。无事招祸，自取灾殃。养虎自伤之愚。占事自招祸。
兑之丰：后时失利，不得所欲。莫享偕结，自求其福。后时失利之失。占事错过时机。
兑之旅：雉兔之东，以野为场。见鹰惊走，死于谷中。雉兔惊走之危。占防意外。
兑之巽：秋蛇见穴，不失其节。夫人姜氏，自齐复入。秋蛇入穴之复。占事有回归。
兑之涣：鸟鸣巢端，一呼三颠。动摇东西，危而不安。鸟巢动摇之危。占家宅不宁。
兑之节：命天不佑，祸灾为咎。抱璞炫售，求其识者。天不佑之困。占事无望。
兑之中孚：南行枣园，恶虎畏逃。执火销金，使我无患。执火退虎之勇。占事先危后安。
兑之小过：东山西岳，会合俱食。百家送从，以成恩福。东西会合之吉。占合作有成。
兑之既济：慈母赤子，飨赐得士。夷狄宾服，干戈卷阁。慈母赤子之仁。占政事大吉。
兑之未济：公孫駕驪，載遊東齊。延陵說劍，遺我寶珠。驾车东游之乐。占出行有获。

