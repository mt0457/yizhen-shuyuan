《太上洞真洞玄灵宝自然券》，简称《自然券》，乃道教灵宝派受经传度之核心法信，位列明《正统道藏》洞真部神符类第976部。自然券者，非人力所造之券契，而是天地自然生成之神符——大道运行之际，阴阳交感，五行凝结，自然形成符券，以为天真地圣、三界十方鉴证之凭证。
