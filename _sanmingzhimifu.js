三命看小儿：年干命、年支命、年纳音命。小儿年柱三命顺生者根基深厚，易养。三命相战者根基薄弱，多病。小儿关煞在三命：干命被月柱天干克——头部易伤。支命被月柱地支冲——肢体易损。纳音命被月柱纳音克——元气不足。

