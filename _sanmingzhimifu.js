三命之说，由来尚矣。太极未判，混沌未分。一气既动，阴阳乃形。天地定位，人处其中。禀五行之秀气，受三光之精华。天以干纪，地以支柱。干支相配，六十周行。纳音寓声，五音六律。天元、地元、人元，三才备矣；干命、支命、纳音命，三命立焉。

夫天干者，日之精也，阳之灵也。甲丙戊庚壬为五阳干，其气刚健；乙丁己辛癸为五阴干，其气柔顺。干命以天干为主，观其五行之偏全、阴阳之顺逆、时令之旺衰。干清者贵，干浊者贱。此干命之大旨也。

夫地支者，月之华也，阴之质也。子丑寅卯辰巳午未申酉戌亥，十二支循环不息。支命以地支为主，观其刑冲合害之有无、生克比和之顺逆。支安者寿，支乱者夭。此支命之大要也。

夫纳音者，干支之音响也。六十甲子，各有所属。以干支之数合大衍之数，用四十九而求其余，以五音定所属，以五行别贵贱。纳音命以纳音为主，观其生克乘侮、相济相制。纳音和者吉，纳音战者凶。此人元纳音命之大法也。

干为君，支为臣，纳音为民。君明则天下治，臣良则国政通，民安则社稷固。三命亦然。干清则根基正，支安则运程通，纳音和则一生顺。三命俱得，大贵之命，福寿绵长。三命有一不备，则该命所主之事有损焉。学者观命，当三命合参，不可执一而废二也。

