滴天髓论五行总纲。五行者，金木水火土。金曰从革，木曰曲直，水曰润下，火曰炎上，土曰稼穑。五行相生：金生水，水生木，木生火，火生土，土生金。五行相克：金克木，木克土，土克水，水克火，火克金。生克循环无穷。旺者宜泄不宜克，弱者宜扶不宜抑。五行中和为上，偏枯为下。

