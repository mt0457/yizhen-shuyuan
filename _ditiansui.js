【看命总诀】
一看日主强弱，二看月令格局，三看用神得失，四看全局清浊，五看调候急缓，六看神煞辅佐，七看大运向背，八看流年应期。依次推进，不杂不乱。先立其体，后推其用。体用既明，吉凶乃见。

【断事十法】
