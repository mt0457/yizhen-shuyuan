滴天髓论地支精要。阳支子寅辰午申戌，动且强，速达显灾祥。阴支丑卯巳未酉亥，静且专，否泰每经年。子为阳水坎位，午为阳火离位。卯为阴木震位，酉为阴金兑位。支重刑冲合害：合则和，冲则动，刑则伤，害则损。地支以安静为上，冲刑多者多变动。三合成局力大势专，六合为和阴阳相配。

