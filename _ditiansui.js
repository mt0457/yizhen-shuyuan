寅中甲丙戊——甲为本气木，丙为长生火，戊为寄生土。寅为火之长生，丙火初萌于此。
卯中独乙——卯为乙木之禄地，纯阴之木。故卯木柔美。
辰中戊乙癸——戊为本气土，乙为余气木，癸为库中水。辰为水库，钥匙在戌。
巳中丙戊庚——丙为本气火，戊为寄生土，庚为长生金。巳为金之长生，庚金萌生于此。
午中丁己——丁为本气火，己为寄生土。午为火之帝旺。
