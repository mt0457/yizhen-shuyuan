【鲍老催】单则是混阳蒸变，看他似虫儿般蠢动把风情搧。一般儿娇凝翠绽魂儿颤。这是景上缘，想内成，因中见。呀！淫邪展污了花台殿。待拈片落花儿惊醒他。（向鬼门丢花介）他梦酣春透了怎留连？拈花闪碎的红如片。

