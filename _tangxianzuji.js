【山桃红】则为你如花美眷，似水流年，是答儿闲寻遍。在幽闺自怜。小姐，和你那答儿讲话去。（旦作含笑不行。生作牵衣介。旦低问）那边去？（生）转过这芍药栏前，紧靠着湖山石边。和你把领扣松，衣带宽，袖梢儿揾着牙儿苫也，则待你忍耐温存一晌眠。（旦作羞。生前抱，旦推介。合）是那处曾相见，相看俨然，早难道这好处相逢无一言？

