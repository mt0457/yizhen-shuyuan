【山桃红】这一霎天留人便，草藉花眠。小姐可好？（旦低头介。生）则把云鬟点，红松翠偏。小姐休忘了呵，见了你紧相偎，慢厮连，恨不得肉儿般团成片也，逗的个日下胭脂雨上鲜。（旦）秀才，你可去呵？（合）是那处曾相见，相看俨然，早难道这好处相逢无一言？

（旦作惊起，低叫介）秀才！秀才！（又作痴睡介。老旦上）夫婿坐黄堂，娇娃立绣窗。怪他裙衩上，花鸟绣双双。我儿，何不做些针指，或观玩书史，舒展情怀？因何昼寝于此？（旦作醒，叫秀才介）孩儿方才……（老旦）方才怎么？（旦作惊介）孩儿方才适才在花园中闲步，身子困倦，不觉睡去。（老旦）孩儿，你且回房将息去。（下。旦长叹介，看老旦下介）哎也，天那，今日杜丽娘有些侥幸也。偶到花园中，百花开遍，睹景伤情。没兴而回，昼眠香阁。忽见一生，年可弱冠，丰姿俊妍。于园中折柳丝一枝，笑对奴家说：姐姐既淹通书史，何不将柳枝题赏一篇？那时待要应他一声，心中自忖：素昧平生，不知名姓，何得轻与交言。正想之间，只见那生向前说了几句伤心话儿，将奴搂定，到牡丹亭畔、芍药栏边，共成云雨之欢。两情和合，真个是千般爱惜、万种温存。欢毕之时，又送我回房，几声将息而去。正待自送那生出门，忽值母亲来到，唤醒将来。我一身冷汗，乃是南柯一梦。娘呵，你教我怎生说！

