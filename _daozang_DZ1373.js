如收音机调至正确频率即能接收电台之信号。
故诵咒贵在——字字清晰不错不漏（口密），
声声入耳返听内心（耳密），
心心与天尊相应不离（心密）。
三密相应感通之力方为具足。
诵咒数次：日常七遍至二十一遍不等；
脱肛发作时急诵还纳咒不拘遍数直至直肠还纳为止；
每满一月之修持（如修持满一月、百日、一年等）
可择吉日诵咒一百零八遍以为阶段性圆满修持。
