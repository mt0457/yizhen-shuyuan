王之涣（688年—742年），字季凌，并州晋阳（今山西太原）人。盛唐著名边塞诗人。少负侠气，豪放不羁，常击剑悲歌。后折节读书，曾任冀州衡水主簿。遭人诬陷，拂衣去官，漫游黄河两岸。晚年复任文安县尉，清白有惠政。天宝元年卒于官，年五十五。其诗以边塞、山水见长，意境开阔，气象雄浑。尤以《登鹳雀楼》《凉州词》传诵千古。惜诗作多散佚，今存仅六首。
