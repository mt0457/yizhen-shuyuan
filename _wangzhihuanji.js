【说明】王之涣墓志铭出土于河南洛阳北邙山，题《唐故文安郡文安县尉太原王府君墓志铭并序》，宣义郎行河南府永宁县尉靳能撰。此志为研究王之涣生平最可靠的第一手资料。

【原文节要】

公名之涣，字季凌，本家晋阳，宦徙绛郡。即后魏绛州刺史隆之五代孙。曾祖信，随朝请大夫、著作佐郎，入唐为安邑县令。祖表，皇朝散大夫、阳翟县丞、瀛州文安县令。父昱，皇汴州浚仪县丞、贝州司法参军、魏州贵乡县令。公即浚仪府君第四子。

公幼而聪颖，秀发当时。不盈弱冠，则究文章之精；未及壮年，已穷经籍之奥。以门子调补冀州衡水主簿。会有诬人交构，公因拂衣去官，遂优游青山，灭裂黄绶。夹河数千里，籍甚之名日彰；去国二十年，高尚之节弥峻。遂能坐销俗累，立于世尘，以致盈虚有数，动静不离。……

公素于邓州南鄙，有田别业，家于洛，耕于郏，岁时伏腊，戴星出入。……公名位未振，天不假年，以天宝元年二月十四日遘疾，终于官舍，春秋五十有五。……

嗣子英、子华，能以其年五月廿二日，葬公于洛阳北原，礼也。……

铭曰：
于铄我公，克岐克嶷。弱不好弄，长而博极。
孝友因心，文章秀出。位卑非罪，道直于职。
其道伊何，以绍以游。其位伊何，唯卑唯幽。
……
万古千秋，德音不朽。

