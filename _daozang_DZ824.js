北方五炁，五灵玄老。<br>
玉清之化，水德之宗。<br>
驾玄武而游重渊，乘坎炁以御北方。<br>
居五炁玄灵之府，治北极紫微之宫。<br>
冠玄玉太渊之冠，衣玄霞五辰之帔。<br>
