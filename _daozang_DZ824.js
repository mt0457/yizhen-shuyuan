中央一炁，玄灵黄老。<br>
玉清之化，土德之宗。<br>
驾麒麟而镇中岳，乘坤炁以御中央。<br>
居一炁中黄之府，治中央玉京之宫。<br>
冠黄玉通天彻地之冠，衣黄霞万化之帔。<br>
手执黄精玉圭，足蹑黄云金履。<br>
