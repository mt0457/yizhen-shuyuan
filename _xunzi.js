国者，天下之制利用也。人主者，天下之利势也。得道以持之，则大安也，大荣也，积美之源也。不得道以持之，则大危也，大累也，有之不如无之。及其綦也，索为匹夫不可得也，齐湣、宋献是也。故人主，天下之利势也，然而不能自安也，安之者必将道也。故用国者，义立而王，信立而霸，权谋立而亡。三者，明主之所谨择也，仁人之所务白也。

挈国以呼礼义而无以害之，行一不义、杀一无罪而得天下，仁者不为也，擽然扶持心国，且若是其固也。之所与为之者，之人则举义士也；之所以为布陈于国家刑法者，则举义法也；主之所极然帅群臣而首乡之者，则举义志也。如是，则下仰上以义矣，是綦定也。綦定而国定，国定而天下定。仲尼无置锥之地，诚义乎志意，加义乎身行，箸之言语，济之日，不隐乎天下，名垂乎后世。今亦以天下之显诸侯诚义乎志意，加义乎法则度量，箸之以政事，案申重之以贵贱杀生，使袭然终始犹一也。如是，则夫名声之部发于天地之间也，岂不如日月雷霆然矣哉！

故曰：以国齐义，一日而白，汤、武是也。汤以亳，武王以鄗，皆百里之地也，天下为一，诸侯为臣，通达之属莫不从服，无它故焉，以济义矣。是所谓义立而王也。


