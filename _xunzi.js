请问为政？曰：贤能不待次而举，罢不能不待须而废，元恶不待教而诛，中庸不待政而化。分未定也则有昭缪。虽王公士大夫之子孙，不能属于礼义，则归之庶人。虽庶人之子孙也，积文学，正身行，能属于礼义，则归之卿相士大夫。故奸言、奸说、奸事、奸能、遁逃反侧之民，职而教之，须而待之，勉之以庆赏，惩之以刑罚，安职则畜，不安职则弃。五疾，上收而养之，材而事之，官施而衣食之，兼覆无遗。才行反时者死无赦。夫是之谓天德，王者之政也。

听政之大分：以善至者待之以礼，以不善至者待之以刑。两者分别，则贤不肖不杂，是非不乱。贤不肖不杂则英杰至，是非不乱则国家治。若是，名声日闻，天下愿，令行禁止，王者之事毕矣。凡听：威严猛厉而不好假道人，则下畏恐而不亲，周闭而不竭；若是，则大事殆乎弛，小事殆乎遂。和解调通，好假道人而无所凝止之，则奸言并至，尝试之说锋起；若是，则听大事烦，是又伤之也。故法而不议，则法之所不至者必废。职而不通，则职之所不及者必坠。故法而议，职而通，无隐谋，无遗善，而百事无过，非君子莫能。故公平者，职之衡也；中和者，听之绳也。

水火有气而无生，草木有生而无知，禽兽有知而无义，人有气、有生、有知，亦且有义，故最为天下贵也。力不若牛，走不若马，而牛马为用，何也？曰：人能群，彼不能群也。人何以能群？曰：分。分何以能行？曰：义。故义以分则和，和则一，一则多力，多力则强，强则胜物，故宫室可得而居也。故序四时，裁万物，兼利天下，无它故焉，得之分义也。故人生不能无群，群而无分则争，争则乱，乱则离，离则弱，弱则不能胜物，故宫室不可得而居也——不可少顷舍礼义之谓也。


