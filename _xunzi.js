假今之世，饰邪说，文奸言，以枭乱天下，矞宇嵬琐，使天下混然不知是非治乱之所存者有人矣。纵情性，安恣睢，禽兽行，不足以合文通治，然而其持之有故，其言之成理，足以欺惑愚众，是它嚣、魏牟也。

忍情性，綦谿利跂，苟以分异人为高，不足以合大众、明大分，然而其持之有故，其言之成理，足以欺惑愚众，是陈仲、史鰌也。不知壹天下、建国家之权称，上功用、大俭约而僈差等，曾不足以容辨异、县君臣，然而其持之有故，其言之成理，足以欺惑愚众，是墨翟、宋钘也。

尚法而无法，下修而好作，上则取听于上，下则取从于俗，终日言成文典，反紃察之，则倜然无所归宿，不可以经国定分，然而其持之有故，其言之成理，足以欺惑愚众，是慎到、田骈也。不法先王，不是礼义，而好治怪说，玩琦辞，甚察而不惠，辩而无用，多事而寡功，不可以为治纲纪，然而其持之有故，其言之成理，足以欺惑愚众，是惠施、邓析也。

略法先王而不知其统，犹然而材剧志大，闻见杂博。案往旧造说，谓之五行，甚僻违而无类，幽隐而无说，闭约而无解。案饰其辞而祇敬之曰：此真先君子之言也。子思唱之，孟轲和之，世俗之沟犹瞀儒，嚾嚾然不知其所非也，遂受而传之，以为仲尼、子游为兹厚于后世。是则子思、孟轲之罪也。

若夫总方略，齐言行，壹统类，而群天下之英杰而告之以大古，教之以至顺；奥窔之间，簟席之上，敛然圣王之文章具焉，佛然平世之俗起焉；六说者不能入也，十二子者不能亲也；无置锥之地而王公不能与之争名，在一大夫之位则一君不能独畜，一国不能独容；成名况乎诸侯，莫不愿以为臣。是圣人之不得势者也，仲尼、子弓是也。

一天下，财万物，长养人民，兼利天下，通达之属，莫不从服，六说者立息，十二子者迁化，则圣人之得势者，舜、禹是也。今夫仁人也，将何务哉？上则法舜、禹之制，下则法仲尼、子弓之义，以务息十二子之说，如是则天下之害除，仁人之事毕，圣王之迹著矣。


