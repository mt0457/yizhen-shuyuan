礼起于何也？曰：人生而有欲，欲而不得，则不能无求；求而无度量分界，则不能不争。争则乱，乱则穷。先王恶其乱也，故制礼义以分之，以养人之欲，给人之求。使欲必不穷乎物，物必不屈于欲，两者相持而长，是礼之所起也。故礼者，养也。刍豢稻粱，五味调香，所以养口也；椒兰芬苾，所以养鼻也；雕琢刻镂，黼黻文章，所以养目也；钟鼓管磬，琴瑟竽笙，所以养耳也；疏房檖貌越席床笫几筵，所以养体也。故礼者，养也。

君子既得其养，又好其别。曷谓别？曰：贵贱有等，长幼有差，贫富轻重皆有称者也。故天子大路越席，所以养体也；侧载睪芷，所以养鼻也；前有错衡，所以养目也；和鸾之声，步中《武》《象》、趋中《韶》《护》，所以养耳也；龙旗九斿，所以养信也；寝兕、持虎、蛟韅、丝末、弥龙，所以养威也。

礼有三本：天地者，生之本也；先祖者，类之本也；君师者，治之本也。无天地恶生？无先祖恶出？无君师恶治？三者偏亡焉，无安人。故礼，上事天，下事地，尊先祖而隆君师。是礼之三本也。

故王者天太祖，诸侯不敢坏，大夫士有常宗，所以别贵始。贵始，得之本也。郊止乎天子，而社止于诸侯，道及士大夫，所以别尊者事尊、卑者事卑、宜大者巨、宜小者小也。故有天下者事七世，有一国者事五世，有五乘之地者事三世，有三乘之地者事二世，持手而食者不得立宗庙，所以别积厚者流泽广、积薄者流泽狭也。

大飨，尚玄尊，俎生鱼，先大羹，贵食饮之本也。飨，尚玄尊而用酒醴，先黍稷而饭稻粱；祭，齐大羹而饱庶羞，贵本而亲用也。贵本之谓文，亲用之谓理，两者合而成文，以归大一，夫是之谓大隆。

礼者，以财物为用，以贵贱为文，以多少为异，以隆杀为要。文理繁，情用省，是礼之隆也；文理省，情用繁，是礼之杀也；文理情用相为内外表里，并行而杂，是礼之中流也。故君子上致其隆，下尽其杀，而中处其中。步骤驰骋厉骛不外是矣，是君子之坛宇宫廷也。

凡礼，始乎梲，成乎文，终乎悦校。故至备，情文俱尽；其次，情文代胜；其下，复情以归大一也。天地以合，日月以明，四时以序，星辰以行，江河以流，万物以昌，好恶以节，喜怒以当，以为下则顺，以为上则明，万变不乱，贰之则丧也。礼岂不至矣哉！立隆以为极，而天下莫之能损益也。

礼者，谨于治生死者也。生，人之始也；死，人之终也。终始俱善，人道毕矣。故君子敬始而慎终。终始如一，是君子之道、礼义之文也。夫厚其生而薄其死，是敬其有知而慢其无知也，是奸人之道而倍叛之心也。


