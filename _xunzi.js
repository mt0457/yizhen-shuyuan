后王之成名：刑名从商，爵名从周，文名从《礼》。散名之加于万物者，则从诸夏之成俗曲期；远方异俗之乡，则因之而为通。散名之在人者：生之所以然者谓之性。性之和所生，精合感应，不事而自然谓之性。性之好、恶、喜、怒、哀、乐谓之情。情然而心为之择谓之虑。心虑而能为之动谓之伪。虑积焉、能习焉而后成谓之伪。正利而为谓之事。正义而为谓之行。所以知之在人者谓之知。知有所合谓之智。智所以能之在人者谓之能。能有所合谓之能。性伤谓之病。节遇谓之命。是散名之在人者也，是后王之成名也。

故王者之制名，名定而实辨，道行而志通，则慎率民而一焉。故析辞擅作名以乱正名，使民疑惑，人多辨讼，则谓之大奸，其罪犹为符节、度量之罪也。故其民莫敢托为奇辞以乱正名，故其民悫。悫则易使，易使则公。其民莫敢托为奇辞以乱正名，故壹于道法而谨于循令矣。如是，则其迹长矣。迹长功成，治之极也。是谨于守名约之功也。

今圣王没，名守慢，奇辞起，名实乱，是非之形不明，则虽守法之吏、诵数之儒，亦皆乱也。若有王者起，必将有循于旧名，有作于新名。然则所为有名，与所缘以同异，与制名之枢要，不可不察也。

异形离心交喻，异物名实玄纽，贵贱不明，同异不别。如是，则志必有不喻之患，而事必有困废之祸。故知者为之分别，制名以指实，上以明贵贱，下以辨同异。贵贱明，同异别，如是，则志无不喻之患，事无困废之祸。此所为有名也。

然则何缘而以同异？曰：缘天官。凡同类同情者，其天官之意物也同，故比方之疑似而通，是所以共其约名以相期也。形体、色理以目异；声音清浊、调竽奇声以耳异；甘苦咸淡辛酸奇味以口异；香臭芬郁腥臊洒酸奇臭以鼻异；疾养凔热滑铍轻重以形体异；说故喜怒哀乐爱恶欲以心异。心有征知。征知，则缘耳而知声可也，缘目而知形可也。然而征知必将待天官之当簿其类然后可也。


