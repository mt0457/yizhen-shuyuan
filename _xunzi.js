凡人之患，蔽于一曲而暗于大理。治则复经，两疑则惑矣。天下无二道，圣人无两心。今诸侯异政，百家异说，则必或是或非，或治或乱。乱国之君，乱家之人，此其诚心莫不求正而以自为也，妒缪于道而人诱其所迨也。私其所积，唯恐闻其恶也；倚其所私，以观异术，唯恐闻其美也。是以与治离走而是已不辍也。岂不蔽于一曲而失正求也哉！

昔人君之蔽者，夏桀、殷纣是也。桀蔽于末喜、斯观而不知关龙逢，以惑其心而乱其行；纣蔽于妲己、飞廉而不知微子启，以惑其心而乱其行。故群臣去忠而事私，百姓怨非而不用，贤良退处而隐逃，此其所以丧九牧之地而虚宗庙之国也。桀死于亭山，纣县于赤斾。身不先知，人又莫之谏，此蔽塞之祸也。成汤监于夏桀，故主其心而慎治之，是以能长用伊尹而身不失道，此其所以代夏王而受九有也。文王监于殷纣，故主其心而慎治之，是以能长用吕望而身不失道，此其所以代殷王而受九牧也。

昔宾孟之蔽者，乱家是也。墨子蔽于用而不知文，宋子蔽于欲而不知得，慎子蔽于法而不知贤，申子蔽于势而不知知，惠子蔽于辞而不知实，庄子蔽于天而不知人。故由用谓之道，尽利矣；由欲谓之道，尽嗛矣；由法谓之道，尽数矣；由势谓之道，尽便矣；由辞谓之道，尽论矣；由天谓之道，尽因矣。此数具者，皆道之一隅也。夫道者，体常而尽变，一隅不足以举之。曲知之人，观于道之一隅而未之能识也，故以为足而饰之，内以自乱，外以惑人，上以蔽下，下以蔽上，此蔽塞之祸也。

人何以知道？曰：心。心何以知？曰：虚壹而静。心未尝不臧也，然而有所谓虚；心未尝不满也，然而有所谓一；心未尝不动也，然而有所谓静。人生而有知，知而有志，志也者，臧也；然而有所谓虚，不以所已臧害所将受谓之虚。心生而有知，知而有异，异也者，同时兼知之；同时兼知之，两也；然而有所谓一，不以夫一害此一谓之壹。心卧则梦，偷则自行，使之则谋。故心未尝不动也，然而有所谓静，不以梦剧乱知谓之静。

未得道而求道者，谓之虚壹而静。作之，则将须道者之虚，则入；将事道者之壹，则尽；将思道者静，则察。知道察，知道行，体道者也。虚壹而静，谓之大清明。万物莫形而不见，莫见而不论，莫论而失位。坐于室而见四海，处于今而论久远，疏观万物而知其情，参稽治乱而通其度，经纬天地而材官万物，制割大理而宇宙里矣。

心者，形之君也，而神明之主也，出令而无所受令。自禁也，自使也，自夺也，自取也，自行也，自止也。故口可劫而使墨云，形可劫而使诎申，心不可劫而使易意，是之则受，非之则辞。故曰：心容，其择也无禁，必自见，其物也杂博，其情之至也不贰。


