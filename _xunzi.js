请成相，世之殃，愚暗愚暗堕贤良。人主无贤，如瞽无相何伥伥！请布基，慎圣人，愚而自专事不治。主忌苟胜，群臣莫谏必逢灾。论臣过，反其施，尊主安国尚贤义。拒谏饰非，愚而上同国必祸。曷谓罢？国多私，比周还主党与施。远贤近谗，忠臣蔽塞主势移。曷谓贤？明君臣，上能尊主下爱民。主诚听之，天下为一海内宾。主之孽，谗人达，贤能遁逃国乃蹶。愚以重愚，暗以重暗成为桀。世之灾，妒贤能，飞廉知政任恶来。卑其志意，大其园囿高其台。武王怒，师牧野，纣卒易乡启乃下。武王善之，封之于宋立其祖。世之衰，谗人归，比干见刳箕子累。武王诛之，吕尚招麾殷民怀。世之祸，恶贤士，子胥见杀百里徙。穆公任之，强配五伯六卿施。世之愚，恶大儒，逆斥不通孔子拘。展禽三绌，春申道缀基毕输。

请牧基，贤者思，尧在万世如见之。谗人罔极，险陂倾侧此之疑。基必施，辨贤罢，文武之道同伏戏。由之者治，不由者乱何疑为？凡成相，辨法方，至治之极复后王。慎、墨、季、惠，百家之说诚不详。治复一，修之吉，君子执之心如结。众人贰之，谗夫弃之形是诘。水至平，端不倾，心术如此象圣人。人而有势，直而用抴必参天。


