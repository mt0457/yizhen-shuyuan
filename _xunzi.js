荀子·荣辱篇第四
═══════════════════════════════════════════════════════════

材性知能，君子小人一也。好荣恶辱，好利恶害，是君子小人之所同也，若其所以求之之道则异矣。小人也者，疾为诞而欲人之信己也，疾为诈而欲人之亲己也，禽兽之行而欲人之善己也。虑之难知也，行之难安也，持之难立也，成则必不得其所好，必遇其所恶焉。故君子者，信矣，而亦欲人之信己也；忠矣，而亦欲人之亲己也；修正治辨矣，而亦欲人之善己也。虑之易知也，行之易安也，持之易立也，成则必得其所好，必不遇其所恶焉。

憍泄者，人之殃也；恭俭者，偋五兵也。虽有戈矛之刺，不如恭俭之利也。故与人善言，暖于布帛；伤人以言，深于矛戟。故薄薄之地，不得履之，非地不安也，危足无所履者，凡在言也。巨涂则让，小涂则殆，虽欲不谨，若云不使。

快快而亡者，怒也；察察而残者，忮也；博而穷者，訾也；清之而俞浊者，口也；豢之而俞瘠者，交也；辩而不说者，争也；直立而不见知者，胜也；廉而不见贵者，刿也；勇而不见惮者，贪也；信而不见敬者，好专行也。此小人之所务而君子之所不为也。


