天行有常，不为尧存，不为桀亡。应之以治则吉，应之以乱则凶。强本而节用，则天不能贫；养备而动时，则天不能病；修道而不贰，则天不能祸。故水旱不能使之饥，寒暑不能使之疾，妖怪不能使之凶。本荒而用侈，则天不能使之富；养略而动罕，则天不能使之全；倍道而妄行，则天不能使之吉。故水旱未至而饥，寒暑未薄而疾，妖怪未至而凶。受时与治世同，而殃祸与治世异，不可以怨天，其道然也。故明于天人之分，则可谓至人矣。

不为而成，不求而得，夫是之谓天职。如是者，虽深，其人不加虑焉；虽大，不加能焉；虽精，不加察焉：夫是之谓不与天争职。天有其时，地有其财，人有其治，夫是之谓能参。舍其所以参而愿其所参，则惑矣。列星随旋，日月递炤，四时代御，阴阳大化，风雨博施，万物各得其和以生，各得其养以成，不见其事而见其功，夫是之谓神。皆知其所以成，莫知其无形，夫是之谓天。唯圣人为不求知天。

大天而思之，孰与物畜而制之？从天而颂之，孰与制天命而用之？望时而待之，孰与应时而使之？因物而多之，孰与骋能而化之？思物而物之，孰与理物而勿失之也？愿于物之所以生，孰与有物之所以成？故错人而思天，则失万物之情。

百王之无变，足以为道贯。一废一起，应之以贯，理贯不乱。不知贯，不知应变，贯之大体未尝亡也。乱生其差，治尽其详。故道之所善，中则可从，畸则不可为，匿则大惑。水行者表深，表不明则陷；治民者表道，表不明则乱。礼者，表也。非礼，昏世也；昏世，大乱也。

星队、木鸣，国人皆恐。曰：是何也？曰：无何也。是天地之变、阴阳之化、物之罕至者也。怪之可也，而畏之非也。夫日月之有蚀，风雨之不时，怪星之党见，是无世而不常有之。上明而政平，则是虽并世起，无伤也；上暗而政险，则是虽无一至者，无益也。夫星之队、木之鸣，是天地之变、阴阳之化、物之罕至者也。怪之可也，而畏之非也。物之已至者，人妖则可畏也。楛耕伤稼，耘耨失秽，政险失民，田秽稼恶，籴贵民饥，道路有死人，夫是之谓人妖；政令不明，举错不时，本事不理，夫是之谓人妖；礼义不修，内外无别，男女淫乱，则父子相疑，上下乖离，寇难并至，夫是之谓人妖。妖是生于乱。三者错，无安国。其说甚尔，其灾甚惨。勉力不时，则牛马相生，六畜作妖，可怪也，而不可畏也。


