荀子·非相篇第五
═══════════════════════════════════════════════════════════

相人，古之人无有也，学者不道也。故相形不如论心，论心不如择术。形不胜心，心不胜术。术正而心顺之，则形相虽恶而心术善，无害为君子也；形相虽善而心术恶，无害为小人也。君子之谓吉，小人之谓凶。故长短、小大、善恶形相，非吉凶也。古之人无有也，学者不道也。

盖帝尧长，帝舜短；文王长，周公短；仲尼长，子弓短。昔者，卫灵公有臣曰公孙吕，身长七尺，面长三尺，焉广三寸，鼻目耳具，而名动天下。楚之孙叔敖，期思之鄙人也，突秃长左，轩较之下，而以楚霸。叶公子高，微小短瘠，行若将不胜其衣。然白公之乱也，令尹子西、司马子期皆死焉；叶公子高入据楚，诛白公，定楚国，如反手尔，仁义功名善于后世。故相形不如论心，论心不如择术。


