	张道陵天师于鹤鸣山受道立教，以清静为本、守一为要、法诫为纲。想尔之注，开道教注老之先河、启正一法脉之正源、奠天师道万年之基业。虽原帙残缺不全，然吉光片羽、弥足珍贵，足以照耀千古。读是书者，当知其在中国思想史、宗教史上承前启后之重要地位——上承老子清静无为之黄老道家哲学，下启天师道守一法诫之制度化道教神学，可谓中国本土宗教之思想奠基之作。

