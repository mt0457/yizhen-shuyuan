【六壬毕法赋】为六壬经典赋文，择其精要录之。

"前后引从升迁吉，干支夹拱利功名。三传递生众人举，三传互克事难成。"
——前后引从者，初传在前末传在后，贵人引之。干支夹拱，青龙贵人夹日干。主升迁之喜。

"有始无终难久远，有终无始事迟延。初空末空皆不济，中传空亡事折中。"
——初传空亡事无始，末传空亡事无终。中传空亡事半途而废。

"三传皆空事不实，课传全吉万事通。贵人临干百殃散，白虎入支灾祸重。"
——三传皆在旬空，万事不实。贵人临日干则百灾消散。白虎临日支则灾祸临门。

"青龙得水财源广，朱雀腾空文信通。玄武入水盗贼至，勾陈入狱讼难终。"
——青龙临亥子水宫，财如泉涌。朱雀临巳午火宫，文书信息通畅。玄武临亥子水宫，盗贼之象。勾陈临辰戌丑未墓库，官司难了。

"六合逢木婚可就，天后遇水喜重逢。太常得土筵席盛，白虎居金血光凶。"
——六合临寅卯木宫，婚姻可成。天后临亥子水宫，喜事临门。太常临辰戌丑未土宫，宴席丰盛。白虎临申酉金宫，血光之灾。

