<b>青牛西去流沙远，紫气东来大道传。化胡为佛示方便，三教归一道根源。善恶因果自招感，守一调息是真诠。愿以此经功德力，普愿群生入道天。皈依道经师三宝。太上老君道德天尊。化胡度人无量天尊。</b>
