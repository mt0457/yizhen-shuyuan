<b>经以明理，律以正行。经律并重，方为正道。一百八十戒，戒戒护道身。受经必盟誓，立誓即如山。退一步戒即破戒，进一步道即成道。老君虽远在天庭，经律即其化身；弟子虽在凡尘，守律即是亲侍老君。至心皈依道经师三宝。皈依太上老君。戒律圆满天尊。度人无量天尊。</b>
