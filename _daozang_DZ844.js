《太上洞神太上老君经律》，又名《老君经律》《太上老君经律》，收入明《正统道藏》洞神部戒律类，编号第844部。此经乃太上老君于喜国为天师张道陵所说，集经戒与法箓之律令于一体，为道教戒律体系之根本经典之一。全经分上下二篇：上篇为《老君说一百八十戒》，乃太上老君亲口宣说之戒条，从“不得杀生”至“不得轻传经戒”，凡一百八十条，涵盖修行者在世出世间之一切行为规范；下篇为《受经盟誓律仪》，详述受经者所须遵守之律令仪轨——包括入道盟誓、受经斋戒、传经资格、守律要则、犯戒惩处、忏悔复戒等。道门向来经律并重——经以明理，律以正行；经为目，律为足，目明而足捷，方能行至大道之彼岸。太上老君于此经中反复告诫：受经必遵律——只受经而不守律，如得宝舟而不操桨，终不能渡生死之海。此经问世二千年来，一直为道教各派遵行之根本戒律，天师道、灵宝派、上清派、全真道等莫不以此为基础而各自制定本宗清规。今道门虽分宗立派，然老君一百八十戒始终是道教徒共同遵守之行为准则，有如儒家之《论语》、佛家之《四分律》，为道门之根本法典。
