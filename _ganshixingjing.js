岁星，木之精也。其色青，其帝太昊，其神句芒。主春，主东方。其行率，岁行三十度十六分度之七，十二岁而周天。其所居久，其国有德厚，五谷丰昌。其行失次，其国有忧。岁星与太白斗，其野有破军。岁星与荧惑合，为内乱。

荧惑，火之精也。其色赤，其帝炎帝，其神祝融。主夏，主南方。荧惑为乱，为贼，为疾，为丧，为饥，为兵。其行无常。荧惑从太白，军忧。离之，军却。出太白阴，有分军。行其阳，有偏将战。当其行，太白逮之，破军杀将。

填星，土之精也。其色黄，其帝黄帝，其神后土。主季夏，主中央。其行率，岁行十二度百十二分度之五，二十八岁而周天。其所居国，吉。填星为福，为社稷之主。其行失次，则女主忧，宫中疫疾。

太白，金之精也。其色白，其帝少昊，其神蓐收。主秋，主西方。太白为兵，为将。其出东为德，出西为刑。太白与列星相犯，小战。五星，大战。其相犯，太白出其南，南国败。出其北，北国败。行疾，武。不行，文。

辰星，水之精也。其色黑，其帝颛顼，其神玄冥。主冬，主北方。辰星为刑，为水。其行率，一日行一度，一岁而周天。辰星不出，太白为客。其出，太白为主。辰星与太白不相从，虽有军不战。

