甘石星经·外传·三垣详考

紫微垣者，中宫之最尊也。北极五星居其中，勾陈六星在其前。天皇大帝一星在勾陈口中，此天之至尊也。华盖十六星列于后，杠九星以承之。御女四星侍于侧，天柱五星卫于旁。尚书五星在东南，大理二星在西南。此紫微垣之大略也。紫微垣主命主度，为天子之常居。星明则主寿昌，星暗则主忧危。客星入紫微，国有大丧。彗星入紫微，天下易主。流星入紫微，有使来自远方。

太微垣者，天子之庭也。五帝坐居中，黄帝坐在中央含枢纽之位。四帝四星夹黄帝坐，苍帝、赤帝、白帝、黑帝也。太子一星在帝坐北，从官一星在太子西。幸臣一星在帝坐东北。内五诸侯五星在九卿西，外五诸侯五星在九卿东。内屏四星在端门内，左右执法各一星在端门两旁。谒者一星在左执法东北，三公三星在谒者东北，九卿三星在三公北，郎将一星在五诸侯后，郎位十五星在帝坐东北。此太微垣之大略也。太微垣主政令，为天子之宫廷。星明则王道昌，星暗则王道衰。五星入太微，天下大政变。

天市垣者，天之市也。帝坐一星在中央，候星在其西。宦者四星在帝坐西南，斗五星在宦者东，斛四星在斗北，列肆二星在斛西北，车肆二星在市门左，屠肆二星在帛度西北。帛度二星在列肆西，天纪九星在贯索东，贯索九星在七公前，七公七星在招摇东，天棓五星在女床北。此天市垣之大略也。天市垣主权衡，主聚众。星明则市井繁荣，国用充足。星暗则市井萧条，国用匮乏。

甘石星经·外传·杂星占

客星者，非常之星也。其出无常，其形多变。有五大客星：一曰周伯，其色黄，其状大而煌煌然，所见之国大昌。二曰老子，其色白，其状大而明，所见之国为饥为凶，为善为恶，为喜为怒。三曰王蓬絮，其色青而有芒角，所见之国大旱，五谷不成。四曰国皇，其色赤，其状大而赤，所见之国有兵起。五曰温星，其色白，其状如风，所见之国大疫。此五客星者，皆天之变也。客星出二十八宿中某宿，则其所主分野之国有事。客星大而明者，事大。客星小而暗者，事小。客星久留者，事变深。客星速去者，事变浅。

流星者，亦天之变也。有五大流星：一曰天使，二曰天晖，三曰天雁，四曰天保，五曰天梁。流星大如瓮者，为天使，其所坠之国有使命。流星大如斗者，为天晖，其所坠之国有大喜。流星大如鸡卵者，为天雁，其所坠之国有远客来。流星长数丈者，为天保，其所坠之国有众保聚。流星光照地者，为天梁，其所坠之国有桥梁成。流星犯五星者，其国有兵事。流星犯二十八宿者，其所主之国有变。

彗星者，妖星也。其状如帚，有长尾。彗星所出之宿，其分野之国有大乱、大兵、大丧、大饥。彗星长竟天者，天下大乱，王者崩，民人流亡。彗星出东方，则东方有兵。彗星出西方，则西方有兵。彗星出南方，则南方有旱。彗星出北方，则北方有水。彗星贯北斗，则天子崩，天下易姓。彗星贯太微，则王者忧，大臣诛。彗星贯紫微，则天下易主。

甘石星经·外传·云气占

凡望云气，仰而望之，三四百里。平望之，在桑榆上，千余里。登高而望之，下属地者，三千里。云气有兽居上者，胜。自华以南，气下黑上赤。嵩高三河之郊，气正赤。恒山之北，气下黑上青。勃碣海岱之间，气皆黑。江淮之间，气皆白。

徒气白，土功气黄，车气乍高乍下，往往而聚。骑气卑而布，卒气抟。前卑而后高者，疾。前方而后高者，锐。后锐而卑者，却。其气平者，其行徐。前高后卑者，不止而反。气相遇者，卑胜高，锐胜方。气来卑而循车通者，不过三四日，去之五六里见。气来高七八尺者，不过五六日，去之十余里见。气来高丈余二丈者，不过三四十日，去之五六十里见。

稍云精白者，其将悍，其士怯。其大根而前绝远者，当战。青白，其前低者，战胜。其前赤而仰者，战不胜。阵云如立垣，杼云类杼，轴云抟，两端锐。杓云如绳者，居前亘天，其半半天。其者类阙旗。故钩云勾曲。诸此云见，以五色合占，而泽抟密。其见动人，乃有占。兵必起。合斗其直。

甘石星经·外传·二十八宿风占

凡风从角宿来，其日辛卯，其辰卯。风从亢宿来，其日壬辰，其辰辰。风从氐宿来，其日癸巳，其辰巳。风从房宿来，其日甲午，其辰午。风从心宿来，其日乙未，其辰未。风从尾宿来，其日丙申，其辰申。风从箕宿来，其日丁酉，其辰酉。风从斗宿来，其日戊戌，其辰戌。风从牛宿来，其日己亥，其辰亥。风从女宿来，其日庚子，其辰子。风从虚宿来，其日辛丑，其辰丑。风从危宿来，其日壬寅，其辰寅。风从室宿来，其日癸卯，其辰卯。风从壁宿来，其日甲辰，其辰辰。

风从奎宿来，其日乙巳，其辰巳。风从娄宿来，其日丙午，其辰午。风从胃宿来，其日丁未，其辰未。风从昴宿来，其日戊申，其辰申。风从毕宿来，其日己酉，其辰酉。风从觜宿来，其日庚戌，其辰戌。风从参宿来，其日辛亥，其辰亥。风从井宿来，其日壬子，其辰子。风从鬼宿来，其日癸丑，其辰丑。风从柳宿来，其日甲寅，其辰寅。风从星宿来，其日乙卯，其辰卯。风从张宿来，其日丙辰，其辰辰。风从翼宿来，其日丁巳，其辰巳。风从轸宿来，其日戊午，其辰午。

