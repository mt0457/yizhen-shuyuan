甘石星经·外传·总论

呜呼，天文学者，人类最古之科学也。自上古结绳而治，至于今日，天文学之发展，未尝一日或止。而甘石星经，实为世界天文学之最早里程碑。其二十八宿体系，沿用二千余年，至今犹为天文学史家所珍视。其五星占，虽杂以星占之说，然其对行星运动之观测记录，实开行星天文学之先河。其星表，共测定一百二十余星之位置，为世界最古之星表，早于希腊依巴谷约二百年。

中国古代天文学，以观象授时为目的，以天人合一为哲学，以敬天法祖为根本。其成就之巨大，影响之深远，在世界文明史上，独树一帜。而甘石星经，正是这一伟大传统的源头活水。

凡治天文者，必先读甘石星经，知二十八宿之名，识五星之行，明分野之说，察星官之变。然后可以上窥天象，下察人事，中通历法。此书虽非完璧，然其遗文散见于各书者，犹足以见中国古代天文学之博大精深。

故曰：欲知中国古代天文学者，必自甘石星经始。欲知世界天文学史者，亦必自甘石星经始。此吾人所以珍视此书，传扬此书，研究此书，使之永垂不朽之故也。

