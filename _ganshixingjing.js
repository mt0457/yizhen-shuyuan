参宿十星，为白虎，主杀伐斩刈。中央三星为三将，左右肩股四星为四佐。伐三星在参中，主斩刈。星明大，则将帅良，兵革息。星暗，则将帅弱，兵革动。星亡，则将帅死，兵大起。日食于参，将帅死，兵大起。月食于参，将相戮，兵大败。岁星犯参，将有功，封赏行。荧惑犯参，兵大起，将死。填星犯参，军垒修，兵守备。太白犯参，兵大起，将帅戮。辰星犯参，大水伤兵。客星出参，有新将起，法令改。彗星入参，天下大乱，兵革尽起。

