甘石星经·卷下·星官总述

凡天文在图籍，昭昭可知者，经星常宿中外官凡一百一十八名，积数七百八十三星，皆有州国官宫物类之象。其伏见蚤晚，邪正存亡，虚实阔狭，及五星所行，合散犯守，陵历斗食，彗孛飞流，日月薄蚀，晕适背穴，抱珥虹霓，迅雷风妖，怪云变气。此皆阴阳之精，其本在地，而上发于天者也。政失于此，则变见于彼。是以明君睹之而寤，饬身正事。思其咎谢，则祸除而福至，自然之符也。

中宫天极星，其一明者，太一常居也。旁三星三公。末大星正妃，余三星后宫之属也。环之匡卫十二星，藩臣。皆曰紫宫。前列直斗口三星，随北端锐，若见若不，曰阴德，或曰天一。紫宫左三星曰天枪，右五星曰天棓，后六星绝汉抵营室，曰阁道。北斗七星，杓携龙角，衡殷南斗，魁枕参首。用昏建者杓，杓自华以西南。夜半建者衡，衡殷中州河济之间。平旦建者魁，魁海岱以东北也。斗为帝车，运于中央，临制四乡。分阴阳，建四时，均五行，移节度，定诸纪，皆系于斗。

