毕宿八星，为天网，主边兵弋猎。附耳一星，在毕下，主听得失。天街二星，在昴毕之间，主国界。星明大，则边兵息，弋猎丰。星暗，则边兵动，弋猎废。星亡，则边兵大起，天下乱。日食于毕，边兵起，王者忧。月食于毕，边将死，兵大败。岁星犯毕，边兵息，弋猎丰。荧惑犯毕，边兵大起，将相忧。填星犯毕，边城修，兵守备。太白犯毕，兵大起，边将戮。辰星犯毕，大水，边城坏。彗星入毕，天下大兵，边境尽乱。

