此石氏所测二十八宿距星去极度也。角宿，去极九十一度。亢宿，去极八十九度。氐宿，去极九十四度。房宿，去极一百八度。心宿，去极一百八度。尾宿，去极一百二十度。箕宿，去极一百十八度。斗宿，去极一百十六度。牵牛，去极百十度。须女，去极百六度。虚宿，去极百四度。危宿，去极九十七度。营室，去极八十五度。东壁，去极八十六度。奎宿，去极七十度。娄宿，去极八十度。胃宿，去极六十七度。昴宿，去极七十四度。毕宿，去极七十八度。觜觽，去极八十四度。参宿，去极九十四度。东井，去极六十九度。舆鬼，去极六十八度。柳宿，去极七十七度。七星，去极九十一度。张宿，去极九十七度。翼宿，去极九十九度。轸宿，去极九十八度。

