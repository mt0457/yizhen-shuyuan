甘石星经·卷下·二十八宿详占

角宿二星，为天关，其间天门也。其内天庭也。故黄道经其中，七曜之所行也。角为天田，亦为天根。左角为理，主刑。其星明大，则王道太平，贤臣在朝。星暗小，则君道失，臣不用。星动摇，则人主忧，臣下叛。星亡，则天下乱，贤人隐。芒角动摇，则王者失嗣。日食于角，王者恶之，大臣诛。月食于角，大臣忧，天下饥。五星犯角，主兵起。岁星犯角，五谷不成。荧惑犯角，王者失位，有内乱。填星犯角，有大丧。太白犯角，兵大起，将军戮。辰星犯角，大水。客星出角，法令更改。彗星入角，天下大乱，兵起宫中。

亢宿四星，为天子之内朝。总摄天下奏事，听讼理狱录功。一名天府，一名天庭。星明大，则辅相忠良，天下安宁。星暗，则辅相有忧，政令不行。星亡，则天下空虚，朝无贤人。星直，则王者仁，天下平。星曲，则政令苛，刑罚重。月犯亢，大臣忧死，五谷伤。岁星犯亢，五谷丰登。荧惑犯亢，有内乱，臣谋君。填星犯亢，五谷不熟，民饥。太白犯亢，将军死，边兵起。辰星犯亢，其年大水，伤五谷。流星入亢，有使来，主兵事。

氐宿四星，为天子之路寝，休解之房。一名天根，一名天府。前二星曰氐，后二星曰房。星明大，则民安，臣奉法度。星暗，则民劳，赋役重。星小，则国弱，民贫。星亡，则天下易主。日食于氐，卿相有忧，天下饥。月食于氐，后宫有忧，大臣诛死。岁星犯氐，天下和平。荧惑犯氐，后宫有火灾，人主忧。填星犯氐，国有土功，宫室兴。太白犯氐，将军忧，边兵动。辰星犯氐，大水伤稼。彗孛入氐，宫中有兵，王者易嗣。

房宿四星，为明堂，天子布政之宫也。亦为四辅，中间为天衢，亦为天马，主车驾。房为天府，主藏。星明大，则天下和平，王者有德。星暗，则王者失政，天下乱。星亡，则王者崩，天下易主。房星明，则王者明。房星暗，则王者暗。日食于房，王者恶之，大臣有忧。月食于房，大臣忧，五谷伤。岁星犯房，王者有喜，赐爵禄。荧惑犯房，内乱，兵起宫中。填星犯房，宫室兴，有大丧。太白犯房，兵大起，将相戮。辰星犯房，大水入城。客星出房，国有大丧，王者崩。

心宿三星，中央大星曰天王，天子之位也。前星为太子，后星为庶子。心为明堂，中大星为天子，前后星为子属。星直，则天子失势。星曲，则天子得势。星明大，则天下同心，万民归往。星暗，则天子失位，民心离散。星亡，则天子崩，天下易姓。日食于心，天子恶之，有大丧。月食于心，王者忧，内乱起。岁星犯心，王者有庆，赐诸侯。荧惑犯心，天子恶之，国有大丧，兵起。填星犯心，王者有土功，宫室兴。太白犯心，兵大起，将军战死。辰星犯心，大水伤民。彗星入心，王者崩，天下大乱。

尾宿九星，为天子后宫，亦为九子。星明大，则后宫安宁，子孙昌盛。星暗，则后宫有忧，子孙夭伤。星亡，则后宫空虚，无嗣。月犯尾，后宫有忧，或失势。岁星犯尾，后宫有喜，赐美人。荧惑犯尾，后宫有火灾，人主忧。填星犯尾，后宫有土功。太白犯尾，后宫有兵，出师。辰星犯尾，后宫有大水。客星出尾，后宫有宠人，或易后。彗星入尾，后宫大乱。

箕宿四星，为敖客，为天口。主口舌，主蛮夷。箕为风伯，月宿于此则大风。星明大，则五谷丰，国用足。星暗，则五谷伤，国用乏。星亡，则天下大饥，民流亡。日食于箕，主口舌，大臣有谗。月食于箕，大风起，王者忧。岁星犯箕，五谷大熟，蛮夷来贡。荧惑犯箕，大旱，兵起。填星犯箕，五谷不成，民流亡。太白犯箕，大风起，兵动。辰星犯箕，大水，五谷伤。彗星入箕，天下大旱，兵起。

斗宿六星，为天庙，丞相太宰之位。主褒赏贤士，禀授爵禄。南二星为天库，中二星为天梁，北二星为天相。星明大，则贤人进，爵禄行。星暗，则贤人退，爵禄不行。星亡，则贤人尽，天下空虚。日食于斗，将相有忧，国危。月食于斗，大臣诛，将相死。岁星犯斗，国有大赦，赐爵禄。荧惑犯斗，大臣逆，兵起。填星犯斗，爵禄不行，贤人隐。太白犯斗，兵大起，将相戮。辰星犯斗，大水伤民。客星出斗，有新人用事，法令改。彗星入斗，天下易主。

牛宿六星，为牺牲，供给鬼神。上一星为天田，主道路。中二星为天市，主关梁。下三星为天仓，主粮储。牵牛为牺牲，主牛马。星明大，则六畜蕃息，天下丰。星暗，则六畜疫死，天下饥。星亡，则关梁不通，天下乱。日食于牛，六畜疫，天下饥。月食于牛，六畜贵，民饥。岁星犯牛，六畜大蕃，五谷丰。荧惑犯牛，牛马疫死，兵起。填星犯牛，土功起，道路修。太白犯牛，牛马贵，兵动。辰星犯牛，牛马多死，大水。彗星入牛，天下大饥，六畜尽。

女宿四星，为天女，主布帛裁制嫁娶。上二星为天女，下二星为天相。星明大，则织作兴，布帛贱。星暗，则织作废，布帛贵。星亡，则女工废，天下乱。日食于女，后妃有忧，织作废。月食于女，后妃忧死，织作不行。岁星犯女，后宫有喜，嫁娶行。荧惑犯女，后宫有火灾，妇人忧。填星犯女，宫中有土功。太白犯女，兵起，妇人忧。辰星犯女，大水伤蚕桑。客星出女，后宫有宠人，或易后。

虚宿二星，为祠祀，主祭祷之事。其下二星曰哭，主哭泣死丧。星明大，则祭祀丰洁，鬼神享。星暗，则祭祀废，鬼神怒。星亡，则宗庙废，社稷危。日食于虚，天下大疫，民多死。月食于虚，王者忧，有内乱。岁星犯虚，天下和平，五谷丰。荧惑犯虚，天下大旱，民饥死。填星犯虚，有土功，宗庙兴。太白犯虚，兵起，民多死亡。辰星犯虚，大水，民多溺死。彗星入虚，天下大丧，王者崩。

