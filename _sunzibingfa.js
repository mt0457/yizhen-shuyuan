孙武，字长卿，春秋末期齐国乐安（今山东惠民）人。约生于公元前545年，卒于公元前470年。其先祖为陈国公子完，因内乱奔齐，改姓田氏。田完五世孙田书伐莒有功，齐景公赐姓孙氏，食采于乐安。孙武即田书之孙。后因齐国内乱，孙武奔吴，隐居穹窿山，著兵法十三篇。吴王阖庐读其书，拜为将军。孙武西破强楚，入郢都；北威齐晋，显名诸侯。功成身退，不知所终。其《孙子兵法》传世二千五百年，被奉为兵家圣典，居《武经七书》之首，影响遍及全球军事、政治、商业诸领域，至今译成四十余种文字，为世界军事思想之巅峰，兵学之圭臬。

