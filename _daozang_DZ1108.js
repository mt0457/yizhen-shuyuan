南斗六司，注生添算。天府司命，执掌寿籍。天相司禄，权衡福禄。天梁延寿，擎举命基。天同益算，核算善功。天枢度厄，剑斩灾殃。天机上生，开启生机。六星朗照，光明赫奕。光降人间，普度众生。至心礼斗，罪灭福生。延寿一纪，消灾解厄。孝感星君，福及眷属。诚诵真经，功德无边。皈依元始天尊。皈依太上老君。皈依南斗六司延寿星君。延寿无量天尊。不可思议功德。
