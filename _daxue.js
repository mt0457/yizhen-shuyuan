大学之书，古之大学所以教人之法也。盖自天降生民，则既莫不与之以仁义礼智之
性矣。然其气质之禀或不能齐，是以不能皆有以知其性之所有而全之也。一有聪明
睿智能尽其性者出于其间，则天必命之以为亿兆之君师，使之治而教之，以复其性。
此伏羲、神农、黄帝、尧、舜，所以继天立极，而司徒之职、典乐之官所由设也。

三代之隆，其法寖备，然后王宫、国都以及闾巷，莫不有学。人生八岁，则自王公
以下，至于庶人之子弟，皆入小学，而教之以洒扫、应对、进退之节，礼乐、射御、
书数之文。及其十有五年，则自天子之元子、众子，以至公、卿、大夫、元士之适
子，与凡民之俊秀，皆入大学，而教之以穷理、正心、修己、治人之道。此又学校
之教、大小之节所以分也。

夫以学校之设，其广如此，教之之术，其次第节目之详又如此，而其所以为教，则
又皆本之人君躬行心得之余，不待求之民生日用彝伦之外，是以当世之人无不学。
其学焉者，无不有以知其性分之所固有，职分之所当为，而各俛焉以尽其力。此古
昔盛时所以治隆于上，俗美于下，而非后世之所能及也！

及周之衰，贤圣之君不作，学校之政不修，教化陵夷，风俗颓败，时则有若孔子之
圣，而不得君师之位以行其政教，于是独取先王之法，诵而传之，以诏后世。若《曲
礼》《少仪》《内则》《弟子职》诸篇，固小学之支流余裔，而此篇者，则因小学
之成功，以著大学之明法，外有以极其规模之大，而内有以尽其节目之详者也。三
千之徒，盖莫不闻其说，而曾氏之传独得其宗，于是作为传义，以发其意。及孟子
没而其传泯焉，则其书虽存，而知者鲜矣！

自是以来，俗儒记诵词章之习，其功倍于小学而无用；异端虚无寂灭之教，其高过
于大学而无实。其他权谋术数，一切以就功名之说，与夫百家众技之流，所以惑世
诬民、充塞仁义者，又纷然杂出乎其间。使其君子不幸而不得闻大道之要，其小人
不幸而不得蒙至治之泽，晦盲否塞，反复沉痼，以及五季之衰，而坏乱极矣！

天运循环，无往不复。宋德隆盛，治教休明。于是河南程氏两夫子出，而有以接乎
孟氏之传。实始尊信此篇而表章之，既又为之次其简编，发其归趣，然后古者大学
教人之法、圣经贤传之指，粲然复明于世。虽以熹之不敏，亦幸私淑而与有闻焉。
顾其为书犹颇放失，是以忘其固陋，采而辑之，间亦窃附己意，补其阙略，以俟后
之君子。极知僭逾，无所逃罪，然于国家化民成俗之意、学者修己治人之方，则未
必无小补云。

淳熙己酉二月甲子，新安朱熹序。


