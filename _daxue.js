【经文】

大学之道，在明明德，在亲民，在止于至善。

    朱子注：大学者，大人之学也。明，明之也。明德者，人之所得乎天，而虚灵
    不昧，以具众理而应万事者也。但为气禀所拘，人欲所蔽，则有时而昏；然其
    本体之明，则有未尝息者。故学者当因其所发而遂明之，以复其初也。新者，
    革其旧之谓也，言既自明其明德，又当推以及人，使之亦有以去其旧染之污也。
    止者，必至于是而不迁之意。至善，则事理当然之极也。言明明德、新民，皆
    当止于至善之地而不迁。盖必其有以尽夫天理之极，而无一毫人欲之私也。此
    三者，大学之纲领也。

知止而后有定，定而后能静，静而后能安，安而后能虑，虑而后能得。

    朱子注：止者，所当止之地，即至善之所在也。知之，则志有定向。静，谓心
    不妄动。安，谓所处而安。虑，谓处事精详。得，谓得其所止。

物有本末，事有终始，知所先后，则近道矣。

    朱子注：明德为本，新民为末。知止为始，能得为终。本始所先，末终所后。
    此结上文两节之意。

古之欲明明德于天下者，先治其国。欲治其国者，先齐其家。欲齐其家者，先修其
身。欲修其身者，先正其心。欲正其心者，先诚其意。欲诚其意者，先致其知。致
知在格物。

    朱子注：明明德于天下者，使天下之人皆有以明其明德也。心者，身之所主也。
    诚，实也。意者，心之所发也。实其心之所发，欲其一于善而无自欺也。致，
    推极也。知，犹识也。推极吾之知识，欲其所知无不尽也。格，至也。物，犹
    事也。穷至事物之理，欲其极处无不到也。此八者，大学之条目也。

物格而后知至，知至而后意诚，意诚而后心正，心正而后身修，身修而后家齐，家
齐而后国治，国治而后天下平。

    朱子注：物格者，物理之极处无不到也。知至者，吾心之所知无不尽也。知既
    尽，则意可得而实矣。意既实，则心可得而正矣。修身以上，明明德之事也。
    齐家以下，新民之事也。物格知至，则知所止矣。意诚以下，则皆得所止之序
    也。

自天子以至于庶人，壹是皆以修身为本。

    朱子注：壹是，一切也。正心以上，皆所以修身也。齐家以下，则举此而措之
    耳。

其本乱而末治者否矣。其所厚者薄，而其所薄者厚，未之有也。

    朱子注：本，谓身也。所厚，谓家也。此两节结上文两节之意。

右经一章，盖孔子之言，而曾子述之。其传十章，则曾子之意而门人记之也。旧本
颇有错简，今因程子所定，而更考经文，别为序次如左。


