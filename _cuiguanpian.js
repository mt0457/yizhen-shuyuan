后十二山之中——以亥山天皇星之催尊——为二十四山之中——等级最高——效验最强——来势最快——但也最难以承受之催官法。亥为紫微垣——天皇大帝之宫殿——至尊至贵——非凡人可享受——自古——有天皇入命之格者——不是开国之帝王——就是中兴之英主——最普通的——也是——一代名臣——位极人臣——执掌一朝之政。而——先天之德——先天之福——先天之命——此三者——非后天之修为——可以弥补——所以——亥山天皇催官法——不可轻施——施之必先察其命——是否能够承当——如蚁之不可承山——蚍之不可撼树——强施——则不仅无功——反有大祸——官未催成——身已先死——可不慎哉——可不惧哉——可不戒哉。

