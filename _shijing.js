蜉蝣
蜉蝣之羽，衣裳楚楚。心之忧矣，于我归处。
蜉蝣之翼，采采衣服。心之忧矣，于我归息。
蜉蝣掘阅，麻衣如雪。心之忧矣，于我归说。

候人
彼候人兮，何戈与祋。彼其之子，三百赤芾。
维鹈在梁，不濡其翼。彼其之子，不称其服。
维鹈在梁，不濡其咮。彼其之子，不遂其媾。
荟兮蔚兮，南山朝隮。婉兮娈兮，季女斯饥。

鸤鸠
鸤鸠在桑，其子七兮。淑人君子，其仪一兮。其仪一兮，心如结兮。
鸤鸠在桑，其子在梅。淑人君子，其带伊丝。其带伊丝，其弁伊骐。
鸤鸠在桑，其子在棘。淑人君子，其仪不忒。其仪不忒，正是四国。
