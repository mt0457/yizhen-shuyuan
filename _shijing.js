诗经·国风·豳风

七月
七月流火，九月授衣。一之日觱发，二之日栗烈。无衣无褐，何以卒岁？三之日于耜，四之日举趾。同我妇子，馌彼南亩。田畯至喜。

七月流火，九月授衣。春日载阳，有鸣仓庚。女执懿筐，遵彼微行，爰求柔桑。春日迟迟，采蘩祁祁。女心伤悲，殆及公子同归。

七月流火，八月萑苇。蚕月条桑，取彼斧斨。以伐远扬，猗彼女桑。七月鸣鵙，八月载绩。载玄载黄，我朱孔阳，为公子裳。

四月秀葽，五月鸣蜩。八月其获，十月陨萚。一之日于貉，取彼狐狸，为公子裘。二之日其同，载缵武功。言私其豵，献豜于公。

五月斯螽动股，六月莎鸡振羽。七月在野，八月在宇，九月在户，十月蟋蟀，入我床下。穹窒熏鼠，塞向墐户。嗟我妇子，曰为改岁，入此室处。

六月食郁及薁，七月亨葵及菽。八月剥枣，十月获稻。为此春酒，以介眉寿。七月食瓜，八月断壶，九月叔苴。采荼薪樗，食我农夫。

九月筑场圃，十月纳禾稼。黍稷重穋，禾麻菽麦。嗟我农夫，我稼既同，上入执宫功。昼尔于茅，宵尔索绹。亟其乘屋，其始播百谷。

二之日凿冰冲冲，三之日纳于凌阴。四之日其蚤，献羔祭韭。九月肃霜，十月涤场。朋酒斯飨，曰杀羔羊。跻彼公堂，称彼兕觥：万寿无疆！

鸱鸮
鸱鸮鸱鸮，既取我子，无毁我室。恩斯勤斯，鬻子之闵斯。
迨天之未阴雨，彻彼桑土，绸缪牖户。今女下民，或敢侮予？
予手拮据，予所捋荼，予所蓄租，予口卒瘏，曰予未有室家。
予羽谯谯，予尾翛翛，予室翘翘，风雨所漂摇，予维音哓哓。

东山
我徂东山，慆慆不归。我来自东，零雨其濛。我东曰归，我心西悲。制彼裳衣，勿士行枚。蜎蜎者蠋，烝在桑野。敦彼独宿，亦在车下。
我徂东山，慆慆不归。我来自东，零雨其濛。果臝之实，亦施于宇。伊威在室，蟏蛸在户。町畽鹿场，熠耀宵行。不可畏也，伊可怀也。

诗经·小雅

鹿鸣
呦呦鹿鸣，食野之苹。我有嘉宾，鼓瑟吹笙。吹笙鼓簧，承筐是将。人之好我，示我周行。
呦呦鹿鸣，食野之蒿。我有嘉宾，德音孔昭。视民不恌，君子是则是效。我有旨酒，嘉宾式燕以敖。
呦呦鹿鸣，食野之芩。我有嘉宾，鼓瑟鼓琴。鼓瑟鼓琴，和乐且湛。我有旨酒，以燕乐嘉宾之心。

四牡
四牡騑騑，周道倭迟。岂不怀归？王事靡盬，我心伤悲。
四牡騑騑，啴啴骆马。岂不怀归？王事靡盬，不遑启处。
翩翩者鵻，载飞载下，集于苞栩。王事靡盬，不遑将父。
翩翩者鵻，载飞载止，集于苞杞。王事靡盬，不遑将母。

常棣
常棣之华，鄂不韡韡。凡今之人，莫如兄弟。
死丧之威，兄弟孔怀。原隰裒矣，兄弟求矣。
脊令在原，兄弟急难。每有良朋，况也永叹。
兄弟阋于墙，外御其务。每有良朋，烝也无戎。
丧乱既平，既安且宁。虽有兄弟，不如友生？

伐木
伐木丁丁，鸟鸣嘤嘤。出自幽谷，迁于乔木。嘤其鸣矣，求其友声。相彼鸟矣，犹求友声。矧伊人矣，不求友生？神之听之，终和且平。

采薇
采薇采薇，薇亦作止。曰归曰归，岁亦莫止。靡室靡家，猃狁之故。不遑启居，猃狁之故。
采薇采薇，薇亦柔止。曰归曰归，心亦忧止。忧心烈烈，载饥载渴。我戍未定，靡使归聘。
采薇采薇，薇亦刚止。曰归曰归，岁亦阳止。王事靡盬，不遑启处。忧心孔疚，我行不来！
彼尔维何？维常之华。彼路斯何？君子之车。戎车既驾，四牡业业。岂敢定居？一月三捷。
驾彼四牡，四牡骙骙。君子所依，小人所腓。四牡翼翼，象弭鱼服。岂不日戒？猃狁孔棘！
昔我往矣，杨柳依依。今我来思，雨雪霏霏。行道迟迟，载渴载饥。我心伤悲，莫知我哀！

鹤鸣
鹤鸣于九皋，声闻于天。鱼在于渚，或潜在渊。乐彼之园，爰有树檀，其下维萚。他山之石，可以为错。
鹤鸣于九皋，声闻于野。鱼潜在渊，或在于渚。乐彼之园，爰有树檀，其下维谷。他山之石，可以攻玉。

诗经·大雅

文王
文王在上，于昭于天。周虽旧邦，其命维新。有周不显，帝命不时。文王陟降，在帝左右。
亹亹文王，令闻不已。陈锡哉周，侯文王孙子。文王孙子，本支百世，凡周之士，不显亦世。
世之不显，厥犹翼翼。思皇多士，生此王国。王国克生，维周之桢。济济多士，文王以宁。
穆穆文王，于缉熙敬止。假哉天命，有商孙子。商之孙子，其丽不亿。上帝既命，侯于周服。
侯服于周，天命靡常。殷士肤敏，裸将于京。厥作裸将，常服黼冔。王之荩臣，无念尔祖。

绵
绵绵瓜瓞，民之初生，自土沮漆。古公亶父，陶复陶穴，未有家室。
古公亶父，来朝走马。率西水浒，至于岐下。爰及姜女，聿来胥宇。
周原膴膴，堇荼如饴。爰始爰谋，爰契我龟。曰止曰时，筑室于兹。
乃慰乃止，乃左乃右。乃疆乃理，乃宣乃亩。自西徂东，周爰执事。

生民
厥初生民，时维姜嫄。生民如何？克禋克祀，以弗无子。履帝武敏歆，攸介攸止。载震载夙，载生载育，时维后稷。
诞弥厥月，先生如达。不坼不副，无菑无害。以赫厥灵，上帝不宁。不康禋祀，居然生子。
诞寘之隘巷，牛羊腓字之。诞寘之平林，会伐平林。诞寘之寒冰，鸟覆翼之。鸟乃去矣，后稷呱矣。实覃实訏，厥声载路。

诗经·颂·周颂

清庙
于穆清庙，肃雍显相。济济多士，秉文之德。对越在天，骏奔走在庙。不显不承，无射于人斯。

诗经·颂·鲁颂

駉
駉駉牡马，在坰之野。薄言駉者，有驈有皇，有骊有黄，以车彭彭。思无疆，思马斯臧。

诗经·颂·商颂

玄鸟
天命玄鸟，降而生商，宅殷土芒芒。古帝命武汤，正域彼四方。方命厥后，奄有九有。商之先后，受命不殆，在武丁孙子。武丁孙子，武王靡不胜。龙旂十乘，大糦是承。邦畿千里，维民所止，肇域彼四海。四海来假，来假祁祁。景员维河，殷受命咸宜，百禄是何。
