【本义】说卦者，备载八卦之象，以广易之用。

昔者圣人之作易也，幽赞于神明而生蓍，参天两地而倚数，观变于阴阳而立卦，发挥于刚柔而生爻，和顺于道德而理于义，穷理尽性以至于命。
【本义】幽赞神明，潜通造化之妙。参天两地，天圆地方，圆者一而围三，方者一而围四。倚数，依天地之数。此言圣人作易之次第。

昔者圣人之作易也，将以顺性命之理。是以立天之道，曰阴与阳。立地之道，曰柔与刚。立人之道，曰仁与义。兼三才而两之，故易六画而成卦。分阴分阳，迭用柔刚，故易六位而成章。
【本义】兼三才而两之，每一才分阴阳，故三画各分而为二，成六画。六位，初三五为阳位，二四上为阴位。迭用，相间而用。

天地定位，山泽通气，雷风相薄，水火不相射，八卦相错。数往者顺，知来者逆，是故易逆数也。
【本义】此言伏羲先天八卦方位：乾南坤北，离东坎西，震东北巽西南，艮西北兑东南。相错，交互成六十四卦。顺数，已往之事。逆推，未来之事。

雷以动之，风以散之，雨以润之，日以烜之，艮以止之，兑以说之，乾以君之，坤以藏之。
【本义】此言八卦之用。震动巽散，坎润离烜，艮止兑说，乾君坤藏。八卦各有所主，其功不同，而造化之全体在焉。

帝出乎震，齐乎巽，相见乎离，致役乎坤，说言乎兑，战乎乾，劳乎坎，成言乎艮。万物出乎震，震东方也。齐乎巽，巽东南也。离也者，明也，万物皆相见，南方之卦也。坤也者，地也，万物皆致养焉。兑，正秋也，万物之所说也。战乎乾，乾西北之卦也。坎者，水也，正北方之卦也，万物之所归也。艮，东北之卦也，万物之所成终而所成始也。
【本义】此言文王后天八卦方位。帝，主宰万物者。震东方，春也。巽东南，春夏之交。离南方，夏也。坤西南，夏秋之交。兑西方，秋也。乾西北，秋冬之交。坎北方，冬也。艮东北，冬春之交。四时运行，八卦各司其序。

乾为天，为圜，为君，为父，为玉，为金，为寒，为冰，为大赤，为良马，为老马，为瘠马，为驳马，为木果。坤为地，为母，为布，为釜，为吝啬，为均，为子母牛，为大舆，为文，为众，为柄，其于地也为黑。震为雷，为龙，为玄黄，为旉，为大涂，为长子，为决躁，为苍筤竹，为萑苇。巽为风，为木，为长女，为绳直，为工，为白，为长，为高，为进退，为不果，为臭。坎为水，为沟渎，为隐伏，为矫輮，为弓轮。其于人也为加忧，为心病，为耳痛，为血卦，为赤。离为火，为日，为电，为中女，为甲胄，为戈兵。其于人也为大腹，为乾卦。艮为山，为径路，为小石，为门阙，为果蓏，为阍寺，为指，为狗，为鼠，为黔喙之属。兑为泽，为少女，为巫，为口舌，为毁折，为附决。其于地也为刚卤，为妾，为羊。
【本义】此章广八卦之象，乃取象之总汇。学者观象玩辞，不可拘泥，亦不可率意。象者，像也，取其近似而已。必求一一吻合，则凿矣。

