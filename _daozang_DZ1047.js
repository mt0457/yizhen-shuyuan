此诰为朝礼三清之总诰，一诰之中，玉清元始天尊、上清灵宝天尊、太清道德天尊——三清道祖之圣号、圣境、圣德、圣功，无不备载；三清之来历本源、化现度世之迹、统御诸天之法，无不包罗。正一道大型斋醮——如罗天大醮、普天大醮、金箓大斋、黄箓大斋、玉箓大斋等——凡启坛、结界、请圣、朝真、谢恩、送圣等各环节，必先诵此诰以通三清、以召万神、以净坛场、以成法事。为何启坛必诵此诰？三清为道教最高尊神，一切道法皆自三清流出，一切科仪皆以三清为归。启坛之初若不先朝礼三清、不通三清之圣意、不禀三清之法旨，则犹如臣子行事不先奏明天子——纵有千般谋划万般手段，名不正则言不顺、言不顺则事不成。故凡正一道士行持法事，无论大小斋醮、简繁科仪，启坛第一事便是恭诵此《金书玉诰》，以三清之圣名开启法坛、以三清之圣德感降天真、以三清之圣力护持道场。此诰之文，字字珠玑、句句玉振——每一字皆蕴三清之玄机、每一句皆含大道之妙理。诵之者，口诵心惟、心与道合，则三清如在顶上、万神如在目前，法事未行而道场已净、科仪未举而天真已降。自古以来，正一道历代天师皆视此诰为传家之宝、镇坛之器——宁可失千金之财不可失此一诰之文、宁可断三尺之剑不可断此诵诰之统。此诰传世千百年，经张道陵天师、张衡嗣师、张鲁系师、寇谦之天师、陆修静天师、杜光庭天师、张继先天师等历代宗师相继整理、润色、增补，至明正统年间编入《道藏》正一部赞颂类，至今仍为天下正一道士每日早晚功课必诵之经、每次斋醮科仪必用之诰。凡志心修道、虔心礼圣者，当以此诰为日课——朝诵一遍则一日之中三清护佑、万神随行；暮诵一遍则一夜之中三清放光、百邪不侵。若能终身持诵不退，则三清之玄功潜移默化、大道之真种自然生根，他日功成果满，三清接引、飞升上清，岂虚言哉。
