素问·上古天真论篇第一

昔在黄帝，生而神灵，弱而能言，幼而徇齐，长而敦敏，成而登天。乃问于天师曰：余闻上古之人，春秋皆度百岁，而动作不衰；今时之人，年半百而动作皆衰者，时世异耶？人将失之耶？

岐伯对曰：上古之人，其知道者，法于阴阳，和于术数，食饮有节，起居有常，不妄作劳，故能形与神俱，而尽终其天年，度百岁乃去。今时之人不然也，以酒为浆，以妄为常，醉以入房，以欲竭其精，以耗散其真，不知持满，不时御神，务快其心，逆于生乐，起居无节，故半百而衰也。

夫上古圣人之教下也，皆谓之虚邪贼风，避之有时，恬惔虚无，真气从之，精神内守，病安从来。是以志闲而少欲，心安而不惧，形劳而不倦，气从以顺，各从其欲，皆得所愿。故美其食，任其服，乐其俗，高下不相慕，其民故曰朴。是以嗜欲不能劳其目，淫邪不能惑其心，愚智贤不肖不惧于物，故合于道。所以能年皆度百岁而动作不衰者，以其德全不危也。

素问·四气调神大论篇第二

春三月，此谓发陈。天地俱生，万物以荣。夜卧早起，广步于庭，被发缓形，以使志生。生而勿杀，予而勿夺，赏而勿罚。此春气之应，养生之道也。逆之则伤肝，夏为寒变，奉长者少。

夏三月，此谓蕃秀。天地气交，万物华实。夜卧早起，无厌于日。使志无怒，使华英成秀，使气得泄，若所爱在外。此夏气之应，养长之道也。逆之则伤心，秋为痎疟，奉收者少，冬至重病。

秋三月，此谓容平。天气以急，地气以明。早卧早起，与鸡俱兴。使志安宁，以缓秋刑。收敛神气，使秋气平。无外其志，使肺气清。此秋气之应，养收之道也。逆之则伤肺，冬为飧泄，奉藏者少。

冬三月，此谓闭藏。水冰地坼，无扰乎阳。早卧晚起，必待日光。使志若伏若匿，若有私意，若已有得。去寒就温，无泄皮肤，使气亟夺。此冬气之应，养藏之道也。逆之则伤肾，春为痿厥，奉生者少。

素问·生气通天论篇第三

黄帝曰：夫自古通天者，生之本，本于阴阳。天地之间，六合之内，其气九州、九窍、五脏、十二节，皆通乎天气。其生五，其气三。数犯此者，则邪气伤人。此寿命之本也。

苍天之气，清净则志意治。顺之则阳气固，虽有贼邪，弗能害也。此因时之序。故圣人传精神，服天气，而通神明。失之则内闭九窍，外壅肌肉，卫气散解。此谓自伤，气之削也。

阳气者，若天与日，失其所则折寿而不彰。故天运当以日光明。是故阳因而上，卫外者也。

素问·金匮真言论篇第四

黄帝问曰：天有八风，经有五风，何谓？岐伯对曰：八风发邪，以为经风，触五脏，邪气发病。所谓得四时之胜者，春胜长夏，长夏胜冬，冬胜夏，夏胜秋，秋胜春。所谓四时之胜也。

素问·阴阳应象大论篇第五

黄帝曰：阴阳者，天地之道也，万物之纲纪，变化之父母，生杀之本始，神明之府也。治病必求于本。故积阳为天，积阴为地。阴静阳躁，阳生阴长，阳杀阴藏。阳化气，阴成形。

寒极生热，热极生寒。寒气生浊，热气生清。清气在下，则生飧泄；浊气在上，则生䐜胀。此阴阳反作，病之逆从也。

素问·阴阳离合论篇第六

黄帝问曰：余闻天为阳，地为阴，日为阳，月为阴。大小月三百六十日成一岁，人亦应之。今三阴三阳不应阴阳，其故何也？

岐伯对曰：阴阳者，数之可十，推之可百；数之可千，推之可万。万之大，不可胜数，然其要一也。

素问·阴阳别论篇第七

黄帝问曰：人有四经十二从，何谓？岐伯对曰：四经应四时，十二从应十二月，十二月应十二脉。

脉有阴阳，知阳者知阴，知阴者知阳。凡阳有五，五五二十五阳。所谓阴者，真脏也，见则为败，败必死也。所谓阳者，胃脘之阳也。

素问·灵兰秘典论篇第八

黄帝问曰：愿闻十二脏之相使，贵贱何如？岐伯对曰：悉乎哉问也，请遂言之。心者，君主之官也，神明出焉。肺者，相傅之官，治节出焉。肝者，将军之官，谋虑出焉。胆者，中正之官，决断出焉。膻中者，臣使之官，喜乐出焉。脾胃者，仓廪之官，五味出焉。大肠者，传道之官，变化出焉。小肠者，受盛之官，化物出焉。肾者，作强之官，伎巧出焉。三焦者，决渎之官，水道出焉。膀胱者，州都之官，津液藏焉，气化则能出矣。

凡此十二官者，不得相失也。故主明则下安，以此养生则寿，殁世不殆，以为天下则大昌。主不明则十二官危，使道闭塞而不通，形乃大伤，以此养生则殃，以为天下者，其宗大危。戒之戒之！

素问·六节藏象论篇第九

黄帝问曰：余闻天以六六之节，以成一岁；人以九九制会，计人亦有三百六十五节，以为天地久矣。不知其所谓也？

岐伯对曰：昭乎哉问也，请遂言之。夫六六之节、九九制会者，所以正天之度、气之数也。天度者，所以制日月之行也；气数者，所以纪化生之用也。

素问·五脏生成篇第十

心之合脉也，其荣色也，其主肾也。肺之合皮也，其荣毛也，其主心也。肝之合筋也，其荣爪也，其主肺也。脾之合肉也，其荣唇也，其主肝也。肾之合骨也，其荣发也，其主脾也。

素问·五脏别论篇第十一

黄帝问曰：余闻方士或以脑髓为脏，或以肠胃为脏，或以为腑。敢问更相反，皆自谓是。不知其道，愿闻其说。

岐伯对曰：脑、髓、骨、脉、胆、女子胞，此六者，地气之所生也，皆藏于阴而象于地，故藏而不泻，名曰奇恒之腑。夫胃、大肠、小肠、三焦、膀胱，此五者，天气之所生也，其气象天，故泻而不藏。此受五脏浊气，名曰传化之腑。此不能久留，输泻者也。

素问·异法方宜论篇第十二

黄帝问曰：医之治病也，一病而治各不同，皆愈，何也？岐伯对曰：地势使然也。故东方之域，天地之所始生也。鱼盐之地，海滨傍水。其民食鱼而嗜咸，皆安其处，美其食。鱼者使人热中，盐者胜血。故其民皆黑色疏理，其病皆为痈疡。其治宜砭石。故砭石者，亦从东方来。

素问·移精变气论篇第十三

黄帝问曰：余闻古之治病，惟其移精变气，可祝由而已。今世治病，毒药治其内，针石治其外，或愈或不愈，何也？

岐伯对曰：往古人居禽兽之间，动作以避寒，阴居以避暑。内无眷慕之累，外无伸宦之形。此恬惔之世，邪不能深入也。故毒药不能治其内，针石不能治其外，故可移精祝由而已。

素问·汤液醪醴论篇第十四

黄帝问曰：为五谷汤液及醪醴奈何？岐伯对曰：必以稻米，炊之稻薪。稻米者完，稻薪者坚。帝曰：何以然？岐伯曰：此得天地之和，高下之宜，故能至完；伐取得时，故能至坚也。

素问·玉版论要篇第十五

黄帝问曰：余闻揆度奇恒，所指不同，用之奈何？岐伯对曰：揆度者，度病之浅深也。奇恒者，言奇病也。请言道之至数。五色脉变，揆度奇恒，道在于一。神转不回，回则不转，乃失其机。

素问·诊要经终论篇第十六

黄帝问曰：诊要何如？岐伯对曰：正月二月，天气始方，地气始发，人气在肝。三月四月，天气正方，地气定发，人气在脾。五月六月，天气盛，地气高，人气在头。七月八月，阴气始杀，人气在肺。九月十月，阴气始冰，地气始闭，人气在心。十一月十二月，冰复，地气合，人气在肾。

素问·脉要精微论篇第十七

黄帝问曰：诊法何如？岐伯对曰：诊法常以平旦，阴气未动，阳气未散，饮食未进，经脉未盛，络脉调匀，气血未乱，故乃可诊有过之脉。切脉动静，而视精明，察五色，观五脏有余不足、六腑强弱、形之盛衰。以此参伍，决死生之分。

素问·平人气象论篇第十八

黄帝问曰：平人何如？岐伯对曰：人一呼脉再动，一吸脉亦再动。呼吸定息，脉五动，闰以太息，命曰平人。平人者，不病也。常以不病调病人。医不病，故为病人平息以调之为法。

素问·玉机真脏论篇第十九

黄帝问曰：春脉如弦，何如而弦？岐伯对曰：春脉者肝也，东方木也，万物之所以始生也。故其气来，软弱轻虚而滑，端直以长，故曰弦。反此者病。

素问·三部九候论篇第二十

黄帝问曰：余闻九针于夫子，众多博大，不可胜数。余愿闻要道，以属子孙，传之后世，著之骨髓，藏之肝肺，歃血而受，不敢妄泄。令合天道，必有终始。上应天光星辰历纪，下副四时五行。贵贱更立，冬阴夏阳。以人应之奈何？愿闻其方。

岐伯对曰：妙乎哉问也！此天地之至数。

素问·经脉别论篇第二十一

黄帝问曰：人之居处、动静、勇怯，脉亦为之变乎？岐伯对曰：凡人之惊恐恚劳动静，皆为变也。是以夜行则喘出于肾，淫气病肺。有所堕恐，喘出于肝，淫气害脾。有所惊恐，喘出于肺，淫气伤心。渡水跌仆，喘出于肾与骨。

素问·脏气法时论篇第二十二

黄帝问曰：合人形以法四时五行而治，何如而从？何如而逆？得失之意，愿闻其事。岐伯对曰：五行者，金木水火土也。更贵更贱，以知死生，以决成败，而定五脏之气、间甚之时、死生之期也。

素问·宣明五气篇第二十三

五味所入：酸入肝，辛入肺，苦入心，咸入肾，甘入脾。是谓五入。五气所病：心为噫，肺为咳，肝为语，脾为吞，肾为欠为嚏。胃为气逆，为哕，为恐。大肠小肠为泄。下焦溢为水。膀胱不利为癃，不约为遗溺。胆为怒。是谓五病。

素问·血气形志篇第二十四

夫人之常数，太阳常多血少气，少阳常少血多气，阳明常多气多血，少阴常少血多气，厥阴常多血少气，太阴常多气少血。此天之常数。

素问·宝命全形论篇第二十五

黄帝问曰：天覆地载，万物悉备，莫贵于人。人以天地之气生，四时之法成。君王众庶，尽欲全形。形之疾病，莫知其情，留淫日深，著于骨髓。心私虑之。余欲针除其疾病，为之奈何？

岐伯对曰：夫盐之味咸者，其气令器津泄；弦绝者，其音嘶败；木敷者，其叶发；病深者，其声哕。人有此三者，是谓坏腑。毒药无治，短针无取。此皆绝皮伤肉，血气争黑。

素问·八正神明论篇第二十六

黄帝问曰：用针之服，必有法则焉。今何法何则？岐伯对曰：法天则地，合以天光。凡刺之法，必候日月星辰、四时八正之气，气定乃刺之。

素问·离合真邪论篇第二十七

黄帝问曰：余闻九针九篇，夫子乃因而九之，九九八十一篇。余尽通其意矣。经言气之盛衰，左右倾移。以上调下，以左调右。有余不足，补泻于荥输。余知之矣。此皆荣卫之倾移，虚实之所生，非邪气从外入于经也。余愿闻邪气之在经也，其病人何如？取之奈何？

素问·通评虚实论篇第二十八

黄帝问曰：何谓虚实？岐伯对曰：邪气盛则实，精气夺则虚。帝曰：虚实何如？岐伯曰：气虚者，肺虚也。气逆者，足寒也。非其时则生，当其时则死。余脏皆如此。

素问·太阴阳明论篇第二十九

黄帝问曰：太阴阳明为表里，脾胃脉也。生病而异者何也？岐伯对曰：阴阳异位，更虚更实，更逆更从。或从内，或从外，所从不同，故病异名也。

素问·阳明脉解篇第三十

黄帝问曰：足阳明之脉病，恶人与火，闻木音则惕然而惊。钟鼓不为动，闻木音而惊，何也？愿闻其故。岐伯对曰：阳明者，胃脉也。胃者，土也。故闻木音而惊者，土恶木也。

素问·热论篇第三十一

黄帝问曰：今夫热病者，皆伤寒之类也。或愈或死。其死皆以六七日之间。其愈皆以十日以上者，何也？不知其解，愿闻其故。岐伯对曰：巨阳者，诸阳之属也。其脉连于风府，故为诸阳主气也。人之伤于寒也，则为病热，热虽甚不死。其两感于寒而病者，必不免于死。

素问·刺热篇第三十二

肝热病者，小便先黄，腹痛多卧身热。热争则狂言及惊，胁满痛，手足躁，不得安卧。庚辛甚，甲乙大汗，气逆则庚辛死。刺足厥阴、少阳。其逆则头痛员员，脉引冲头也。

素问·评热病论篇第三十三

黄帝问曰：有病温者，汗出辄复热，而脉躁疾不为汗衰，狂言不能食，病名为何？岐伯对曰：病名阴阳交。交者死也。帝曰：愿闻其说。岐伯曰：人所以汗出者，皆生于谷，谷生于精。今邪气交争于骨肉而得汗者，是邪却而精胜也。

素问·逆调论篇第三十四

黄帝问曰：人身非常温也，非常热也。为之热而烦满者，何也？岐伯对曰：阴气少而阳气胜，故热而烦满也。帝曰：人身非衣寒也，中非有寒气也。寒从中生者何？岐伯曰：是人多痹气也，阳气少，阴气多，故身寒如从水中出。

素问·疟论篇第三十五

黄帝问曰：夫痎疟皆生于风，其蓄作有时者，何也？岐伯对曰：疟之始发也，先起于毫毛，伸欠乃作，寒栗鼓颔，腰脊俱痛。寒去则内外皆热，头痛如破，渴欲冷饮。帝曰：何气使然？愿闻其道。岐伯曰：阴阳上下交争，虚实更作，阴阳相移也。

素问·刺疟篇第三十六

足太阳之疟，令人腰痛头重，寒从背起。先寒后热，熇熇暍暍然。热止汗出，难已。刺郄中出血。足少阳之疟，令人身体解㑊，寒不甚，热不甚，恶见人。见人心惕惕然，热多汗出甚。刺足少阳。

素问·气厥论篇第三十七

黄帝问曰：五脏六腑，寒热相移者何？岐伯曰：肾移寒于脾，痈肿少气。脾移寒于肝，痈肿筋挛。肝移寒于心，狂，隔中。心移寒于肺，肺消。肺消者，饮一溲二，死不治。肺移寒于肾，为涌水。涌水者，按腹不坚，水气客于大肠，疾行则鸣濯濯，如囊裹浆，水之病也。

素问·咳论篇第三十八

黄帝问曰：肺之令人咳，何也？岐伯对曰：五脏六腑皆令人咳，非独肺也。帝曰：愿闻其状。岐伯曰：皮毛者，肺之合也。皮毛先受邪气，邪气以从其合也。其寒饮食入胃，从肺脉上至于肺，则肺寒。肺寒则外内合邪，因而客之，则为肺咳。

素问·举痛论篇第三十九

黄帝问曰：余闻善言天者，必有验于人；善言古者，必有合于今；善言人者，必有厌于己。如此，则道不惑而要数极，所谓明也。今余问于夫子，令言而可知，视而可见，扪而可得，令验于己，而发蒙解惑，可得而闻乎？

岐伯再拜稽首对曰：何道之问也？帝曰：愿闻人之五脏卒痛，何气使然？

素问·腹中论篇第四十

黄帝问曰：有病心腹满，旦食则不能暮食，此为何病？岐伯对曰：名为鼓胀。帝曰：治之奈何？岐伯曰：治之以鸡矢醴。一剂知，二剂已。

素问·刺腰痛篇第四十一

足太阳脉令人腰痛，引项脊尻背如重状。刺其郄中，太阳正经出血，春无见血。少阳令人腰痛，如以针刺其皮中，循循然不可以俯仰，不可以顾。刺少阳成骨之端出血。成骨在膝外廉之骨独起者。夏无见血。

素问·风论篇第四十二

黄帝问曰：风之伤人也，或为寒热，或为热中，或为寒中，或为疠风，或为偏枯，或为风也。其病各异，其名不同。或内至五脏六腑。不知其解，愿闻其说。岐伯对曰：风气藏于皮肤之间，内不得通，外不得泄。风者善行而数变。腠理开则洒然寒，闭则热而闷。

素问·痹论篇第四十三

黄帝问曰：痹之安生？岐伯对曰：风寒湿三气杂至，合而为痹也。其风气胜者为行痹，寒气胜者为痛痹，湿气胜者为着痹也。

帝曰：其有五者何也？岐伯曰：以冬遇此者为骨痹，以春遇此者为筋痹，以夏遇此者为脉痹，以至阴遇此者为肌痹，以秋遇此者为皮痹。

素问·痿论篇第四十四

黄帝问曰：五脏使人痿，何也？岐伯对曰：肺主身之皮毛，心主身之血脉，肝主身之筋膜，脾主身之肌肉，肾主身之骨髓。故肺热叶焦，则皮毛虚弱急薄，著则生痿躄也。

素问·厥论篇第四十五

黄帝问曰：厥之寒热者，何也？岐伯对曰：阳气衰于下，则为寒厥；阴气衰于下，则为热厥。帝曰：热厥之为热也，必起于足下者，何也？岐伯曰：阳气起于足五指之表，阴脉者集于足下而聚于足心，故阳气胜则足下热也。

素问·病能论篇第四十六

黄帝问曰：人病胃脘痈者，诊当何如？岐伯对曰：诊此者，当候胃脉。其脉当沉细，沉细者气逆。逆者人迎甚盛，甚盛则热。人迎者，胃脉也。逆而盛，则热聚于胃口而不行，故胃脘为痈也。

素问·奇病论篇第四十七

黄帝问曰：人有重身，九月而喑，此为何也？岐伯对曰：胞之络脉绝也。帝曰：何以言之？岐伯曰：胞络者，系于肾。少阴之脉，贯肾系舌本。故不能言。帝曰：治之奈何？岐伯曰：无治也，当十月复。

素问·大奇论篇第四十八

肝满、肾满、肺满皆实，即为肿。肺之雍，喘而两胠满。肝雍，两胠满，卧则惊，不得小便。肾雍，胠下至少腹满，胫有大小，髀䯒大跛，易偏枯。

素问·脉解篇第四十九

太阳所谓肿腰脽痛者，正月太阳寅。寅，太阳也。正月阳气出在上，而阴气盛，阳未得自次也。故肿腰脽痛也。病偏虚为跛者，正月阳气冻解，地气而出也。所谓偏虚者，冬寒颇有不足者，故偏虚为跛也。

素问·刺要论篇第五十

黄帝问曰：愿闻刺要。岐伯对曰：病有浮沉，刺有浅深，各至其理，无过其道。过之则内伤，不及则生外壅，壅则邪从之。浅深不得，反为大贼。内动五脏，后生大病。

素问·刺齐论篇第五十一

黄帝问曰：愿闻刺浅深之分。岐伯对曰：刺骨者无伤筋，刺筋者无伤肉，刺肉者无伤脉，刺脉者无伤皮，刺皮者无伤肉，刺肉者无伤筋，刺筋者无伤骨。

素问·刺禁论篇第五十二

黄帝问曰：愿闻禁数。岐伯对曰：脏有要害，不可不察。肝生于左，肺藏于右。心部于表，肾治于里。脾为之使，胃为之市。膈肓之上，中有父母。七节之傍，中有小心。从之有福，逆之有咎。

素问·刺志论篇第五十三

黄帝问曰：愿闻虚实之要。岐伯对曰：气实形实，气虚形虚。此其常也，反此者病。谷盛气盛，谷虚气虚。此其常也，反此者病。脉实血实，脉虚血虚。此其常也，反此者病。

素问·针解篇第五十四

黄帝问曰：愿闻九针之解，虚实之道。岐伯对曰：刺虚则实之者，针下热也，气实乃热也。满而泄之者，针下寒也，气虚乃寒也。菀陈则除之者，出恶血也。邪胜则虚之者，出针勿按。

素问·长刺节论篇第五十五

刺家不诊，听病者言。在头，头疾痛，为藏针之。刺至骨，病已止。无伤骨肉及皮。皮者，道也。阴刺，入一傍四处。治寒热，深专者，刺大脏。迫脏刺背，背俞也。刺之迫脏，脏会。腹中寒热去而止。与刺之要，发针而浅出血。

素问·皮部论篇第五十六

黄帝问曰：余闻皮有分部，脉有经纪，筋有结络，骨有度量。其所生病各异，别其分部，左右上下，阴阳所在，病之始终。愿闻其道。岐伯对曰：欲知皮部，以经脉为纪者，诸经皆然。

素问·经络论篇第五十七

黄帝问曰：夫络脉之见也，其五色各异，青黄赤白黑不同。其故何也？岐伯对曰：经有常色，而络无常变也。心赤、肺白、肝青、脾黄、肾黑。皆亦应其经脉之色也。

素问·气穴论篇第五十八

黄帝问曰：余闻气穴三百六十五，以应一岁。未知其所，愿卒闻之。岐伯稽首再拜对曰：窘乎哉问也！其非圣帝，孰能穷其道焉。因请溢意，尽言其处。

素问·气府论篇第五十九

足太阳脉气所发者七十八穴：两眉头各一，入发至项三寸半，傍五，相去三寸。其浮气在皮中者，凡五行，行五，五五二十五。

素问·骨空论篇第六十

黄帝问曰：余闻风者百病之始也。以针治之奈何？岐伯对曰：风从外入，令人振寒，汗出头痛，身重恶寒。治在风府。调其阴阳，不足则补，有余则泻。

素问·水热穴论篇第六十一

黄帝问曰：少阴何以主肾？肾何以主水？岐伯对曰：肾者，至阴也。至阴者，盛水也。肺者，太阴也。少阴者，冬脉也。故其本在肾，其末在肺，皆积水也。

素问·调经论篇第六十二

黄帝问曰：余闻刺法言，有余泻之，不足补之。何谓有余？何谓不足？岐伯对曰：有余有五，不足亦有五。帝欲何问？帝曰：愿尽闻之。岐伯曰：神有余有不足，气有余有不足，血有余有不足，形有余有不足，志有余有不足。凡此十者，其气不等也。

素问·缪刺论篇第六十三

黄帝问曰：余闻缪刺，未得其意。何谓缪刺？岐伯对曰：夫邪之客于形也，必先舍于皮毛。留而不去，入舍于孙脉。留而不去，入舍于络脉。留而不去，入舍于经脉。内连五脏，散于肠胃。阴阳俱感，五脏乃伤。此邪之从皮毛而入，极于五脏之次也。如此则治其经焉。今邪客于皮毛，入舍于孙络，留而不去，闭塞不通，不得入于经，流溢于大络，而生奇病也。

素问·四时刺逆从论篇第六十四

厥阴有余，病阴痹；不足，病生热痹。滑则病狐疝风；涩则病少腹积气。少阴有余，病皮痹隐轸；不足，病肺痹。滑则病肺风疝；涩则病积溲血。

素问·标本病传论篇第六十五

黄帝问曰：病有标本，刺有逆从。奈何？岐伯对曰：凡刺之方，必别阴阳，前后相应，逆从得施，标本相移。故曰：有其在标而求之于标，有其在本而求之于本，有其在本而求之于标，有其在标而求之于本。故治有取标而得者，有取本而得者，有逆取而得者，有从取而得者。故知逆与从，正行无问。知标本者，万举万当。不知标本，是谓妄行。

素问·天元纪大论篇第六十六

黄帝问曰：天有五行御五位，以生寒暑燥湿风。人有五脏化五气，以生喜怒思忧恐。论言五运相袭，而皆治之，终期之日，周而复始。余已知之矣。愿闻其与三阴三阳之候，奈何合之？

鬼臾区稽首再拜对曰：昭乎哉问也。夫五运阴阳者，天地之道也，万物之纲纪，变化之父母，生杀之本始，神明之府也，可不通乎！

素问·五运行大论篇第六十七

黄帝坐明堂，始正天纲，临观八极，考建五常。请天师而问之曰：论言天地之动静，神明为之纪。阴阳之升降，寒暑彰其兆。余闻五运之数于夫子，夫子之所言，正五气之各主岁尔。首甲定运，余因论之。

鬼臾区曰：土主甲己，金主乙庚，水主丙辛，木主丁壬，火主戊癸。

素问·六微旨大论篇第六十八

黄帝问曰：呜呼远哉！天之道也，如迎浮云，若视深渊。视深渊尚可测，迎浮云莫知其极。夫子数言谨奉天道，余闻而藏之。心私异之，不知其所谓也。愿夫子溢志，尽言其事，令终不灭，久而不绝。天之道可得闻乎？

岐伯稽首再拜对曰：明乎哉问！天之道也，此因天之序，盛衰之时也。

素问·气交变大论篇第六十九

黄帝问曰：五运更治，上应天期。阴阳往复，寒暑迎随。真邪相薄，内外分离。六经波荡，五气倾移。太过不及，专胜兼并。愿言其始，而有常名。可得闻乎？

岐伯稽首再拜对曰：昭乎哉问也！是明道也。此上帝所贵，先师传之。臣虽不敏，往闻其旨。

素问·五常政大论篇第七十

黄帝问曰：太虚寥廓，五运回薄。衰盛不同，损益相从。愿闻平气何如而名？何如而纪也？岐伯对曰：昭乎哉问也！木曰敷和，火曰升明，土曰备化，金曰审平，水曰静顺。

素问·六元正纪大论篇第七十一

黄帝问曰：六化六变，胜复淫治，甘苦辛咸酸淡，先后不同。余知其然矣。不知其所以然者，何也？愿闻其故。岐伯对曰：夫气之所至，厥阴所至为和平，少阴所至为暄，太阴所至为埃溽，少阳所至为炎暑，阳明所至为清劲，太阳所至为寒雰。

素问·刺法论篇第七十二（遗篇）

黄帝问曰：升降不前，气交有变，即成暴郁。余已知之。何如预救生灵？可得闻乎？岐伯稽首再拜对曰：昭乎哉问！臣闻夫子言，既明天元，须穷刺法。可以折郁扶运，补弱全真，泻盛蠲余，令除斯苦。

素问·本病论篇第七十三（遗篇）

黄帝问曰：天元九窒，余已知之。愿闻气交，何名失守？岐伯曰：谓其上下升降，迁正退位，各有经论。上下各有胜复，而作为灾眚。失时之和，亦为胜复。胜有微甚，复有多少。

素问·至真要大论篇第七十四

黄帝问曰：五气交合，盈虚更作。余知之矣。六气分治，司天地者，其至何如？岐伯再拜对曰：明乎哉问也！天地之大纪，人神之通应也。厥阴司天，其化以风；少阴司天，其化以热；太阴司天，其化以湿；少阳司天，其化以火；阳明司天，其化以燥；太阳司天，其化以寒。以所临脏位，命其病者也。

素问·著至教论篇第七十五

黄帝坐明堂，召雷公而问之曰：子知医之道乎？雷公对曰：诵而未能解，解而未能别，别而未能明，明而未能彰。足以治群僚，不足治侯王。愿得受树天之度，四时阴阳合之。别星辰与日月光，以彰经术，后世益明。上通神农，著至教，拟于二皇。

帝曰：善。无失之。此皆阴阳表里、上下雌雄，相输应也。而道，上知天文，下知地理，中知人事，可以长久。以教众庶，亦不疑殆。医道论篇，可传后世，可以为宝。

素问·示从容论篇第七十六

黄帝燕坐，召雷公而问之曰：汝受术诵书者，若能览观杂学，及于比类，通合道理。为余言子所长。五脏六腑，胆、胃、大小肠、脾、胞、膀胱，脑髓、涕唾、哭泣、悲哀，水所从行，此皆人之所生。治之过失，子务明之。可以十全，即不能知，为世所怨。

雷公曰：臣请诵《脉经·上下篇》甚众多矣。别异比类，犹未能以十全，又安足以明之？

素问·疏五过论篇第七十七

黄帝曰：呜呼远哉！闵闵乎若视深渊，若迎浮云。视深渊尚可测，迎浮云莫知其际。圣人之术，为万民式。论裁志意，必有法则。循经守数，按循医事，为万民副。故事有五过四德，汝知之乎？

雷公避席再拜曰：臣年幼小，蒙愚以惑。不闻五过与四德。比类形名，虚引其经，心无所对。

素问·征四失论篇第七十八

黄帝在明堂，雷公侍坐。黄帝曰：夫子所通书受事，众多矣。试言得失之意，所以得之，所以失之。雷公对曰：循经受业，皆言十全。其时有过失者，请闻其事解也。

帝曰：子年少智未及邪？将言以杂合耶？夫经脉十二，络脉三百六十五，此皆人之所明知，工之所循用也。所以不十全者，精神不专，志意不理，外内相失，故时疑殆。

素问·阴阳类论篇第七十九

孟春始至，黄帝燕坐，临观八极，正八风之气，而问雷公曰：阴阳之类，经脉之道，五中所主，何脏最贵？雷公对曰：春甲乙，青中主肝。治七十二日，是脉之主时。臣以其脏最贵。

素问·方盛衰论篇第八十

雷公请问：气之多少，何者为逆？何者为从？黄帝答曰：阳从左，阴从右。老从上，少从下。是以春夏归阳为生，归秋冬为死。反之则归秋冬为生。是以气多少，逆皆为厥。

素问·解精微论篇第八十一

黄帝在明堂，雷公请曰：臣受业，传之行，教以经论，从容形法，阴阳刺灸，汤药所滋。行治有贤不肖，未必能十全。若先言悲哀喜怒，燥湿寒暑，阴阳妇女。请问其所以然者，卑贱富贵，人之形体所从，群下通使，临事以适道术，谨闻命矣。请问有毚愚仆漏之问，不在经者，欲闻其状。

灵枢·九针十二原第一

黄帝问于岐伯曰：余子万民，养百姓，而收其租税。余哀其不给，而属有疾病。余欲勿使被毒药，无用砭石，欲以微针通其经脉，调其血气，营其逆顺出入之会。令可传于后世，必明为之法。令终而不灭，久而不绝，易用难忘，为之经纪。异其章，别其表里，为之终始。令各有形，先立针经。愿闻其情。

岐伯答曰：臣请推而次之，令有纲纪。始于一，终于九焉。请言其道。小针之要，易陈而难入。粗守形，上守神。神乎神，客在门。未睹其疾，恶知其原。刺之微，在速迟。粗守关，上守机。机之动，不离其空。空中之机，清静而微。其来不可逢，其往不可追。

灵枢·本输第二

黄帝问于岐伯曰：凡刺之道，必通十二经络之所终始，络脉之所别处，五输之所留，六腑之所与合，四时之所出入，五脏之所溜处。阔数之度，浅深之状，高下所至。愿闻其解。

灵枢·小针解第三

所谓易陈者，易言也；难入者，难着于人也。粗守形者，守刺法也；上守神者，守人之血气有余不足，可补泻也。神客者，正邪共会也。神者，正气也；客者，邪气也。在门者，邪循正气之所出入也。未睹其疾者，先知邪正何经之疾也。恶知其原者，先知何经之病所取之处也。

灵枢·邪气脏腑病形第四

黄帝问于岐伯曰：邪气之中人也，奈何？岐伯答曰：邪气之中人高也。黄帝曰：高下有度乎？岐伯曰：身半已上者，邪中之也；身半已下者，湿中之也。故曰：邪之中人也，无有常。中于阴则溜于腑，中于阳则溜于经。

灵枢·根结第五

岐伯曰：天地相感，寒暖相移。阴阳之道，孰少孰多。阴道偶，阳道奇。发于春夏，阴气少，阳气多。阴阳不调，何补何泻。发于秋冬，阳气少，阴气多。阴气盛而阳气衰。故茎叶枯槁，湿雨下归。阴阳相移，何泻何补？

灵枢·寿夭刚柔第六

黄帝问于少师曰：余闻人之生也，有刚有柔，有弱有强，有短有长，有阴有阳。愿闻其方。少师答曰：阴中有阴，阳中有阳。审知阴阳，刺之有方。得病所始，刺之有理。谨度病端，与时相应。内合于五脏六腑，外合于筋骨皮肤。

灵枢·官针第七

凡刺之要，官针最妙。九针之宜，各有所为。长短大小，各有所施也。不得其用，病弗能移。疾浅针深，内伤良肉，皮肤为痈；病深针浅，病气不泻，支为大脓。病小针大，气泻太甚，疾必为害；病大针小，气不泄泻，亦复为败。

灵枢·本神第八

黄帝问于岐伯曰：凡刺之法，先必本于神。血脉营气精神，此五脏之所藏也。至其淫泆离脏，则精失、魂魄飞扬、志意恍乱、智虑去身者，何因而然乎？天之罪与？人之过乎？何谓德气生精神魂魄心意志思智虑？请问其故。

岐伯答曰：天之在我者，德也；地之在我者，气也。德流气薄而生者也。故生之来谓之精，两精相搏谓之神。随神往来者谓之魂，并精而出入者谓之魄。所以任物者谓之心。

灵枢·终始第九

凡刺之道，毕于终始。明知终始，五脏为纪，阴阳定矣。阴者主脏，阳者主腑。阳受气于四末，阴受气于五脏。故泻者迎之，补者随之。知迎知随，气可令和。和气之方，必通阴阳。五脏为阴，六腑为阳。传之后世，以血为盟。敬之者昌，慢之者亡。无道行私，必得夭殃。

灵枢·经脉第十

黄帝曰：人始生，先成精。精成而脑髓生。骨为干，脉为营，筋为刚，肉为墙。皮肤坚而毛发长。谷入于胃，脉道以通，血气乃行。

雷公曰：愿卒闻经脉之始生。黄帝曰：经脉者，所以能决死生、处百病、调虚实，不可不通。

灵枢·经别第十一

黄帝问于岐伯曰：余闻人之合于天道也，内有五脏，以应五音、五色、五时、五味、五位也；外有六腑，以应六律。六律建阴阳诸经，而合之十二月、十二辰、十二节、十二经水、十二时、十二经脉者。此五脏六腑之所以应天道。夫十二经脉者，人之所以生，病之所以成，人之所以治，病之所以起。学之所始，工之所止也。

灵枢·经水第十二

黄帝问于岐伯曰：经脉十二者，外合于十二经水，而内属于五脏六腑。夫十二经水者，其有大小、深浅、广狭、远近各不同。五脏六腑之高下、小大、受谷之多少亦不等。相应奈何？

灵枢·经筋第十三

足太阳之筋，起于足小指上，结于踝，邪上结于膝。其下循足外踝，结于踵，上循跟，结于腘。其别者，结于踹外，上腘中内廉，与腘中并上结于臀，上挟脊上项。其支者，别入结于舌本。

灵枢·骨度第十四

黄帝问于伯高曰：《脉度》言经脉之长短，何以立之？伯高曰：先度其骨节之大小、广狭、长短，而脉度定矣。黄帝曰：愿闻众人之度。人长七尺五寸者，其骨节之大小长短各几何？

灵枢·五十营第十五

黄帝曰：余愿闻五十营奈何？岐伯答曰：天周二十八宿，宿三十六分。人气行一周，千八分。日行二十八宿。人经脉上下左右前后二十八脉，周身十六丈二尺，以应二十八宿。漏水下百刻，以分昼夜。

灵枢·营气第十六

黄帝曰：营气之道，内谷为宝。谷入于胃，乃传之肺，流溢于中，布散于外。精专者，行于经隧，常营无已，终而复始，是谓天地之纪。故气从太阴出，注手阳明。上行注足阳明，下行至跗上，注大指间，与太阴合。

灵枢·脉度第十七

黄帝曰：愿闻脉度。岐伯答曰：手之六阳，从手至头，长五尺，五六三丈。手之六阴，从手至胸中，三尺五寸，三六一丈八尺，五六三尺，合二丈一尺。足之六阳，从足上至头，八尺，六八四丈八尺。

灵枢·营卫生会第十八

黄帝问于岐伯曰：人焉受气？阴阳焉会？何气为营？何气为卫？营安从生？卫于焉会？老壮不同气，阴阳异位。愿闻其会。岐伯答曰：人受气于谷。谷入于胃，以传于肺。五脏六腑，皆以受气。其清者为营，浊者为卫。营在脉中，卫在脉外。营周不休，五十而复大会。阴阳相贯，如环无端。

灵枢·四时气第十九

黄帝问于岐伯曰：夫四时之气，各不同形。百病之起，皆有所生。灸刺之道，何者为定？岐伯答曰：四时之气，各有所在。灸刺之道，得气穴为定。

灵枢·五邪第二十

邪在肺，则病皮肤痛，寒热，上气喘，汗出，咳动肩背。取之膺中外腧，背三节五脏之傍。以手疾按之，快然，乃刺之。取之缺盆中以越之。

邪在肝，则两胁中痛，寒中，恶血在内。行善掣节，时脚肿。取之行间，以引胁下，补三里以温胃中。

灵枢·寒热病第二十一

皮寒热者，不可附席，毛发焦，鼻槁腊，不得汗。取三阳之络，以补手太阴。肌寒热者，肌痛，毛发焦而唇槁腊，不得汗。取三阳于下，以去其血者，补足太阴以出其汗。

灵枢·癫狂第二十二

目眦外决于面者，为锐眦；在内近鼻者，为内眦。上为外眦，下为内眦。癫疾始生，先不乐，头重痛，视举目赤。甚作极已而烦心。候之于颜。取手太阳、阳明、太阴，血变而止。

灵枢·热病第二十三

偏枯，身偏不用而痛，言不变，志不乱，病在分腠之间。巨针取之。益其不足，损其有余，乃可复也。痱之为病也，身无痛者，四肢不收。智乱不甚，其言微知。可治，甚则不能言，不可治也。

灵枢·厥病第二十四

厥头痛，面若肿起而烦心。取之足阳明、太阴。厥头痛，头脉痛，心悲善泣。视头动脉反盛者，刺尽去血，后调足厥阴。厥头痛，贞贞头重而痛。泻头上五行，行五。先取手少阴，后取足少阴。

灵枢·病本第二十五

先病而后逆者，治其本。先逆而后病者，治其本。先寒而后生病者，治其本。先病而后生寒者，治其本。先热而后生病者，治其本。先泄而后生他病者，治其本。必且调之，乃治其他病。

灵枢·杂病第二十六

厥，挟脊而痛者，至顶，头沉沉然，目䀮䀮然，腰脊强。取足太阳腘中血络。厥，胸满面肿，唇漯漯然，暴言难，甚则不能言。取足阳明。厥，气走喉而不能言，手足清，大便不利。取足少阴。

灵枢·周痹第二十七

黄帝问于岐伯曰：周痹之在身也，上下移徙随脉。其上下左右相应，间不容空。愿闻此痛，在血脉之中邪？将在分肉之间乎？何以致是？其痛之移也，间不及下针。其慉痛之时，不及定治，而痛已止矣。何道使然？愿闻其故。

灵枢·口问第二十八

黄帝闲居，辟左右而问于岐伯曰：余已闻九针之经，论阴阳逆顺六经已毕。愿得口问。岐伯避席再拜曰：善乎哉问也。此先师之所口传也。黄帝曰：愿闻口传。岐伯答曰：夫百病之始生也，皆生于风雨寒暑、阴阳喜怒、饮食居处。大惊卒恐，则血气分离，阴阳破败，经络厥绝，脉道不通，阴阳相逆，卫气稽留，经脉虚空，血气不次，乃失其常。

灵枢·师传第二十九

黄帝曰：余闻先师，有所心藏，弗著于方。余愿闻而藏之，则而行之。上以治民，下以治身，使百姓无病。上下和亲，德泽下流。子孙无忧，传于后世，无有终时。可得闻乎？

岐伯曰：远乎哉问也。夫治民与自治，治彼与治此，治小与治大，治国与治家，未有逆而能治之也。夫惟顺而已矣。顺者，非独阴阳脉，论气之逆顺也。百姓人民，皆欲顺其志也。

灵枢·决气第三十

黄帝曰：余闻人有精、气、津、液、血、脉，余意以为一气耳。今乃辨为六名。余不知其所以然。岐伯曰：两神相搏，合而成形，常先身生，是谓精。何谓气？岐伯曰：上焦开发，宣五谷味，熏肤、充身、泽毛，若雾露之溉，是谓气。何谓津？岐伯曰：腠理发泄，汗出溱溱，是谓津。

灵枢·肠胃第三十一

黄帝问于伯高曰：余愿闻六腑传谷者，肠胃之大小长短，受谷之多少，奈何？伯高曰：请尽言之。谷所从出入、浅深、远近、长短之度。唇至齿长九分，口广二寸半。齿以后至会厌，深三寸半，大容五合。

灵枢·平人绝谷第三十二

黄帝曰：愿闻人之不食，七日而死，何也？伯高曰：臣请言其故。胃大一尺五寸，径五寸，长二尺六寸，横屈受水谷三斗五升。其中之谷，常留二斗，水一斗五升而满。

灵枢·海论第三十三

黄帝问于岐伯曰：余闻刺法于夫子，夫子之所言，不离于营卫血气。夫十二经脉者，内属于腑脏，外络于肢节。夫子乃合之于四海乎？岐伯答曰：人亦有四海、十二经水。经水者，皆注于海。海有东西南北，命曰四海。

灵枢·五乱第三十四

黄帝曰：经脉十二者，别为五行，分为四时。何失而乱？何得而治？岐伯曰：五行有序，四时有分。相顺则治，相逆则乱。黄帝曰：何谓相顺？岐伯曰：经脉十二者，以应十二月。十二月者，分为四时。四时者，春秋冬夏。其气各异，营卫相随。阴阳已和，清浊不相干。如是则顺之而治。

灵枢·胀论第三十五

黄帝曰：脉之应于寸口，如何而胀？岐伯曰：其脉大坚以涩者，胀也。黄帝曰：何以知脏腑之胀也？岐伯曰：阴为脏，阳为腑。黄帝曰：夫气之令人胀也，在于血脉之中耶？脏腑之内乎？岐伯曰：三者皆存焉。然非胀之舍也。

灵枢·五癃津液别第三十六

黄帝问于岐伯曰：水谷入于口，输于肠胃。其液别为五。天寒衣薄则为溺与气，天热衣厚则为汗。悲哀气并则为泣，中热胃缓则为唾。邪气内逆，则气为之闭塞而不行，不行则为水胀。余知其然也，不知其何由生？愿闻其道。

灵枢·五阅五使第三十七

黄帝问于岐伯曰：余闻刺有五官五阅，以观五气。五气者，五脏之使也，五时之副也。愿闻其五使当安出？岐伯曰：五官者，五脏之阅也。黄帝曰：愿闻其所出，令可为常。岐伯曰：脉出于气口，色见于明堂。五色更出，以应五时。各如其常，经气入脏，必当治里。

灵枢·逆顺肥瘦第三十八

黄帝问于岐伯曰：余闻针道于夫子，众多毕悉矣。夫子之道，应若失，而据未有坚然者也。夫子之问学熟乎？将审察于物而心生之乎？岐伯曰：圣人之为道者，上合于天，下合于地，中合于人事。必有明法，以起度数，法式检押，乃后可传焉。

灵枢·血络论第三十九

黄帝曰：愿闻其奇邪而不在经者。岐伯曰：血络是也。黄帝曰：刺血络而仆者，何也？血出而射者，何也？血少黑而浊者，何也？血出清而半为汁者，何也？发针而肿者，何也？血出若多若少而面色苍苍者，何也？发针而面色不变而烦悗者，何也？多出血而不动摇者，何也？愿闻其故。

灵枢·阴阳清浊第四十

黄帝曰：余闻十二经脉，以应十二经水者。其五色各异，清浊不同。人之血气若一，应之奈何？岐伯曰：人之血气，苟能若一，则天下为一矣，恶有乱者乎？黄帝曰：余问一人，非问天下之众。岐伯曰：夫一人者，亦有乱气。天下之众，亦有乱人。其合为一耳。

灵枢·阴阳系日月第四十一

黄帝曰：余闻天为阳，地为阴。日为阳，月为阴。其合之于人，奈何？岐伯曰：腰以上为天，腰以下为地。故天为阳，地为阴。故足之十二经脉，以应十二月。月生于水，故在下者为阴。手之十指，以应十日。日主火，故在上者为阳。

灵枢·病传第四十二

黄帝曰：余受九针于夫子，而私览于诸方，或有导引行气、乔摩、灸、熨、刺、焫、饮药之一者，可独守耶？将尽行之乎？岐伯曰：诸方者，众人之方也，非一人之所尽行也。黄帝曰：此乃所谓守一勿失、万物毕者也。

灵枢·淫邪发梦第四十三

黄帝曰：愿闻淫邪泮衍，奈何？岐伯曰：正邪从外袭内，而未有定舍。反淫于脏，不得定处。与营卫俱行，而与魂魄飞扬。使人卧不得安而喜梦。气淫于腑，则有余于外，不足于内。气淫于脏，则有余于内，不足于外。

灵枢·顺气一日分为四时第四十四

黄帝曰：夫百病之所始生者，必起于燥湿寒暑风雨、阴阳喜怒、饮食居处。气合而有形，得脏而有名。余知其然也。夫百病者，多以旦慧、昼安、夕加、夜甚。何也？岐伯曰：四时之气使然。

灵枢·外揣第四十五

黄帝曰：余闻九针九篇，余亲受其调，颇得其意。夫九针者，始于一而终于九。然未得其要道也。夫九针者，小之则无内，大之则无外。深不可为下，高不可为盖。恍惚无穷，流溢无极。余知其合于天道人事四时之变也。然余愿杂之毫毛，浑束为一，可乎？

灵枢·五变第四十六

黄帝问于少俞曰：余闻百疾之始期也，必生于风雨寒暑，循毫毛而入腠理。或复还，或留止。或为风肿汗出，或为消瘅，或为寒热，或为留痹，或为积聚。奇邪淫溢，不可胜数。愿闻其故。

灵枢·本脏第四十七

黄帝问于岐伯曰：人之血气精神者，所以奉生而周于性命者也。经脉者，所以行血气而营阴阳、濡筋骨、利关节者也。卫气者，所以温分肉、充皮肤、肥腠理、司关阖者也。志意者，所以御精神、收魂魄、适寒温、和喜怒者也。

灵枢·禁服第四十八

雷公问于黄帝曰：细子得受业，通于九针六十篇。旦暮勤服之，近者编绝，久者简垢。然尚讽诵弗置，未尽解于意矣。外揣言浑束为一，未知所谓也。夫大则无外，小则无内。大小无极，高下无度。束之奈何？

灵枢·五色第四十九

雷公问于黄帝曰：五色独决于明堂乎？小子未知其所谓也。黄帝曰：明堂者，鼻也。阙者，眉间也。庭者，颜也。蕃者，颊侧也。蔽者，耳门也。其间欲方大，去之十步，皆见于外。如是者寿，必中百岁。

灵枢·论勇第五十

黄帝问于少俞曰：有人于此，并行并立。其年之长少等也，衣之厚薄均也。卒然遇烈风暴雨，或病或不病，或皆病，或皆不病。其故何也？少俞曰：帝问何急？黄帝曰：愿尽闻之。少俞曰：春青风，夏阳风，秋凉风，冬寒风。凡此四时之风者，其所病，各不同形。

灵枢·背腧第五十一

黄帝问于岐伯曰：愿闻五脏之腧，出于背者。岐伯曰：背中大腧，在杼骨之端。肺腧在三焦之间，心腧在五焦之间，膈腧在七焦之间，肝腧在九焦之间，脾腧在十一焦之间，肾腧在十四焦之间。皆挟脊，相去三寸所。

灵枢·卫气第五十二

黄帝曰：五脏者，所以藏精神魂魄者也。六腑者，所以受水谷而行化物者也。其气内干五脏，而外络肢节。其浮气之不循经者，为卫气。其精气之行于经者，为营气。阴阳相随，外内相贯，如环之无端。亭亭淳淳乎，孰能穷之。

灵枢·论痛第五十三

黄帝问于少俞曰：筋骨之强弱，肌肉之坚脆，皮肤之厚薄，腠理之疏密，各不同。其于针石火焫之痛何如？肠胃之厚薄坚脆亦不等。其于毒药何如？愿尽闻之。少俞曰：人之骨强、筋弱、肉缓、皮肤厚者，耐痛。其于针石之痛、火焫亦然。

灵枢·天年第五十四

黄帝问于岐伯曰：愿闻人之始生，何气筑为基？何立而为楯？何失而死？何得而生？岐伯曰：以母为基，以父为楯。失神者死，得神者生也。黄帝曰：何者为神？岐伯曰：血气已和，营卫已通，五脏已成。神气舍心，魂魄毕具，乃成为人。

灵枢·逆顺第五十五

黄帝问于伯高曰：余闻气有逆顺，脉有盛衰，刺有大约。可得闻乎？伯高曰：气之逆顺者，所以应天地阴阳四时五行也。脉之盛衰者，所以候血气之虚实有余不足也。刺之大约者，必明知病之可刺，与其未可刺，与其已不可刺也。

灵枢·五味第五十六

黄帝曰：愿闻谷气有五味，其入五脏，分别奈何？伯高曰：胃者，五脏六腑之海也。水谷皆入于胃，五脏六腑皆禀气于胃。五味各走其所喜。谷味酸，先走肝。谷味苦，先走心。谷味甘，先走脾。谷味辛，先走肺。谷味咸，先走肾。

灵枢·水胀第五十七

黄帝问于岐伯曰：水与肤胀、鼓胀、肠覃、石瘕、石水，何以别之？岐伯答曰：水始起也，目窠上微肿，如新卧起之状。其颈脉动，时咳，阴股间寒，足胫肿，腹乃大。其水已成矣。以手按其腹，随手而起，如裹水之状。此其候也。

灵枢·贼风第五十八

黄帝曰：夫子言贼风邪气之伤人也，令人病焉。今有其不离屏蔽，不出室穴之中，卒然病者。非不离贼风邪气，其故何也？岐伯曰：此皆尝有所伤于湿气，藏于血脉之中，分肉之间，久留而不去。若有所堕坠，恶血在内而不去。卒然喜怒不节，饮食不适，寒温不时，腠理闭而不通，其开而遇风寒，则血气凝结，与故邪相袭，则为寒痹。

灵枢·卫气失常第五十九

黄帝曰：卫气之留于腹中，蓄积不行，菀蕴不得常所。使人支胁胃中满，喘呼逆息者，何以去之？伯高曰：其气积于胸中者，上取之。积于腹中者，下取之。上下皆满者，傍取之。

灵枢·玉版第六十

黄帝曰：余以小针为细物也。夫子乃言上合之于天，下合之于地，中合之于人。余以为过针之意矣。愿闻其故。岐伯曰：何物大于天乎？夫大于针者，惟五兵者焉。五兵者，死之备也。非生之具。且夫人者，天地之镇也。其不可不参乎？夫治民者，亦唯针焉。夫针之与五兵，其孰小乎？

灵枢·五禁第六十一

黄帝问于岐伯曰：余闻刺有五禁，何谓五禁？岐伯曰：禁其不可刺也。黄帝曰：余闻刺有五夺。岐伯曰：无泻其不可夺者也。黄帝曰：余闻刺有五过。岐伯曰：补泻无过其度。

灵枢·动输第六十二

黄帝曰：经脉十二，而手太阴、足少阴、阳明独动不休，何也？岐伯曰：是明胃脉也。胃为五脏六腑之海。其清气上注于肺，肺气从太阴而行之。其行也，以息往来。故人一呼脉再动，一吸脉亦再动。呼吸不已，故动而不止。

灵枢·五味论第六十三

黄帝问于少俞曰：五味入于口也，各有所走，各有所病。酸走筋，多食之，令人癃。咸走血，多食之，令人渴。辛走气，多食之，令人洞心。苦走骨，多食之，令人变呕。甘走肉，多食之，令人悗心。余知其然也，不知其何由？愿闻其故。

灵枢·阴阳二十五人第六十四

黄帝曰：余闻阴阳之人，何如？伯高曰：天地之间，六合之内，不离于五。人亦应之。故五五二十五人之政。而阴阳之人不与焉。其态又不合于众者五。余已知之矣。愿闻二十五人之形，血气之所生，别而以候，从外知内，何如？

灵枢·五音五味第六十五

右徵与少徵，调右手太阳上。左商与左徵，调左手阳明上。少徵与大宫，调左手阳明上。右角与大角，调右足少阳下。大徵与少徵，调左手太阳上。众羽与少羽，调右足太阳下。少商与右商，调右手太阳下。

灵枢·百病始生第六十六

黄帝问于岐伯曰：夫百病之始生也，皆生于风雨寒暑、清湿喜怒。喜怒不节则伤脏，风雨则伤上，清湿则伤下。三部之气，所伤异类。愿闻其会。岐伯曰：三部之气各不同。或起于阴，或起于阳。请言其方。

灵枢·行针第六十七

黄帝问于岐伯曰：余闻九针于夫子，而行之于百姓。百姓之血气，各不同形。或神动而气先针行，或气与针相逢，或针已出气独行，或数刺乃知，或发针而气逆，或数刺病益剧。凡此六者，各不同形。愿闻其方。

灵枢·上膈第六十八

黄帝曰：气为上膈者，食饮入而还出。余已知之矣。虫为下膈。下膈者，食晬时乃出。余未得其意。愿卒闻之。岐伯曰：喜怒不适，食饮不节，寒温不时。则寒汁流于肠中。流于肠中则虫寒，虫寒则积聚。守于下管，则肠胃充郭。卫气不营，邪气居之。人食则虫上食，虫上食则下管虚，下管虚则邪气胜之。积聚以留，留则痈成，痈成则下管约。其痈在管内者，即而痛深。其痈在外者，则痈外而痛浮，痈上皮热。

灵枢·忧恚无言第六十九

黄帝问于少师曰：人之卒然忧恚而言无音者，何道之塞？何气出行，使音不彰？愿闻其方。少师答曰：咽喉者，水谷之道也。喉咙者，气之所以上下者也。会厌者，音声之户也。口唇者，音声之扇也。舌者，音声之机也。悬雍垂者，音声之关也。颃颡者，分气之所泄也。横骨者，神气所使，主发舌者也。

灵枢·寒热第七十

黄帝问于岐伯曰：寒热瘰疬，在于颈腋者，皆何气使生？岐伯曰：此皆鼠瘘寒热之毒气也。留于脉而不去者也。黄帝曰：去之奈何？岐伯曰：鼠瘘之本，皆在于脏。其末上出于颈腋之间。其浮于脉中，而未内着于肌肉，而外为脓血者，易去也。

灵枢·邪客第七十一

黄帝问于伯高曰：夫邪气之客人也，或令人目不瞑、不卧出者，何气使然？伯高曰：五谷入于胃也，其糟粕、津液、宗气，分为三隧。故宗气积于胸中，出于喉咙，以贯心脉，而行呼吸焉。营气者，泌其津液，注之于脉，化以为血，以荣四末，内注五脏六腑，以应刻数焉。卫气者，出其悍气之慓疾，而先行于四末分肉皮肤之间，而不休者也。昼日行于阳，夜行于阴。常从足少阴之分间，行于五脏六腑。

灵枢·通天第七十二

黄帝问于少师曰：余尝闻人有阴阳，何谓阴人？何谓阳人？少师曰：天地之间，六合之内，不离于五。人亦应之，非徒一阴一阳而已也。而略言耳，口弗能遍明也。

黄帝曰：愿略闻其意。有贤人圣人，心能备而行之乎？少师曰：盖有太阴之人、少阴之人、太阳之人、少阳之人、阴阳和平之人。凡五人者，其态不同。其筋骨气血各不等。

灵枢·官能第七十三

黄帝问于岐伯曰：余闻九针于夫子，众多矣，不可胜数。余推而论之，以为一纪。余司诵之，子听其理。非则语余，请正其道。令可久传，后世无患。得其人乃传，非其人勿言。

岐伯稽首再拜曰：请听圣王之道。黄帝曰：用针之理，必知形气之所在，左右上下，阴阳表里，血气多少，行之逆顺，出入之合。谋伐有过。

灵枢·论疾诊尺第七十四

黄帝问于岐伯曰：余欲无视色持脉，独调其尺，以言其病。从外知内，为之奈何？岐伯曰：审其尺之缓急、小大、滑涩、肉之坚脆，而病形定矣。视人之目窠上微痈，如新卧起状，其颈脉动，时咳。按其手足上，窅而不起者，风水肤胀也。

灵枢·刺节真邪第七十五

黄帝问于岐伯曰：余闻刺有五节，奈何？岐伯曰：固有五节。一曰振埃，二曰发蒙，三曰去爪，四曰彻衣，五曰解惑。黄帝曰：夫子言五节，余未知其意。岐伯曰：振埃者，刺外经，去阳病也。发蒙者，刺腑输，去腑病也。去爪者，刺关节肢络也。彻衣者，尽刺诸阳之奇输也。解惑者，尽知调阴阳，补泻有余不足，相倾移也。

灵枢·卫气行第七十六

黄帝问于岐伯曰：愿闻卫气之行，出入之合，何如？岐伯曰：岁有十二月，日有十二辰。子午为经，卯酉为纬。天周二十八宿，而一面七星，四七二十八星。房昴为纬，虚张为经。是故房至毕为阳，昴至心为阴。阳主昼，阴主夜。故卫气之行，一日一夜五十周于身。昼日行于阳，二十五周。夜行于阴，二十五周。周于五脏。

灵枢·九宫八风第七十七

太一常以冬至之日，居叶蛰之宫四十六日。明日居天留四十六日。明日居仓门四十六日。明日居阴洛四十五日。明日居天宫四十六日。明日居玄委四十六日。明日居仓果四十六日。明日居新洛四十五日。明日复居叶蛰之宫，曰冬至矣。

灵枢·九针论第七十八

黄帝曰：余闻九针于夫子，众多博大矣。余犹不能寤。敢问九针焉生？何因而有名？岐伯曰：九针者，天地之大数也。始于一而终于九。故曰：一以法天，二以法地，三以法人，四以法时，五以法音，六以法律，七以法星，八以法风，九以法野。

灵枢·岁露论第七十九

黄帝问于岐伯曰：《经》言夏日伤暑，秋病疟。疟之发以时。其故何也？岐伯对曰：邪客于风府，病循膂而下。卫气一日一夜，常大会于风府。其明日，日下一节。故其日作晏。此其先客于脊背也。故每至于风府则腠理开，腠理开则邪气入，邪气入则病作。此所以日作尚晏也。

灵枢·大惑论第八十

黄帝问于岐伯曰：余尝上于清冷之台。中阶而顾，匍匐而前，则惑。余私异之，窃内怪之。独瞑独视，安心定气，久而不解。独博独眩，披发长跪。俯而视之，后久之不已也。卒然自上，何气使然？

岐伯对曰：五脏六腑之精气，皆上注于目而为之精。精之窠为眼。骨之精为瞳子，筋之精为黑眼，血之精为络。其窠气之精为白眼，肌肉之精为约束。裹撷筋骨血气之精，而与脉并为系。上属于脑，后出于项中。

灵枢·痈疽第八十一

黄帝曰：余闻肠胃受谷，上焦出气，以温分肉，而养骨节，通腠理。中焦出气如露，上注溪谷，而渗孙脉。津液和调，变化而赤为血。血和则孙脉先满溢，乃注于络脉。皆盈，乃注于经脉。阴阳已张，因息乃行。行有经纪，周有道理。与天合同，不得休止。切而调之，从虚去实。泻则不足，疾则气减，留则先后。从实去虚，补则有余。血气已调，形气乃持。余已知血气之平与不平，未知痈疽之所从生。成败之时，死生之期。期有远近，何以度之？可得闻乎？

岐伯曰：经脉留行不止，与天同度，与地合纪。故天宿失度，日月薄蚀；地经失纪，水道流溢。草萓不成，五谷不殖。径路不通，民不往来。巷聚邑居，则别离异处。血气犹然。请言其故。夫血脉营卫，周流不休。上应星宿，下应经数。寒邪客于经络之中，则血泣，血泣则不通，不通则卫气归之，不得复反，故痈肿。寒气化为热，热胜则腐肉，肉腐则为脓。脓不泻则烂筋，筋烂则伤骨，骨伤则髓消。不当骨空，不得泄泻。血枯空虚，则筋骨肌肉不相荣。经脉败漏，熏于五脏，脏伤故死矣。
