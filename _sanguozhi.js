臣松之言：臣闻智周则万理自宾，鉴远则物无遗照。虽尽性穷微，深不可识，至于绪余所寄，则必接乎粗迹。……寿书铨叙可观，事多审正。诚游览之苑囿，近世之嘉史。然失在于略，时有所脱漏。臣奉旨寻详，务在周悉。上搜旧闻，傍摭遗逸。……其寿所不载，事宜存录者，则罔不毕取以补其阙。或同说一事而辞有乖杂，或出事本异，疑不能判，并皆抄内以备异闻。若乃纰缪显然，言不附理，则随违矫正以惩其妄。其时事当否及寿之小失，颇以愚意有所论辩。……元嘉六年七月二十四日，中书侍郎西乡侯臣裴松之上。

