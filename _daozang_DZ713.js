诵此总咒时，须配合存思——观想五方五帝各乘五色祥云从五方而来，齐集坛场上空。
东方青帝乘青龙，从东方青炁中降；南方赤帝乘朱雀，从南方赤炁中降；
中央黄帝乘黄龙，从中央黄炁中降；西方白帝乘白虎，从西方白炁中降；
北方黑帝乘玄武，从北方黑炁中降。
五帝齐降之后，各放本炁之光，五色光明交织融汇，照彻坛场和修持者全身，
五色光炁分别灌注五脏——青炁入肝、赤炁入心、黄炁入脾、白炁入肺、黑炁入肾——
五脏同时得到五方真炁的灌注滋润，一切病炁、邪炁、浊炁、秽炁，皆被五色光明驱散净化。
