<b>
太上洞玄灵宝天尊，大罗天上放光明。悯念众生咳喘苦，金口亲宣禳解经。
符箓丹药导引术，诵经持咒饮食方。六法融通无遗漏，标本兼治妙难量。
至心诵持勿懈怠，七日见轻四九康。更将此经广传播，功德无边福寿长。
凡诸咳喘受苦者，得遇此经是大缘。珍重受持如至宝，病愈身安道自全。
皈依道经师三宝。灵宝无量度人天尊。福生无量天尊。
</b>
