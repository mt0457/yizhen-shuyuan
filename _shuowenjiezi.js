鸿——鸿鹄也。从鸟江声。
鹄——鸿鹄也。从鸟告声。
鹏——古文凤，象形。凤飞群鸟从以万数，故以为朋党字。
鹰——鸟也。从鸟雁声。
燕——玄鸟也。籋口布翅枝尾。象形。凡燕之属皆从燕。
