汉安帝建光元年（121年），许慎病重，命其子许冲将《说文解字》献于朝廷。许冲上表曰：
召陵万岁里公乘草莽臣冲稽首再拜上书皇帝陛下：臣伏见陛下神灵盛德，承遵圣业，上考度于天，下流化于民。先帝（汉和帝）诏侍中骑都尉贾逵修理旧文，殊艺异术，王教一端，苟有可以加于国者靡不悉集。臣父故太尉南阁祭酒慎，本从逵受古学。盖圣人不空作，皆有依据。慎博问通人，考之于逵，作《说文解字》。六艺群书之诂皆训其意，而天地鬼神山川草木鸟兽昆虫杂物奇怪王制礼仪世间人事莫不毕载。凡十五卷十三万三千四百四十一字。慎前以诏书校书东观，教小黄门孟生李喜等。以文字未定，未奏上。今慎已病，遣臣赍诣阙。慎又学《孝经》孔氏古文说。慎本从逵受古学，著《说文解字》十五篇、《五经异义》一篇。
汉安帝诏曰：可。赐召陵公乘许冲布四十匹。
