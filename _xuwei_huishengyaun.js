【第一折】

（正旦扮黄崇嘏，男装，上，云）妾身姓黄，名崇嘏，西蜀临邛人也。自幼父母双亡，家道凋零。好在我腹有诗书，胸怀大志。闻知当朝开科取士，我不免扮作男子，前去应试。若得一官半职，也可光大门楣。

（黄崇嘏扮男装，改名黄崇嘏，赴京应试。三场已毕，黄崇嘏做状元及第。除授成都府司户参军。）

【第二折】

（黄崇嘏冠带，上任。丞相周庠见黄崇嘏才貌双全，欲招为婿。）

（周庠云）黄参军年少有才，老夫有一女，欲招你为婿。你意下如何？

（黄崇嘏做为难科，云）蒙丞相美意，只是下官……（背云）这如何是好？

（黄崇嘏思忖，乃云）既蒙丞相厚爱，下官从命便是。

【第三折】

（洞房花烛夜。周小姐与黄崇嘏相对。黄崇嘏推故不眠。周小姐疑之，以言探问。黄崇嘏不得已，以实情相告。）

（黄崇嘏云）小姐，实不相瞒。我本是女子，为求功名，女扮男装。如今冒渎小姐，罪该万死。

（周小姐惊，后转喜，云）原来如此！姐姐真乃奇女子也！既如此，你我不如今夜结为姐妹，日后你若遇佳偶，我当为你做媒。

（黄崇嘏云）多谢小姐海涵。

【第四折】

（丞相闻知此事，奏明天子。天子奇之，云）世间竟有如此奇女子！黄崇嘏女扮男装，高中状元，足见才华出众。今既为丞相所识，丞相之子新中进士，可为婚配。着即完婚！

（黄崇嘏与周公子成婚。丞相云）老夫原以为招了女婿，不想竟是招了个状元媳妇！更不料如今又成了真女婿！哈哈哈！

【尾声】世间奇事有还无？女子未必逊丈夫。状元本是蛾眉客，辞凰得凤天下无。

