【入燕三首·其一】

大鹏奋南徙，岂为北海笼。
越鸟巢南枝，常怀故山风。
丈夫志四海，安能守一蓬。
朝发钱塘门，暮宿燕山烽。
仰观天宇阔，俯察人事穷。
行矣各自爱，勿为歧路恫。

【入燕三首·其二】

燕山何苍苍，易水何汤汤。
游子去不返，壮士心慨慷。
白虹贯日影，寒风起天霜。
荆卿已长逝，千载有余伤。
我今过其里，慷慨泪沾裳。
古来重意气，谁复论剑铓。

【入燕三首·其三】

驱车入燕市，日暮风沙黄。
举目无相识，但见侠少场。
击筑歌呜呜，酒酣气扬扬。
黄金买歌舞，白刃报恩雠。
我亦慷慨士，安能守故常。
拂衣出门去，长啸归山乡。

【夜宿山村】

山深人迹少，日落鸟声稀。
野店炊烟起，孤村灯火微。
寒泉鸣石罅，冷月照柴扉。
客子衣裳薄，秋风透骨吹。

【登北固山】

北固临江渚，登高望帝京。
云开吴会远，日落楚山横。
天地孤舟小，江湖白发生。
古今多少恨，都付一江声。

【越王台】

越王台上望，烟雨暗江津。
霸气消沉久，山花寂寞春。
鹧鸪啼断处，芳草没荒榛。
唯有城头月，年年照故人。

【严陵钓台】

羊裘老钓客，天子不能臣。
星动客星犯，风清江水春。
高台空寂寂，古木自榛榛。
千载清风在，何曾染世尘。

【山阴道上】

山阴道上行，如在镜中游。
千岩竞奇秀，万壑争清流。
竹色含新雨，松声带早秋。
若耶溪水碧，浣女唱歌舟。

【镜湖】

镜湖三百里，菡萏发荷花。
五月渔郎醉，清歌日已斜。
采莲归去晚，荡桨入烟霞。
何处菱歌起，风吹到若耶。

【夜泊钱塘】

钱塘江上夜，潮涌月明中。
万马奔腾势，千雷吼怒风。
吴山青未了，越水白无穷。
独坐孤舟里，悠悠思不穷。

【兰亭】

兰亭修禊处，曲水至今流。
竹影摇书幌，花光照酒瓯。
右军遗迹在，千载仰风流。
我欲临池学，池边月正秋。

【会稽山】

会稽何峻极，禹穴古来传。
石匮藏金简，云封护玉篇。
登临一长啸，天地入茫然。
霸业随流水，空余万壑烟。

【秋日山居】

