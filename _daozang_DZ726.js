<p style="margin:8px 0 0 0;line-height:2;">《太上正一盟威妙经》，简称《盟威妙经》，一卷，收入明《正统道藏》正一部本文类，编号第726部。此经为天师道（正一道）根本经典之一，述太上老君于汉安元年（142年）正月十五日降临鹤鸣山，授张道陵天师"正一盟威之道"之圣迹。</p>
