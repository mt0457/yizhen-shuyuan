游目极妙伎，清听厌宫商。主人寂无为，众宾进乐方。
长筵坐戏客，斗鸡观闲房。群雄正翕赫，双翘自飞扬。
挥羽激清风，悍目发朱光。觜落轻毛散，严距往往伤。
长鸣入青云，扇翼独翱翔。愿蒙狸膏助，常得擅此场。

