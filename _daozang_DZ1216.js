<b>太上洞神老君说，齿疾之苦遍人间。齿为骨余骨肾合，固齿即固骨命根。
叩齿三十六通法，晨集神兮暮安魄。左九右九前九叩，全齿九通合天罡。
赤龙搅海生玉液，三咽归宫润五脏。青盐擦龈咸入肾，杀菌收敛牙龈固。
五真散剂填精髓，地黄牛膝补骨脂。骨碎补合细辛佐，入肾坚骨齿如石。
三法兼修永不辍，齿固骨坚寿延长。皈依道经师三宝。禳齿疾老君说福生无量天尊。</b>
