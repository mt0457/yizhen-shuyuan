三洞经书者，道教一切经典之总汇，乃元始天尊、灵宝天尊、道德天尊三清道祖所说之无上真经。
正一道自东汉张道陵天师创教以来，历代天师搜集整理三洞经文，至南朝刘宋陆修静天师编定《三洞经书目录》，唐代孟安排法师撰《道教义枢》详述三洞义理，宋明两代天师屡加修订增补，最终形成此《正一三洞真经总目》，成为正一道藏经目录之权威版本。
此目不仅是检索道经之工具书，更是三洞经教体系之总纲——明其目者，即明道教一切经典之源流、分类、品级、传承，实为入道之门、穷经之钥。
