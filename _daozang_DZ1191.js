《太上老君养生诀》一卷、《太清导引养生经》一卷、《太上老君按摩经》一卷、
《太上老君服气经》一卷、《太上老君咽液经》一卷、《太清调气经》一卷、
《太清服气口诀》一卷、《太上保真养生论》一卷、《养性延命录》二卷、
