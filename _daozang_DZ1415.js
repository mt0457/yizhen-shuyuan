然后观想脑神手中之紫玉如意放射紫色光明——此光明充满脑部九宫，从头颅中心向四周扩展：百会、印堂、太阳、风池、风府、后顶——光明所到之处，一切疼痛如冰消融、一切邪气化为青烟消散、一切瘀滞化为净水排出。
