洞玄虚通，化应声天。元始之炁，化为此天。观世音声，寻声救苦。十方众生，称名求救。天人闻之，即放光明。声到光到，无远弗届。如响应声，无有差失。如影随形，无有迟滞。天中有镜，名曰圆光。照见十方，一切音声。善声恶声，苦声乐声。声声入镜，镜镜分明。今有亡魂，呼号求救。其声虽微，其苦实深。伏愿天人，闻声救拔。放洞玄光，照其所在。引魂出苦，拔魂超升。乘此玉章，声达天听。洞玄之炁，生我胆气。碧帝护持，永脱厄难。
