颜之推（531年—约591年），字介，琅琊临沂（今山东临沂）人。南北朝至隋初著名学者、文学家。
少遭丧乱，历经梁、北齐、北周、隋四朝。博学多识，精于文字音韵。所著《颜氏家训》二十篇，
以儒家思想教育子弟，体系完整，论述精辟，援引史实，辞旨恳切。
陈振孙《直斋书录解题》誉其为“古今家训，以此为祖”。
