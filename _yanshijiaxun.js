《颜氏家训》是中国古代家庭教育理论的经典著作，被誉为“古今家训之祖”。
全书二十篇，内容涵盖教子、治家、风操、勉学、文章、养生、归心等诸多方面。
颜之推以儒家思想为核心，融合佛道，兼容并包，形成了系统的家训体系。

其书核心思想包括：
一、重视早期教育——“教妇初来，教儿婴孩”，强调教育当从幼年开始。
二、主张严慈相济——父母威严而有慈，既不溺爱也不苛责。
三、强调学以致用——读书不仅为博取功名，更为修身利行、应世经务。
四、倡导勤俭持家——施而不奢，俭而不吝，以义制利。
五、注重环境熏陶——与善人居如入芝兰之室，交友须谨慎。
六、主张少欲知足——谦虚冲损，可以免害，反对贪得无厌。
七、兼收并蓄——内教外教本为一体，打通儒释道三家思想。

此书在训诂学、音韵学、历史学、民俗学等方面亦具极高学术价值。
