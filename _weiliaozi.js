尉缭子·伍制令第十四

军中之制，五人为伍，伍相保也；十人为什，什相保也；五
十人为属，属相保也；百人为闾，闾相保也。伍有干令犯禁
者，揭之，免于罪；知而弗揭，全伍有诛。什有干令犯禁者，
揭之，免于罪；知而弗揭，全什有诛。属有干令犯禁者，揭
之，免于罪；知而弗揭，全属有诛。闾有干令犯禁者，揭之，
免于罪；知而弗揭，全闾有诛。

吏自什长以上，至左右将，上下皆相保也。有干令犯禁者，
揭之，免于罪；知而弗揭者，皆与同罪。夫什伍相结，上下
相联，无有不得之奸，无有不揭之罪。父不得以私其子，兄
不得以私其弟，而况国人？聚舍同食，乌能以干令相私者
哉？

【篇旨】论军队的连保制度，以伍、什、属、闾四级编制，互相监督，防止犯禁。

