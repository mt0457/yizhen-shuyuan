尉缭子·将理第九

凡将，理官也，万物之主也，不私于一人。夫能无私于一人，故万物至而制之，万物至而命之。君子不救囚于桎梏，不凿人之垣墙。救囚于桎梏，无宽仁之名。凿垣墙，无多积之名。然则善将者，不妄杀一人，不妄赏一人。不妄杀一人，则众无离心；不妄赏一人，则众无幸心。杀一人而三军震者杀之，赏一人而万人喜者赏之。杀之贵大，赏之贵小。当杀而虽贵重，必杀之，是刑上究也。赏及牛童马圉者，是赏下流也。夫能刑上究、赏下流，此将之武也。故人主重将。夫将，提鼓挥枹，临难决战。接兵角刃，鼓之而当，则赏功立名；鼓之而不当，则身死国亡。是存亡安危在于枹端，奈何无重将也。

尉缭子·兵令上第二十三

兵者，凶器也。争者，逆德也。事必有本。故王者伐暴乱，本仁义焉。战国则以立威抗敌相图，而不能废兵也。兵者，以武为植，以文为种。武为表，文为里。能审此二者，知胜败矣。文所以视利害，辨安危；武所以犯强敌，力攻守也。专一则胜，离散则败。陈以密则固，锋以疏则达。卒畏将甚于敌者胜，卒畏敌甚于将者败。所以知胜败者，称将于敌也。敌与将犹权衡焉。安静则治，暴疾则乱。

尉缭子·兵令下第二十四

诸去大军为前御之备者，边县列侯，各相去三五里。闻大军为前御之备，战则皆禁行，所以安内也。诸战而亡其将吏者，及将吏弃卒独北者，尽斩之。三军大战，若大将死，而从吏五百人以上不能死敌者，斩。大将左右近卒在陈中者，皆斩。军之利害，在国之名实。今名在官，而实在家，官不得其实，家不得其名。聚卒为军，有空名无实，外不足以御敌，内不足以守国，此军之所以不给，将之所以夺威也。
