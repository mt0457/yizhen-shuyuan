尉缭子·十二陵第七

威在于不变，惠在于因时，机在于应事，战在于治气，攻在
于意表，守在于外饰，无过在于度数，无困在于豫备，慎在
于畏小，智在于治大，除害在于敢断，得众在于下人。

侮在于任疑，孽在于屠戮，偏在于多私，不祥在于恶闻己过，
不度在于竭民财，不明在于受间，不实在于轻发，固陋在于
离贤，祸在于好利，害在于亲小人，亡在于无所守，危在于
无号令。

