尉缭子·分塞令第十五

中军、左军、右军、前军、后军，皆有分地。方之以行垣，
而无通其交往。将有分地，帅有分地，伯有分地。皆营其沟
洫，而明其塞令。使非有职事者，无得通行于其分地之间。
非其百人而入者，伯诛之；伯不诛，与之同罪。

军中纵横之道，百有二十步而立一府柱，量人与地，柱道相
