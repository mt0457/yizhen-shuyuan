尉缭子·将理第九

凡将，理官也，万物之主也，不私于一人。夫能无私于一人，
故万物至而制之，万物至而命之。君子不救囚于桎梏，不凿
人之垣墙。救囚于桎梏，无宽仁之名。凿垣墙，无多积之名。
然则善将者，不妄杀一人，不妄赏一人。不妄杀一人，则众
无离心；不妄赏一人，则众无幸心。

杀一人而三军震者杀之，赏一人而万人喜者赏之。杀之贵大，
赏之贵小。当杀而虽贵重，必杀之，是刑上究也。赏及牛童
马圉者，是赏下流也。夫能刑上究、赏下流，此将之武也。

凡将理官也，万物之主也。凡将理之善者，不懈于虑，不怠
于听。将无还令，赏罚必信。如天如地，乃可御人。士卒有
死事，家有父母妻子，皆给其家。将能清正自为，与众均其
劳佚，则其下皆尽力而不怨矣。

【篇旨】论将帅治理军务的职责，强调公正无私、赏罚分明，刑上究赏下流。

