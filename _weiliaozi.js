尉缭子·重刑令第十三

将自千人以上，有战而北，守而降，离地逃众，命曰国贼。
身戮家残，去其籍，发其坟墓，暴其骨于市，男女公于官。
自百人以上，有战而北，守而降，离地逃众，命曰军贼。身
死家残，男女公于官。使民内畏重刑，则外轻敌。故先王明
制度于前，重威刑于后。刑重则内畏，内畏则外坚矣。

