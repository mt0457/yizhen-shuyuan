尉缭子·踵军令第二十

所谓踵军者，去大军百里，期于会地，为三日熟食，前军而
行。为战合之表，合表乃起。踵军飨士，使为之战势，是谓
趋战者也。兴军者，前踵军而行，合表乃起。去大军一倍其
道，去踵军百里，期于会地，为六日熟食，使为战备。
分卒据要害，战利则追北，按兵而趋之。踵军遇有还者，
诛之。所谓诸将之兵在四奇之内者，胜也。

兵有什伍，有分有合，豫为之职，守要塞关梁而分居之。战
合表起，即皆会也。大军为计日之食，豫为之备。战合表起，
即出击之。如此，则令行而卒不散，将死而鼓不丧矣。

