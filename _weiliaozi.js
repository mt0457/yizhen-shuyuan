尉缭子·束伍令第十六

束伍之令曰：五人为伍，共一符，收于将吏之所。亡伍而得
伍，当之；得伍而不亡，有赏；亡伍不得伍，身死家残。亡
长得长，当之；得长而不亡，有赏；亡长不得长，身死家残。
复战得首长，除之。亡将得将，当之；得将而不亡，有赏；
亡将不得将，坐离地遁逃之法。

战诛之法曰：什长得诛十人，伯长得诛什长，千人之将得诛
百人之长，万人之将得诛千人之将，左右将军得诛万人之将，
大将军无不得诛。夫能禁暴止乱，一军之制也。

