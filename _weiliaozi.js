尉缭子·战威第四

凡兵有以道胜，有以威胜，有以力胜。讲武料敌，使敌之气
失而师散，虽形全而不为之用，此道胜也。审法制，明赏罚，
便器用，使民有必战之心，此威胜也。破军杀将，乘闉发机，
溃众夺地，成功乃返，此力胜也。王侯知此，所以三胜者
毕矣。

夫将之所以战者，民也；民之所以战者，气也。气实则斗，
气夺则走。善用兵者，能夺人而不夺于人。夺者心之机也。
令者一众心也。众不审则数变，数变则令虽出，众不信矣。
故令之法，小过无更，小疑无申。故上无疑令，则众不二听；
动无疑事，则众不二志。

未有不信其心，而能得其力者；未有不得其力，而能致死战
者。故国必有礼信亲爱之义，则可以饥易饱；国必有孝慈廉
耻之俗，则可以死易生。古者率民，必先礼信而后爵禄，先
廉耻而后刑罚，先亲爱而后律其身。故战者必本乎率身以励
众士，如心之使四肢也。志不励则士不死节，士不死节则众
不战。励士之道，民之生不可不厚也；爵列之等，死丧之亲，
民之所营，不可不显也。必也因民所生而制之，因民所营而
显之。田禄之实，饮食之亲，乡里相劝，死生相救，兵役相
从，此民之所励也。使什伍如亲戚，卒伯如朋友，止如堵墙，
动如风雨，车不结辙，士不旋踵，此本战之道也。

地所以养民也，城所以守地也，战所以守城也。故务耕者民
不饥，务守者地不危，务战者城不围。三者先王之本务也。
本务者兵最急。故先王专于兵有五焉：委积不多则士不行，
赏禄不厚则民不劝，武士不选则众不强，备用不便则力不壮，
刑赏不中则众不畏。务此五者，静能守其所固，动能成其所
欲。夫以居攻出，则居欲重，陈欲坚，发欲毕，斗欲齐。

王国富民，霸国富士，仅存之国富大夫，亡国富仓府。所谓
上满下漏，患无所救。故曰，举贤任能，不时日而事利；明
法审令，不卜筮而获吉；贵功养劳，不祷祠而得福。又曰，
天时不如地利，地利不如人和。圣人所贵，人事而已。

夫勤劳之师，将必先己。暑不张盖，寒不重衣，险必下步。
军井成而后饮，军食熟而后饭，军垒成而后舍，劳佚必以身
同之。如此，师虽久而不老不弊。

【篇旨】论战胜之道有三：道胜、威胜、力胜。强调将帅以身作则，士卒同心，方为制胜根本。

