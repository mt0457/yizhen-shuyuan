尉缭子·守权第六

凡守者，进不郭圉，退不亭障，以御战非善者也。豪杰英俊，
坚甲利兵，劲弩强矢，尽在郭中。乃收窖廪，毁拆而入保。
令客气十百倍，而主之气不半焉，敌攻者伤之甚也。然而世
将弗能知。

夫守者，不失险者也。守法：城一丈，十人守之，工食不与
焉。出者不守，守者不出。一而当十，十而当百，百而当千，
千而当万。故为城郭者，非妄费于民聚土壤也，诚为守也。
千丈之城，则万人之守。池深而广，城坚而厚，士民备，薪
食给，弩坚矢强，矛戟称之，此守法也。

攻者不下十余万之众，其有必救之军者，则有必守之城；无
必救之军者，则无必守之城。若彼城坚而救诚，则愚夫蠢妇
无不蔽城尽资血城者。期年之城，守余于攻者，救余于守者。
若彼城坚而救不诚，则愚夫蠢妇无不守陴而泣下，此人之常
情也。遂发其窖廪救抚，则亦不能止矣。必鼓其豪杰英俊，
坚甲利兵，劲弩强矢并于前，幺么毁瘠者并于后。十万之军，
顿于城下。救必开之，守必出之。出据要塞，但救其后，无
绝其粮道，中外相应。此救而示之不诚。示之不诚，则倒敌
而待之者也。后其壮，前其老，彼敌无前，守不得而止矣。
此守权之谓也。

【篇旨】论防守的策略原则，强调守城必须依托险要，内外呼应，守中有攻。

