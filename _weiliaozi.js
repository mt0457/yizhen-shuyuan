简本的出土确证了《尉缭子》为先秦著作，彻底推翻了
此前有学者怀疑其为后世伪书的说法。

简本残存篇目包括：兵谈、制谈、守权、将理、原官、
兵令等六篇的部分内容。虽非完帙，然其文献价值极高。

