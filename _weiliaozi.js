尉缭子·兵教上第二十一

兵之教令，分营居陈。有非令而进退者，加犯教之罪。前行
者，前行教之；后行者，后行教之；左行者，左行教之；右
行者，右行教之。教举五人，其甲首有赏。弗教，如犯教之
罪。罗地者自揭其伍，伍内互揭之，免其罪。

凡伍临陈，若一人有不进死于敌，则教者如犯法者之罪。凡
什保什，若亡一人，而九人不尽死于敌，则教者如犯法者之
罪。自什以上至于裨将，有不若法者，则教者如犯法者之罪。
凡明刑罚，正劝赏，必在乎兵教之法。

将异其旗，卒异其章。左军章左肩，右军章右肩，中军章胸
前。书其章曰：某甲某士。前后章各属其行。伍长教其四人，
以板为鼓，以瓦为金，以竿为旗。击鼓而进，低旗则趋；击
金而退，麾而左之，麾而右之；金鼓俱击而坐。伍长教成，
合之什长。什长教成，合之卒长。卒长教成，合之伯长。伯
长教成，合之兵尉。兵尉教成，合之裨将。裨将教成，合之
大将。大将教之，陈于中野，置大表三，百步而一。既陈，
去表百步而决，百步而趋，百步而骛。习战以成其节，乃为
之赏罚。

自尉吏而下尽有旗。战胜得旗者，各视其所得之爵，以明赏
劝之心。战胜在乎立威，立威在乎戮力，戮力在乎正罚。正
罚者，所以明赏也。令民背国门之限，决死生之分，教之死
而不疑者，有以也。令守者必固，战者必斗；奸谋不作，奸
民不语；令行无变，兵行无猜；轻者若霆，奋敌若惊。举功
别德，明如白黑，令民从上令，如四肢应心也。

前军绝行乱陈，破坚如溃者，有以也。此谓之兵教。所以开
封疆，守社稷，除患害，成武德也。

【篇旨】论军队的教育训练制度，从伍到军逐级教战，强调教者与士卒连坐的责任制。

