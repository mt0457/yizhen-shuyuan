尉缭子·原官第十

官者，事之所主，为治之本也。制者，职分四民，治之分也。
贵爵富禄，必称于尊卑之体也。好善罚恶，正比法，会计民
之具也。均地分，节赋敛，取与之度也。程工人，备器用，
匠工之功也。分地塞要，殄怪禁淫之事也。

守法稽断，臣下之节也。明法稽验，主上之操也。明主之守
也，明其等，正其法，一时之权也。官无事治，物无用备，
上无虚授，下无虚受。智士因计而处，贤者因事而虑，勇者
因变而奋。使天下各安其性，各尽其能，农工商贾皆安其业，
则兵无与为敌矣。

【篇旨】论设官分职的原则，认为官职制度是治理的根本，强调各安其位、各尽其能。

