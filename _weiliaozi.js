尉缭子·兵令下第二十四

诸去大军为前御之备者，边县列侯，各相去三五里。闻大军
为前御之备，战则皆禁行，所以安内也。内卒出戍，令将吏
授旗鼓戈甲。发日，后将吏及出县封界者，以坐后戍法。兵
戍边一岁遂亡，不候代者，法比亡军。父母妻子知之，与同
罪；弗知，赦之。卒后将吏而至大将所一日，父母妻子尽同
罪。卒逃归至家一日，父母妻子弗捕执及不言，亦同罪。

诸战而亡其将吏者，及将吏弃卒独北者，尽斩之。前吏弃其
卒而北，后吏能斩之而夺其卒者，赏。军无功者，戍三岁。
三军大战，若大将死，而从吏五百人以上不能死敌者，斩。
大将左右近卒在陈中者，皆斩。余士卒有军功者，夺一级；
无军功者，戍三岁。战亡伍人，及伍人战死不得其尸，尽夺
其功。战亡五人，及伍人战死不得其尸，同伍尽夺其功。得
其尸，罪皆赦。

军之利害，在国之名实。今名在官，而实在家，官不得其实，
家不得其名。聚卒为军，有空名无实，外不足以御敌，内不
足以守国，此军之所以不给，将之所以夺威也。臣以谓卒逃
归者，同舍伍人及吏罚入粮为饶，名为军实，是有一军之名，
而有二实之出。国内空虚，自竭民岁，曷以免奔北之祸乎？
今以法止逃归、禁亡军，是兵之一胜也。什伍相联，及战斗，
则卒吏相救，是兵之二胜也。将能立威，卒能节制，号令明
信，攻守皆得，是兵之三胜也。

臣闻古之善用兵者，能杀士卒之半。其次杀其十三，其下杀
其十一。能杀其半者，威加海内；杀十三者，力加诸侯；杀
十一者，令行士卒。故曰，百万之众不用命，不如万人之斗
也；万人之斗不用命，不如百人之奋也。赏如日月，信如四
时，令如斧钺，制如干将，士卒不用命者，未之闻也。

【篇旨】论军队的法令制度，包括戍边、逃归、阵亡等情况的处置，强调名实相符和严明赏罚。

