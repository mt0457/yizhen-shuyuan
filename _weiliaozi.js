尉缭子·兵令上第二十三

兵者，凶器也。争者，逆德也。事必有本。故王者伐暴乱，
本仁义焉。战国则以立威抗敌相图，而不能废兵也。兵者，
以武为植，以文为种。武为表，文为里。能审此二者，知胜
败矣。文所以视利害，辨安危；武所以犯强敌，力攻守也。
专一则胜，离散则败。

陈以密则固，锋以疏则达。卒畏将甚于敌者胜，卒畏敌甚于
将者败。所以知胜败者，称将于敌也。敌与将犹权衡焉。安
静则治，暴疾则乱。

出卒陈兵有常令，行伍疏数有常法。先后之次有适宜。常令
者，非追北袭邑攸用也。前后不次则失也。乱先后，斩之。
常陈皆向敌，有内向，有外向，有立陈，有坐陈。夫内向所
以顾中也，外向所以备外也，立陈所以行也，坐陈所以止也。
立坐之陈，相参进止。将在其中，坐之兵剑斧，立之兵戟弩，
将亦居中。善御敌者，正兵先合，而后扼之。此必胜之术也。

陈之斧钺，饰之旗章，有功必赏，犯令必死。存亡死生，在
枹之端。虽天下有善兵者，莫能御此矣。矢射未交，长刃未
接，前噪者谓之虚，后噪者谓之实，不噪者谓之秘。虚实秘
者，兵之体也。

【篇旨】论战争的根本原则，以文武、表里、专散论胜败，兼论阵法布置。

