尉缭子·勒卒令第十八

金、鼓、铃、旗，四者各有法。鼓之则进，重鼓则击。金之
则止，重金则退。铃，传令也。旗麾之左则左，麾之右则右。
奇兵则反是。一鼓一击而左，一鼓一击而右。一步一鼓，步
鼓也；十步一鼓，趋鼓也。音不绝，鹜鼓也。商，将鼓也；
角，帅鼓也；小鼓，伯鼓也。三鼓同，则将帅伯其心一也。
奇兵则反是。

鼓失次者有诛，喧哗者有诛，不听金鼓铃旗而动者有诛。百
人而教战，教成合之千人；千人教成，合之万人；万人教成，
会之于三军。三军之众，有分有合，为大战之法。教成试之
以阅。方亦胜，圆亦胜，错斜亦胜，临险亦胜。敌在山，缘
而从之；敌在渊，没而从之。求敌若求亡子，从之无疑，故
能败敌而制其命。

夫蚤决先定。若计不先定，虑不蚤决，则进退不定，疑生必
败。故正兵贵先，奇兵贵后。或先或后，制敌者也。世将不
知法者，专命而行，先击而勇，无不败者也。其举有疑而不
疑，其往有信而不信，其致有迟疾而不迟疾。是三者，战之
累也。

