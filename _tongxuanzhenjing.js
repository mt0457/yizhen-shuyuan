老子曰：有物混成，先天地生。惟象无形，窈窈冥冥，寂寥淡漠，不闻其声。吾强为之名，字之曰道。夫道者，高不可极，深不可测。苞裹天地，禀受无形。原流泏泏，冲而不盈。浊以静之徐清，施之无穷，无所朝夕。表之不盈一握，约而能张，幽而能明，柔而能刚。含阴吐阳，而章三光。山以之高，渊以之深。兽以之走，鸟以之飞。麟以之游，凤以之翔。星历以之行。以亡取存，以卑取尊，以退取先。古者三皇得道之统，立于中央，神与化游，以抚四方。是故能天运地滞，轮转而无废，水流而不止，与物终始。风兴云蒸，雷声雨降，并应无穷。已雕已琢，还复于朴。无为为之而合乎生死，无为言之而通乎道德，恬愉无矜而得乎和，有万不同而便乎生。和阴阳，节四时，调五行。润乎草木，浸乎金石。禽兽硕大，毫毛润泽。鸟卵不败，兽胎不殰。父无丧子之忧，兄无哭弟之哀。童子不孤，妇人不孀。虹霓不见，盗贼不行。含德之所致也。大常之道，生物而不有，成化而不宰。万物恃之而生，莫之知德；恃之而死，莫之能怨。收藏畜积而不加富，布施禀受而不益贫。忽兮恍兮不可为象兮，恍兮忽兮用不诎兮。窈兮冥兮应化无形兮，遂兮通兮不虚动兮，与刚柔卷舒兮，与阴阳俯仰兮。

老子曰：大丈夫恬然无思，憺然无虑。以天为盖，以地为车，以四时为马，以阴阳为御。行乎无路，游乎无怠，出乎无门。以天为盖则无所不覆也，以地为车则无所不载也。四时为马则无所不使也，阴阳为御则无所不备也。是故疾而不摇，远而不劳。四支不动，聪明不损。而照见天下者，执道之要观无穷之地也。故天下之事不可为也，因其自然而推之；万物之变不可究也，秉其要而归之。是以圣人内修其本而不外饰其末，厉其精神，偃其知见。故漠然无为而无不为，无治而无不治也。所谓无为者不先物为也，无治者不易自然也，无不治者因物之相然也。

老子曰：执道以御民者，事来而循之，物动而因之。万物之化无不应也，百事之变无不耦也。故道者，虚无、平易、清静、柔弱、纯粹素朴，此五者道之形象也。虚无者道之舍也，平易者道之素也，清静者道之鉴也，柔弱者道之用也。反者道之常也，柔者道之刚也，弱者道之强也。纯粹素朴者道之干也。虚者中无载也，平者心无虑也。嗜欲不载虚之至也，无所好憎平之至也，一而不变静之至也，不与物杂粹之至也，不忧不乐德之至也。夫至人之治也，弃其聪明，灭其文章，依道废智，与民同出乎公。约其所守，寡其所求，去其诱慕，除其嗜欲，损其思虑。约其所守即察，寡其所求即得。故以中制外，百事不废。中能得之，则外能牧之。中之得也，五藏宁，思虑平，筋骨劲强，耳目聪明。大道坦坦，去身不远，求之远者，往而复返。

老子曰：圣人忘乎治人，而在乎自理。贵忘乎势位，而在乎自得。自得即天下得我矣。乐忘乎富贵而在乎和，知大己而小天下，几于道矣。故曰：致虚极也，守静笃也，万物并作，吾以观其复。夫道者，陶冶万物，终始无形，寂然不动，大通混冥。深闳广大不可为外，析毫剖芒不可为内。无环堵之宇，而生有无之总名也。真人者，大己而小天下，贵治身而贱治人。不以物滑和，不以欲乱情。隐其名姓，有道则隐，无道则见。为无为，事无事，知不知也。怀大道，包天心。嘘吸阴阳，吐故纳新。与阴俱闭，与阳俱开。与刚柔卷舒，与阴阳俯仰。与天同心，与道同体。无所乐，无所苦，无所喜，无所怒。万物玄同，无非无是。

孔子问道，老子曰：正汝形，一汝视，天和将至。摄汝知，正汝度，神将来舍。德将为汝容，道将为汝居。瞳兮若新生之犊，而无求其故。形若枯木，心若死灰。真其实知而不以曲。故自持恢恢，无心可谋。明白四达，能无知乎？

老子曰：夫事生者应变而动，变生于时，知时者无常之行。故道可道，非常道；名可名，非常名。人生而静，天之性也；感物而动，性之欲也。物至而应，智之动也。智与物接，而好憎生焉。好憎成形而智出于外，不能反己而天理灭矣。是故圣人不以人易天，外与物化而内不失情。故通于道者反于清静，究于物者终于无为。以恬养智，以漠合神，即乎无门。循天者与道游也，随人者与俗交也。

老子曰：夫人从欲失性，动未尝正也。以治国则乱，以治身则秽。故不闻道者无以反其性，不通物者不能清静。原人之性无邪秽，久湛于物即易，易而忘其本，即合于其若性。水之性欲清，沙石秽之。人之性欲平，嗜欲害之。唯圣人能遗物反己。清静者德之至也，柔弱者道之用也。虚无恬愉者万物之祖也。无形者一之谓也，一者无心合于天下也。无形而有形生焉，无声而五音鸣焉，无味而五味形焉，无色而五色成焉。故有生于无，实生于虚。音者宫立而五音形矣，味者甘立而五味定矣，色者白立而五色成矣，道者一立而万物生矣。

老子曰：万物之总，皆阅一孔。百事之根，皆出一门。故圣人一度循轨，不变其故，不易其常。放准循绳，曲因其常。夫喜怒者道之邪也，忧悲者德之失也，好憎者心之过也，嗜欲者生之累也。人大怒破阴，大喜坠阳。薄气发暗，惊怖为狂。忧悲焦心，疾乃成积。人能除此五者，即合于神明。神明者得之内也。得其内者五藏宁，思虑平，耳目聪明，筋骨劲强。天下莫柔弱于水。水之道也，广不可极，深不可测。长极无穷，远沦无涯。上天为雨露，下地为润泽。万物不得不生，百事不得不成。大包群生而无私好，泽及蛟蛲而不求报。富赡天下而不既，德施百姓而不费。夫水所以能成其至德者，以其绰约润滑也。故曰：天下之至柔，驰骋天下之至坚。

老子曰：夫得道者志弱而事强，心虚而应当。志弱者柔毳安静，藏于不敢，行于不能。澹然无为，动不失时。故贵必以贱为本，高必以下为基。欲刚者必以柔守之，欲强者必以弱保之。积柔即刚，积弱即强。观其所积，以知存亡。故兵强即灭，木强即折，革强即裂。齿坚于舌而先毙。故柔弱者生之干也，坚强者死之徒也。先唱者穷之路，后动者达之原。故圣人不贵尺之璧，而贵寸之阴。时难得而易失。故圣人随时而举事，因资而立功。守清道，拘雌节。因循而应变，常后而不先。柔弱以静，安徐以定。功大靡坚，莫能与之争也。

老子曰：机械之心藏于中，即纯白之不粹。体道者佚而不穷，任数者劳而无功。夫无形大，有形细；无形多，有形少；无形强，有形弱；无形实，有形虚。有形者遂事也，无形者作始也。有形产于无形，故无形者有形之始也。有名产于无名，无名者有名之母也。夫道，有无相生也，难易相成也。是以圣人执道虚静微妙，以成其德。

老子曰：道者万物之奥，善人之宝，不善人之所保。美言可以市，尊行可以加人。人之不善，何弃之有？故立天子，置三公，虽有拱璧以先驷马，不如坐进此道。古之所以贵此道者何？不曰求以得，有罪以免邪？故为天下贵。

老子曰：道生一，一生二，二生三，三生万物。万物负阴而抱阳，冲气以为和。人之所恶，唯孤寡不谷，而王公以为称。故物或损之而益，或益之而损。人之所教，我亦教之。强梁者不得其死，吾将以为教父。天下之至柔，驰骋天下之至坚。无有入无间，吾是以知无为之有益。不言之教，无为之益，天下希及之。

老子曰：道者，虚无也。以虚无为体，以清静为用。清静者道之鉴也，虚无者道之舍也。夫道者陶冶万物，终始无形。寂然不动，大通混冥。深闳广大不可为外，析毫剖芒不可为内。无环堵之宇，而生有无之总名。是故真人用心若镜，不将不迎，应而不藏。故能胜物而不伤。

老子曰：夫道覆载万物者也，洋洋乎大哉。君子不可不刳心焉。无为为之之谓天，无为言之之谓德。爱人利物之谓仁，不同同之之谓大，行不崖异之谓宽，有万不同之谓富。故执德之谓纪，德成之谓立，循于道之谓备，不以物挫志之谓完。君子明于此十者，则韬乎其事心之大也，沛乎其为万物逝也。若然者，藏金于山，藏珠于渊，不利货财，不近贵富，不乐寿，不哀夭，不荣通，不丑穷。不拘一世之利以为己私分，不以王天下为己处显，显则明。万物一府，死生同状。

老子曰：夫道，于大不终，于小不遗，故万物备。广广乎其无不容也，渊渊乎其不可测也。形德仁义，神之末也，非至人孰能定之？夫至人有世，不亦大乎，而不足以为之累。天下奋棅而不与之偕，审乎无假而不与利迁。极物之真，能守其本。故外天地，遗万物，而神未尝有所困也。通乎道，合乎德，退仁义，摈礼乐，至人之心有所定矣。

老子曰：世之学者多辩，行于天下，反以惑人。至人之学，欲以反性于无，游心于虚。世人之学，摇荡精神，劳苦心志。至人之学，静漠恬惔，抱德炀和。是故通于道者，如车轴运于毂中，不致远迹，而致千里之远，转无穷之原也。圣人体道，反至清静，究物之变，终于无为。万物之化，无不应也。百事之变，无不耦也。

