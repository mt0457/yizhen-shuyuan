老子曰：天致其高，地致其厚。日月照，列星朗。阴阳和，非有为焉，正其道而物自然。阴阳四时非生万物也，雨露时降非养草木也。神明接，阴阳和，万物生矣。夫道者，藏精于内，栖神于心。静漠恬惔，悦穆胸中。廓然无形，寂然无声。官府若无事，朝廷若无人。无隐士，无逸民。无劳役，无怨刑。天下莫不仰上之德，象主之旨。绝国殊俗莫不重译而至，非家至而人见之也。推其诚心施之天下而已。故赏善罚暴者，正令也；其所以能行者，精诚也。令虽明不能独行，必待精诚。

老子曰：天设日月，列星辰，张四时，调阴阳。日以暴之，夜以息之，风以干之，雨露以濡之。其生物也，莫见其所养而万物长；其杀物也，莫见其所丧而万物亡。此谓神明。是故圣人象之。其起福也，不见其所以而福起；其除祸也，不见其所由而祸除。稽之不得，察之不虚。日计不足，岁计有余。寂然无声，一言而大动天下，是以天心动化者也。故精诚内形，气动于天。景星见，黄龙下，凤皇至，醴泉出，嘉谷生，河不满溢，海不波涌。天之与人，有以相通。故大人与天地合德，与日月合明，与鬼神合灵，与四时合信。怀天心，抱地气。执冲含和，不下堂而行四海。变易习俗，民化迁善，若生诸己，能以神化者也。

老子曰：夫人道者，全性保真，不亏其身。遭急迫难，精通乎天。若乃未始出其宗者，何为而不成。死生同域，不可胁凌。又况官天地，怀万物，返造化，含至和，而已未尝死者也。精诚形乎内，而外喻于人心，此不传之道也。圣人在上，怀道而不言，泽及万民。故不言之教，芒乎大哉。天道无私就也，无私去也。能者有余，诎者不足。顺之者利，逆之者凶。是故以智为治者难以持国，唯同乎大和而持自然应者，为能有之。

老子曰：夫道之与德，若韦之与革。远之即近，近之即疏。稽之不得，察之不虚。是故圣人若镜，不将不迎，应而不藏，万物而不伤。其得之也，乃失之也。其失之也，乃得之也。故通于大和者，闇若醇醉而甘卧以游其中，若未始出其宗，是谓大通。

老子曰：昔黄帝之治天下，调日月之行，治阴阳之气。节四时之度，正律历之数。别男女，明上下。使强不掩弱，众不暴寡。民保命而不夭，岁时熟而不凶。百官正而无私，上下调而无尤。法令明而不闇，辅佐公而不阿。田者让畔，道不拾遗，市不预贾。故于此时，日月星辰不失其行，风雨时节，五谷丰昌。凤皇翔于庭，麒麟游于郊。然而不章其功，不扬其名。隐真人之道，以从天地之固然。何即道德上通，而智故消灭也。

老子曰：天不定日月无所载，地不定草木无所立，身不宁是非无所形。是故有真人而后有真智。积惠重货，使万民欣欣，人乐其生者，仁也。举大功，显令名，体君臣，正上下，明亲疏，存危国，继绝世，立无后者，义也。闭九窍，藏志意，弃聪明，反无识，芒然仿佯乎尘垢之外，逍遥乎无事之业，含阴吐阳而与万物同和者，德也。是故道散而为德，德溢而为仁义，仁义立而道德废矣。

老子曰：神越者言华，德荡者行伪。至精芒乎中，而言行观乎外，此不免以身役物也。精有愁尽而行无穷极，所守不定而外淫于世俗之风。是故圣人内修道术而不外饰仁义，知九窍四支之宜，而游乎精神之和，此圣人之游也。

老子曰：人主之思，神不驰于胸中，智不出于四域。怀其仁诚之心，甘雨以时，五谷蕃殖。春生夏长，秋收冬藏。月省时考，终岁献贡。养民以公，威厉以诚。法省不烦，教化如神。法宽刑缓，囹圄空虚。天下一俗，莫怀奸心。此圣人之思也。夫上好取而无量，即下贪功而无让。民贫苦而分争生事，力劳而无功。智诈萌生，盗贼滋彰。上下相怨，号令不行。夫水浊者鱼噞，政苛者民乱。上多欲即下多诈，上烦扰即下不定。不治其本而救之于末，无以异于凿渠而止水，抱薪而救火。圣人事省而治，求寡而赡。不施而仁，不言而信，不求而得，不为而成。怀自然，保至真，抱道推诚。天下从之如响之应声，影之像形。所修者本也。

老子曰：精神越于外，智虑荡于内者，不能治形。神之所用者远，则所遗者近。故不出于户以知天下，不窥于牖以知天道。其出弥远，其知弥少。此言精诚发于内，神气动于天也。

老子曰：冬日之阳，夏日之阴。万物归之而莫之使极。自然至精之感，弗召自来，不去而往。窈窈冥冥，不知所为者而功自成。待目而照见，待言而使命，其于治难矣。皋陶喑而为大理，天下无虐刑，有贵乎言者也。师旷瞽而为太宰，晋国无乱政，有贵乎见者也。不言之令，不视之见，圣人所以为师也。民之化上，不从其言从其所行。故刑罚不足以移风，杀戮不足以禁奸。唯神化为贵，精至为神。精之所动，若春气之生，秋气之杀。

老子曰：悬法设赏而不能移风易俗者，诚心不抱也。故听其音则知其风，观其乐即知其俗，见其俗即知其化。夫抱真效诚者，感动天地，神逾方外。令行禁止，诚通其道而达其意。虽无一言，天下万民、禽兽、鬼神与之变化。

老子曰：大道无为，无为即无有。无有者不居也，不居者即处无形。无形者不动，不动者无言也。无言者即静而无声无形。无声无形者，视之不见，听之不闻。是谓微妙，是谓至神。绵绵若存，是谓天地根。

老子曰：心之精者，可以神化，而不可说道。圣人不降席而匡天下。故同言而信，信在言前也。同令而行，诚在令外也。信，君子之言。忠，君子之意。忠信形于内，感动应乎外，贤圣之化也。

老子曰：圣人之从事也，所由异路而同归。存亡定倾若一，志不忘乎欲利人也。故秦楚燕魏之歌，异声而皆乐。九夷八狄之哭，异声而皆哀。夫歌者乐之征，哭者哀之效也。愔于中，发于外，故在所以感之矣。圣人之心，日夜不忘乎欲利人，其泽之所及亦远矣。

文子曰：至人精诚内形，德流四方。见天下有利也，喜而不忘；天下有害也，忧若有丧。夫忧民之忧者，民亦忧其忧；乐民之乐者，民亦乐其乐。故忧以天下，乐以天下，然而不王者，未之有也。圣人之法，始于不可见，终于不可及。处于不倾之地，积于不尽之仓，载于不竭之府。出令如流水之原，使民于不争之官。开必得之门，不为不可成，不求不可得。

老子曰：天道至精，无形无状。不雄不雌，不壮不老。不大不小，不长不短。不方不圆，不柔不刚。不白不黑，不先不后。不有不无。视之不见，听之不闻。搏之不得，言之不形。不可为象，不可为状。其所以然者，以其至大无外，至小无内也。故大人者，与天地合其德，与日月合其明，与鬼神合其吉凶。先天而天弗违，后天而奉天时。天且弗违，而况于人乎？况于鬼神乎？

老子曰：夫至人之精诚也，非一日之积也。积之也久，故感之也深。精诚积于中，神明应于外。不求而自至，不召而自来。故曰：精诚者天之道也，诚之者人之道也。诚者不勉而中，不思而得。从容中道，圣人也。诚之者，择善而固执之者也。博学之，审问之，慎思之，明辨之，笃行之。有弗学，学之弗能弗措也。有弗问，问之弗知弗措也。有弗思，思之弗得弗措也。有弗辨，辨之弗明弗措也。有弗行，行之弗笃弗措也。人一能之己百之，人十能之己千之。果能此道矣，虽愚必明，虽柔必强。

通玄真经·卷三·九守篇

老子曰：天地未形，窈窈冥冥。浑而为一，寂然清澄。重浊为地，精微为天。离而为四时，分而为阴阳。精气为人，粗气为虫。刚柔相成，万物乃生。精神本乎天，骨骸根于地。精神入其门，骨骸反其根。我尚何存？故圣人法天顺地，不拘于俗，不诱于人。以天为父，以地为母，阴阳为纲，四时为纪。天静以清，地定以宁。万物逆之者死，顺之者生。故静漠者神明之宅，虚无者道之所居。

老子曰：人受天地变化而生。一月而膏，二月血脉，三月而胚，四月而胎，五月而筋，六月而骨，七月而成形，八月而动，九月而躁，十月而生。形骸已成，五藏乃分。头圆法天，足方象地。天有四时五行九曜三百六十日，人有四支五藏九窍三百六十节。天有风雨寒暑，人有取与喜怒。人与天地相类，而心为之主。耳目者日月也，血气者风雨也。日月失行，薄蚀无光；风雨非时，毁坼生灾。天地之道，至闳以大，尚犹节其章光，爱其神明。人之耳目，何能久熏而不息？精神何能驰骋而不乏？是故圣人守内而不失外。夫孔窍者精神之户牖，血气者五藏之使候。故耳目淫于声色，即五藏摇动而不定，血气滔荡而不休，精神驰骋而不守。故五色乱目，使目不明；五音乱耳，使耳不聪；五味乱口，使口生创；趣舍滑心，使行飞扬。故嗜欲使人气淫，好憎使人精劳。不疾去之，则志气日耗。夫人所以不能终其天年者，以其生生之厚。夫惟无以生为者，即所以得长生。天地运而相通，万物总而为一。能知一，即无一之不知也；不能知一，即无一之能知也。

【守虚】老子曰：所谓圣人者，因时而安其位，当世而乐其业。夫哀乐者德之邪，好憎者心之累，喜怒者道之过。故其生也天行，其死也物化。静即与阴合德，动即与阳同波。故心者形之主也，神者心之宝也。形劳而不休即蹶，精用而不已则竭。是以圣人遵之不敢越也。以无应有，必究其理；以虚受实，必穷其节。恬愉虚静，以终其命。无所疏，无所亲。抱德炀和，以顺于天。与道为际，与德为邻。不为福始，不为祸先。死生无变于己，故曰至神。

【守无】老子曰：轻天下即神无累，细万物即心不惑。齐生死则意不慑，同变化则明不眩。夫至人倚不桡之柱，行无关之途。禀不竭之府，学不死之师。无往而不遂，无之而不通。屈伸俯仰，抱命不惑。祸福利害，不足以患心。夫为义者，可迫以仁而不可劫以兵，可正以义而不可悬以利。君子死义，不可以富贵留也。无为者即无累，无累之人以天下为影柱。

【守平】老子曰：尊势厚利，人之所贪，比之身则贱。故圣人食足以充虚接气，衣足以盖形御寒。适情辞余，不贪得，不多积。清目不视，静耳不听，闭口不言，委心不虑。弃聪明，反太素，休精神，去知故。无好无憎，是谓大通。除秽去累，莫若未始出其宗，何为而不成？知养生之和者，即不可悬以利；通内外之符者，不可诱以势。无外之外至大，无内之内至贵。能知大贵，何往不遂？

【守易】老子曰：古之为道者，理情性，治心术。养以和，持以适。乐道而忘贱，安德而忘贫。性有不欲，无欲而不得；心有不乐，无乐而不为。无益于性者不以累德，不便于生者不以滑和。不纵身肆意，而制度可以为天下仪。量腹而食，制形而衣，容身而居，适情而行。余天下而不有，委万物而不利。岂为贫富贵贱失其性命哉！

【守清】老子曰：人受气于天者，耳目之于声色也，鼻口之于芳臭也，肌肤之于寒温也，其情一也。或以死，或以生，或为君子，或为小人，所以为制者异。神者智之渊也，神清则智明。智者心之府也，智公则心平。人莫鉴于流潦而鉴于澄水，以其清且静也。故神清意平，乃能形物之情。故治天下者，必达性命之情而后可也。

【守真】老子曰：夫所谓圣人者，适情而已。量腹而食，度形而衣。节乎己，而贪污之心无由生也。故能有天下者，必无以天下为也。能有名誉者，必不以越行求之。诚达性命之情，仁义因附也。若夫神无所掩，心无所载。通洞条达，澹然无事。势利不能诱，声色不能淫。辩者不能说，智者不能动，勇者不能恐。此真人之游也。

【守静】老子曰：静漠恬惔，所以养生也；和愉虚无，所以据德也。外不乱内即性得其宜，静不动和即德安其位。养生以经世，抱德以终年，可谓能体道矣。血脉无郁滞，五藏无积气。祸福不能矫滑，非誉不能尘垢。夫目察秋毫之末者，耳不闻雷霆之声；耳调金玉之音者，目不见太山之形。故小有所志，则大有所忘。人之精神，难清而易浊，犹盆水也。

【守法】老子曰：上圣法天，其次尚贤，其下任臣。任臣者危亡之道也，尚贤者痴惑之原也，法天者治天地之道也。虚静为主，虚无不受，静无不持。知虚静之道，乃能终始。故圣人以静为治，以动为乱。故曰：勿挠勿撄，万物将自清；勿惊勿骇，万物将自理。是谓天道也。

【守弱】老子曰：天子公侯，以天下一国为家，以万物为畜。怀天下之大，有万物之多，即气实而志骄。大者用兵侵小，小者倨傲凌下。用心奢广，譬犹飘风暴雨，不可长久。是以圣人以道镇之，执一无为而不损冲气。见小守柔，退而勿有。法于江海，江海不为，故功名自化。弗强故能成其王，为天下牝故能神不死。天道极即反，盈即损，日月是也。故圣人日损而冲气不敢自满，日进以牝，功德不衰，天道然也。圣人法天，弗为而成，弗执而得。与人同情而异道，故能长久。故三皇五帝有戒之器，命曰侑卮，其冲即正，其盈即覆。夫物盛则衰，日中则移，月满则亏，乐终而悲。是故聪明广智守以愚，多闻博辩守以俭，武力勇毅守以畏，富贵广大守以狭，德施天下守以让。此五者，先王所以守天下也。服此道者不欲盈，夫唯不盈，是以弊不新成。

【守朴】老子曰：所谓真人者，性合乎道也。故有而若无，实而若虚。治其内不治其外。明白太素，无为而复朴。体本抱神，以游天地之根。芒然仿佯尘垢之外，逍遥乎无事之业。机械智巧，不载于心。审于无假，不与物迁。见事之化，而守其宗。心意专于内，通达祸福于一。居不知所为，行不知所之。感而应，迫而动。如光之耀，如影之效。以道为循，廓然而虚，清静而无。以千生为一化，以万异为一宗。其寐不梦，其智不萌。其动无形，其静无体。存而若亡，生而若死。精神之所能登假于道。使精神畅达而不失于元，日夜无隙而与物为春。故形有靡而神未尝化。以不化应化，千变万转而未始有极。此真人之游纯粹素道。

老子曰：九守者，守虚、守无、守平、守易、守清、守真、守静、守法、守弱、守朴也。此九者，修身治世之要道也。守虚则能容，守无则能生，守平则能和，守易则能久，守清则能明，守真则能固，守静则能安，守法则能治，守弱则能强，守朴则能全。圣人执此十守，以应万物，故无往而不通也。夫人之所以不能守者，以外物惑之也。声色滋味，权势名利，此皆伐性之斧、伤身之贼也。圣人去彼取此，故能长久。

老子曰：夫守者，非徒闭门塞窦也。心有所守，则万变不扰。神有所守，则众邪不入。志有所守，则利害不移。夫守虚者，不以盈满害其虚也。守无者，不以有累害其无也。守平者，不以好憎害其平也。守易者，不以难行害其易也。守清者，不以浊秽害其清也。守真者，不以伪饰害其真也。守静者，不以躁动害其静也。守法则，不以私枉害其法也。守弱者，不以强梁害其弱也。守朴者，不以文华害其朴也。是故圣人终日行不离辎重，虽有荣观，燕处超然。奈何万乘之主，而以身轻天下？轻则失本，躁则失君。

通玄真经·卷四·符言篇

老子曰：道至高无上，至深无下。平乎准，直乎绳，圆乎规，方乎矩。包裹宇宙而无表里，洞同覆载而无所碍。是故体道者不怒不喜，其居也若无，其动也若拙。

老子曰：欲治天下，必先正身。身者国之本也。正身有道，其本在诚。诚者天道也。天道无为，而万物自化。

老子曰：人之情，心服于德，不服于力。德在与，不在求。是以圣人之欲贵于人者，先贵于人；欲尊于人者，先尊于人；欲胜人者，先自胜。

老子曰：夫有德者，内治于己，外治于人。内治于己者，存乎精诚；外治于人者，存乎法术。精诚形乎内，法术应乎外。内治则身安，外治则人安。

老子曰：山生金，石生玉。反相剥蚀，非有期会而自然至。君子非有远虑，而患害不及身。诚心正行，而祸福自转也。

老子曰：圣人无屈奇之服，诡异之行。服不杂，行不观。通而不华，穷而不慑。荣而不显，隐而不辱。异而不怪，同而不随。用而不匮，张而不费。是谓全德。

老子曰：言者所以通己于人也，闻者所以通人于己也。既暗且聋，与人道绝。人无言而神，有言也即伤。故至人去言，大圣无为。

老子曰：道者守其所已有，不求其所以未得。求其所未得，即所有者亡。修其所已有，即所欲者至。故治未固于不乱，而事为治者必危。行未固于无非，而急求名者必挫。福莫大于无祸，利莫大于不丧。

老子曰：善游者溺，善骑者堕。各以其所好，反自为祸。是以圣人内修其本，而不外饰其末。无为者，不先物为也。无治者，不易自然也。无不治者，因物之相然也。

老子曰：天地之道，以恬愉为务，以自得为功。神明接，道自生焉。夫水之势胜火，一勺不能救一车之薪。金之势胜木，一刃不能残一林。土之势胜水，一掬不能塞一河。是故圣人因天地之自然，而不敢为。

老子曰：出言必信，则令不穷。为行必正，则身不辱。行不正则民不服，言不信则令不行。是故言出于口，不可止于人。行发于近，不可禁于远。君子重其言行，言行者，立身之基也。

老子曰：日月欲明，浮云蔽之。河水欲清，沙石秽之。人性欲平，嗜欲害之。唯圣人能遗物反己。是故圣人内藏于不测之地，外游于无为之境。不以人易天，不以欲乱情。守其一以处其和。故能通乎道而合乎德也。

老子曰：德少而宠多者危，才下而位高者殆。无德而尊，无才而任，其为祸也必矣。故君子知微知彰，知柔知刚，万夫之望。

老子曰：凡人之道，心欲小，志欲大。智欲圆，行欲方。能欲多，事欲少。所谓心小者，虑患未生，戒祸慎微，不敢纵其欲也。志大者，兼包万国，一齐殊俗，是非辐凑中为之毂也。智圆者，终始无端，方流四远，渊泉而不竭也。行方者，立直而不挠，素白而不污，穷不易操，达不肆志也。能多者，文武备具，动静中仪，举措废置，曲得其宜也。事少者，秉要以偶众，执约以治广，处静以持躁也。

老子曰：心之精者，可以神化，而不可说道。圣人不降席而匡天下，情甚于言也。同言而信，信在言前也。同令而行，诚在令外也。圣人在上，民化如神，情以先之也。动于上不应于下者，情令殊也。

老子曰：时之行也，不可追及。已去不可止，将来不可待。得时则昌，失时则亡。善者见利不失，遭时不疑。失利后时，反受其殃。智者不倍时而弃利，勇士不怯死而灭名。

老子曰：上善若水，水善利万物而不争。处众人之所恶，故几于道。居善地，心善渊，与善仁，言善信，政善治，事善能，动善时。夫唯不争，故无尤。天下柔弱莫过于水，而攻坚强者莫之能胜，以其无以易之也。

老子曰：明主不用其智，而任圣人之智。不用其力，而任众人之力。故以圣人之智思虑者，无不知也。以众人之力起事者，无不成也。能自得师者王。谓人莫己若者亡。好问则裕，自用则小。

老子曰：其施厚者其报美，其怨大者其祸深。薄施而厚望，蓄怨而无患者，古今未之有也。故圣人度己以绳，接人用枻。夫度己以绳故足以为天下法则，接人用枻故能宽容因众。与众同和，则无不得也。

老子曰：人皆以无用害有用。故知无用之言，而不知无用之用也。知无用而始可与言用矣。夫天地不包一物，阴阳不产一类。海不让水潦以成其大，山不让土石以成其高。圣人不辞其言以成其名。

通玄真经·卷五·道德篇

老子曰：道者物之所道也，德者生之所扶也。道者万物之元也，德者万物之容也。道生之，德畜之。长之育之，亭之毒之，养之覆之。生而不有，为而不恃，长而不宰，是谓玄德。

文子问曰：夫子之言，非道德无以治天下。上世之王，继嗣相因，其法籍有存者，可得闻乎？

老子曰：上古之世，其民童蒙，不知东西。貌不离情，行不越轨。言不逾德，动不合义。其心愉然而无伪，其事简素而无饰。是以圣人执道而治，无为而化。

文子问德。老子曰：畜之养之，遂之长之。兼利无择，与天地合，是之谓德。

文子问仁。老子曰：为上不矜其功，为下不羞其病。于大不矜，于小不偷。兼爱无私，是谓仁也。

文子问义。老子曰：为上则辅弱，为下则守节。循理而动，不系于物。不苟其得，不避难险。是谓义也。

文子问道。老子曰：天之道，其犹张弓乎？高者抑之，下者举之。有余者损之，不足者与之。天之道损有余而补不足。人之道则不然，损不足以奉有余。孰能有余以奉天下？唯有道者。

老子曰：夫道德者，所以相生养也。所以相畜长也，所以相亲爱也，所以相敬贵也。夫聋虫虽愚，不害其所爱。诚使天下之民，皆怀仁爱之心，祸害何由生乎？

老子曰：至德之世，贾便其市，农乐其野。大夫安其职，处士修其道。人民乐其业。是以风雨不毁折，草木不夭死。河出图，洛出书。及世之衰也，赋敛无度，杀戮无止。故世治则小人守正，而利不能诱也。世乱则君子为奸，而法不能禁也。

文子问曰：古之王者，以道莅天下，为之奈何？

老子曰：执一无为，因天地之自然，与之俯仰。天下，大器也，不可执也，不可为也。为者败之，执者失之。执一者，见小也。见小故能成其大也。无为者，守静也。守静能为天下正。处大，满而不溢。居高，贵而无骄。处大不溢，盈而不亏。居上不骄，高而不危。盈而不亏，所以长守富也。高而不危，所以长守贵也。富贵不离其身，禄及子孙，古之王道，其于此矣。

老子曰：民有道所同行，有法所同守。义不能相固，威不能相必，故立君以一之。君执一即治，无常即乱。君道者，非所以有为也，所以无为也。智者不以德为事，勇者不以力为暴，仁者不以位为惠。可谓一矣。一也者，无适之道也，万物之本也。

老子曰：至人之治也，心与神处，形与性调。静而体德，动而理通。循自然之道，缘不得已之符。安静者道之素也，虚无者道之舍也。为治之本，务在安民。安民之本，在于足用。足用之本，在于勿夺时。勿夺时之本，在于省事。省事之本，在于节用。节用之本，在于去骄奢。去骄奢，在于虚无。虚无者，道之所居也。是故道立而万物生，道废而万物衰。圣人得之，以治天下。

文子问曰：仁义礼何以薄于道德？

老子曰：为仁者必以哀乐论之，为义者必以取与明之。四海之内，哀乐不能遍，竭府库之财货不足以赡万民。故知不如修道而行德。因天地之性，万物自正而天下赡，仁义因附也。是以大丈夫居其厚不居其薄。

老子曰：夫道者，无为无形，可传而不可受，可得而不可见。自本自根，未有天地，自古以固存。神鬼神帝，生天生地。在太极之先而不为高，在六极之下而不为深。先天地生而不为久，长于上古而不为老。

文子问曰：何以得道？

老子曰：学道者，损之又损，以至于无为。无为而无不为。取天下常以无事，及其有事，不足以取天下。为学日益，为道日损。损之又损，以至于无为。无为而无不为矣。故圣人云：我无为而民自化，我好静而民自正，我无事而民自富，我无欲而民自朴。

老子曰：夫慈，以战则胜，以守则固。天将救之，以慈卫之。我有三宝，持而保之。一曰慈，二曰俭，三曰不敢为天下先。慈故能勇，俭故能广，不敢为天下先故能成器长。今舍慈且勇，舍俭且广，舍后且先，死矣。夫慈，以战则胜，以守则固。天将救之，以慈卫之。

老子曰：善为士者不武，善战者不怒，善胜敌者不与，善用人者为之下。是谓不争之德，是谓用人之力，是谓配天古之极。用兵有言：吾不敢为主而为客，不敢进寸而退尺。是谓行无行，攘无臂，扔无敌，执无兵。祸莫大于轻敌，轻敌几丧吾宝。故抗兵相加，哀者胜矣。

通玄真经·卷六·上德篇

老子曰：主者，国之心也。心治则百节皆安，心扰则百节皆乱。故其身治者，支体相遗也；其国治者，君臣相忘也。

老子曰：道以无有为体。视之不见其形，听之不闻其声，谓之幽冥。幽冥者，所以论道而非道也。夫道者，内视而自反，反于太素，体于自然。

老子曰：天之道，不争而善胜，不言而善应，不召而自来，繟然而善谋。天网恢恢，疏而不失。

老子曰：日者天之阳也，月者天之阴也。星辰者天之正也，三光者天之明也。四时者天之信也，五行者天之理也。圣人法天而治天下。

老子曰：高莫高于天，下莫下于泽。天高泽下，圣人法之。尊卑有制，天下定矣。地载万物而长之，圣人不宰万物而任之。任万物者，因天下之自为也，故能无不为。

老子曰：山高者基扶，道高者德辅。故天道无私就也，无私去也。能者有余，拙者不足。顺之者利，逆之者凶。

老子曰：天覆万物，施其德而养之。地载万物，因其性而长之。圣人因天地之自然，而不敢为。故能覆载万物，与天地相参。

老子曰：夫至人之德也，犹天之道也。不言而信，不令而行。不为而成，自然而应。感而后动，迫而后应。不得己而后起。故去知与故，循天之理。天无私覆，地无私载。日月无私照，雨露无私润。圣人无私惠，国乃治矣。

老子曰：天地之气，莫大于和。和者阴阳调，日夜分而生物。春分而生，秋分而成。生之与成，必得和之精。故积阴不生，积阳不化。阴阳交接，乃能成和。是以圣人之道，宽而栗，严而温，柔而直，猛而仁。夫太刚则折，太柔则卷。道正在于刚柔之间。

老子曰：天行有常，不为尧存，不为桀亡。应之以治则吉，应之以乱则凶。强本而节用，则天不能贫。养备而动时，则天不能病。修道而不贰，则天不能祸。故水旱不能使之饥，寒暑不能使之疾，妖怪不能使之凶。本荒而用侈，则天不能使之富。养略而动罕，则天不能使之全。背道而妄行，则天不能使之吉。

老子曰：天之生物，必因其材而笃焉。故栽者培之，倾者覆之。种善得福，种恶得祸。祸福之应，如影随形，如响随声。上天之载，无声无臭。仪形文王，万邦作孚。是以圣人不求福而福自来，不避祸而祸自远。

老子曰：怒出于不怒，为出于不为。视于无有，则得所不见。听于无声，则得所不闻。夫至明者视于无形，至聪者听于无声。故目之所不见，非无形也。耳之所不闻，非无声也。心之所不知，非无理也。慎终如始，则无败事矣。

老子曰：天有明，不忧民之晦也，百姓开户而自见之。地有财，不忧民之贫也，百姓斩木而自取之。圣人无为，不忧民之不化也，百姓顺道而自成之。故上德若谷，广德若不足，建德若偷，质真若渝。大白若辱，大方无隅，大器晚成，大音希声，大象无形，道隐无名。夫唯道，善贷且成。

老子曰：冬日之扇，夏日之裘，无用于己，则万物变为尘埃矣。故以道观之，万物一也。以俗观之，贵贱差等。以道观之，无贵无贱。以物观之，自贵而相贱。以俗观之，贵贱不在己。以道观之，玄同无别。是故圣人不以人易天，不以物乱心。

老子曰：天静以清，地定以宁。万物之生也，各以其类。圣人体天，法其清静。清静者，万物之鉴也。天不为一物枉其时，明君不为一事易其法。故道之在天下也，犹江海之与川谷。江海处下，故能为百谷王。圣人处上，能柔其心，故为天下贵。

通玄真经·卷七·微明篇

老子曰：人能知一，万事毕。一心之所通，万物皆通。一心之所迷，万物皆迷。是故圣人执一以为天下牧。

老子曰：道可以弱，可以强；可以柔，可以刚；可以阴，可以阳；可以幽，可以明。可以苞裹天地，可以应待无方。道不可以言传，不可以智索。唯神会于心者，可以得之。

老子曰：见本而知末，观指而睹归。执一而应万，握要而治详。是谓术也。居知所以为，行知所之。事知所乘，动知所止。是谓道也。

老子曰：相去远者，其言也深；相去近者，其言也浅。是故圣人之言，微妙而难知。众人之见，浅近而易见。

老子曰：凡人之患，蔽于一曲而暗于大理。治天下者，当观其大略。不察秋毫，而明于日月之照；不视掌中，而见天地之广大。

老子曰：人皆知救患，莫知使患无生。夫使患无生，易于救患。今不务使患无生，而务于救之，虽圣人不可以为谋。

老子曰：天地之气，莫大于和。和者，阴阳调，日夜分。故万物春分而生，秋分而成。生与成，必得和之精。故积阴不生，积阳不化。阴阳交接，乃能成和。

老子曰：道者，寂寞以虚无。非有为于物也，不以有为于己也。是故举事而顺于道者，非道者之所为也，道之所施也。

老子曰：夫行道者，使人虽勇，刺之不入；虽巧，击之不中。夫刺之不入，击之不中，而犹辱也，未若使人虽勇不敢刺，虽巧不敢击。夫不敢者，非无其意也，未若使人无其意。夫无其意者，未有爱利之心也。不若使天下丈夫女子，莫不欢然皆欲爱利之。若然者，无地而为君，无官而为长。

老子曰：相马者失之瘦，相士者失之贫。以贫贱论士，则无士矣。以瘦论马，则无马矣。故明主之用人也，不以卑贱而弃之，不以微陋而遗之。择其能者而用之，量其才而任之。天下无弃人，无弃物矣。

老子曰：天地之道，利而不害。圣人之道，为而不争。故与时争者昌，与天地争者亡。善用人者，为之下。是谓不争之德。是谓用人之力。是谓配天古之极。

老子曰：凡万物之变，皆有由也。其生也，莫知其所以生。其成也，莫知其所以成。故明于微者，不惑于事。知于始者，不忧于终。见微知著，见始知终。非天下之至神，其孰能与于此？

老子曰：道之大也，天地不能载。道之小也，毫末不能遗。存而若亡，实而若虚。故圣人处物不伤物，应事不乱事。事之至也，因其自然之势；物之来也，顺其本然之性。不先物动，不后事起。感而后应，迫而后动。其应也不失其和，其动也不失其理。

老子曰：夫狂者伤于热，寒者伤于冷。伤于热者发于内，伤于冷者感于外。治热以寒，治寒以热。治内以养，治外以御。知此四者，可以调天下矣。

老子曰：天有五色，地有五行。人有五藏，事有五变。五色不乱，目乃明。五音不乱，耳乃聪。五藏不乱，身乃康。五变不乱，事乃成。是以圣人审于五者之间，察于变化之微。

老子曰：道不可闻，闻而非也。道不可见，见而非也。道不可言，言而非也。知形形之不形乎，道不当名。夫问道者不能得道，不知所以问此道者。故善言道者无闻，善见道者无视。道之在天下，犹川谷之于江海也。

老子曰：曲则全，枉则直，洼则盈，敝则新，少则得，多则惑。是以圣人抱一为天下式。不自见故明，不自是故彰，不自伐故有功，不自矜故长。夫唯不争，故天下莫能与之争。古之所谓曲则全者，岂虚言哉！诚全而归之。

老子曰：知不知上，不知知病。夫唯病病，是以不病。圣人不病，以其病病，是以不病。知者不言，言者不知。塞其兑，闭其门，挫其锐，解其纷，和其光，同其尘，是谓玄同。

通玄真经·卷八·自然篇

老子曰：天地之道，以自然为体，以无为为用。道生万物，理于有无，化于阴阳。清者上为天，浊者下为地。天地相合，而降甘露。民莫之令而自均。

老子曰：朴至大者无形状，道至妙者无度量。故天之圆也不中规，地之方也不中矩。自古及今，其名不去，以阅众甫。

老子曰：圣人忘乎治人，而在乎自治。贵忘乎势位，而在乎自得。自得即天下得我矣。其自治也，不待法而正。其自得也，不待赏而劝。

老子曰：夫道者至精之感也。不言而信，不令而从。舟浮江海，不为莫乘而沉。君子行道，不为莫知而止。性之所在也。

老子曰：天之所覆，地之所载。日月所照，雨露所润。道德所扶，天地所生。万物并育而不相害，道并行而不相悖。夫德者，不自有其功，不自持其力。

老子曰：古之善为君者，法于江海。江海无为以成其大，窊下以成其广。故能长久。为天下溪，其德不离。为天下谷，其德乃足。

老子曰：天道无私，去知与故。天道无亲，唯德是与。道者，虚无、平易、清静、柔弱、纯粹素朴。此五者，道之形也。圣人法天，贵清静而贱躁扰。

老子曰：所谓道者，无状之状，无物之象。无状之状者，视之不见而能形物。无物之象者，听之不闻而能应物。是故道者，万物之始，是非之纪也。是以明君守之，以治天下。其治也，不尚贤，不使能。上如标枝，民如野鹿。端正而不知以为义，相爱而不知以为仁，实而不知以为忠，当而不知以为信，蠢动而相使不以为赐。是故行而无迹，事而无传。

老子曰：清静者德之至也，柔弱者道之用也。虚无恬愉者万物之祖也。三者行，则沦于无形。无形者，一之谓也。一者，无心合于天下也。布德不溉，用之不勤。视之不见，听之不闻。无形而有形生焉，无声而五音鸣焉，无味而五味形焉，无色而五色成焉。故有生于无，实生于虚。善之于不善，相去何若？

老子曰：天致其高，地致其厚。圣人法之，德无不被。天之道，不争而善胜。不言而善应。不召而自来。繟然而善谋。天网恢恢，疏而不失。圣人之道，渊乎莫测。心与天游，身与道合。百姓日用而不知，万物资焉而不匮。

老子曰：夫至人者，因天地之自然，循道理以行。不造事端，不谋智巧。藏其用于不用，伏其功于无功。春生夏长，秋收冬藏。取予有节，出入有时。不开人之天，而开天之天。开天者德生，开人者贼生。圣人不厌于天，不忽于人。不谋于物，不诈于情。

老子曰：天地任自然，无为无造。万物自相治理，故不仁也。仁者必忧，忧则万物不遂矣。是以圣人不仁，大仁不仁。百川学海而至于海，丘陵学山而不至于山。故恶迹者不可以止足，恶死者不可以养生。唯体自然者能得之。

老子曰：春风至则甘雨降，生育万物。羽者妪伏，毛者孕育。草木荣华，鸟兽卵胎。莫见其为者，而功既成矣。秋风至则霜露降，草木凋落，鸟兽毛毨。莫见其为者，而万物已杀矣。天运四时而化万物，非有心于生物也，非有心于杀物也。感而后应，迫而后动。不得已而生，不得已而死。此天地之所以为大也。

老子曰：夫道者，无为无形。生而不有，为而不恃。天地之所由生，万物之所由成。不可为也，不可执也。自然而已矣。故曰：人法地，地法天，天法道，道法自然。夫自然者，万物之祖，天地之宗。太上下知有之，其次亲而誉之。功成事遂，百姓皆谓我自然。

通玄真经·卷九·下德篇

老子曰：治世之职易守也，其事易为也，其礼易行也，其患易去也。非其智能愈于古也，以其时也。天下之势，其来久矣。虽有智能，不乘其势，不能成也。

老子曰：法能杀不孝，而不能使人孝。能刑不仁，而不能使人仁。法之所加，必有弊也。故圣人务治其本，而不治其末。

老子曰：阴阳陶冶万物，皆乘一气而生。天地之间，六合之内。其气有九。九窍、五藏、十二节，皆通乎天气。不顺则灾害生，顺之则疾病不起。

老子曰：为治之本，务在安民。安民之本，在于足用。足用之本，在于勿夺时。勿夺时之本，在于省事。省事之本，在于节用。节用之本，在于去骄奢。去骄奢之本，在于无为。

老子曰：废道而任法者，虽劳而无功。废德而任刑者，虽威而不立。是以圣人因天地之自然，以成其治。

老子曰：人之言曰：国有亡主，世无亡道。人有穷而理无不通。故无为者道之宗也。得道之宗，并应无穷。

老子曰：治国有常，而利民为本。政教有道，而令行为上。苟利于民，不必法古。苟周于事，不必循旧。

老子曰：圣人制法，因民之性而为之节文。无其性，不可使顺教。有其性，无其资，不可使遵道。人之性有仁义之资，非圣人为之法度，不可使向方。

老子曰：衰世之主，钻山石，挈金玉，摘砻蜃，消铜铁，而万物不滋。刳胎焚郊，覆巢毁卵，凤皇不翔，麒麟不游。构木为台，焚林而畋，竭泽而渔，积壤而丘处。掘地而井饮，濬川而为池，筑城而为固，拘兽以为畜。则阴阳缪戾，四时失序。雷霆毁折，雹霰为害。万物焦夭，处于太半。草木夏枯，三川绝而不流。分山川溪谷，使有壤界。计人众寡，使有分数。设机械险阻以为备，立仁义礼乐以为制。此末世之政也，虽强不可久也。

老子曰：古之立帝王者，非以奉养其欲也。圣人践位者，非以逸乐其身也。为天下强掩弱，众暴寡，诈者欺愚，勇者侵怯，又为其怀智诈不以相教，积财不以相分，故立天子以齐一之。为一人之明，不能遍照海内，故立三公九卿以辅翼之。为绝国殊俗，不得被泽，故立诸侯以教诲之。是以天地四时无不应也。官无隐事，国无遗利。所以衣寒食饥，养老弱，息劳倦，无不以也。

老子曰：国之所以存者，得道也。所以亡者，理塞也。故圣人见化以观其征。德有昌衰，风有盛微，皆先见于天，后应于物。是故圣人知天道之吉凶，而为之备。智而若愚，辩而若讷。不自有其能，不自矜其功。故能去祸致福，去凶致吉。

老子曰：欲知天道，察其数。欲知地道，物其树。欲知人道，审其欲。教人养气，不如导之以虚。教人养形，不如遗之以素。故圣人审于虚实之际，察于动静之变，通于利害之端，达于治乱之原。

老子曰：夫至人之治也，弃其聪明，灭其文章。依道废智，与民同出乎公。约其所守，寡其所求。去其诱慕，除其嗜欲，损其思虑。约其所守即察，寡其所求即得。故以道治天下，非易人性也，因其所有而条畅之。故因即大，作即小。古之渎水者，因水之流也。生稼者，因地之宜也。征伐者，因民之欲也。能因，则无敌于天下矣。物必有自然，而后人事有治也。

老子曰：天下莫易於为善，莫难於为不善。所谓为善者，静而无为，适情辞余，无所诱惑。循性保真，无变于己。故为善易。所谓为不善难者，篡弑矫诈，躁而多欲，非人之性也。故为不善难。今之以为大患者，由无常厌度量生也。故利害之地，祸福之际，不可不察也。

老子曰：圣人无欲也，无避也。事或欲之，适足以失之。事或避之，适足以就之。志有所欲，即忘其所为。是以圣人审动静之变，适受与之度。理好憎之情，和喜怒之节。夫动静得，即患不侵也。受与适，即罪不累也。好憎理，即忧不近也。喜怒和，即怨不犯也。己不侵物，物不伤己。己不犯人，人不怨己。

通玄真经·卷十·上仁篇

老子曰：为仁者，必以哀乐论之，以嗜欲发之。仁者，积恩之见证也。仁莫大于爱人，智莫大于知人。爱人即无怨刑，知人即无乱政。

老子曰：天地之生物也，不遗其小。圣人之养民也，不弃其微。是故善为国者，务在养民。养民之要，在于足食。足食之道，在于务农。务农之本，在于不夺农时。

老子曰：水之性欲清，沙石秽之。人之性欲平，嗜欲害之。唯圣人能遗物反己。不以身役物，不以欲乱和。

老子曰：小德川流，大德敦化。此天地之所以为大也。是以圣人法天，贵清静而贱躁扰，贵仁爱而贱残贼，贵宽缓而贱急暴，贵慈祥而贱苛刻。

老子曰：上仁者，为天下而无私。不以己身易天下，不以己利害百姓。是故仁者，不以私恩害公义，不以小利伤大体。

老子曰：君子之爱人也，以德。小人之爱人也，以姑息。以德爱人者，必求其是。以姑息爱人者，必求其非。故仁者，必合天下之公义。

老子曰：仁者，非求名也，求实也。非为己也，为天下也。是以仁者不争，而天下莫能与之争。

老子曰：天地之养万物也，不夺其性。圣人之养民也，不违其情。故善治者，顺性而动，因情而教。不强其所不能，不责其所不欲。寒者衣之，饥者食之，劳者息之，老者养之，幼者长之。此仁政之实也。

老子曰：仁者，非徒爱人而已也。必知爱人之所以为爱。爱人以德，而不以姑息。爱人以义，而不以私恩。爱人以道，而不以求报。上仁为之而无以为，此天地之仁也。天地不仁，以万物为刍狗。圣人不仁，以百姓为刍狗。然而不仁之中，仁乃大焉。不私一物，故能成万物。不私一人，故能成天下。

老子曰：为天下者，不以天下奉一人。为一人者，不可以天下私己。古之明王，取下有节，自养有度。必计岁而收，量民积聚。知有余不足之数，然后取奉。如此，即得承所受于天地，而离于饥寒之患。其惨怛于民也，国有饥者，食不重味。民有寒者，冬不被裘。与民同苦乐，即天下无哀民矣。

老子曰：食者民之本也，民者国之基也。故上食民之食，而民不以饥。上衣民之衣，而民不以寒。上安民之居，而民不以劳。上息民之力，而民不以怨。此四者，仁君之德也。

老子曰：仁君之治天下也，非以自为也，为天下也。非以养己也，养民也。故仁君之于天下也，如父母之于赤子。有饥寒者，则食之衣之。有疾病者，则医药之。有困穷者，则赈救之。有冤屈者，则伸理之。仁君爱民如子，故民戴仁君如父母。上下相亲，故能长久。

老子曰：国之所以为国者，民也。民之所以为民者，食也。食之所出，农也。农之所依，时也。故明主之治，不夺农时。春省耕而补不足，秋省敛而助不给。春生夏长，秋收冬藏。教民养育六畜，以时种树。务修田畴，滋植桑麻。肥墝高下，各因其宜。丘陵阪险，不生五谷者，以树竹木。春伐枯槁，夏取果蓏，秋畜疏食，冬伐薪蒸。以为民资。是故生无乏用，死无转尸。此仁政之至也。

通玄真经·卷十一·上义篇

老子曰：凡学者，能明于天人之分，通于治乱之本。澄心清意以存之，见其终始，反于虚无。可谓达矣。

老子曰：治国有常，而利民为本。政教有道，而令行为上。苟利于民，不必法古。苟周于事，不必循旧。

老子曰：义者，人之所宜也。赏善罚恶，以正国法。法者治之具也，而非所以治也。犹弓矢，中之具，而非所以中也。治之本在道，治之具在法。

老子曰：君子之道，静以修身，俭以养德。非淡泊无以明志，非宁静无以致远。夫学须静也，才须学也。非学无以广才，非志无以成学。

老子曰：天地之道，极则反，盈则损。故圣人治世，不以极盛为美，而以中和为贵。不为已甚，去泰去奢。守其雌，守其黑，守其辱。

老子曰：义者，所以合君臣、父子、兄弟、夫妇、朋友之际也。义立而道行，义废而道隐。故君子以义为上，勇次之，智又次之。

老子曰：自古及今，未有能全其行者也。故君子不责备于人。有大略者不可责以捷巧，有小智者不可任以大功。

老子曰：义莫大于正名，名正则治，名不正则乱。正名者，使君臣父子夫妇长幼各得其宜也。夫礼者，因人之情而为之节文。义者，因人之宜而为之法度。法非从天降，非从地出，发于人间，因于人心。先王制法，非以治人，所以使人自治也。

老子曰：天下之事，不可为也，因其自然而推之。万物之变，不可救也，秉其要而归之。是以圣人修其本，而不恃其末。厉其精神，偃其知见。漠然无为而无不为也，无治而无不治也。

老子曰：御民之道，犹御马也。马不可竭其力，民不可极其劳。善御者，量马力而与之进退。善治者，察民情而与之作息。故用人之力，必以其所能。责人之功，必以其所有。不强人以不能，不苦人以所难。

老子曰：法生于义，义生于众适，众适合乎人心。此治之要也。法非从天出，非从地出，生于人间，反于己身。己身正则法正，己身不正则法不正。故曰：君子有诸己而后求诸人，无诸己而后非诸人。

老子曰：善治国者，因民之性以治之。顺其心而导之，因其势而利之。不违其时，不夺其利。民安其俗，乐其业。至德之世，其民朴鄙，纯白不分。后世衰微，圣人出焉。立仁义，设礼乐，为之法度以齐之。此不得已而为之，非道之至也。太上，不知有之。其次，亲而誉之。其次，畏之。其次，侮之。信不足焉，有不信焉。

老子曰：烈士徇名，贪夫徇财。其所徇一也，而所以徇者异。徇名者以名为利，徇财者以财为利。故圣人去甚去奢去泰。不为名尸，不为谋府，不为事任，不为知主。体道而游于无有，因性而动于自然。

老子曰：用兵有五：有义兵，有应兵，有忿兵，有贪兵，有骄兵。诛暴救弱，谓之义。敌来加己，不得已而用之，谓之应。争小故，不胜其心，谓之忿。利人土地，欲人财货，谓之贪。恃其国家之大，矜其人民之众，欲见威于敌，谓之骄。义兵王，应兵胜，忿兵败，贪兵死，骄兵灭。此天道也。

老子曰：夫为义者，非以徇名也，求其实也。非以逞志也，安其民也。故义者，所以济世安民，非以暴寡凌弱也。是故圣人不以兵强天下。其事好还。师之所处，荆棘生焉。大军之后，必有凶年。善者果而已，不敢以取强。果而勿矜，果而勿伐，果而勿骄，果而不得已，果而勿强。物壮则老，是谓不道，不道早已。

通玄真经·卷十二·上礼篇

老子曰：礼者，敬而已矣。故礼之于人也，犹酒之有糵也。君子以厚，小人以薄。夫礼者，忠信之薄而乱之首也。前识者，道之华而愚之始也。

老子曰：圣人不积，既以为人己愈有，既以与人己愈多。天之道，利而不害。圣人之道，为而不争。

老子曰：古之善为道者，非以明民，将以愚之。民之难治，以其智多。故以智治国，国之贼。不以智治国，国之福。

老子曰：上礼为之而莫之应，则攘臂而扔之。故失道而后德，失德而后仁，失仁而后义，失义而后礼。夫礼者，忠信之薄而乱之首也。

老子曰：礼义法度者，应时而变者也。今取古之法度而施之，犹以猿狙衣周公之服。彼必龁啮挽裂，尽去而后慊。古今之变，其不同也如此。

老子曰：礼者，因人情而为之节文者也。人之情，欲寿而恶夭，欲安而恶危，欲荣而恶辱，欲逸而恶劳。四者不失其时，则礼可得而行矣。故圣人制礼，不使人过之，不使人不及。适其中而已矣。

老子曰：礼之本在诚，礼之用在敬。诚者天道也，敬者人事也。天道不言而善应，人事不令而自行。故至诚无息，不息则久，久则征，征则悠远，悠远则博厚，博厚则高明。博厚所以载物也，高明所以覆物也，悠久所以成物也。

老子曰：五帝异道而德覆天下，三王殊事而名施后世。故圣人随时而举事，因资而立功。时异则事变，事变则礼异。礼者，世之末也，非所以治之本也。道德者，治之本也。仁义者，治之末也。礼乐者，治之文也。弃本而求末，舍源而逐流，虽劳而无功，虽贤而不治。

老子曰：夫礼乐者，所以节行也，非所以修身也。修身者在于正心，正心者在于诚意。意诚而后心正，心正而后身修。身修而后家齐，家齐而后国治，国治而后天下平。古之欲明明德于天下者，先治其国。欲治其国者，先齐其家。欲齐其家者，先修其身。欲修其身者，先正其心。欲正其心者，先诚其意。欲诚其意者，先致其知。致知在格物。物格而后知至，知至而后意诚，意诚而后心正，心正而后身修，身修而后家齐，家齐而后国治，国治而后天下平。

老子曰：上礼者，末世之教也。道废而后德，德废而后仁义礼乐生焉。仁义礼乐者，所以救败也，非所以治也。故圣人论世之变，而为之法；推古之道，而为之备。昔者三皇，得道之统，立于中央，神与化游。无礼而民不违，无法而国不乱。后世衰微，圣人不作。诸侯放恣，处士横议。杨朱墨翟之言盈天下。天下之言，不归杨则归墨。杨氏为我，是无君也。墨氏兼爱，是无父也。无父无君，是禽兽也。故圣人作，为礼以教人。使人以有礼，知自别于禽兽。是以礼之用，和为贵。先王之道，斯为美，小大由之。有所不行，知和而和，不以礼节之，亦不可行也。

老子曰：昔者仲尼问礼于老聃。老聃曰：子所言者，其人与骨皆已朽矣，独其言在耳。且君子得其时则驾，不得其时则蓬累而行。吾闻之，良贾深藏若虚，君子盛德容貌若愚。去子之骄气与多欲，态色与淫志，是皆无益于子之身。吾所以告子，若是而已。仲尼归，三日不谈。弟子问曰：夫子见老聃，亦将何规哉？仲尼曰：吾乃今于是乎见龙。龙合而成体，散而成章，乘乎云气而养乎阴阳。予口张而不能嗋，予又何规老聃哉！

老子曰：礼者，非以文饰为尚也，敬而已矣。非以繁缛为贵也，诚而已矣。治世之礼，简而易行。末世之礼，繁而难从。故圣人制礼，上则因天，下则因地。天有春夏秋冬，礼有吉凶宾军。天有四时，人有四体。四时合则万物生，四体调则万事成。故礼者，天地之序也，人道之纪也。得之者治，失之者乱。行之者安，弃之者危。不可不察也。

老子曰：礼乐之设，非以娱乐也，所以节民也，所以和民也。乐以和其心，礼以节其行。心和则气和，气和则声和，声和则天地之和应矣。故圣王作乐，非以自娱也，将以治民也。礼乐行于上，万民化于下。民心正，则天下平矣。

老子曰：至礼无礼，至乐无乐。无礼者不文，无乐者不声。天地之礼，不言而民自化。天地之乐，无声而民自和。圣人体此，以治天下。故曰：大礼无文，大乐无声。无声之乐，所以和神人也。无文之礼，所以通上下也。

计然曰：通玄真经十二卷，究天人之际，通古今之变。道原者，万物之本也。精诚者，感通之要也。九守者，修身之方也。符言者，言行之准也。道德者，治世之纲也。上德者，天道之显也。微明者，知几之妙也。自然者，无为之道也。下德者，治术之变也。上仁者，爱民之实也。上义者，法度之宜也。上礼者，文教之终也。此十二者，循环相因，本末相承。道失而后德，德失而后仁，仁失而后义，义失而后礼。苟能守其本，抱其道，则天下可运于掌矣。

附：通玄真经外篇·补遗辑要

老子曰：道者万物之奥，善人之宝，不善人之所保。美言可以市尊，美行可以加人。人之不善，何弃之有？故立天子，置三公，虽有拱璧以先驷马，不如坐进此道。古之所以贵此道者何？不曰求以得，有罪以免邪？故为天下贵。大道泛兮，其可左右。万物恃之而生而不辞，功成不名有。衣养万物而不为主，常无欲，可名于小。万物归焉而不为主，可名为大。以其终不自为大，故能成其大。

老子曰：名与身孰亲？身与货孰多？得与亡孰病？是故甚爱必大费，多藏必厚亡。知足不辱，知止不殆，可以长久。罪莫大于可欲，祸莫大于不知足，咎莫大于欲得。故知足之足，常足矣。大成若缺，其用不弊。大盈若冲，其用不穷。大直若屈，大巧若拙，大辩若讷。躁胜寒，静胜热。清静为天下正。

文子问曰：何谓至人之道？老子曰：至人者，处天地之和，从八风之理。适嗜欲于世俗之间，无恚嗔之心。行不欲离于世，被服章，不诡于俗。外不劳形于事，内无思想之患。以恬愉为务，以自得为功。形体不敝，精神不散。亦可以百数。其次有圣人者，处天地之和，从八风之理。适嗜欲于世俗之间，无恚嗔之心。行不欲离于世，被服章，不诡于俗。外不劳形于事，内无思想之患。以恬愉为务，以自得为功。形体不敝，精神不散。亦可以百数。其次有贤人者，法则天地，象似日月。辨列星辰，逆从阴阳。分别四时，将从上古。合同于道，亦可使益寿而有极时。

老子曰：圣人居无为之事，行不言之教。万物作焉而不辞，生而不有，为而不恃，功成而弗居。夫唯弗居，是以不去。不尚贤，使民不争。不贵难得之货，使民不为盗。不见可欲，使民心不乱。是以圣人之治，虚其心，实其腹，弱其志，强其骨。常使民无知无欲，使夫智者不敢为也。为无为，则无不治。

老子曰：天地不仁，以万物为刍狗。圣人不仁，以百姓为刍狗。天地之间，其犹橐籥乎？虚而不屈，动而愈出。多言数穷，不如守中。谷神不死，是谓玄牝。玄牝之门，是谓天地根。绵绵若存，用之不勤。天长地久。天地所以能长且久者，以其不自生，故能长生。是以圣人后其身而身先，外其身而身存。非以其无私邪？故能成其私。

老子曰：上士闻道，勤而行之。中士闻道，若存若亡。下士闻道，大笑之。不笑不足以为道。故建言有之：明道若昧，进道若退，夷道若颣。上德若谷，大白若辱，广德若不足，建德若偷，质真若渝。大方无隅，大器晚成，大音希声，大象无形，道隐无名。夫唯道，善贷且成。

老子曰：道者，万物之奥也。善人之宝，不善人之所保。至道之精，窈窈冥冥。至道之极，昏昏默默。无视无听，抱神以静。形将自正，必静必清。无劳汝形，无摇汝精，乃可以长生。目无所见，耳无所闻，心无所知。汝神将守形，形乃长生。慎汝内，闭汝外，多知为败。我为汝遂于大明之上矣，至彼至阳之原也。为汝入于窈冥之门矣，至彼至阴之原也。天地有官，阴阳有藏。慎守汝身，物将自壮。我守其一以处其和。故我修身千二百岁矣，吾形未常衰。

文子问曰：道何以为体？老子曰：道以虚无为体，以清静为宗，以柔弱为用，以无为为治。虚无者，道之舍也。清静者，道之鉴也。柔弱者，道之刚也。无为者，道之常也。是故圣人守虚无，体清静，行柔弱，法无为。以此修身，身无不治。以此治国，国无不理。

老子曰：夫道有情有信，无为无形。可传而不可受，可得而不可见。自本自根，未有天地，自古以固存。神鬼神帝，生天生地。在太极之先而不为高，在六极之下而不为深。先天地生而不为久，长于上古而不为老。道生一，一生二，二生三，三生万物。万物负阴而抱阳，冲气以为和。

文子问曰：何以知天道？老子曰：天道如张弓，高者抑之，下者举之。有余者损之，不足者补之。天道损有余而补不足。人道则不然，损不足以奉有余。孰能有余以奉天下？唯有道者。是以圣人为而不恃，功成而不处。不欲见贤。

老子曰：江海所以能为百谷王者，以其善下之，故能为百谷王。是以圣人欲上民，必以言下之。欲先民，必以身后之。是以处上而民不重，处前而民不害。是以天下乐推而不厌。以其不争，故天下莫能与之争。天下皆谓我道大，似不肖。夫唯大，故似不肖。若肖，久矣其细也夫。

老子曰：含德之厚，比于赤子。毒虫不螫，猛兽不据，攫鸟不搏。骨弱筋柔而握固。未知牝牡之合而脧作，精之至也。终日号而不嗄，和之至也。知和曰常，知常曰明。益生曰祥，心使气曰强。物壮则老，谓之不道，不道早已。知者不言，言者不知。塞其兑，闭其门，挫其锐，解其纷，和其光，同其尘，是谓玄同。

老子曰：以政治国，以奇用兵，以无事取天下。吾何以知其然哉？以此：天下多忌讳，而民弥贫。民多利器，国家滋昏。人多伎巧，奇物滋起。法令滋彰，盗贼多有。故圣人云：我无为而民自化，我好静而民自正，我无事而民自富，我无欲而民自朴。其政闷闷，其民淳淳。其政察察，其民缺缺。祸兮福之所倚，福兮祸之所伏。孰知其极？其无正。正复为奇，善复为妖。人之迷，其日固久。是以圣人方而不割，廉而不刿，直而不肆，光而不耀。

文子问曰：治国之本何在？老子曰：治大国若烹小鲜。以道莅天下，其鬼不神。非其鬼不神，其神不伤人。非其神不伤人，圣人亦不伤人。夫两不相伤，故德交归焉。大国者下流，天下之交，天下之牝。牝常以静胜牡，以静为下。故大国以下小国，则取小国。小国以下大国，则取大国。故或下以取，或下而取。大国不过欲兼畜人，小国不过欲入事人。夫两者各得其所欲，大者宜为下。

老子曰：道者，万物之奥。天下皆谓我道大，似不肖。夫唯大，故似不肖。若肖，久矣其细也夫。我有三宝，持而保之。一曰慈，二曰俭，三曰不敢为天下先。慈故能勇，俭故能广，不敢为天下先故能成器长。今舍慈且勇，舍俭且广，舍后且先，死矣。夫慈，以战则胜，以守则固。天将救之，以慈卫之。善为士者不武，善战者不怒，善胜敌者不与，善用人者为之下。是谓不争之德，是谓用人之力，是谓配天古之极。

文子问曰：道无始终，何以言始？老子曰：有物混成，先天地生。寂兮寥兮，独立而不改，周行而不殆，可以为天下母。吾不知其名，字之曰道，强为之名曰大。大曰逝，逝曰远，远曰反。故道大，天大，地大，王亦大。域中有四大，而王居其一焉。人法地，地法天，天法道，道法自然。自然者，万物之祖也。道者，万物之奥也。德者，万物之养也。道德相因，而生化无穷。

老子曰：信言不美，美言不信。善者不辩，辩者不善。知者不博，博者不知。圣人不积，既以为人己愈有，既以与人己愈多。天之道，利而不害。圣人之道，为而不争。夫唯不争，故天下莫能与之争。古之所谓曲则全者，岂虚言哉！诚全而归之。

