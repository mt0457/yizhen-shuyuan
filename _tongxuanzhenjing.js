老子曰：道生之，德畜之，物形之，势成之。是以万物莫不尊道而贵德。道之尊，德之贵，夫莫之命而常自然。故道生之，德畜之，长之育之，亭之毒之，养之覆之。生而不有，为而不恃，长而不宰，是谓玄德。

老子曰：反者道之动，弱者道之用。天下万物生于有，有生于无。道常无为而无不为。侯王若能守之，万物将自化。化而欲作，吾将镇之以无名之朴。无名之朴，夫亦将无欲。不欲以静，天下将自定。

老子曰：知人者智，自知者明。胜人者有力，自胜者强。知足者富，强行者有志。不失其所者久，死而不亡者寿。大道泛兮，其可左右。万物恃之以生而不辞，功成不名有。衣养万物而不为主，常无欲，可名于小；万物归焉而不为主，可名为大。是以圣人终不为大，故能成其大。

文子问曰：何以修身？老子曰：修身者，先修其心。心者，身之主也。心正则身正，心邪则身邪。正心之道，在于寡欲。寡欲则心清，心清则神宁，神宁则气和，气和则形康。故曰：五色令人目盲，五音令人耳聋，五味令人口爽，驰骋畋猎令人心发狂，难得之货令人行妨。是以圣人为腹不为目，故去彼取此。

文子问曰：何以治学？老子曰：为学日益，为道日损。损之又损，以至于无为。无为而无不为。取天下常以无事，及其有事，不足以取天下。圣人无常心，以百姓心为心。善者吾善之，不善者吾亦善之，德善。信者吾信之，不信者吾亦信之，德信。圣人在天下，歙歙为天下浑其心。百姓皆注其耳目，圣人皆孩之。

老子曰：出生入死。生之徒十有三，死之徒十有三。人之生动之死地，亦十有三。夫何故？以其生生之厚。盖闻善摄生者，陆行不遇兕虎，入军不被甲兵。兕无所投其角，虎无所措其爪，兵无所容其刃。夫何故？以其无死地。

老子曰：道生之，德畜之。是以万物莫不尊道而贵德。道之尊，德之贵，夫莫之命而常自然。道者，万物之奥。善人之宝，不善人之所保。不贵其师，不爱其资，虽智大迷，是谓要妙。

文子问曰：治天下可有常法乎？老子曰：天下神器，不可为也。为者败之，执者失之。故物或行或随，或嘘或吹，或强或羸，或挫或隳。是以圣人去甚，去奢，去泰。将欲取天下而为之，吾见其不得已。

老子曰：上善若水。水善利万物而不争，处众人之所恶，故几于道。居善地，心善渊，与善仁，言善信，政善治，事善能，动善时。夫唯不争，故无尤。天下柔弱莫过于水，而攻坚强者莫之能胜，以其无以易之。弱之胜强，柔之胜刚，天下莫不知，莫能行。是以圣人云：受国之垢，是谓社稷主；受国不祥，是为天下王。正言若反。

文子问曰：何谓玄德？老子曰：玄德深矣远矣，与物反矣，然后乃至大顺。道生之，德畜之，物形之，势成之。是以万物莫不尊道而贵德。道之尊，德之贵，夫莫之命而常自然。道如江海，德如川流。江海居下而纳百川，圣人居下而容天下。此玄德之至也。

老子曰：和大怨，必有余怨，安可以为善？是以圣人执左契而不责于人。有德司契，无德司彻。天道无亲，常与善人。圣人不积，既以为人己愈有，既以与人己愈多。天之道，利而不害。圣人之道，为而不争。

老子曰：小国寡民。使有什伯之器而不用，使民重死而不远徙。虽有舟舆，无所乘之。虽有甲兵，无所陈之。使民复结绳而用之。甘其食，美其服，安其居，乐其俗。邻国相望，鸡犬之声相闻，民至老死不相往来。此至治之极也，非道之衰也。民朴事简，顺天之时，因地之利。无烦令，无苛政。上不扰下，下不怨上。各安其分，各乐其生。如此，则天下自治矣。

老子曰：道常无名，朴虽小，天下莫能臣也。侯王若能守之，万物将自宾。天地相合，以降甘露。民莫之令而自均。始制有名，名亦既有，夫亦将知止。知止可以不殆。譬道之在天下，犹川谷之于江海。大道泛兮，其可左右。万物恃之以生而不辞，功成不名有。衣养万物而不为主，常无欲，可名于小；万物归焉而不为主，可名为大。是以圣人终不为大，故能成其大。夫唯道，善贷且成。

文子问曰：夫子之道，至矣尽矣。敢问一言而可以终身行之者乎？老子曰：其柔乎！柔弱胜刚强。柔弱者生之徒，刚强者死之徒。天下莫柔弱于水，而攻坚强者莫之能胜。故曰：守柔曰强。以柔胜刚，以弱胜强。天下莫不知，莫能行。夫唯不争，故天下莫能与之争。是谓玄同。玄同者，与道为一，与天地为友。顺其自然，守其清静。抱一为天下式。此圣人所以成其大也。

文子再拜而问曰：至道深远，弟子请事斯语矣。老子曰：吾言甚易知，甚易行。天下莫能知，莫能行。言有宗，事有君。夫唯无知，是以不我知。知我者希，则我者贵。是以圣人被褐怀玉。天之道，不争而善胜，不言而善应，不召而自来，繟然而善谋。天网恢恢，疏而不失。圣人之道，深根固柢，长生久视。守柔处下，与世无争。功成身退，天之道也。

老子曰：大道废，有仁义。智慧出，有大伪。六亲不和，有孝慈。国家昏乱，有忠臣。绝圣弃智，民利百倍。绝仁弃义，民复孝慈。绝巧弃利，盗贼无有。此三者以为文不足，故令有所属。见素抱朴，少私寡欲。绝学无忧。唯之与阿，相去几何？善之与恶，相去若何？人之所畏，不可不畏。荒兮其未央哉。众人熙熙，如享太牢，如春登台。我独泊兮其未兆，如婴儿之未孩。儽儽兮若无所归。众人皆有余，而我独若遗。我愚人之心也哉，沌沌兮。俗人昭昭，我独昏昏。俗人察察，我独闷闷。澹兮其若海，飂兮若无止。众人皆有以，而我独顽似鄙。我独异于人，而贵食母。

文子问曰：古之善为道者，其状若何？老子曰：古之善为道者，微妙玄通，深不可识。夫唯不可识，故强为之容：豫兮若冬涉川，犹兮若畏四邻，俨兮其若客，涣兮若冰之将释，敦兮其若朴，旷兮其若谷，混兮其若浊。孰能浊以静之徐清？孰能安以久动之徐生？保此道者不欲盈。夫唯不盈，故能蔽不新成。

文子问曰：夫子著书十二篇，可以蔽一言乎？老子曰：然。吾道一以贯之。曰道，曰德，曰自然。三者一也。道者德之体，德者道之用，自然者道德之归也。知此三者，则十二篇之旨可坐而致矣。通玄之谓也，通达玄妙，归于自然。是故通玄者，通天人之道，穷阴阳之变，究万物之理，明吉凶之征。得其要者，一言而终。不得其要，流散无穷。吾所以著十二篇者，欲使后之学者，循其序而得其门，由其门而入其室，入其室而见其奥。至于奥矣，则忘其言，忘其篇，忘其道，忘其德，忘其自然。忘忘亦忘，乃见其真。此通玄之极功也。

老子曰：吾道大矣，不可以一端尽也。深远矣，不可以浅近测也。然其要归，曰柔曰弱曰下曰后曰虚曰静曰朴曰素。能守此八者，则道可得而行矣。柔弱胜刚强，处下而得上，居后而能先，心虚而能应，守静而能动，抱朴而能巧，怀素而能文。此八者，相反相成，相为体用。通于一而万事毕。故曰：通于一而万事毕，无心得而鬼神服。此通玄真经之大旨也。

老子曰：夫道，覆载万物者也，洋洋乎大哉。君子不可不刳心焉。无为为之之谓天，无为言之之谓德。爱人利物之谓仁，不同同之之谓大，行不崖异之谓宽，有万不同之谓富。故执德之谓纪，德成之谓立，循于道之谓备，不以物挫志之谓完。君子明于此十者，则韬乎其事心之大也，沛乎其为万物逝也。若然者，藏金于山，藏珠于渊，不利货财，不近贵富，不乐寿，不哀夭，不荣通，不丑穷。不拘一世之利以为己私分，不以王天下为己处显。万物一府，死生同状。此之谓至人。

文子问曰：何为真人？老子曰：真人体之以虚无，反于太素。不以物滑和，不以欲乱情。其寝不梦，其觉无忧。其食不甘，其息深深。真人之息以踵，众人之息以喉。其神纯粹，其魂不罢。虚无恬愉，乃合天德。无所于忤，虚之至也。不与物交，淡之至也。无所于违，粹之至也。故真人者，法天贵真，不拘于俗。愚者反是，不能法天而恤于人，不知贵真，禄禄而受变于俗，故不足。

老子曰：通玄之要，一言蔽之曰和。和也者，阴阳调，四时序，万物生。天和则清，地和则宁，人和则寿。不和则乱，乱则败。故圣人法天地之和，调阴阳之气。不可为也，不可执也。为者败之，执者失之。夫唯无以生为者，乃能长生。无以治为者，乃能大治。此和之至也，通玄之极功也。学者于此尽心焉，则十二篇之旨可无憾矣。

老子曰：道之出口，淡乎其无味。视之不足见，听之不足闻，用之不足既。夫道，不可须臾离也，可离非道也。是故君子戒慎乎其所不睹，恐惧乎其所不闻。莫见乎隐，莫显乎微，故君子慎其独也。喜怒哀乐之未发谓之中，发而皆中节谓之和。中也者天下之大本也，和也者天下之达道也。致中和，天地位焉，万物育焉。此通玄真经之归，圣人传道之旨也。后之学者，苟能潜心于此，反复玩味，则通玄之义可明，大道之门可入矣。

老子曰：昔之得一者，天得一以清，地得一以宁，神得一以灵，谷得一以盈，万物得一以生，侯王得一以为天下贞。其致之一也。天无以清将恐裂，地无以宁将恐废，神无以灵将恐歇，谷无以盈将恐竭，万物无以生将恐灭，侯王无以贵高将恐蹶。故贵以贱为本，高以下为基。是以侯王自称孤寡不谷，此非以贱为本邪？非乎？故致数誉无誉。不欲琭琭如玉，珞珞如石。

文子再拜稽首曰：善哉言乎！通玄之旨，至矣备矣。请书诸绅，以贻后昆。

老子曰：吾言甚易知，甚易行。天下莫能知，莫能行。大道甚夷，而民好径。夫轻诺必寡信，多易必多难。是以圣人犹难之，故终无难矣。合抱之木，生于毫末。九层之台，起于累土。千里之行，始于足下。为者败之，执者失之。民之从事，常于几成而败之。慎终如始，则无败事。是以圣人欲不欲，不贵难得之货。学不学，复众人之所过。以辅万物之自然，而不敢为。

