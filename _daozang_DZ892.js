三元三品，三官大帝。紫微清虚，洞阴洞灵。上元赐福，中元赦罪，下元解厄。
正月十五，七月十五，十月十五。三元考校，注寿延生。沐浴斋戒，设供诵经。
至诚忏悔，改过迁善。三官感格，注生落死。罪灭福生，灾消厄解。
延生长寿，却病安康。超度先亡，祈福求嗣。功满德就，与道合真。
皈依上元天官紫微大帝。皈依中元地官清虚大帝。皈依下元水官洞阴大帝。
三元延寿，福生无量天尊。
