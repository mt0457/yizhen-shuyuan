此药囊佩戴法简便易行、成本低廉，在疫情中可作为全民防疫之基础措施推广——尤以老人、儿童、体弱者及必须出入公共场所之人为佩戴之重点人群。
药囊每半月更换一次内容物，以确保药气之力不衰。
