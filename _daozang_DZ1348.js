艾叶烟熏法——於屋中关闭门窗，取干艾叶一大把，点燃后以暗火（非明火）熏之，令其产生之浓烟弥漫全屋各个角落，持续一炷香（约半小时）。
艾烟具有很强的杀菌消毒作用，可大幅降低室内空气中的病原体密度。
此法於以下场合尤为重要：家中有人染疫之后的其余房间、刚从疫区返回之后的更衣室、接待过疫区来人之后的客堂。
