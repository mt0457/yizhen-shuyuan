疫鬼速退，瘟气速清。
敕令某甲（诵咒者持念病人姓名），急急续命。
元始安镇，普告万灵。
岳渎真官，土地祇灵。
左社右稷，不得妄惊。
回向正道，内外澄清。
各安方位，备守坛庭。
