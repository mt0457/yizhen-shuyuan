《易》叙宓羲、神农、黄帝作教化民，而《传》述其官。以为宓羲龙师名官，神农火师火名，黄帝云师云名。少昊鸟师鸟名。自颛顼以来，为民师而命以民事。

秦兼天下，建皇帝之号，立百官之职。汉因循而不革，明简易，随时宜也。其后颇有所改。

相国、丞相，皆秦官，金印紫绶，掌丞天子助理万机。秦有左右，高帝即位，置一丞相，十一年更名相国，绿绶。孝惠、高后置左右丞相，文帝二年复置一丞相。

太尉，秦官，金印紫绶，掌武事。武帝建元二年省。元狩四年初置大司马，以冠将军之号。

御史大夫，秦官，位上卿，银印青绶，掌副丞相。有两丞，秩千石。一曰中丞，在殿中兰台，掌图籍秘书，外督部刺史，内领侍御史员十五人，受公卿奏事，举劾按章。

太傅，古官，高后元年初置，金印紫绶。后省，八年复置。后省，哀帝元寿二年复置。太师、太保，皆古官，平帝元始元年皆初置，金印紫绶。太师位在太傅上，太保次太傅。

奉常，秦官，掌宗庙礼仪。景帝中六年更名太常。属官有太乐、太祝、太宰、太史、太卜、太医六令丞。

郎中令，秦官，掌宫殿掖门户。武帝太初元年更名光禄勋。属官有大夫、郎、谒者。大夫掌论议，有太中大夫、中大夫、谏大夫。郎掌守门户，出充车骑，有议郎、中郎、侍郎、郎中。谒者掌宾赞受事。

卫尉，秦官，掌宫门卫屯兵。太仆，秦官，掌舆马。廷尉，秦官，掌刑辟。典客，秦官，掌归义蛮夷。景帝中六年更名大行令，武帝太初元年更名大鸿胪。宗正，秦官，掌亲属。治粟内史，秦官，掌谷货。景帝后元年更名大农令，武帝太初元年更名大司农。少府，秦官，掌山海池泽之税，以给共养。中尉，秦官，掌徼循京师。武帝太初元年更名执金吾。

自太师至执金吾，秩皆中二千石。自太子太傅至右扶风，秩皆二千石。

凡吏秩比二千石以上，皆银印青绶。秩比六百石以上，皆铜印黑绶。秩比二百石以上，皆铜印黄绶。

县万户以上为令，秩千石至六百石。减万户为长，秩五百石至三百石。皆有丞、尉，秩四百石至二百石。乡有三老、有秩、啬夫、游徼。三老掌教化。啬夫职听讼，收赋税。游徼徼循禁贼盗。县大率方百里，其民稠则减，稀则旷，乡、亭亦如之。皆秦制也。

