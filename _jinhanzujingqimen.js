生门艮宫主财源，种植经营修造吉。
伤门震宫主动静，捕猎索债伤损及。
杜门巽宫主隐藏，潜形遁迹遮身立。
景门离宫主文书，投书献策利名集。
死门坤宫主埋葬，吊丧行刑田猎急。
惊门兑宫主惊恐，官司口舌声名失。

开休生门为三吉，出行婚嫁百事宜。
死惊伤门为三凶，捕盗行刑事可施。
杜景二门为中平，隐伏投书各有时。

