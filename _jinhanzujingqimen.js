【八门五行方位】
开门属金居西北乾宫，旺于秋季申酉月，相于四季土月，休于冬季，囚于春季，死于夏季火月。
休门属水居正北坎宫，旺于冬季亥子月，相于秋季，休于春季，囚于夏季，死于四季土月。
生门属土居东北艮宫，旺于四季辰戌丑未月，相于夏季，休于秋季，囚于冬季，死于春季。
伤门属木居正东震宫，旺于春季寅卯月，相于冬季，休于夏季，囚于四季土月，死于秋季。
杜门属木居东南巽宫，旺于春季寅卯月，相于冬季，休于夏季，囚于四季土月，死于秋季。因巽为风木，与震宫木同而气异，故杜门藏风纳气。
景门属火居正南离宫，旺于夏季巳午月，相于春季，休于四季土月，囚于秋季，死于冬季。
死门属土居西南坤宫，旺于四季辰戌丑未月，相于夏季，休于秋季，囚于冬季，死于春季。坤为地母，万物归藏之处。
惊门属金居正西兑宫，旺于秋季申酉月，相于四季土月，休于冬季，囚于春季，死于夏季。兑为口舌，故惊门主惊恐争讼。

【八门克应总诀】
开门逢奇位至公，凡事谋为百事通。若遇凶星并凶格，求名求利总成空。
休门吉宿最为良，求财修造甚相当。若临坎宫兼得使，扬帆入海任翱翔。
生门临土万事亨，求财种植五谷登。若遇丙奇乘旺气，天财地宝入门庭。
伤门捕猎索债宜，出师报怨此中施。若与天冲同临位，扬威耀武正当时。
杜门隐伏最为奇，潜形遁迹此中推。若得太阴同聚会，藏身避祸得安宜。
景门献策利功名，投书破阵此中行。若遇丁奇天辅照，文章锦绣万言成。
死门吊丧行刑吉，畋猎埋葬此中觅。若逢天芮加死气，病人问卜实堪泣。
惊门争讼最乖张，口舌官非此中藏。若逢白虎天柱在，伤人惹祸实难防。

