【奇门总要序】奇门遁甲之学，以八卦配九宫，以八门定方向，以九星断吉凶，以八神察动静，以三奇六仪辨时机，以阴阳二遁分顺逆。此六者，奇门之大纲也。学奇门者，先明此六纲，而后可以论其余。

【九宫八卦歌】
坎居一位水之源，坤二离三火气炎。
震四巽五中宫寄，乾六兑七艮八全。
离九在南为火位，九宫八卦一周天。

戴九履一妙无穷，左三右七掌上功。
二四为肩六八足，纵横十五在其中。
若能识得九宫诀，天地玄机一掌通。

