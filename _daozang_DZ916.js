<p style="font-size:16px;color:#8b1a1a;line-height:2.2;margin:0;">
<b>太上降敕，正一真传。三五斩邪，雌雄二剑。桃木七星，各禀灵炁。净通注封，五符依次。七星罡步，北斗剑咒。法剑既成，代天行化。所指之处，邪魔辟易。所向之地，妖氛澄清。剑在道在，剑气长存。志心皈命，太上正一敕剑秘法。敕剑度人无量天尊。皈依道经师三宝。福生无量天尊。</b>
</p>
