<p style="font-size:16px;color:#8b1a1a;line-height:2.2;margin:0;"><b>灵宝天尊大慈尊，三涂五苦悉照临。
地狱化为清凉池，饿鬼饱满甘露饮。
畜生脱得愚痴壳，五蕴照破见天真。
诵经功德难思议，回向亡者即超升。
九幽十类皆离苦，三界六道尽沾恩。
至心称念灵宝号，拔度妙经永流传。
皈依道经师三宝。
福生无量天尊。
</b></p>
