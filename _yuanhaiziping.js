渊海子平论十神喜忌。正官喜印护财生，忌伤官克。七杀喜食制印化，忌无制。正财喜食生官护，忌比劫夺。正印喜官生杀化，忌财破。食神喜财泄身旺，忌枭夺。伤官喜印制财泄，忌见官。比肩喜官制食泄，忌财弱。劫财喜食泄官制，忌夺财。

