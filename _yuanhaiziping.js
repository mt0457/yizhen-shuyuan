渊海子平论地支六害。子未害——水克土，土壅水。丑午害——湿土晦火。寅巳害——木生火焚。卯辰害——木克土壅。申亥害——金生水泄。酉戌害——金土暗损。害者暗中破坏。用神被害——暗中有阻。忌神被害——暗中有救。配偶宫被害——夫妻暗斗。子女宫被害——亲子不睦。害之应期：大运流年填实或引发。

