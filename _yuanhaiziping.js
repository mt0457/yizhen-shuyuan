渊海子平论地支三合。申子辰合水局：水生申旺子墓辰。亥卯未合木局：木生亥旺卯墓未。寅午戌合火局：火生寅旺午墓戌。巳酉丑合金局：金生巳旺酉墓丑。三合成局力大势专。三合局全者格局提升。半合亦有力（如申子无辰）。三合局忌冲破——破则局散力失。

