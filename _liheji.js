贞元十二年（796年），七岁。以能诗名动京师。韩愈、皇甫湜闻而造访，贺赋《高轩过》，二人大惊。
贞元十九年（803年），十四岁。居昌谷读书。始与王参元、杨敬之、权璩等游。
