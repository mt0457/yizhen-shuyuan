"议者以震川为明文第一，似矣。试取诸家选本观之，震川之入选者，其文独多。非以其情深而辞达也乎？情深而辞达，则文之至也。"

三、方苞《书归震川文集后》

"震川之文，发于亲旧及人微而语无忌者，盖多近古之文。至事关天属，其尤善者，不事修饰，而情辞并至，使览者恻然有隐。其气韵盖得之《史记》，而章法之变化，则得之韩愈。要其大本，则原本经术而依于事物之理。"

四、姚鼐《古文辞类纂序目》

"归震川之文，于不要紧之题，说不要紧之语，却自风韵疏淡，是于太史公深有会处。"

五、曾国藩《家训》

"震川之文，气味渊永，反复读之，使人悄然以思，有淡然冰释之乐。"

六、林纾《春觉斋论文》

"震川之文，以琐琐屑屑之谈，写悱恻缠绵之意。读之如见家人妇子，絮絮语家常，而意自深长。非有至性至情者，不能为也。"

七、鲁迅论归有光

"归有光的文章是很感人的。他写他的母亲、妻子、婢女，生活琐事，真切动人。"

