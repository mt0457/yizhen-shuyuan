参宿又名实沈，为白虎最后一宿，主西方之终结。参宿七星对应地上七将军。参宿星君居大将之宫，掌人间将帅武职、军事统帅、行军布阵之事。
参宿值日，宜拜将、出征、军事演训、武举考试。不宜婚嫁、动土。
