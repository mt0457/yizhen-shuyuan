书此符时，面西而立，心存参宿黑水之气化为百万雄兵，护卫道场。焚符之后，参水猿星君下降，护持修行之人不受刀兵之灾，武将得之勇猛无敌。
参宿符配丁丑、戊寅、己卯三日值日，于申时（下午三时至五时）焚化最验。感验徵兆：焚符之后梦军中点兵或闻战鼓之声，即为星君感格之验。
