将《内观经》的心法扩充为一部完整的修行指南，七篇层层递进，纲举目张。
《坐忘论》被后世道教奉为心性修炼之圭臬，其核心思想——收心、真观、泰定——皆脱胎于《内观经》。
司马承祯住世八十八岁，临终端坐而化，颜色如生，异香满室，七日不散。
唐代是道教鼎盛时期，《坐忘论》被收入《道藏》，成为上清派茅山宗的根本修行经典。
此后千余年，凡是修习道教心法者，无不研读《坐忘论》——而《坐忘论》的灵魂，正是此《内观经》。

