《太上正一安龙镇宅宝箓》，一卷，太上老君于鹤鸣山亲授祖天师张道陵之安龙镇宅无上秘法，收入明《正统道藏》正一部威仪类。安龙者，安抚宅中之龙神也。盖天地之间，山川有山脉龙神，江河有水脉龙神，人居之宅亦有宅脉龙神。龙神安则宅气通顺、家道兴隆、人口平安；龙神惊则宅气紊乱、家运衰败、灾祸频生。凡动土修造——或建宅筑基、或翻修旧屋、或凿井开池、或植树移石——皆有可能惊动地下龙神，轻则家人无故生病、口舌是非不断、财运日渐衰退，重则家宅不宁、怪异频现、甚至人丁损伤。此非迷信妄言，乃天地之气与人身之气相交感应的自然规律——龙神者，地脉之灵气所聚，动土惊之则地气紊乱，地气乱则宅气乱，宅气乱则人气乱，一乱百乱，诸事不顺。此宝箓详述安龙之科仪（召龙、安龙、谢龙之完整法事程序）、镇宅之符法（二十四道镇宅灵符之篆形、画法、用诀）、召龙之神咒（七道安龙秘咒及存思法门）、谢土之醮礼（动土后酬谢土府神祇之仪轨），以及居家日常安龙养龙之简易法门。经中符箓篆法古奥、咒诀灵验非常、科仪严谨完备，乃正一道安龙镇宅法事之总纲，亦为天下信众居家保安之至宝。子孙得此宝箓，依法行持，则龙神归位、八方清净、邪秽不侵、家宅平安、福寿康宁、万事亨通。
