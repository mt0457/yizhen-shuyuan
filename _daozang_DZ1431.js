不拘场所，唯以至诚之心，默诵请圣文一遍、忏悔文一遍、根本神咒七遍或二十一遍，同时以手掌按于臂痛处，存想灵宝天尊放金光照射患处，诵毕叩首三次即可。天尊慈悲，不苛求形式之完备，但以至诚心为贵——极简之法倘以赤诚之心行之，其功德不亚于完整科仪。
