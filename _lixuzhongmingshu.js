五月建午。午为离，火帝旺。芒种始，夏至五月中。一阴初生，阳极阴生。午月火烈，得水既济为贵。

六月建未。未为坤，季夏土旺。小暑始，大暑六月中。未为木库，藏己丁乙。未月土燥，木气归库，宜水润泽。

七月建申。申为坤，金临官。立秋始，处暑七月中。申中藏庚壬戊。申月金旺水相，秋气肃杀。

