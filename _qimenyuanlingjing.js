【心法十则】一则净心——占前洗手焚香静坐。二则诚意——专心致志不问杂事。三则敬畏——奇门为天道之术心存敬畏。四则勤勉——日日练习不可懈怠。五则谦虚——学无止境不可自满。六则守德——不可用于邪途害人。七则保密——不轻泄天机于非人。八则精准——时辰节气不可有误。九则全面——大局细节不可偏废。十则通达——不拘于形心与天通。

【元灵绝句】元灵心法妙无穷，净心诚意第一宗。若问奇门何最要，心与天通万事通。排盘只在心中转，占断全凭灵机动。十年磨得心如玉，一朝悟入九天中。

