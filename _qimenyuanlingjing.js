【入门三要】一曰熟读统宗——明其理法。二曰精研元灵——悟其心法。三曰勤习玉镜——练其实战。三者并进，三月可入门，一年可通晓，三年可精熟。

【进阶三阶】初阶学排盘——熟节气定局、六仪三奇布列。中阶学占断——八门九星八神配合。高阶学心法——与天地灵气相通，占无不验。

【传习警言】奇门之术非一朝一夕可成。忌急功近利，忌浅尝辄止，忌好高骛远。日积月累，水到渠成。先贤有言：奇门一道，十年小成，三十年大成。学者当以此为志。

