斋者，齐也。齐整三业，乃为斋矣。三业者，身业、口业、心业也。身不妄行，谓之身斋。口不妄言，谓之口斋。心不妄念，谓之心斋。外不染尘，内无欲念，内外清静，方为真斋。斋法有三：一曰设供斋，二曰节食斋，三曰心斋。设供斋者，以供养祈福。节食斋者，以节食养神。心斋者，以清心合道。三者之中，心斋为上。

