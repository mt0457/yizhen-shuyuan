云笈七签·卷七十六·方药部·金石药部

凡金石之药，有可服者，有不可服者。可服者，丹砂、雄黄、云母、玉屑、钟乳、白石英、紫石英、赤石脂、禹余粮之类。不可服者，金银铜铁铅锡，此六者虽为世之所贵，而不可入药。服之伤人，慎之慎之。丹砂者，朱砂之上品也，出辰州者为佳。服之可以安神定魄，益气明目，久服通神不死。雄黄者，出武都山者为佳。服之可以杀百虫，辟百邪。云母者，有五色，各有所主。白者补肺，赤者补心，青者补肝，黄者补脾，黑者补肾。凡服金石之药，当先沐浴斋戒，以枣膏或蜜和为丸，服之。服后当行气导引，以助药力。不可多服，多服则中毒。

云笈七签·卷七十七·方药部·草木药部

草木之药，有益于人者多矣。上品者，可以延年益寿，如黄精、人参、茯苓、天门冬、地黄、白术、菖蒲、菊花、枸杞、五味子、松脂、柏实之类。中品者，可以却病强身，如甘草、桂心、防风、细辛、当归、川芎、芍药、黄芪、黄芩、黄连之类。下品者，可以攻病去邪，如大黄、巴豆、附子、乌头、半夏、南星、芫花、甘遂之类。修道之士服食者，当用上品，慎用中品，不取下品。上品之药，性味平和，久服无弊。黄精者，得坤土之精，故曰黄精。久服可以轻身延年，辟谷不饥。人参者，得人形之气，故曰人参。久服可以大补元气，益智安神。

云笈七签·卷七十八·符图部·太上三五正一盟威宝箓

