<p style="font-size:16px;color:#8b1a1a;line-height:2.2;margin:0;">
<b>太上正一解冤释结妙经。十二类冤业，一一说分明。杀害损伤偷盗欺诳邪淫口舌负约忘恩嫉妒侵占牵连宿世——种种冤仇，皆因无明造作而生。老君慈悲，说此解冤释结无上妙法：忏悔为前导，诵经为核心，回向为归结，行善为助缘。四法齐修，无冤不解，无结不释。冤家得超度而怨气消散，信士得解脱而身心康泰。冤冤相报何时了？解冤释结在今朝。诵此妙经，功不唐捐。皈依道经师三宝。解冤释结大天尊。</b>
</p>
