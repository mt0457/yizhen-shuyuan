<p style="margin:4px 0 0 0;font-size:11px;color:#999;"><b>【流通功德】</b>若有善信发心抄写、刻印、流通此经于世者，其功德不可思议——不仅利益自身消业解冤，亦令一切有缘众生得闻此解冤妙法，脱离冤苦。一人传十人，十人传百人，使解冤释结之言教广布人间——则世间冤仇渐减，祥和之气渐增，此乃老君说经之终极心愿。愿诸善信，各各发心，辗转流通，共襄善举。太上正一解冤释结妙经终。</p>
