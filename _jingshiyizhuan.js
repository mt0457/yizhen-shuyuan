【例一·占天气】甲子日，乾为天卦。世在上爻戌土，官鬼午火临五爻。午火旺相，当日大晴。果晴。
【例二·占求财】乙丑日，风天小畜卦。妻财未土持世，青龙临财。财爻旺相，求财大吉。果得财。
【例三·占婚姻】丙寅日，泽山咸卦。世应相生，妻财临应爻。婚可成。果成婚。
【例四·占疾病】丁卯日，水火既济。官鬼子水持世，病在肾。子孙寅木临青龙。服药有救。果服药愈。
【例五·占出行】戊辰日，雷天大壮。驿马在寅，寅爻发动。出行大吉。果出行顺利。
【例六·占官运】己巳日，火天大有。官鬼巳火持世临青龙。升迁有望。果升。
【例七·占失物】庚午日，天泽履。妻财子水伏藏，玄武临之。失物在北方近水处。果寻得。
【例八·占子嗣】辛未日，山雷颐。子孙巳火旺相持世。子息旺盛。果得子。
【例九·占词讼】壬申日，天水讼。官鬼亥水旺相，世应相冲。官司不利。后败诉。
【例十·占家宅】癸酉日，地火明夷。官鬼临二爻（家宅位），火克金。家中有火灾隐患。后果小火灾。

