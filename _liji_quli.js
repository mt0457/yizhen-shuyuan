《礼记》为儒家十三经之一，与《周礼》《仪礼》合称三礼，是中国古代礼学之核心经典。全书四十九篇，为西汉戴圣编纂。

《曲礼》为《礼记》之首篇，分上下两篇。曲礼之名取义于礼之细微曲折——礼不在宏大而在细节。郑玄注曰：曲礼者以其篇记五礼之事委曲说之故名曲礼。

《曲礼》为中国古代礼仪规范之总纲，涵盖日常起居、言语应对、饮食起居、命名禁忌等方方面面。其中命名论述与左传白虎通义相呼应，共同构成中华命名文化之经典体系。

