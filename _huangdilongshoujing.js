【天文诀】观天之道执天行，五星顺逆定吉凶。二十八宿分分野，日月合朔有变通。七十二候知时节，四时八节各不同。

【地理诀】天有五行地有五，山川形势各有所。东西南北中为五方，各以其气应天象。地气上升为云雨，天气下降为霜露。

【人事诀】人生天地法自然，四时调养身乃安。五行配脏知病所，干支择吉避凶残。天人感应如影随，顺应天时万事宽。

【总纲诀】龙首一经传古今，黄帝垂训示天心。观天察地知人事，顺时而行免祸侵。天地之道中和贵，偏枯太过必灾临。法天则地通人事，此是龙首经中金。

