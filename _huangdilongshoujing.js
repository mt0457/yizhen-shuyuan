【五星占诀】岁星东方木之精，其色青来其德仁。荧惑南方火之精，其色赤来其德礼。镇星中央土之精，其色黄来其德信。太白西方金之精，其色白来其德义。辰星北方水之精，其色黑来其德智。五星顺行天下治，五星逆行天下乱。五星聚舍王者兴，五星失次灾祸连。

【二十八宿占诀】角亢氐房心尾箕，东方青龙七宿齐。斗牛女虚危室壁，北方玄武七宿依。奎娄胃昴毕觜参，西方白虎七宿西。井鬼柳星张翼轸，南方朱雀七宿栖。二十八宿分野定，观星知事古今稽。

【七十二候诀】五日一候三候气，六气为时四时岁。二十四气七十二候，物候之变天机泄。先时而动谓之妄，后时而动谓之怠。与时偕行天道要，观候知时万事济。

【择吉避凶诀】大事必择吉日行，干支五行配月令。月令当旺择生助，失令避克保安宁。天有异象勿举事，地有异变宜修德。见凶而禳三法在，修德祭祀避忌明。

【天人感应诀】天地大宇宙人身小，天人相应如影形。天有风雨人有情，四时调养身乃平。法天则地通人事，顺时而行免祸刑。中和为上偏为下，此是龙首经中铭。

【四季养生诀】春三月夜卧早起，广步于庭志生发。夏三月夜卧早起，无厌于日志无怒。秋三月早卧早起，与鸡俱兴志安宁。冬三月早卧晚起，必待日光志伏匿。四时养生顺天道，身康体健享遐龄。

【五行干支诀】甲乙寅卯东方木，丙丁巳午南方火。戊己辰戌丑未土，庚辛申酉西方金。壬癸亥子北方水，十干十二支配行。五行生克循环转，干支纳音各不同。六十甲子周复始，天地气数在其中。

【天地中和诀】天之道损有余补不足，地之道高者为山低为川。人之道法天则地通人事，命之道中和为贵偏为灾。观天之道执天之行，察时之变知事之征。顺之者昌逆之者亡，此龙首经万古不灭之至理也。

【龙首传世诀】黄帝垂经示后昆，龙首之名天下闻。天文地理与人事，尽在此中细细论。后世三式源于此，六壬奇门太乙尊。薪火相传三千载，华夏瑰宝永长存。

