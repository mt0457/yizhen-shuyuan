《太上正一太上玄灵北斗本命长生妙经》，一卷，收入明《正统道藏》正一部本文类。此经乃太上老君于太清境大赤天宫中，为北斗九皇及诸天圣众所说延生长寿之无上妙法。北斗者，九天之精魂、九地之灵魄、九幽之冥主、九霄之司命，乃造化之枢机、人神之主宰、生死之门户、寿命之权柄。人人皆有本命星君，随其生辰所属北斗第几星而主掌其一生寿夭穷通。经中详述北斗九皇——贪狼、巨门、禄存、文曲、廉贞、武曲、破军、左辅、右弼——之名号、神职、本命所属及延生秘法。全经包含：北斗九皇之本起与功德、十二本命星君之说、延生长寿之存思秘法、北斗长生神咒与灵符、朝斗拜斗之科仪轨范、禳灾解厄延寿增算之醮仪、持诵之禁忌与斋戒、功德利益等。此经与《太上玄灵北斗本命延生真经》（洞神部本文类）互为表里——彼经重在消灾解厄、度亡济幽；此经专在延生长寿、固命安身。二经合参，方得北斗法门之全体大用。此经为天师道正一派长生命功之根本经典，历代天师秘传，不轻授受。凡遇此经者，皆宿世与北斗有深缘，当生难遭之想，珍重受持。
