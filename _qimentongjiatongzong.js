【排盘实例】冬至后阳遁一局，甲子日甲子时。
一步定局：冬至阳遁一局，甲子戊在坎一宫。
二步布六仪：戊在坎一，己在坤二，庚在震三，辛在巽四，壬在中五（寄坤二），癸在乾六。
三步布三奇：丁在兑七，丙在艮八，乙在离九。
四步排八门：甲子时值使为休门，休门在坎一。开门在乾六，生门在艮八，伤门在震三，杜门在巽四，景门在离九，死门在坤二，惊门在兑七。
五步布九星：值符为天蓬星在坎一。天芮在坤二，天冲在震三，天辅在巽四，天禽在中五，天心在乾六，天柱在兑七，天任在艮八，天英在离九。
