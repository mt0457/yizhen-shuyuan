【玄机赋】

混沌初开气为先，河图洛书定坤乾。
八卦分居八方地，九宫配卦理通天。
三奇乙丙丁为日月星三光普照，
六仪戊己庚辛壬癸隐甲兵权。
八门开休生伤杜景死惊各司其职，
九星蓬任冲辅禽心芮柱英各有其能。
