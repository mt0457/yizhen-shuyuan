【千金诀序】千金诀者奇门之精华要诀也，得其诀者千金不换故曰千金诀。此诀汇集奇门历代宗师之心得要旨，简明扼要便于记诵。学者宜朝夕诵读烂熟于心。

【千金排盘诀】先查节气定阴阳，再查局数戊起方。阳顺阴逆排六仪，顺三奇与逆三奇。八门值使随时辰，阳顺阴逆转宫位。九星值符随天干，八神随符顺逆分。五步排完盘即成，奇门一局在掌中。

【千金占断诀】开门乾宫谒贵通，死门坤宫送丧终。惊门兑宫防口舌，伤门震宫利渔猎。生门艮宫求财吉，景门离宫文采扬。杜门巽宫宜隐匿，休门坎宫养身体。天辅读书天心医，天禽百事天蓬盗。天任守成天冲战，天芮授徒天柱讼。天英宴乐文采事，各星各司莫弄错。

【千金应期诀】宫数为主时为准，内盘应速外盘迟。一宫应一近一日，九宫应九远九月。阳局专用奇数推，阴局但取偶数验。戊为己身庚为阻，三奇临日吉应期。马星冲动事立至，值符到宫万事齐。

【千金择吉诀】出行开门丙奇好，求财生门值符高。婚嫁六合加三奇，赴任开门九天豪。疗病天心丁奇效，考试景门天辅妙。修造生门加天任，安葬死门天芮昭。谈判签约六合吉，捕盗伤门天冲骁。

【千金总诀】奇门之术古来珍，千金不换此诀文。若能日夜勤习诵，不出三年可通神。先识九宫八卦位，再认八门九星名。阴阳遁局须熟记，排盘占断次第行。择吉各有所宜忌，应期自有定数存。莫将此诀轻传世，非人勿授谨记心。

