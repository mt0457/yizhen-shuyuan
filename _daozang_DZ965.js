<p style="font-size:16px;color:#8b1a1a;line-height:2.2;margin:0;">
<b>太上道君说智慧观身大戒已竟。定光真人及诸圣众闻说是戒，皆大欢喜，信受奉行。一时天雨妙华、地涌金莲、虚空之中自然奏起天乐。三百观身大戒，犹如三百慧日，照破无始无明。三百观身大戒，犹如三百利剑，斩断生死根本。三百观身大戒，犹如三百宝阶，直通大罗天境。愿闻者生信、信者受持、持者精进、进者成就。智慧观身天尊。福生无量天尊。</b>
</p>
