井之否：否塞時井，井泥不食。賢人隱退，君子道息。
井之同人：同人共井，共享其利。和睦相處，無有爭異。
井之大有：大有之年，井泉湧溢。五穀豐登，井之功績。
井之谦：謙虛如井，處下不爭。水流就下，井德之貞。
井之豫：豫樂井養，宴飲無憂。井以養人，其樂悠悠。
