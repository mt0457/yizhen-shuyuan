井之乾：井以養人，其德如天。養而不窮，萬民賴焉。
井之坤：井泉在地，養育萬民。往來井井，和睦鄉鄰。
井之屯：井渫不食，為我心惻。可用汲矣，王明並受其福。
井之蒙：井泥不食，舊井無禽。時舍也，不可汲飲。
井之需：需待井泉，如渴望泉。久旱得井，中心歡忭。
井之讼：爭井致訟，鄰里不和。共享為上，爭則兩禍。
井之师：行師得井，軍不乏水。水為軍要，井之利美。
井之比：親比如井，養而不窮。良朋益友，如井之功。
井之小畜：小畜如井，點滴積蓄。雖少不匱，細水長續。
井之履：履道如井，小心翼翼。如臨深淵，如履薄冰。
